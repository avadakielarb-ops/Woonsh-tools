r"""
ПОСТОЯННЫЕ НОМЕРА: раздать тем строкам, у кого их ещё нет.

Зачем номер вообще — написано в код/common/номер.py. Здесь только раздача.

ДВА ШАГА, и второй нельзя сделать в скрипте таблицы:
  1. рабочие листы и «Отработано» — номера выдаёт сам скрипт: клеток две с
     половиной тысячи, гонять их через сеть незачем;
  2. «Реестр» — его строки надо СВЯЗАТЬ с номерами, уже выданными на листах,
     а связь идёт по ключу «ГЕО|нормализованное имя». Правила нормализации
     живут в Python и второй копии в JS не получат — иначе однажды две копии
     ответят по-разному. Поэтому карту считаем здесь и отдаём готовой.

Запускать можно сколько угодно раз: выданные номера не трогаются, работа идёт
только по пустым клеткам.

Запуск:
    .venv\Scripts\python.exe код\номера_фирмам.py            — показать
    .venv\Scripts\python.exe код\номера_фирмам.py --писать   — и раздать
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from part2.core.matching import normalize

СЛУЖЕБНЫЕ = {"Слова", "Лог", "Реестр", "Лист1"}


def карта_реестра(log=print) -> dict[str, str]:
    """
    {ключ «Реестра» → номер строки на листе}.

    Ключ строим ровно так же, как его строит выгрузка: «ГЕО|нормализованное
    имя». Гео берём из колонки, а нет её — из имени листа: «EE.БС» → EE.
    """
    from common import таблица as т

    карта: dict[str, str] = {}
    спорных = 0
    # Вся таблица одним запросом, включая «Отработано»: там тоже лежат фирмы
    # с номерами, и «Реестр» должен знать про них.
    for л in т.всё(служебные=True):
        if л["имя"] in СЛУЖЕБНЫЕ or not л["строк"] or not л["строки"]:
            continue
        ш = л["строки"][0]
        if "Организация" not in ш or "ID" not in ш:
            continue
        iо, iи = ш.index("Организация"), ш.index("ID")
        iг = ш.index("Гео") if "Гео" in ш else -1
        свой = л["имя"].split(".")[0].upper()
        for с in л["строки"][1:]:
            орг = с[iо].strip() if iо < len(с) and с[iо] else ""
            ид = с[iи].strip() if iи < len(с) and с[iи] else ""
            if not орг or not ид:
                continue
            гео = (с[iг].strip().upper() if 0 <= iг < len(с) and с[iг] else "")
            гео = гео or (свой if len(свой) == 2 else "")
            ключ = f"{гео}|{normalize(орг)}"
            # ОДНА ФИРМА В ДВУХ СТРОКАХ — не выдумка: она могла попасть и на
            # лист гео, и в «Мультигео». Оставляем первую: правка по любой из
            # них доедет, а гадать, какая «настоящая», не на чем.
            if ключ in карта:
                спорных += 1
                continue
            карта[ключ] = ид
    log(f"  · связок «Реестр → номер»: {len(карта)}"
        + (f", повторов пропущено {спорных}" if спорных else ""))
    return карта


if __name__ == "__main__":
    from common import таблица as т

    писать = "--писать" in sys.argv
    print("Смотрю, у кого нет номера…")
    пусто = []
    for л in т.схема():
        if л["имя"] in СЛУЖЕБНЫЕ or not л["строк"]:
            continue
        if "Организация" in л["шапка"] and "ID" not in л["шапка"]:
            пусто.append(f"{л['имя']} ({л['строк']})")
    print(f"   листов без колонки ID: {len(пусто)}"
          + (f" — {', '.join(пусто[:8])}" if пусто else ""))

    if not писать:
        print()
        print("Это ПРИМЕРКА. Раздать номера: --писать")
        raise SystemExit(0)

    о = т.проставить_ид()
    print(f"   ✔ выдано номеров: {о.get('выдано')}, "
          f"строк с номером: {о.get('всего')}")

    карта = карта_реестра()
    о2 = т.проставить_ид(реестр=карта)
    print(f"   ✔ в «Реестре» проставлено: {о2.get('реестр')}")
