r"""
ОТМЕТИТЬ ОТРАБОТАННЫЕ ФИРМЫ по списку от пользователя.

Список — обычный текст: имя фирмы, иногда с адресом и гео в конце строки.
Что делаем:
  1. сопоставляем с тем, что лежит у нас, — по имени, по имени БЕЗ скобок,
     по псевдониму В скобках и по имени файла выписки (Часть 2 называет файл
     именем из РЕЕСТРА, и в списке пользователя встречается именно оно:
     «ABB AQUA LIMITED» вместо «HYDRIADES LIMITED»);
  2. спорные — когда одно имя нашлось в нескольких странах — разводим по
     ПРАВОВОЙ ФОРМЕ: «SPÓŁKA Z O.O.» это Польша, «LIMITED» — Британия;
  3. найденные помечаем «отработано» и убираем с рабочего листа в скрытый;
  4. те, кого у нас нет вовсе, всё равно кладём в «Реестр» — иначе следующий
     прогон найдёт их заново и человек будет проверять их у бота второй раз.

Запуск:
    .venv\Scripts\python.exe код\отметить_отработанные.py данные\отработанные_08-09.txt
    …тот же вызов с --писать — применить
"""
