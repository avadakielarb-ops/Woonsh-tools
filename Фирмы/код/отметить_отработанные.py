# Длинные написания форм: в списках от пользователя они приходят полностью
# («SPÓŁKA Z OGRANICZONĄ ODPOWIEDZIALNOŚCIĄ»), а в LEGAL_FORMS лежат сокращения.
ДЛИННЫЕ_ФОРМЫ = {
    "korlatolt felelossegu tarsasag": "HU",
    "spolka z ograniczona odpowiedzialnoscia": "PL",
    "gesellschaft mit beschrankter haftung": "DE",
    "osauhing": "EE",
}


def ключи_имени(имя: str) -> set[str]:
    """Все написания, под которыми фирма может у нас лежать."""
    к = {normalize(имя), normalize(re.sub(r"\([^)]*\)", " ", имя))}
    for вн in re.findall(r"\(([^)]*)\)", имя):
        if len(вн.strip()) > 2:
            к.add(normalize(вн))
    return {x for x in к if x}


def _сложить(с: str) -> str:
    """
    Опустить регистр и диакритику, но ФОРМУ ОСТАВИТЬ.

    Проектный normalize() здесь не годится: он специально срезает правовые
    формы («DIAMOND SHINE Kft.» → «diamond shine»), а нам нужна ровно она.
    """
    import unicodedata
    т = unicodedata.normalize("NFKD", с or "").lower()
    т = "".join(x for x in т if not unicodedata.combining(x))
    for a, b in (("ł", "l"), ("ø", "o"), ("đ", "d"), ("ß", "ss")):
        т = т.replace(a, b)
    return " " + re.sub(r"[^a-z0-9]+", " ", т).strip() + " "


def гео_формы(имя: str) -> set[str]:
    """
    Какие страны допускает правовая форма в названии.

    Возвращает МНОЖЕСТВО: «limited» — это и Британия, и США, и Австралия, и
    Ирландия, и сама по себе она ничего не решает. Но если кандидатов всего
    два и один из них в этом множестве — вопрос закрыт.
    """
    н = _сложить(имя)
    страны: set[str] = set()
    for гео, формы in LEGAL_FORMS.items():
        for ф in формы:
            if _сложить(ф).strip() and _сложить(ф) in н:
                страны.add(гео)
                break
    for ф, гео in ДЛИННЫЕ_ФОРМЫ.items():
        if _сложить(ф) in н:
            страны.add(гео)
    return страны


def разобрать_список(путь: Path, гео_всем: str = "") -> list[tuple[str, str]]:
    """
    Строка → (имя, гео). Гео берём из конца строки, а если задано гео_всем —
    оно и побеждает: списки обычно приходят по одной стране.

    Списки пользователь копирует прямо из окна, и там имя идёт блоком:
        "Aqua Greenland OÜ
         Address: Harju maakond, Tallinn, …
         Website:"
    Строки «Address:» и «Website:» — это не фирмы. Раньше они превращались
    в мусорные записи и портили счёт «не нашлось».
    """
    записи = []
    for строка in путь.read_text(encoding="utf-8").splitlines():
        строка = строка.strip().strip('"').strip()
        if not строка:
            continue
        низ = строка.lower()
        if низ.startswith(("address:", "website:", "адрес:", "сайт:")):
            continue
        гео = гео_всем
        куски = [к for к in строка.split("  ") if к.strip()]
        хвост = куски[-1].strip() if len(куски) > 1 else ""
        if not гео and len(хвост) == 2 and хвост.isalpha():
            гео, строка = хвост.upper(), куски[0]
        elif гео and len(хвост) == 2 and хвост.isalpha():
            строка = куски[0]
        записи.append((строка.strip(), гео))
    return записи


def свести(путь: Path, log=print, гео_всем: str = "") -> dict:
    записи = разобрать_список(путь, гео_всем)
    итог = перенос.собрать(log=lambda s: None)

    по_ключу: dict[str, list] = {}
    for (гео, _), з in итог["фирмы"].items():
        варианты = ключи_имени(з["орг"])
        from common import раскладка
        файл = раскладка.взять(з["строка"], "Файл выписки")
        if файл:
            варианты |= ключи_имени(Path(файл).stem)
        for в in варианты:
            по_ключу.setdefault(в, []).append((гео, з))

    отметки, в_реестр, спорные = [], [], []
    видели = set()
    for имя, гео in записи:
        кандидаты = {}
        for к in ключи_имени(имя):
            for г, з in по_ключу.get(к, []):
                кандидаты[(г, з["орг"])] = (г, з)
        список = list(кандидаты.values())
        if гео:
            список = [(г, з) for г, з in список if г == гео] or список
        if len({г for г, _ in список}) > 1:
            # Пересекаем страны-кандидаты с теми, что допускает правовая форма.
            # «BRONZE INC LIMITED» нашлась и в PL, и в UK; «limited» бывает в
            # UK/US/AU/IE — пересечение даёт ровно UK, и гадать не нужно.
            допустимо = гео_формы(имя)
            сужено = [(г, з) for г, з in список if г in допустимо]
            if len({г for г, _ in сужено}) == 1:
                список = сужено
            else:
                спорные.append((имя, sorted({г for г, _ in список})))
                continue
        if not список:
            свои = гео_формы(имя)
            г = гео or (свои.pop() if len(свои) == 1 else "")
            в_реестр.append([f"{г or '??'}|{normalize(имя)}", г, имя,
                             "отработано", f"{date.today():%d-%m-%Y}", "",
                             f"список {путь.name}, в книгах не найдена", ""])
            continue
        г, з = список[0]
        если = (г, normalize(з["орг"]))
        if если in видели:
            continue
        видели.add(если)
        if з["лист"]:
            # Номер шлём только «свой» — прочитанный из книги. Выданный на
            # ходу в таблице не значится и искать по нему нечего.
            отметки.append({"лист": з["лист"], "орг": з["орг"],
                            "ид": з["ид"] if з.get("ид_из_книги") else ""})
    return {"отметки": отметки, "в_реестр": в_реестр, "спорные": спорные,
            "всего": len(записи)}


def показать(с: dict, log=print) -> None:
    log(f"строк в списке:        {с['всего']}")
    log(f"  найдено у нас:       {len(с['отметки'])}")
    log(f"  нет у нас → в Реестр: {len(с['в_реестр'])}")
    log(f"  спорных (не трогаю): {len(с['спорные'])}")
    по_листам = Counter(о["лист"] for о in с["отметки"])
    log("")
    for л, n in sorted(по_листам.items()):
        log(f"   {л:12} {n:>4}")
    if с["спорные"]:
        log("")
        log("=== СПОРНЫЕ: одно имя в нескольких странах, решай глазами ===")
        for имя, гео in с["спорные"]:
            log(f"   «{имя[:70]}» → {', '.join(гео)}")


