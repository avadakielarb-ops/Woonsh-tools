r"""
УБРАТЬ МЕЖЛИСТОВЫХ БЛИЗНЕЦОВ: фирма лежит на двух листах сразу.

Зачем. Правка статуса находит ТОЛЬКО ПЕРВУЮ строку с нужным номером — вторая
навсегда остаётся такой, какой записалась. Таблица начинает противоречить
сама себе, и ни один счётчик этого не показывает.

Замер 23.09.2026: 729 фирм на двух листах, 1265 лишних строк.
    268 — «Мультигео» + «Недостойные», статус «отклонена»
    461 — «Мультигео» + лист страны, статус «годная»/«найдена»/«выписка»
Статусы при этом НИГДЕ не расходились — значит какую строку оставить, вопрос
не данных, а места: лишняя всегда та, что на «Мультигео».

ПОЧЕМУ ИМЕННО «Мультигео». Это перевалочный лист мультигеошного прогона:
партию удобно видеть целиком, пока она идёт. Постоянное место фирмы — лист
её страны, а отклонённой — «Недостойные». Туда смотрят глазами, оттуда
считают счётчики.

«дубли_строк» здесь не помогает: он чистит повторы ВНУТРИ листа и оставляет
первую строку, а «Мультигео» идёт в книге первым.

Запуск:
    …\убрать_близнецов.py             — примерка, ничего не трогает
    …\убрать_близнецов.py --писать    — убрать
"""
from __future__ import annotations

import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

ЛИШНИЙ = "Мультигео"
# «Реестр» — не близнец, а отдельный справочник виденных фирм: своя шапка,
# свой смысл. Строка там не спорит с рабочей, она про другое.
НЕ_СЧИТАЕМ = {"Реестр", "Слова", "Лог"}


def где_лежат() -> dict[str, list[tuple[str, str]]]:
    from common import таблица as т

    где: dict[str, list[tuple[str, str]]] = defaultdict(list)
    for л in т.всё(служебные=True):
        имя = л.get("имя") or ""
        if имя in НЕ_СЧИТАЕМ:
            continue
        стр = л.get("строки") or []
        if not стр:
            continue
        ш = [str(х or "").strip() for х in стр[0]]
        if "ID" not in ш or "Статус" not in ш:
            continue
        ки, кс = ш.index("ID"), ш.index("Статус")
        ко = ш.index("Организация") if "Организация" in ш else -1
        for с in стр[1:]:
            if 0 <= ко < len(с) and not str(с[ко]).strip():
                continue
            и = str(с[ки]).strip() if len(с) > ки else ""
            if и:
                где[и].append(
                    (имя, (str(с[кс]).strip() if len(с) > кс else "") or "(пусто)"))
    return где


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    print("Читаю таблицу…")
    где = где_лежат()

    убрать: list[str] = []
    спорят: list[str] = []
    прочие: list[str] = []
    расклад = Counter()
    for и, места in где.items():
        листы = {л for л, _ in места}
        if len(места) < 2:
            continue
        if len({ст for _, ст in места}) > 1:
            # СТРОКИ СПОРЯТ О СТАТУСЕ — руками. Удалить одну наугад значит
            # выбрать за человека, какая правда.
            спорят.append(и)
            continue
        if ЛИШНИЙ in листы and len(листы) > 1:
            убрать.append(и)
            расклад[tuple(sorted(листы - {ЛИШНИЙ}))] += 1
        else:
            прочие.append(и)

    print()
    print(f"=== УБРАТЬ С «{ЛИШНИЙ}»: {len(убрать)} фирм ===")
    for листы, n in расклад.most_common(12):
        print(f"  {n:>5}  настоящее место: {', '.join(листы)}")
    if спорят:
        print()
        print(f"  ⚠ строки спорят о статусе — НЕ трогаю: {len(спорят)}")
        for и in спорят[:5]:
            print(f"      {и}: {где[и]}")
    if прочие:
        print()
        print(f"  ⚠ близнецы мимо «{ЛИШНИЙ}» — НЕ трогаю: {len(прочие)}")
        for и in прочие[:5]:
            print(f"      {и}: {где[и]}")

    if not убрать:
        print()
        print("Убирать нечего.")
        raise SystemExit(0)

    if "--писать" not in sys.argv:
        print()
        print("Это ПРИМЕРКА, таблица не тронута. Убрать: --писать")
        raise SystemExit(0)

    from common import таблица as т

    print()
    о = т.убрать_строки(ЛИШНИЙ, убрать, примерка=False)
    print(f"  ☁ убрано строк с «{ЛИШНИЙ}»: {о.get('убрано', 0)}")
    print()
    print("Теперь у каждой фирмы одна рабочая строка, и правка статуса "
          "попадает именно в неё.")
