r"""
ПЕРЕНОС ЛОКАЛЬНОГО ХОЗЯЙСТВА В GOOGLE ТАБЛИЦУ.

Зачем. Пользователь не может ответить на простой вопрос: «работал я с этой
фирмой или нет». Данные размазаны по 23 книгам, 97 листам и ПЯТНАДЦАТИ разным
наборам колонок, а выписки лежат в папках, которые называются по-разному.
Этот скрипт сводит всё в одно место и приводит к одной раскладке.

ЧТО ДЕЛАЕТ (ровно в этом порядке, как договорились):
  1. собирает все фирмы из книг, приводя разные шапки к одной — через
     переходник common/колонки;
  2. раскладывает по трём корзинам:
        есть сайт            → лист гео («EE»)
        сайта нет, адрес есть → лист «EE.БС»
        адреса нет           → только в «Реестр», в рабочие листы не попадает;
  3. смотрит, у каких фирм выписка РЕАЛЬНО лежит на диске: сперва по имени
     файла из колонки, потом по имени+гео. Не сошлось — в «Разобрать руками»;
  4. схлопывает повторы: одна фирма могла попасть и в книгу гео, и в мультигео.

ЧЕГО НЕ ДЕЛАЕТ. Не ставит «отработано» — это отдельный шаг, когда пользователь
даст список. И не трогает локальные файлы вообще: только читает.

Запуск:
    .venv\Scripts\python.exe код\перенос_в_таблицу.py           — только показать
    .venv\Scripts\python.exe код\перенос_в_таблицу.py --писать  — и выгрузить
"""
from __future__ import annotations

import re
import sys
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from openpyxl import load_workbook

from common import номер, раскладка
from common.колонки import Шапка
from common.пути import ВЫПИСКИ, КОРЕНЬ
from part1.data.countries import NAME_TO_CODE
from part2.core.matching import normalize

# Раскладка листа в таблице — та же, что в доки/таблица_скрипт.js.
# Раскладка одна на весь проект — см. common/раскладка.py. Здесь только
# псевдоним, чтобы не менять полсотни упоминаний.
КОЛОНКИ = раскладка.КОЛОНКИ
РЕЕСТР = ["Ключ", "Гео", "Организация", "Статус", "Дата", "Слово", "Откуда",
          "ID"]

ЛИСТЫ_МИМО = {"Лог"}          # служебный лист Части 1, фирм там нет
ДОКУМЕНТЫ = (".pdf", ".docx")


# ---------------------------------------------------------------- выписки

def выписки_на_диске(папка: Path, log=print) -> tuple[dict, dict]:
    """
    Что реально скачано. Возвращает два указателя:
      по имени файла  — {'FIRMA.pdf': путь}
      по имени фирмы  — {(гео, нормализованное имя): путь}

    Гео берём из пути: в раскладке оно либо первой папкой («UK/…»), либо
    вложенной («Мультигео/23-08/PL/…»). Не нашли — ключ без гео, такие
    сойдутся только по имени файла.
    """
    по_файлу: dict[str, Path] = {}
    по_имени: dict[tuple[str, str], Path] = {}
    if not папка.exists():
        return по_файлу, по_имени
    for п in папка.rglob("*"):
        if not п.is_file() or п.suffix.lower() not in ДОКУМЕНТЫ:
            continue
        по_файлу.setdefault(п.name, п)
        части = [ч for ч in п.relative_to(папка).parts[:-1]]
        гео = next((ч.upper() for ч in reversed(части)
                    if len(ч) == 2 and ч.isalpha()), "")
        ключ = normalize(п.stem)
        if ключ:
            # Ключ БЕЗ гео заводим только тогда, когда страну из пути не
            # вычислили. Иначе британский файл «BRONZE LTD.pdf» цеплялся бы к
            # эстонской фирме с похожим именем, и в таблице появилась бы
            # выписка там, где её нет, — худший вид вранья.
            по_имени.setdefault((гео or "", ключ), п)
    log(f"  · выписок на диске: {len(по_файлу)} файлов")
    return по_файлу, по_имени


# ---------------------------------------------------------------- гео

def гео_книги(имя_файла: str) -> str:
    """«Czech Republic.xlsx» → CZ. «Мультигео 07-09.xlsx» → пусто."""
    основа = Path(имя_файла).stem.lower().strip()
    return NAME_TO_CODE.get(основа, "")


def гео_листа(имя_листа: str) -> str:
    """«23-08 PL» → PL. «Без сайта» → пусто."""
    куски = (имя_листа or "").split()
    if куски and len(куски[-1]) == 2 and куски[-1].isalpha():
        return куски[-1].upper()
    return ""


def дата_листа(имя_листа: str) -> str:
    """«23-08 PL» → 23-08, «0709» → 07-09. Не разобрали — пусто."""
    m = re.match(r"^\s*(\d{2})[-. ]?(\d{2})", имя_листа or "")
    return f"{m.group(1)}-{m.group(2)}" if m else ""


# ---------------------------------------------------------------- сбор

def собрать(log=print, только_книга: Path | None = None,
            только_лист: str | None = None) -> dict:
    """
    Собрать фирмы из книг. Без ограничений — из всех, это разовый перенос.

    только_книга/только_лист — для ВЫГРУЗКИ ПОСЛЕ ПРОГОНА: там нужен ровно тот
    лист, который сейчас отработали. Раньше приходилось перечитывать все 23
    книги ради десяти новых строк.
    """
    к = КОРЕНЬ
    по_файлу, по_имени = выписки_на_диске(ВЫПИСКИ, log)

    лучшие: dict[tuple[str, str], dict] = {}
    разобрать: list[list] = []
    счёт = Counter()
    по_книгам = defaultdict(Counter)

    книги = ([Path(только_книга)] if только_книга
             else sorted((к / "фирмы").glob("*.xlsx")))
    for книга in книги:
        гк = гео_книги(книга.name)
        try:
            wb = load_workbook(книга, read_only=True, data_only=True)
        except Exception as e:
            log(f"  ✘ {книга.name}: {type(e).__name__}")
            continue
        for имя_листа in wb.sheetnames:
            if имя_листа in ЛИСТЫ_МИМО:
                continue
            if только_лист and имя_листа not in (только_лист, "Без сайта"):
                continue      # «Без сайта» берём всегда: туда падает вторая корзина
            ws = wb[имя_листа]
            ш = Шапка(ws)
            гл = гео_листа(имя_листа) or гк
            дата = дата_листа(имя_листа)
            # На листе «Без сайта» раскладка своя: Организация первой колонкой.
            без_сайта_лист = "без сайта" in имя_листа.lower()
            зап = {"Организация": 1, "Адрес": 2, "Город": 3, "Индекс": 4} \
                if без_сайта_лист else \
                {"Платёжный профиль": 2, "Организация": 3, "Адрес": 4,
                 "Город": 5, "Индекс": 6, "Штат": 7, "Website": 8,
                 "Номер в реестре": 9, "Файл выписки": 10,
                 "Платёжный профиль выписки": 11}
            но = {поле: ш.номер(поле, зап.get(поле, 0)) for поле in
                  ("Платёжный профиль", "Организация", "Адрес", "Город",
                   "Индекс", "Штат", "Website", "Номер в реестре",
                   "Файл выписки", "Платёжный профиль выписки", "ID",
                   "Слово")}
            к_гео = ш.номер("Гео")
            ширина = max([n for n in но.values() if n] + [к_гео, 1])

            # Лист читаем В ПАМЯТЬ целиком: нужен второй взгляд на все имена
            # этого листа, чтобы отличить «файл назван по реестру» от «файл
            # чужой». Листы маленькие, самый большой — 810 строк.
            все_строки = list(ws.iter_rows(min_row=2, min_col=1,
                                           max_col=ширина, values_only=True))
            к_орг = но.get("Организация", 0)
            имена_листа = {normalize(str(с[к_орг - 1]))
                           for с in все_строки
                           if к_орг and к_орг <= len(с) and с[к_орг - 1]}

            for строка in все_строки:
                def взять(поле: str) -> str:
                    i = но.get(поле, 0)
                    if not i or i > len(строка) or строка[i - 1] is None:
                        return ""
                    return str(строка[i - 1]).strip()

                орг = взять("Организация")
                if not орг or орг.lower() in ("организация", "название"):
                    continue
                гео = ""
                if к_гео and к_гео <= len(строка) and строка[к_гео - 1]:
                    гео = str(строка[к_гео - 1]).strip().upper()
                гео = гео or гл
                счёт["всего строк"] += 1
                if not гео:
                    разобрать.append([орг, книга.name, имя_листа, "не понял гео"])
                    счёт["без гео"] += 1
                    continue

                сайт, адрес = взять("Website"), взять("Адрес")
                индекс = взять("Индекс")
                # ВЫПИСКА. Имя файла и имя фирмы РАЗЛИЧАЮТСЯ законно: Часть 2
                # называет файл именем из РЕЕСТРА, а в листе лежит имя с dnb.
                # Поэтому «не совпало» само по себе ни о чём не говорит.
                # А вот если имя файла — это имя ДРУГОЙ фирмы С ЭТОГО ЖЕ ЛИСТА,
                # то файл действительно чужой: так нашлось «HYDRIADES LIMITED»
                # с файлом ABB AQUA LIMITED.pdf — след замены, при которой
                # строку переиспользовали, а имя файла не стёрли. Переносить
                # такое нельзя: в таблице будет «выписка есть», а в ней другая
                # фирма.
                файл = взять("Файл выписки")
                путь = None
                if файл:
                    из_колонки = по_файлу.get(файл)
                    свой = normalize(орг)
                    чей = normalize(Path(файл).stem)
                    if из_колонки is None:
                        разобрать.append([орг, книга.name, имя_листа,
                                          f"в колонке файл «{файл}», на диске нет"])
                        счёт["файл записан, но не найден"] += 1
                    elif чей != свой and чей in имена_листа:
                        разобрать.append([орг, книга.name, имя_листа,
                                          f"в колонке файл другой фирмы «{файл}»"])
                        счёт["в колонке чужой файл"] += 1
                    else:
                        путь = из_колонки
                if путь is None:
                    путь = (по_имени.get((гео, normalize(орг)))
                            or по_имени.get(("", normalize(орг))))

                # ТРИ КОРЗИНЫ. Без адреса фирма бесполезна обеим линиям:
                # в «с сайтом» её незачем, в «без сайта» — нечего показать.
                if сайт:
                    корзина, лист = "с сайтом", гео
                elif адрес or индекс:
                    корзина, лист = "без сайта", f"{гео}.БС"
                else:
                    корзина, лист = "без адреса", ""
                счёт[корзина] += 1
                по_книгам[книга.name][корзина] += 1

                профиль = взять("Платёжный профиль")
                # НОМЕР ИЗ КНИГИ — единственный, которому можно верить: он
                # тот же самый, что лежит в строке таблицы. Нет его (книга
                # старая, писалась до колонки) — выдаём новый, но помечаем
                # это. Новым номером НЕЛЬЗЯ искать существующую строку: он
                # только что придуман и в таблице его нет.
                свой_ид = взять("ID")
                ид = свой_ид or номер.новый(гео)
                запись = {
                    "лист": лист, "гео": гео, "орг": орг, "корзина": корзина,
                    "ид": ид, "ид_из_книги": bool(свой_ид),
                    # СТРОКА СОБИРАЕТСЯ ПО ИМЕНАМ, а не по порядку: порядок
                    # колонок менялся и будет меняться, а список позиций
                    # переживает ровно до первой перестановки — и ломается
                    # молча, раскладывая адрес в город.
                    "строка": раскладка.собрать({
                        "Статус": "найдена",
                        "Платёжный профиль": профиль,
                        "Организация": орг,
                        "Адрес": адрес,
                        "Город": взять("Город"),
                        "Индекс": индекс,
                        "Штат": взять("Штат"),
                        "Website": сайт,
                        "Номер в реестре": взять("Номер в реестре"),
                        "Файл выписки": путь.name if путь else "",
                        "Платёжный профиль выписки":
                            взять("Платёжный профиль выписки"),
                        "Гео": гео,
                        "Дата": дата,
                        # СЛОВО, по которому фирма найдена. В старых книгах
                        # колонки нет — там будет пусто, и это честно:
                        # выдумывать слово задним числом нельзя.
                        "Слово": взять("Слово"),
                        "Исходное с dnb": профиль,
                        "ID": ид,
                    }),
                    "откуда": f"{книга.name} / {имя_листа}",
                    "выписка": bool(путь),
                }
                ключ = (гео, normalize(орг))
                прежняя = лучшие.get(ключ)
                if прежняя is None:
                    лучшие[ключ] = запись
                else:
                    счёт["повторов схлопнуто"] += 1
                    # Побеждает запись, у которой БОЛЬШЕ правды: сперва с
                    # выпиской, потом с сайтом, потом с длинным профилем.
                    вес = lambda з: (
                        з["выписка"],
                        bool(раскладка.взять(з["строка"], "Website")),
                        len(раскладка.взять(з["строка"], "Платёжный профиль")))
                    if вес(запись) > вес(прежняя):
                        лучшие[ключ] = запись
        wb.close()

    return {"фирмы": лучшие, "разобрать": разобрать, "счёт": счёт,
            "по_книгам": по_книгам}


# ---------------------------------------------------------------- показ

def показать(итог: dict, log=print) -> None:
    счёт, фирмы = итог["счёт"], итог["фирмы"]
    log("")
    log("=== ЧТО СОБРАЛОСЬ ===")
    for к in ("всего строк", "повторов схлопнуто", "с сайтом", "без сайта",
              "без адреса", "без гео", "файл записан, но не найден",
              "в колонке чужой файл"):
        if счёт.get(к):
            log(f"   {к:32} {счёт[к]:>6}")
    log(f"   {'уникальных фирм':32} {len(фирмы):>6}")

    по_листам = Counter(з["лист"] or "(без адреса → только Реестр)"
                        for з in фирмы.values())
    с_выпиской = Counter(з["лист"] for з in фирмы.values() if з["выписка"])
    log("")
    log("=== ПО ЛИСТАМ (фирм / из них с выпиской на диске) ===")
    for лист, n in sorted(по_листам.items()):
        log(f"   {лист:28} {n:>5} / {с_выпиской.get(лист, 0):>4}")


def выгрузить(итог: dict, log=print) -> None:
    from common import таблица

    по_листам: dict[str, list] = defaultdict(list)
    реестр: list[list] = []
    for (гео, ключ), з in sorted(итог["фирмы"].items()):
        if з["лист"]:
            по_листам[з["лист"]].append(з["строка"])
        статус = "найдена" if з["лист"] else "без адреса"
        реестр.append([f"{гео}|{ключ}", гео, з["орг"], статус,
                       раскладка.взять(з["строка"], "Дата"), "",
                       з["откуда"], з["ид"]])

    log("")
    log("=== ВЫГРУЗКА ===")
    for лист in sorted(по_листам):
        строки = по_листам[лист]
        try:
            n = таблица.дописать(лист, строки)
            log(f"   ✔ {лист:14} {n:>5} строк")
        except Exception as e:
            log(f"   ✘ {лист:14} {type(e).__name__}: {str(e)[:120]}")
    try:
        n = таблица.дописать("Реестр", реестр)
        log(f"   ✔ {'Реестр':14} {n:>5} записей")
    except Exception as e:
        log(f"   ✘ Реестр: {type(e).__name__}: {str(e)[:120]}")

    if итог["разобрать"]:
        строки = [[о, к, л, п, str(datetime.now())[:16]]
                  for о, к, л, п in итог["разобрать"]]
        try:
            таблица.создать([])          # убедимся, что служебные листы есть
            n = таблица.дописать("Лог", [["", "перенос", "разобрать руками",
                                          f"{о} — {п} ({к} / {л})"]
                                         for о, к, л, п in итог["разобрать"]])
            log(f"   ✔ {'Лог':14} {n:>5} замечаний «разобрать руками»")
        except Exception as e:
            log(f"   ✘ Лог: {type(e).__name__}: {str(e)[:120]}")


if __name__ == "__main__":
    итог = собрать()
    показать(итог)
    if "--писать" in sys.argv:
        выгрузить(итог)
    else:
        print("")
        print("Это была ПРИМЕРКА, в таблицу ничего не ушло.")
        print("Выгрузить: .venv\\Scripts\\python.exe код\\перенос_в_таблицу.py --писать")
