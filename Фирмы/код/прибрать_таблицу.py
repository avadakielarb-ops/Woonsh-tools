r"""
ПРИБРАТЬ ТАБЛИЦУ: увести якоря и разложить строки по порядку.

ЯКОРЬ — фирма, которая уже никогда не даст выписку: ликвидирована, нет в
реестре, красный флаг, документ не выдают. Она лежит на рабочем листе и
занимает место, а глазом её от годной не отличить. Каждый прогон мы к ней
возвращаемся, каждый раз впустую.

Такие строки уезжают на скрытый «Отработано» — но БЕЗ пометки «отработано».
Статус сохраняется («брак», «нет выписки»), причина остаётся в колонке «Файл
выписки». Иначе завтра не отличить «сделали» от «не годится», а это разные
вещи: первое — результат, второе — брак.

Потом листы сортируются: гео, затем организация. Освобождённые места (строки
без организации) уходят вниз, чтобы не рвать список посередине.

Запуск:
    .venv\Scripts\python.exe код\прибрать_таблицу.py            — примерка
    .venv\Scripts\python.exe код\прибрать_таблицу.py --писать   — применить
"""
from __future__ import annotations

import sys
from collections import Counter
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import таблица as т

# Что считаем закрытым. «дубль» тоже: он уже заменён, держать нечего.
ЯКОРЬ = {"нет выписки", "брак", "дубль"}


def найти_якоря(log=print) -> tuple[list[dict], Counter]:
    якоря, причины = [], Counter()
    for л in т.всё():                     # вся таблица одним запросом
        if л["скрыт"] or not л["строк"]:
            continue
        строки = л["строки"]
        if not строки:
            continue
        ш = строки[0]
        iо = ш.index("Организация") if "Организация" in ш else -1
        iс = ш.index("Статус") if "Статус" in ш else -1
        iф = ш.index("Файл выписки") if "Файл выписки" in ш else -1
        iи = ш.index("ID") if "ID" in ш else -1
        if iо < 0 or iс < 0:
            continue
        сколько = 0
        for с in строки[1:]:
            орг = с[iо].strip() if iо < len(с) and с[iо] else ""
            статус = с[iс].strip().lower() if iс < len(с) and с[iс] else ""
            if орг and статус in ЯКОРЬ:
                якоря.append({"лист": л["имя"], "орг": орг,
                              "ид": (с[iи].strip() if 0 <= iи < len(с) else "")})
                причины[(с[iф].strip() if 0 <= iф < len(с) else "")[:50]
                        or "(без причины)"] += 1
                сколько += 1
        if сколько:
            log(f"   {л['имя']:10} {сколько:>4}")
    return якоря, причины


if __name__ == "__main__":
    писать = "--писать" in sys.argv
    print("Ищу якоря по листам…")
    якоря, причины = найти_якоря()
    print()
    print(f"ЯКОРЕЙ ВСЕГО: {len(якоря)}")
    for п, n in причины.most_common(10):
        print(f"   {n:>4}  {п}")

    if not писать:
        print()
        print("Это ПРИМЕРКА, таблица не тронута.")
        raise SystemExit(0)

    if якоря:
        о = т.отработать(якоря, f"{date.today():%d-%m-%Y}", сохранять_статус=True)
        print()
        print(f"   ✔ уведено с рабочих листов: {о['помечено']} "
              f"(статус сохранён, причина при них)")

    print()
    print("Сортирую листы…")
    for л in т.схема():
        if л["скрыт"] or л["строк"] < 2:
            continue
        try:
            n = т.сортировать(л["имя"])
            print(f"   ✔ {л['имя']:10} {n:>4} строк")
        except Exception as e:
            print(f"   ✘ {л['имя']:10} {type(e).__name__}: {str(e)[:80]}")
