r"""
ПРОДОЛЖИТЬ ПРЕРВАННЫЙ ПРОГОН.

Зачем. Заказ «19 стран по 100» идёт часами. Человек уходит спать, жмёт «Стоп»
— и назавтра всё начинается с нуля: какие страны добраны, а какие нет, помнит
только лог, и разбирать его глазами никто не будет.

ГЛАВНОЕ РЕШЕНИЕ: сколько уже сделано, СЧИТАЕМ ПО КНИГЕ, а не по закладке.
Закладка, которую пишут «в нужный момент», врёт ровно тогда, когда нужна: если
приложение прибили или свет выключили, последняя запись не успела лечь. А книга
пишется после КАЖДОЙ фирмы — она и есть правда. Закладка помнит только ЗАКАЗ
(какие страны просили, по сколько, какая линия), потому что заказ из книги не
восстановишь.

Файл заказа: данные/продолжение.json.
"""
from __future__ import annotations

import json
from collections import Counter
from datetime import datetime
from pathlib import Path

from common.колонки import Шапка
from common.пути import данные

ФАЙЛ = данные("продолжение.json")


def запомнить(книга: Path, лист: str, гео: list[str], сколько: int,
              линия: str = "сайт", источник: str = "dnb",
              слово: str = "") -> None:
    """Запомнить ЗАКАЗ. Зовётся при старте прогона, а не при остановке."""
    try:
        ФАЙЛ.write_text(json.dumps({
            "когда": datetime.now().strftime("%Y-%m-%d %H:%M"),
            "книга": str(книга), "лист": лист, "гео": list(гео),
            "сколько": int(сколько), "линия": линия, "источник": источник,
            "слово": слово,
        }, ensure_ascii=False, indent=1), encoding="utf-8")
    except Exception:
        pass          # не смогли записать — прогон из-за этого падать не должен


def забыть() -> None:
    """Заказ выполнен целиком — предлагать продолжение больше нечего."""
    try:
        ФАЙЛ.unlink()
    except Exception:
        pass


def заказ() -> dict | None:
    try:
        return json.loads(ФАЙЛ.read_text(encoding="utf-8"))
    except Exception:
        return None


def сделано(книга: Path, лист: str) -> dict[str, int]:
    """
    Сколько фирм ПО КАЖДОЙ СТРАНЕ уже лежит в листе.

    Считаем строки с непустой организацией — ровно то, что движок называет
    «взято». Гео берём из колонки: в мультилисте страны идут вперемешку.
    """
    from openpyxl import load_workbook

    книга = Path(книга)
    if not книга.exists():
        return {}
    try:
        wb = load_workbook(книга, read_only=True, data_only=True)
    except Exception:
        return {}
    try:
        if лист not in wb.sheetnames:
            return {}
        ws = wb[лист]
        ш = Шапка(ws)
        iо = ш.номер("Организация", 3)
        iг = ш.номер("Гео")
        if not iг:
            return {}
        счёт: Counter = Counter()
        for стр in ws.iter_rows(min_row=2, max_col=max(iо, iг), values_only=True):
            орг = стр[iо - 1] if iо <= len(стр) else None
            гео = стр[iг - 1] if iг <= len(стр) else None
            if орг and гео:
                счёт[str(гео).strip().upper()] += 1
        return dict(счёт)
    finally:
        wb.close()


def остаток(з: dict | None = None) -> dict:
    """
    Что осталось добрать: {'гео': [...], 'сколько_по_гео': {...}, ...}.

    Пустой список гео означает, что заказ выполнен целиком.
    """
    з = з or заказ()
    if not з:
        return {}
    книга, лист = Path(з["книга"]), з["лист"]
    есть = сделано(книга, лист)
    нужно = int(з.get("сколько", 0))
    осталось = {г: нужно - есть.get(г.upper(), 0) for г in з.get("гео", [])}
    неполные = [г for г in з.get("гео", []) if осталось.get(г, 0) > 0]
    return {**з, "есть": есть, "сколько_по_гео": осталось,
            "гео_осталось": неполные,
            "всего_есть": sum(есть.values()),
            "всего_надо": нужно * len(з.get("гео", []))}


def словами(о: dict) -> str:
    """Короткая строка для окна: где остановились и что осталось."""
    if not о:
        return ""
    сделано_всего, надо = о.get("всего_есть", 0), о.get("всего_надо", 0)
    осталось = о.get("гео_осталось", [])
    if not осталось:
        return (f"Заказ от {о.get('когда', '?')} выполнен: "
                f"{сделано_всего} из {надо}.")
    первые = ", ".join(f"{г}:{о['сколько_по_гео'][г]}" for г in осталось[:6])
    хвост = "…" if len(осталось) > 6 else ""
    return (f"Прогон от {о.get('когда', '?')}: набрано {сделано_всего} из "
            f"{надо}. Осталось {len(осталось)} стран — {первые}{хвост}")


if __name__ == "__main__":
    import sys
    sys.stdout.reconfigure(encoding="utf-8")
    о = остаток()
    if not о:
        print("Незаконченного прогона нет.")
    else:
        print(словами(о))
        print()
        print(f"книга: {о['книга']}")
        print(f"лист:  {о['лист']}")
        for г in о.get("гео", []):
            есть = о["есть"].get(г.upper(), 0)
            print(f"   {г:4} есть {есть:>4}, осталось {о['сколько_по_гео'][г]:>4}")
