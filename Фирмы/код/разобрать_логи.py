r"""
ЧТО НА САМОМ ДЕЛЕ БЫЛО СКАЧАНО — по логам прогонов.

Зачем отдельно от осмотра диска. Диск отвечает только на «файл есть или нет».
Лог отвечает на всё остальное, и это как раз то, чего не хватало в таблице:

  · какой файл получила КАКАЯ фирма — а имена расходятся, потому что файл
    называется именем из реестра, а в листе лежит имя с dnb («HYDRIADES
    LIMITED» → «ABB AQUA LIMITED.pdf»); по диску это не связать никак;
  · номер в реестре;
  · ПОЧЕМУ выписки нет: нет НДС, красный флаг, ликвидирована, нет в реестре.
    Пустая клетка «Файл выписки» одинаково выглядит и когда фирма негодная,
    и когда мы просто до неё не дошли.

Формат лога (пишет part2/engine):
    Эстония: 163 фирм из листа «21-07 EE»      ← гео и лист
    [116/163] MRK Energy OU                     ← фирма
      ✔ MRK ENERGY OÜ.pdf  (номер 12609108)     ← удача
      ✘ нет номера НДС (EE…)                    ← отказ с причиной
      ⏭ [4/75] BM TRUSTEES LIMITED — уже скачана ранее, пропускаю

Логи читаются ПО ПОРЯДКУ ДАТ, поздний ответ перекрывает ранний: фирму могли
сначала не найти, а через неделю скачать.

Запуск:  .venv\Scripts\python.exe код\разобрать_логи.py
"""
from __future__ import annotations

import re
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common.пути import ВЫПИСКИ, КОРЕНЬ
from part2.core.matching import normalize
from part2.geos.registry import DRIVERS

# «Эстония» → «EE». Названия берём у самих драйверов, чтобы не держать
# второй список, который однажды разойдётся с первым.
ГЕО_ПО_НАЗВАНИЮ = {д.title: код for код, д in DRIVERS.items()}

ЗАГОЛОВОК = re.compile(r"^(?P<страна>[^:]+):\s*\d+\s+фирм из листа\s+«(?P<лист>[^»]*)»")
ФИРМА = re.compile(r"^\s*\[(?P<i>\d+)/(?P<n>\d+)\]\s*(?P<имя>.+?)\s*$")
ПРОПУСК = re.compile(r"^\s*⏭\s*\[\d+/\d+\]\s*(?P<имя>.+?)\s*—\s*(?P<почему>.+?)\s*$")
УДАЧА = re.compile(r"^\s*✔\s*(?P<файл>.+?\.(?:pdf|docx))\s*(?:\(номер\s*(?P<номер>[^)]*)\))?\s*$")
ОТКАЗ = re.compile(r"^\s*✘\s*(?P<почему>.+?)\s*$")


def разобрать(папка: Path | None = None, log=print) -> dict:
    папка = папка or (КОРЕНЬ / "логи")
    файлы = sorted(папка.glob("лог_*.txt"))          # имена начинаются с даты
    итог: dict[tuple[str, str], dict] = {}
    счёт = Counter()

    for ф in файлы:
        гео = лист = ""
        текущая = ""
        for строка in ф.read_text(encoding="utf-8", errors="replace").splitlines():
            m = ЗАГОЛОВОК.match(строка)
            if m:
                гео = ГЕО_ПО_НАЗВАНИЮ.get(m.group("страна").strip(), "")
                лист = m.group("лист")
                текущая = ""
                continue

            m = ПРОПУСК.match(строка)
            if m:
                # «уже скачана ранее» — результат есть, но он от прошлого прогона;
                # запись о нём уже лежит в более раннем логе, здесь не портим.
                текущая = ""
                continue

            m = ФИРМА.match(строка)
            if m and not строка.lstrip().startswith(("·", "✔", "✘", "⚠", "⏭")):
                текущая = m.group("имя")
                continue

            if not (текущая and гео):
                continue

            m = УДАЧА.match(строка)
            if m:
                # «(номер —)» пишется, когда реестр номера не дал. Это не номер,
                # и в таблицу такое ставить нельзя: прочерк выглядит как данные.
                номер = (m.group("номер") or "").strip()
                if номер in ("—", "-", "?", "нет"):
                    номер = ""
                итог[(гео, normalize(текущая))] = {
                    "гео": гео, "имя": текущая, "файл": m.group("файл"),
                    "номер": номер,
                    "причина": "", "лист": лист, "лог": ф.name}
                счёт["скачано"] += 1
                текущая = ""
                continue

            m = ОТКАЗ.match(строка)
            if m:
                почему = m.group("почему")
                # СБОЙ ПРОГОНА — НЕ ПРИГОВОР ФИРМЕ. «Сайт лежит», «браузер
                # закрыт», «формы поиска нет» — это про нас и про реестр, а не
                # про компанию. Запиши такое в таблицу — и фирма навсегда
                # останется помеченной негодной, хотя с ней всё в порядке.
                низ = почему.lower()
                if (почему.startswith(("ошибка:", "гео ")) or "сайт лежит" in низ
                        or "формы поиска" in низ or "targetclosed" in низ
                        or "playwright" in низ):
                    continue
                итог[(гео, normalize(текущая))] = {
                    "гео": гео, "имя": текущая, "файл": "", "номер": "",
                    "причина": почему, "лист": лист, "лог": ф.name}
                счёт["отказано"] += 1
                текущая = ""

    log(f"логов прочитано: {len(файлы)}")
    log(f"записей о фирмах: {len(итог)} "
        f"(удач {счёт['скачано']}, отказов {счёт['отказано']}, "
        f"поздние перекрыли ранние)")
    return итог


def свод(итог: dict, log=print) -> None:
    с_файлом = {к: з for к, з in итог.items() if з["файл"]}
    log("")
    log(f"=== СКАЧАНО ПО ЛОГАМ: {len(с_файлом)} фирм ===")
    по_гео = Counter(з["гео"] for з in с_файлом.values())
    for г, n in sorted(по_гео.items()):
        log(f"   {г:4} {n:>4}")

    log("")
    log("=== ПОЧЕМУ НЕ СКАЧАНО (топ причин) ===")
    причины = Counter(re.sub(r"«[^»]*»", "«…»", з["причина"])
                      for з in итог.values() if з["причина"])
    for п, n in причины.most_common(12):
        log(f"   {n:>4}  {п[:78]}")

    # ЕСТЬ ЛИ ФАЙЛ НА ДИСКЕ. Лог говорит «скачал», но файл могли убрать
    # руками или сбросить скриптом — тогда в таблице стоять «есть» не должно.
    диск = {p.name for p in (ВЫПИСКИ).rglob("*") if p.is_file()}
    пропали = [з for з in с_файлом.values() if з["файл"] not in диск]
    log("")
    log(f"=== в логе скачано, а файла на диске НЕТ: {len(пропали)} ===")
    for з in пропали[:15]:
        log(f"   {з['гео']}  {з['имя'][:44]:46} → {з['файл'][:40]}")


if __name__ == "__main__":
    свод(разобрать())
