    def _книга_и_лист(self) -> bool:
        """
        Убедиться, что известно, с каким листом работаем.

        РАБОТАЕТ И БЕЗ СВЕЖЕГО ПОИСКА. Книга и лист жили только в памяти окна:
        после перезапуска ни дубли заменить, ни выписки скачать было нельзя —
        приходилось искать фирмы заново. Берём из закладки прошлого прогона:
        она пишется при старте и переживает и «Стоп», и закрытие окна.
        """
        if self.книга and self.лист:
            return True
        з = продолжение.заказ() or {}
        книга, лист = Path(з.get("книга", "")), з.get("лист", "")
        if з.get("книга") and лист and книга.exists():
            self.книга, self.лист = книга, лист
            self._лог(f"Работаю с прошлым прогоном: {книга.name}, "
                      f"лист «{лист}»", "тускло")
            return True
        messagebox.showinfo(
            "ФИРМЫ", "Не знаю, с каким листом работать.\n"
                     "Найди фирмы или запусти «Продолжить прерванный».")
        return False

    def скачать_выписки(self):
        """
        ГЕО → СКОЛЬКО → ПОЕХАЛИ. Никаких книг и листов.

        Раньше кнопка работала по книге и листу прошлого прогона, и это было
        неправильно по существу: фирмы одной страны лежат не в одном листе, а
        где придётся — часть в «Мультигео», часть на листе гео, часть добрана
        вчера. «Лист» перестал быть ответом на вопрос «что качать по Франции»
        ещё тогда, когда появился мультигео.

        Правда теперь в ТАБЛИЦЕ. Берём оттуда фирмы выбранных стран, у которых
        выписки ещё нет, складываем наряд и отдаём Части 2. Мультигео это было
        или нет — человека не касается.
        """
        коды = self.выбранные_гео()
        if not коды:
            messagebox.showwarning("ФИРМЫ", "Выбери страну в списке.")
            return
        выбор = self._сколько_выписок(коды)
        if выбор is None:                        # человек передумал
            return
        сколько, линия = выбор
        только_с_сайтом = _линия_в_флаг(линия)

        self._сбросить_статус(
            "⬇ Качаем выписки " + {"сайт": "с сайтом", "без": "без сайта",
                                   "все": "обе линии"}[линия],
            гео=коды[0] if len(коды) == 1 else "")
        self._включить_шаги(поиск_идёт=True)
        self._отметить_шаг(2)
        выписки = пути.ВЫПИСКИ
        подпись_линии = {"сайт": "с сайтом", "без": "без сайта",
                         "все": "обе линии"}[линия]
        self._лог(f"Выписки: {', '.join(коды)}, {подпись_линии} — "
                  + ("все, что без выписки" if not сколько
                     else f"по {сколько} на страну"), "важное")

        def работа(h):
            строки = задание_выписок.найти(коды, сколько, log=self._лог_поток,
                                           только_с_сайтом=только_с_сайтом)
            if not строки:
                return {"скачано": 0, "нечего": True}
            книга, лист = задание_выписок.книга_задания(строки,
                                                        log=self._лог_поток)
            self.книга, self.лист = книга, лист
            итог = движок2.run_мультилист(
                книга, лист, выписки, h, log=self._лог_поток,
                stop=self.стоп, pause=self.пауза, только_недостающие=True,
                # РЕЖИМ — ПО ТОМУ, ЧТО ВЫБРАЛ ЧЕЛОВЕК: одна страна значит
                # папка страны, несколько — «Мультигео». Наряд всегда
                # мультилист по устройству, но это внутренняя кухня.
                мультигео=len(коды) > 1)
            # РЕЗУЛЬТАТ — ОБРАТНО В ТАБЛИЦУ. Наряд это наряд, хранилище —
            # таблица; оставить выписку только в книге значит потерять её.
            try:
                задание_выписок.вернуть_в_таблицу(книга, лист,
                                                  log=self._лог_поток)
            except Exception as e:
                self._лог_поток(f"⚠ в таблицу не вернулось: "
                                f"{type(e).__name__}: {str(e)[:80]}")
            return итог

        self._запустить(работа, после=self._после_выписок)

