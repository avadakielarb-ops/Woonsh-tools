    def старт(self, продолжаем: dict | None = None):
        """
        Запустить поиск. продолжаем — остаток прерванного прогона (см.
        «Продолжить»): те же страны и тот же ЛИСТ, но добираем только нехватку.
        """
        if self.поток and self.поток.is_alive():
            messagebox.showinfo("ФИРМЫ", "Прогон уже идёт.")
            return
        коды = (продолжаем.get("гео_осталось") if продолжаем
                else self.выбранные_гео())
        if not коды:
            messagebox.showwarning("ФИРМЫ", "Выбери страну в списке.")
            return
        сколько = int(продолжаем["сколько"]) if продолжаем else self._сколько()
        без_сайта = self.линия.get() == "без"
        слово = self.слово.get().strip()
        слово_руками = bool(слово)

        страны = [CODE_TO_NAME.get(к, к) for к in коды]
        имя_книги = ("Мультигео" if len(коды) > 1 else CODE_TO_NAME.get(коды[0], коды[0]))
        книга = пути.фирмы(f"{имя_книги}.xlsx")

        if not слово:
            слово = движок1.слово_из_запаса(
                коды[0], self._лог_поток,
                линия="бс" if без_сайта else "сайт")
            if not слово:
                messagebox.showwarning(
                    "Нет слов", f"Запас слов по {коды[0]} пуст.\n"
                                "Впиши слово руками или пополни запас.")
                return
            # ГЕО В СКОБКАХ ОБЯЗАТЕЛЬНО: по этой строке статистика слов
            # связывает слово со страной. Без него запись есть, а толку ноль.
            self._лог(f"🎲 Слово взято само: «{слово}» ({коды[0]})", "важное")

        self.книга = книга
        self.мульти = len(коды) > 1
        self.новые_строки = set()        # новый прогон — списка замен ещё нет

        # ЗАКЛАДКА — ЧТОБЫ БЫЛО КУДА ВЕРНУТЬСЯ. Пишем ЗАКАЗ и пишем СРАЗУ, а не
        # при остановке: прогон могут прибить, свет выключить, окно закрыть
        # крестиком — и запись «в нужный момент» не состоится ровно тогда,
        # когда она и нужна. Сколько уже сделано, потом посчитаем по книге:
        # книга пишется после каждой фирмы и врать не умеет.
        лист_прогона = имя_листа(коды[0], self.мульти,
                                 продолжаем.get("лист") if продолжаем else None)
        продолжение.запомнить(книга, лист_прогона, коды, сколько,
                              линия=self.линия.get(),
                              источник=self.источник.get(), слово=слово)
        # СНИМАЕМ ВСЁ, ЧТО ЖИВЁТ В ВИДЖЕТАХ, ЗДЕСЬ — в главном потоке.
        # Дальше начнётся рабочий поток, и любое обращение к Tk из него вешает
        # окно намертво (так и было: «авто_слова=self.автономно.get()»
        # исполнялось уже в потоке).
        self._гео_прогона = list(коды)
        сам = self.самоход.is_set()
        быстро = self.ускоренно.get()
        if быстро and not сам:
            # ЧЕСТНО ГОВОРИМ, ЧТО ГАЛОЧКА НЕ СРАБОТАЕТ. Закрыть пустое слово
            # можно лишь тогда, когда есть чем его заменить, а следующее слово
            # из запаса берёт автономный режим. Промолчать здесь значило бы
            # оставить человека в уверенности, что прогон ускорен.
            self._лог("⚡ Ускоренный режим включён, но без автономности он "
                      "не работает: менять слово некому. Включи «Автономно».",
                      "беда")
            быстро = False
        self._сбросить_статус(
            "🔍 Ищем фирмы " + ("без сайта" if без_сайта else "с сайтом"),
            гео=коды[0] if len(коды) == 1 else "")
        self._включить_шаги(поиск_идёт=True)
        self._отметить_шаг(0)

        # ВТОРОЙ ПУТЬ ЛИНИИ «БЕЗ САЙТА»: искать прямо в реестре, минуя dnb.
        # Сайт этой линии не нужен, а имя с адресом реестр отдаёт сам — и без
        # Cloudflare. Для линии «с сайтом» источник один, выбора там нет.
        if без_сайта and self.источник.get() == "реестр":
            # Слово, взятое из запаса САМО, — не приказ искать только по нему:
            # одного слова на сотню фирм не хватает (19.10: просили 100,
            # набрали 14). Добираем следующими словами из запаса.
            # Вписанное руками — ищем только по нему, как просили.
            self._запустить(
                lambda h: self._из_реестра(h, коды, сколько, слово, книга,
                                           добирать=not слово_руками),
                после=self._после_поиска)
            return

        def работа(h):
            # «сам» снят ДО запуска потока: читать галочку отсюда нельзя.
            # ЖИВАЯ ДОЗАПИСЬ: фирмы уезжают в таблицу по ходу прогона, пачкой
            # после каждой страницы выдачи. Прогон, прерванный на середине,
            # больше не оставляет таблицу пустой.
            # Лист ТАБЛИЦЫ, а не книги: в книге он зовётся датой, в таблице —
            # «Мультигео». Передать сюда «09-09» значит писать в лист, которого
            # в таблице нет.
            куда = дозапись.Дозапись(дозапись.Дозапись.ЛИСТ_МУЛЬТИГЕО,
                                     self._лог_поток, мультигео=self.мульти)
            if len(коды) > 1:
                return движок1.run_мультигео(
                    слово, страны, сколько, книга, h, log=self._лог_поток,
                    stop=self.стоп, pause=self.пауза, искать_без_сайта=без_сайта,
                    авто_слова=сам, лист=лист_прогона, дозапись=куда,
                    ускоренно=быстро,
                    сколько_по_гео=(продолжаем.get("сколько_по_гео")
                                    if продолжаем else None))
            return движок1.run(слово, страны[0], сколько, книга, h,
                               log=self._лог_поток, stop=self.стоп,
                               pause=self.пауза, искать_без_сайта=без_сайта,
                               # автономно — слова берём из запаса сами, без
                               # остановки на вопрос «дай следующее»
                               авто_слова=сам, дозапись=куда, ускоренно=быстро)

        self._запустить(работа, после=self._после_поиска)

    def _из_реестра(self, human, коды: list[str], сколько: int, слово: str,
                    книга, добирать: bool = False) -> dict:
        """
        Набрать фирмы прямо из реестров и положить их на лист «Без сайта».

        Пишем тем же ExcelWriter, что и находки dnb: дальше по конвейеру
        разницы нет, и все прежние проверки продолжают работать.
        """
        from part1 import из_реестра
        from part1.excel_out import ExcelWriter
        from part1.запас import Запас

        буфер = Запас(log=self._лог_поток)
        всего = 0
        лист = ""
        for гео in коды:
            if self.стоп.is_set():
                break
            if not из_реестра.умеет(гео):
                self._лог_поток(f"⏭ {гео}: драйвера реестра нет, пропускаю")
                continue
            своё = not слово or добирать
            слова = ([слово] if слово else []) + (
                буфер.взять(гео, 8) or [] if своё else [])
            слова = list(dict.fromkeys(слова))
            if not слова:
                self._лог_поток(f"⏭ {гео}: слов в запасе нет")
                continue
            испробованы: list[str] = []
            фирмы = из_реестра.искать(гео, слова, сколько, human,
                                      log=self._лог_поток, stop=self.стоп,
                                      pause=self.пауза, испробованы=испробованы)
            # ЛИШНИЕ СЛОВА ВОЗВРАЩАЕМ. Берём с запасом (нужное число фирм
            # набирается на втором-третьем слове), а «взять» помечает выданными
            # сразу все восемь. Без возврата каждый прогон сжигал бы по пять
            # НЕИСПРОБОВАННЫХ слов — при том, что запас у нас на счету.
            # Слово, которое пробовали и оно дало ноль, не возвращаем: оно
            # отработало, и второй заход даст тот же ноль.
            if своё:
                лишние = [с for с in слова if с not in испробованы]
                if лишние:
                    буфер.вернуть(гео, лишние)
                    self._лог_поток(f"  · вернул в запас неиспробованные: "
                                    f"{', '.join(лишние)}")
            if not фирмы:
                continue
            писарь = ExcelWriter(книга, гео, human=human,
                                 только_без_сайта=True)
            for ф in фирмы:
                писарь.без_сайта(ф)
            писарь.save()
            лист = писарь.sheet_name
            всего += len(фирмы)
            self._лог_поток(f"✔ {гео}: записано {len(фирмы)} на «{лист}»")
        return {"взято": всего, "лист": лист or "Без сайта"}

    def _после_поиска(self, итог):
        # Движок возвращает «взято» для одной страны и «всего» для мультигео —
        # берём то, что есть, а не гадаем по одному имени.
        итог = итог or {}
        self.лист = итог.get("лист", "") or self.лист
        найдено = итог.get("всего", итог.get("взято", 0))
        self._лог(f"Поиск закончен. Найдено: {найдено}. Лист «{self.лист}»",
                  "успех")
        self._отметить_шаг(1)
        self.кн_выписки.configure(state="normal")
        self.обновить_счётчики()
        # Прогон кончился — своим ходом или «Стопом». Пересчитываем остаток по
        # книге: если заказ добран целиком, кнопка «Продолжить» уйдёт сама.
        self.показать_остаток()

