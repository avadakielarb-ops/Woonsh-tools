    def _выбор(self, _e=None):
        коды = self.выбранные_гео()
        if коды and self.гео_поле.get() != коды[0]:
            self.гео_поле.set(коды[0])
        # Цифры на кнопках — ПО ВЫБРАННЫМ странам, значит пересчитываем на
        # каждую смену выбора. Иначе кнопка говорит про вчерашний выбор.
        self._цифры_на_кнопки()
        if not коды:
            self.подпись_выбора.configure(text="Страна не выбрана")
            return
        если = " · ".join(коды[:6]) + ("…" if len(коды) > 6 else "")
        сколько = self._сколько()
        д = self.счётчики.get(коды[0], {})
        # ГОТОВО К ВЫДАЧЕ И СКОЛЬКО КАЧАТЬ — те же цифры, но словами: это два
        # рабочих вопроса, и считать разницу в уме каждый раз незачем.
        хвост = ""
        if len(коды) == 1 and д:
            качать = max(д.get("сайт", 0) - д.get("сайт_в", 0), 0)
            качать_бс = max(д.get("бс", 0) - д.get("бс_в", 0), 0)
            хвост = (f"   ·   с сайтом {д.get('сайт', 0)} "
                     f"(готово {д.get('сайт_в', 0)}, качать {качать})"
                     f"   ·   без сайта {д.get('бс', 0)} "
                     f"(готово {д.get('бс_в', 0)}, качать {качать_бс})")
        self.подпись_выбора.configure(
            text=(f"{len(коды)} стран ({если}) × {сколько} = "
                  f"{len(коды) * сколько} фирм → лист «Мультигео»"
                  if len(коды) > 1 else f"{коды[0]} — {сколько} фирм{хвост}"))

    def выбранные_гео(self) -> list[str]:
        коды = list(self.список.selection())
        # Список свёрнут и в нём ничего не выделено — значит человек выбирал
        # выпадашкой. Она и есть ответ.
        if not коды and self.гео_поле.get():
            коды = [self.гео_поле.get()]
        return коды

    def _сколько(self) -> int:
        try:
            return max(1, int(self.сколько.get()))
        except Exception:
            return 10

