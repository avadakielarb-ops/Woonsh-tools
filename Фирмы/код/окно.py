def тек_время() -> str:
    """ЧЧ-ММ. В имени папки нужна не только дата: за день выдач бывает
    несколько, и без времени вторая легла бы в первую."""
    import time as _t
    return _t.strftime("%H-%M")


def имена_из_платёжек(сырое: str) -> list[str]:
    """
    Вытащить названия фирм из вставленного текста.

    Платёжка приходит блоком — имя, «Address:», «Website:». Человек может
    вставить и просто список названий. Берём ПЕРВУЮ содержательную строку
    каждого блока и пропускаем служебные: иначе «Address: …» уедет в поиск как
    название фирмы.

    ПРАВИЛО ПРОСТОЕ: имя — это всё, что НЕ служебная строка и не пусто.

    Оно было хитрее — «первая строка блока», а блок кончается пустой строкой.
    И сломалось на том, как платёжки копируют из таблицы: они приходят в
    кавычках и ВПЛОТНУЮ, без пустых строк между собой —

        "Benjamin BRINDAMOUR (POLITICAL HEAT)
        Address: 27 BOULEVARD SAINT-MARTIN, 75003 PARIS
        Website:"
        "Maria GARDINAL (CEREZO RIZO)
        …

    Блок тут не кончается никогда, и из четырёх фирм разбиралась ОДНА.
    Считать границы блоков не нужно вовсе: в платёжке всего три вида строк, и
    две из них подписаны («Address:», «Website:»). Всё остальное — имя. Так
    разбирается и голый список названий, и блоки через пустую строку.
    """
    СЛУЖЕБНЫЕ = ("address:", "адрес:", "website:", "сайт:", "tel", "vat",
                 "email", "phone", "reg. number", "номер:")
    имена = []
    for строка in (сырое or "").splitlines():
        с = строка.strip().strip('"').strip()
        if not с or с.lower().startswith(СЛУЖЕБНЫЕ):
            continue
        имена.append(с)
    return имена


def первая_строка(текст: str) -> str:
    """Имя фирмы из платёжки — это её первая строка, дальше адрес и сайт."""
    for с in (текст or "").splitlines():
        если = с.strip()
        if если:
            return если
    return ""


