        состояние = {"все": None, "файл": None, "имя": "",
                     "позиция": 0, "порция": None, "по_сколько": 50}

        def выдать_порцию():
            """Следующая пачка — в буфер обмена и в журнал."""
            все = состояние["все"] or []
            с = состояние["позиция"]
