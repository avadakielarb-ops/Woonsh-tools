    def _ручное_переключить(self):
        """
        Галочка открывает и закрывает ряд команд.

        Команды НЕ выполняются здесь. Окно только кладёт приказ в шлюз, а
        забирает и исполняет его сам движок — в своём потоке, на ближайшей
        передышке. Иначе никак: Playwright привязан к потоку, который его
        создал, и дёрнуть браузер из окна значит сломать прогон вернее, чем
        он уже сломан.
        """
        for w in self.ручная_панель.winfo_children():
            w.destroy()
        if not self.ручное.get():
            self.ручная_панель.pack_forget()
            return
        self.ручная_панель.pack(side="top", fill="x", pady=(0, 6))
        ttk.Label(self.ручная_панель, foreground=тема.ТЕМА["muted"],
                  text="Сработает, как только прогон освободится:"
                  ).pack(anchor="w")
        ряд = ttk.Frame(self.ручная_панель)
        ряд.pack(fill="x", pady=(4, 0))
        for ключ, подпись in self.КОМАНДЫ:
            ttk.Button(ряд, text=подпись, width=20,
                       command=lambda к=ключ: self._приказать(к)
                       ).pack(side="left", padx=(0, 4))

    def _приказать(self, ключ: str, повод: str = ""):
        # Шлюз разворачивает «повторить» в прошлую команду и возвращает, что
        # встало в очередь на самом деле: пишем в лог ЕЁ, а не «повторить» —
        # иначе человек не узнает, что именно сейчас произойдёт.
        встало = self.human.приказать(ключ)
        подпись = dict(self.КОМАНДЫ).get(встало, встало or "—")
        self._лог(f"✋ {повод or 'Поставил в очередь'}: {подпись}", "важное")

    def _чп_повтор(self):
        """
        «Обновить» — перечитать страницу, НЕ отвечая на вопрос.

        Сайты реестров подвисают на ровном месте: страница открыта, данных на
        ней нет. Раньше человеку оставалось только смириться — «Продолжить»
        или «Пропустить». Теперь он жмёт обновление, страница перезагружается,
        а вопрос ОСТАЁТСЯ на экране: посмотрел — и ответил уже по-настоящему.

        Кнопки нет, пока браузер не дал ссылку на перезагрузку: обещать
        действие, которого не существует, хуже, чем его не предлагать.
        """
        if not getattr(self.human, "перезагрузить", None):
            return
        self._чп_кнопка("🔄  Обновить страницу", *тема.КН_ДЕЙСТВИЕ,
                        self._повторить_действие)

    def _повторить_действие(self):
        """
        Кладём приказ, а НЕ дёргаем браузер сами.

        Сперва это было сделано в лоб: окно звало `перезагрузить()` в своём
        потоке. Так нельзя — Playwright привязан к потоку, который его создал,
        и чужой вызов роняет не только перезагрузку, а весь прогон. Теперь
        приказ забирает движок: на передышке между попытками он сам перечитает
        страницу, а вопрос на экране останется — человек ответит, посмотрев.
        """
        self.human.приказать("обновить")
        self._лог("✋ Поставил в очередь: 🔄 Обновить страницу", "важное")

    def _ответ(self, выбор):
        self._человек_покой()
        self.human.answer(выбор)

    def _вопрос_меню(self, заголовок, текст, варианты, фирма):
        self._человек_вид(тема.ПАНЕЛЬ_ЧЕЛОВЕК, заголовок,
                          (f"Фирма: {фирма}\n\n" if фирма else "") + текст)
        цвета = [тема.КН_УСПЕХ, тема.КН_ДЕЙСТВИЕ, тема.КН_НЕЙТРАЛЬ,
                 тема.КН_ОПАСНОСТЬ]
        for i, (ключ, подпись) in enumerate(варианты):
            фон, актив = цвета[min(i, len(цвета) - 1)]
            self._чп_кнопка(подпись, фон, актив,
                            lambda к=ключ: self._ответ_меню(к))
        # ОБНОВЛЕНИЕ ДОСТУПНО И ЗДЕСЬ — повод спросить человека чаще всего
        # один и тот же: страница ведёт себя не так, как ждали. Но только
        # если спрашивающий не предложил «повтор» сам: две кнопки про одно
        # и то же сбивают с толку.
        if not any(к == "повтор" for к, _ in варианты):
            self._чп_повтор()

    def _ответ_меню(self, ключ):
        self._человек_покой()
        self.human.answer_menu(ключ)

    def _вопрос_слово(self, сообщение):
        self._человек_вид(тема.ПАНЕЛЬ_ДОБОР, "Нужно слово", сообщение)
        поле = tk.Entry(self.чп_кнопки, font=("Segoe UI", 12))
        поле.pack(fill="x", pady=(0, 6))
        поле.focus_set()
        ввод.включить(поле)
        self._чп_кнопка("🔍  Искать", *тема.КН_УСПЕХ,
                        lambda: self._ответ_слово(поле.get().strip()))
        self._чп_кнопка("■  Хватит", *тема.КН_ОПАСНОСТЬ,
                        lambda: self._ответ_слово(движок1.СТОП_ДОБОРА))

    def _ответ_слово(self, слово):
        self._человек_покой()
        self.human.answer_keyword(слово)

    def _показать_отметку(self, итог: dict):
        помечено = итог.get("помечено", 0)
        не_нашлись = итог.get("не_нашлись", [])
        папка = итог.get("папка")
        self._отметить_шаг(3)
        self._лог(f"Отмечено отработанными: {помечено} из {итог.get('всего', 0)}, "
                  f"выписок собрано: {итог.get('выписок', 0)}",
                  "успех" if помечено else "беда")
        if папка:
            self._лог(f"Папка выдачи: {папка}", "важное")
            try:
                subprocess.Popen(["explorer", str(папка)])
            except Exception:
                pass
        хвост = ""
        if не_нашлись:
            # Не молчим: не нашлась — значит либо она уже отработана, либо
            # приехала не из нашей таблицы. И то, и другое надо видеть.
            хвост = ("\n\nНе нашлись в таблице "
                     f"({len(не_нашлись)}):\n· "
                     + "\n· ".join(не_нашлись[:12])
                     + ("\n…" if len(не_нашлись) > 12 else ""))
            for имя in не_нашлись:
                self._лог(f"  ? не нашлась: {имя}", "важное")
        messagebox.showinfo(
            "Взято в работу",
            f"Помечено отработанными: {помечено}\n"
            f"Выписок собрано в папку: {итог.get('выписок', 0)}\n"
            + (f"Папка: {папка.name}\n" if папка else "")
            + "\nСтроки ушли с рабочих листов на скрытый «Отработано» "
              "и больше не предложатся." + хвост)
        self.обновить_счётчики()


