    def _отметить(self, имена: list[str], гео: str) -> dict:
        """
        Найти эти фирмы в таблице, СОБРАТЬ ИХ ВЫПИСКИ В ОДНУ ПАПКУ и пометить
        отработанными.

        Папка — главное здесь. Отработал полсотни фирм — руками выискивать их
        выписки среди шестисот файлов невозможно. Складываем ровно те, что
        назвал, и рядом кладём книгу с платёжками, чтобы всё было в одном
        месте и с датой.
        """
        from common import таблица as т
        from part2.core.matching import normalize

        # ГЕО — СПИСОК. Заказ бывает собран из трёх стран, и сузить поиск до
        # одной значит не найти две трети. Строка на входе тоже принимается:
        # раньше сюда приходило одно гео, и ломать вызовы ради этого незачем.
        гео = [гео] if isinstance(гео, str) else list(гео or [])
        гео = [г.strip().upper() for г in гео if г and г.strip()]

        # Вся таблица одним запросом — раньше это был обход по листу за раз.
        все = [л for л in т.всё() if not л["скрыт"] and л["строк"]]
        if гео:
            все = [л for л in все
                   if л["имя"].split(".")[0].upper() in гео
                   or л["имя"] == "Мультигео"]

        где: dict[str, dict] = {}
        for л in все:
            имя_листа, строки = л["имя"], л["строки"]
            if not строки:
                continue
            ш = строки[0]
            if "Организация" not in ш:
                continue
            но = {к: (ш.index(к) if к in ш else -1) for к in
                  ("Организация", "Статус", "Файл выписки",
                   "Платёжный профиль", "Платёжный профиль выписки",
                   "Гео", "ID")}

            def взять(с, поле):
                i = но[поле]
                return с[i].strip() if 0 <= i < len(с) and с[i] else ""

            for с in строки[1:]:
                орг = взять(с, "Организация")
                if not орг or взять(с, "Статус").lower() == "отработано":
                    continue
                запись = {
                    "лист": имя_листа, "орг": орг, "ид": взять(с, "ID"),
                    "файл": взять(с, "Файл выписки"),
                    # В РАБОТУ УХОДИТ ПЛАТЁЖКА ВЫПИСКИ — имя и адрес из
                    # РЕЕСТРА, а не с dnb. Профиль с dnb остаётся запасным:
                    # у старых фирм колонки выписки может не быть вовсе.
                    "платёжка": (взять(с, "Платёжный профиль выписки")
                                 or взять(с, "Платёжный профиль")),
                    "гео": взять(с, "Гео") or имя_листа.split(".")[0].upper()}
                # ОДНА ФИРМА — НЕСКОЛЬКО ИМЁН, и это законно. В «Организации»
                # лежит имя с dnb («BRINDAMOUR BENJAMIN»), а вставляют обычно
                # платёжку с именем ИЗ РЕЕСТРА («Benjamin BRINDAMOUR (POLITICAL
                # HEAT)»). Замер 10.09.2026: из четырёх вставленных фирм
                # нашлась одна — та, у которой имена совпали случайно.
                # Поэтому запоминаем строку под всеми её написаниями.
                варианты = [орг,
                            первая_строка(взять(с, "Платёжный профиль выписки")),
                            первая_строка(взять(с, "Платёжный профиль")),
                            Path(взять(с, "Файл выписки")).stem]
                for имя in варианты:
                    к = normalize(имя or "")
                    if к:
                        где.setdefault(к, запись)

        отметки, не_нашлись, взяли = [], [], []
        видели = set()
        for имя in имена:
            к = normalize(имя)
            нашлось = где.get(к)
            if нашлось is None:
                не_нашлись.append(имя)
            elif к not in видели:
                видели.add(к)
                взяли.append(нашлось)
                отметки.append({"лист": нашлось["лист"], "орг": нашлось["орг"],
                                "ид": нашлось.get("ид", "")})

        папка = self._собрать_папку(взяли, гео) if взяли else None
        о = т.отработать(отметки, f"{date.today():%d-%m-%Y}") if отметки else {}
        return {"помечено": о.get("помечено", 0), "не_нашлись": не_нашлись,
                "всего": len(имена), "папка": папка,
                "выписок": sum(1 for з in взяли if з.get("_скопирован"))}

    def _собрать_папку(self, взяли: list[dict], гео) -> Path:
        """
        Папка выдачи: выписки этих фирм + книга с платёжками.

        ФАЙЛЫ ПЕРЕЕЗЖАЮТ, А НЕ КОПИРУЮТСЯ. Выписка отдана в работу — значит из
        хранилища она ушла: иначе завтра непонятно, что уже роздано, а что
        лежит свободным. Раньше копировали, и в «выписки» оставался двойник —
        те же файлы числились и выданными, и доступными.

        Платёжку в книгу кладём ИЗ КОЛОНКИ «Платёжный профиль выписки»: это
        имя и адрес ИЗ РЕЕСТРА, то, что уходит в работу. Профиль с dnb здесь
        не годится — он про другое написание.
        """
        from openpyxl import Workbook

        # Имя папки — по странам, которые в выдаче ФАКТИЧЕСКИ оказались, а не
        # по тому, что ввели в поле: ввод может быть пустым или шире выдачи.
        страны = sorted({(з.get("гео") or "").upper() for з in взяли} - {""})
        подпись = ("-".join(страны) if 0 < len(страны) <= 3
                   else (f"{len(страны)}гео" if страны else "разное"))
        метка = f"{date.today():%d-%m}_{тек_время()}_{подпись}_{len(взяли)}шт"
        папка = пути.КОРЕНЬ / "выдачи" / метка
        папка.mkdir(parents=True, exist_ok=True)
        выписки = пути.ВЫПИСКИ

        wb = Workbook()
        ws = wb.active
        ws.title = "Платёжки"
        ws.append(["№", "Гео", "Организация", "Платёжный профиль",
                   "Файл выписки", "Выписка найдена"])
        for c, ширина in zip("ABCDEF", (5, 8, 40, 60, 40, 16)):
            ws.column_dimensions[c].width = ширина

        пусто = []
        for n, з in enumerate(взяли, 1):
            нашли = ""
            файл = з.get("файл", "")
            if файл.lower().endswith(ДОКУМЕНТЫ):
                for п in выписки.rglob(файл):
                    if п.is_file() and п.stat().st_size:
                        цель = папка / п.name
                        try:
                            shutil.move(str(п), str(цель))
                        except Exception as e:
                            # Не смогли перенести — хотя бы копируем: потерять
                            # выдачу из-за занятого файла нельзя.
                            shutil.copy2(п, цель)
                            self._лог(f"  ⚠ {п.name}: перенести не вышло "
                                      f"({type(e).__name__}), скопировал",
                                      "беда")
                        пусто.append(п.parent)
                        з["_скопирован"] = True
                        нашли = "да"
                        break
                нашли = нашли or "файла нет на диске"
            else:
                нашли = "выписки не было"
            ws.append([n, з.get("гео", ""), з["орг"], з.get("платёжка", ""),
                       файл, нашли])

        # ОПУСТЕВШИЕ ПАПКИ УБИРАЕМ. Иначе в «выписки» остаётся дерево пустых
        # каталогов, и по нему уже не понять, где что-то есть, а где ничего.
        for п in {p for p in пусто}:
            try:
                while (п != выписки and п.is_dir()
                       and not any(п.iterdir())):
                    п.rmdir()
                    п = п.parent
            except Exception:
                pass
        wb.save(папка / "платёжки.xlsx")
        (папка / "платёжки.txt").write_text(
            "\n\n".join(з.get("платёжка", "") or з["орг"] for з in взяли),
            encoding="utf-8")
        return папка

