    def показать_остаток(self):
        """
        Есть ли что продолжать. Зовётся при открытии окна и после прогона.

        Считаем не по закладке, а по КНИГЕ — читаем её каждый раз заново:
        человек мог править лист руками, и вчерашняя цифра соврала бы.
        """
        try:
            о = продолжение.остаток()
        except Exception:
            о = {}
        if not о or not о.get("гео_осталось"):
            self.кн_продолжить.grid_remove()
            self.подпись_остатка.configure(text="")
            self._остаток = {}
            return
        self._остаток = о
        self.подпись_остатка.configure(text=продолжение.словами(о))
        self.кн_продолжить.grid()

    def продолжить(self):
        """Добрать то, что осталось от прерванного прогона."""
        о = getattr(self, "_остаток", {}) or продолжение.остаток()
        if not о or not о.get("гео_осталось"):
            messagebox.showinfo("ФИРМЫ", "Продолжать нечего — заказ выполнен.")
            self.показать_остаток()
            return
        self._лог(продолжение.словами(о), "важное")
        self._лог(f"Продолжаю в лист «{о['лист']}» — фирмы лягут туда же, "
                  f"а не в новый лист по сегодняшней дате.", "тускло")
        self.старт(продолжаем=о)

    def _переключить_самоход(self):
        """Галочка → событие. Только здесь, и только из главного потока."""
        if self.автономно.get():
            self.самоход.set()
            self._лог("🤖 Автономный режим включён: спорное пропускаю.", "важное")
            if self.поток and self.поток.is_alive():
                self._человек_вид(тема.ПАНЕЛЬ_ДОБОР, "Работаю сам",
                                  "Вопросов больше не будет: спорное пропускаю "
                                  "и пишу в лог.\n\nОстановить — «Стоп».")
        else:
            self.самоход.clear()
            self._лог("👤 Автономный режим выключен: спрошу, как раньше.",
                      "важное")
            if self.поток and self.поток.is_alive():
                self._человек_покой()
        # ПЕРЕКЛЮЧЕНИЕ РЕЖИМА — ЭТО ЕЩЁ И «СДВИНЬСЯ».
        #
        # Человек дёргает эту галочку не из любви к настройкам, а когда прогон
        # встал: «включаю и выключаю режим бота — значит хочу, чтобы он дальше
        # работал». Раньше галочка меняла только то, кого спрашивать, и на
        # зависшем прогоне не меняла ничего.
        #
        # Теперь она же повторяет последнюю команду (а если её не было —
        # перечитывает страницу). Для идущего прогона это безвредно: приказ
        # исполняется на ближайшей передышке, а «обновить» на живой странице
        # ничего не портит.
        if self.поток and self.поток.is_alive():
            self._приказать("повторить", повод="Переключил режим, повторяю")

