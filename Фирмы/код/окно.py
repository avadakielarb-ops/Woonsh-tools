            self.clipboard_clear()
            self.clipboard_append(имена)
            поле_ответа.delete("1.0", "end")
            всего = len(все)
            номер = с // состояние["по_сколько"] + 1
            сколько_всего = (всего + состояние["по_сколько"] - 1) // состояние["по_сколько"]
