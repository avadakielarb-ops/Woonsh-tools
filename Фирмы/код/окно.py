    ФАЙЛ_ЦИФР = пути.данные("счётчики.json")

    def _цифры_из_кэша(self) -> dict:
        """
        Что показывать СРАЗУ. Чтение таблицы идёт минуты (каждый лист —
        отдельный запрос), и держать человека перед пустым списком нельзя:
        он выбирает страну первым делом. Показываем прошлые цифры, а свежие
        подставляем по мере чтения.
        """
        import json
        try:
            д = json.loads(self.ФАЙЛ_ЦИФР.read_text(encoding="utf-8"))
        except Exception:
            return {}
        # КЭШ ОТ ПРОШЛОЙ РАСКЛАДКИ ХУЖЕ ПУСТОГО. Набор цифр менялся («свободно»
        # разошлось на «с сайтом» и «без сайта», выписки — по линиям), а старый
        # файл на диске остаётся. Читая его как есть, окно показывало НУЛИ там,
        # где в таблице сотни фирм, — и это не отличить от «правда пусто».
        # Ключи не совпали — забываем кэш и ждём свежих цифр.
        строка = next(iter(д.values()), None)
        if isinstance(строка, dict) and not set(ПУСТОЙ_СЧЁТ) <= set(строка):
            return {}
        return д

    def _цифры_в_кэш(self, счёт: dict) -> None:
        import json
        try:
            self.ФАЙЛ_ЦИФР.write_text(
                json.dumps(счёт, ensure_ascii=False, indent=1), encoding="utf-8")
        except Exception:
            pass

    def обновить_счётчики(self):
        self._показать_счётчики(self._цифры_из_кэша(), свежие=False)
        self._лог("Обновляю цифры по гео…", "тускло")

        def работа():
            try:
                from common import таблица as т
                if not т.настроена():
                    self.очередь.put(("счётчики", {}))
                    return
                счёт: dict[str, dict] = {}
                отставшие: dict[str, list[str]] = {}
                # ВСЯ ТАБЛИЦА ОДНИМ ЗАПРОСОМ. Лист за листом это стоило 145
                # секунд на каждое обновление (замер 10.09.2026); одним
                # запросом — четырнадцать, и данные те же до знака.
                for л in т.всё():
                    if л["скрыт"] or not л["строк"]:
                        continue
                    # «Мультигео» СЧИТАЕМ ТОЖЕ. Заказ из нескольких стран лежит
                    # там целиком, и если пропустить лист, цифры покажут пусто
                    # ровно там, где на самом деле лежит вся партия.
                    свой = None if л["имя"] == "Мультигео" else \
                        л["имя"].split(".")[0].upper()
                    строки = л["строки"]
                    if not строки:
                        continue
                    ш = строки[0]
                    iс = ш.index("Статус") if "Статус" in ш else -1
                    iф = ш.index("Файл выписки") if "Файл выписки" in ш else -1
                    iо = ш.index("Организация") if "Организация" in ш else -1
                    iг = ш.index("Гео") if "Гео" in ш else -1
                    iw = ш.index("Website") if "Website" in ш else -1
                    iи = ш.index("ID") if "ID" in ш else -1
                    тронуты = set()
                    for с in строки[1:]:
                        if iо < 0 or iо >= len(с) or not с[iо].strip():
                            continue
                        статус = с[iс].strip().lower() if 0 <= iс < len(с) else ""
                        # СТРОКА-ОТСТАВШАЯ: помечена закрытой, а лежит на
                        # рабочем листе. Так бывает, когда выдача проставила
                        # статус, а перенос в архив не дошёл — связь оборвалась,
                        # окно закрыли. Замер 22.09.2026: 133 строки, 129 из них
                        # венгерские. Они мешают дважды: путаются в счётчиках и
                        # всплывают в списках. Собираем их здесь, раз уж и так
                        # читаем всю таблицу, и увозим в архив после подсчёта.
                        if статус in ЗАКРЫТЫЕ:
                            ид = с[iи].strip() if 0 <= iи < len(с) else ""
                            if ид:
                                отставшие.setdefault(статус, []).append(ид)
                        if статус in НЕ_ВЫДАВАТЬ:
                            continue
                        гео = свой or ((с[iг].strip().upper()
                                        if 0 <= iг < len(с) else "") or "??")
                        д = счёт.setdefault(гео, ПУСТОЙ_СЧЁТ.copy())
                        тронуты.add(гео)
                        # С САЙТОМ И БЕЗ — ДВЕ РАЗНЫЕ ЛИНИИ, и одним числом
                        # они не складываются: «свободно 506» не отвечает на
                        # вопрос, можно ли набрать из этого заказ. Решаем по
                        # САМОЙ строке, а не по имени листа: так верно и для
                        # «Мультигео», где лежат обе.
                        сайт = с[iw].strip() if 0 <= iw < len(с) else ""
                        линия = "сайт" if сайт else "бс"
                        д[линия] += 1
                        # ВЫПИСКА СЧИТАЕТСЯ ПО СВОЕЙ ЛИНИИ. Одно общее число
                        # не отвечало на рабочий вопрос: «готово к выдаче» —
                        # это фирма с выпиской в ТОЙ линии, которую сейчас
                        # выдают, а не сумма по обеим.
                        файл = с[iф].strip() if 0 <= iф < len(с) else ""
                        есть_файл = файл.lower().endswith(ДОКУМЕНТЫ)
                        if есть_файл:
                            д[линия + "_в"] += 1
                        # ГОДНАЯ — ЭТО «ВЫПИСКА ЕСТЬ И БОТ ПОДТВЕРДИЛ»
                        # (определение человека). Подтверждённая без выписки
                        # идёт только в «проверенных»: отдать её нечем.
                        if статус == ГОДНАЯ:
                            д["пров"] += 1
                            if есть_файл:
                                д["годн"] += 1
                        else:
                            д["непров"] += 1
                    # показываем страну СРАЗУ, как дочитали, а не в конце:
                    # так список наполняется на глазах, а не через три минуты
                    for гео in тронуты:
                        self.очередь.put(("гео", (гео, dict(счёт[гео]))))
                # Лист «Отработано» НЕ читаем: это история, работать с ней
                # нельзя, а чтение двадцати тысяч строк стоит времени.
                self.очередь.put(("счётчики", счёт))
                self._прибрать_застрявших(отставшие)
            except Exception as e:
                self.очередь.put(("лог", (f"⚠ цифры не прочитались: {e}", "беда")))
                self.очередь.put(("счётчики", {}))

        threading.Thread(target=работа, daemon=True).start()

    def _прибрать_застрявших(self, отставшие: dict[str, list[str]]) -> None:
        """
        Увезти в архив строки, которые помечены закрытыми, но остались в работе.

        Почему это делается ЗДЕСЬ. Обновление цифр и так читает всю таблицу —
        единственное место, где мы видим её целиком. Отдельная кнопка «прибрать»
        означала бы второе такое чтение и ещё одну вещь, о которой надо помнить.

        Почему это безопасно. Статус проставлен не нами сейчас, а раньше — при
        выдаче или по ответу бота; мы лишь доводим до конца переезд, который
        тогда не дошёл. Данные строки не меняются, она переезжает целиком.
        """
        if not отставшие:
            return
        куда = {ОТРАБОТАНО: ОТРАБОТАНО_ЛИСТ}
        for с in (ОТКЛОНЕНА, ДУБЛЬ, БРАК):
            куда[с] = НЕДОСТОЙНЫЕ

        def работа():
            from common import таблица as т
            всего = 0
            for статус, ид in отставшие.items():
                лист = куда.get(статус)
                if not лист or not ид:
                    continue
                try:
                    о = т.перенести(лист, ид)
                    n = о.get("перенесено", 0)
                    всего += n
                    if n:
                        self.очередь.put(("лог", (
                            f"· прибрал отставших: {n} со статусом «{статус}» "
                            f"уехали на «{лист}»", "тускло")))
                except Exception as e:
                    self.очередь.put(("лог", (
                        f"⚠ не смог прибрать «{статус}»: "
                        f"{type(e).__name__}: {str(e)[:60]}", "беда")))
            if всего:
                self.очередь.put(("вызов", self.обновить_счётчики))

        threading.Thread(target=работа, daemon=True).start()

    def _цифры_на_кнопки(self) -> None:
        """
        Написать на кнопках, сколько для них работы по ВЫБРАННЫМ странам.

        Зачем. Цифры уже посчитаны и лежат в окне, но держались при себе:
        человек жал «Скачать выписки» и только внутри окошка узнавал, что
        качать нечего. То же с проверкой у бота. Кнопка должна говорить о себе
        сама.

        Ничего не выбрано — считаем по ВСЕМ странам: это ответ на вопрос
        «сколько работы вообще осталось».
        """
        if not hasattr(self, "кн_выписки"):
            return
        коды = self.выбранные_гео() or list(self.счётчики)
        качать = проверять = выдавать = 0
        for к in коды:
            д = self.счётчики.get(к) or {}
            # Качать — у кого выписки ещё нет, по обеим линиям.
            качать += (д.get("сайт", 0) - д.get("сайт_в", 0)
                       + д.get("бс", 0) - д.get("бс_в", 0))
            # Проверять — выписка есть, а бот не подтверждал.
            проверять += max(0, д.get("сайт_в", 0) + д.get("бс_в", 0)
                             - д.get("пров", 0))
            выдавать += д.get("годн", 0)

        def подпись(кнопка, основа: str, сколько: int) -> None:
            кнопка.configure(text=f"{основа} ({сколько})" if сколько else основа)

        подпись(self.кн_выписки, "⬇  Скачать выписки", качать)
        подпись(self.кн_проверка, "🤖  Проверить у бота", проверять)
        подпись(self.кн_выдача, "✅  Взять в работу", выдавать)

    def _показать_счётчики(self, счёт: dict, свежие: bool = True):
        self.счётчики = счёт
        выбрано = set(self.список.selection())
        self.список.delete(*self.список.get_children())
        for код in sorted(DRIVERS):
            д = счёт.get(код, ПУСТОЙ_СЧЁТ)
            # Зелёным те, где выписки уже есть: с ними можно работать сегодня.
            self.список.insert("", "end", iid=код,
                               values=self._строка_гео(код, д),
                               tags=("есть" if (д.get("сайт_в", 0)
                                                or д.get("бс_в", 0))
                                     else "пусто",))
        for код in выбрано:
            if код in self.список.get_children():
                self.список.selection_add(код)
        self._ширины_по_содержимому()
        self._цифры_на_кнопки()
        if свежие:
            self._цифры_в_кэш(счёт)
            self._лог(f"Цифры обновлены: стран {len(счёт)}", "тускло")

    def _обновить_строку_гео(self, гео: str, д: dict):
        """Одна страна дочиталась — показываем её, не дожидаясь остальных."""
        д = dict(д)
        self.счётчики[гео] = д
        if гео in self.список.get_children():
            self.список.item(гео, values=self._строка_гео(гео, д),
                             tags=("есть" if (д.get("сайт_в", 0)
                                              or д.get("бс_в", 0)) else "пусто",))
            self._ширины_по_содержимому()

    def _строка_гео(self, код: str, д: dict) -> tuple:
        """Одна строка списка: по две цифры на линию плюс итог по боту."""
        return (код, CODE_TO_NAME.get(код, код),
                д.get("сайт", 0), д.get("сайт_в", 0),
                д.get("бс", 0), д.get("бс_в", 0),
                д.get("годн", 0), д.get("пров", 0), д.get("непров", 0))

    def _ширины_по_содержимому(self) -> None:
        """
        Подогнать ширину колонок под самое длинное значение.

        Вбитая ширина врёт, как только в счёте появляется четвёртая цифра или
        страна с длинным именем: цифра обрезается, и человек видит «248»
        вместо «2489». Считаем по факту — заголовок и все строки, — и берём
        ширину буквы из самого шрифта, а не на глаз: на другом мониторе или
        при ином масштабе «восемь пикселей на символ» перестают быть правдой.
        """
        try:
            from tkinter import font as tkfont
            шрифт = tkfont.nametofont("TkDefaultFont")
        except Exception:
            return
        строки = [self.список.item(и, "values")
                  for и in self.список.get_children()]
        for н, к in enumerate(self.список["columns"]):
            длина = шрифт.measure(self.подписи_колонок.get(к, к))
            for з in строки:
                if н < len(з):
                    длина = max(длина, шрифт.measure(str(з[н])))
            self.список.column(к, width=длина + 24)   # поля слева и справа

