    def _включить_шаги(self, поиск_идёт: bool):
        сост = "disabled" if поиск_идёт else "normal"
        for к in (self.пуск, self.кн_выписки, self.кн_проверка,
                  self.кн_выдача, self.кн_слова):
            к.configure(state=сост)
        self.стоп_кн.configure(state="normal" if поиск_идёт else "disabled")
        # РАБОТА КОНЧИЛАСЬ — СТРОКА СОСТОЯНИЯ ДОЛЖНА ЭТО СКАЗАТЬ. Оставить на
        # ней «качаем выписки, 43/50» после конца значит соврать: человек
        # отойдёт и вернётся к надписи, которая уже ничего не значит.
        if not поиск_идёт:
            сост_ = getattr(self, "_состояние", None)
            if сост_ and сост_.get("что"):
                сост_["что"] = "✔ " + сост_["что"].split(" ", 1)[-1] + " — конец"
                self._показать_статус()

    def _шлюз(self) -> HumanGate:
        """
        Один шлюз на оба режима. Кого спрашивать — решает СОБЫТИЕ, и решает
        в момент вопроса, а не на старте прогона.

        Почему так, а не два разных шлюза. Раньше режим выбирался один раз при
        запуске: включил автономность — и выключить её было уже нельзя, прогон
        держал свой шлюз и галочку не видел. Теперь передумать можно на ходу.

        Всё, что здесь исполняется, идёт из РАБОЧЕГО потока, поэтому виджетов
        тут не касаемся вообще: только события, очередь и снимок гео. Обращение
        к Tk из чужого потока — это и есть то самое «заело».

        «Пропустить страну» и «стоп» автономно не отвечаем никогда: они убили
        бы весь прогон, а смысл режима ровно обратный.
        """
        def спросить(заголовок, сообщение, фирма=""):
            if not self.самоход.is_set():
                self.очередь.put(("человек", (заголовок, сообщение, фирма)))
                return
            self._лог_поток(f"  🤖 {заголовок} → пропускаю "
                            f"({фирма or 'без фирмы'})")
            self.human.answer(HumanChoice.SKIP)

        def меню(заголовок, сообщение, варианты, фирма=""):
            if not self.самоход.is_set():
                self.очередь.put(("меню", (заголовок, сообщение, варианты, фирма)))
                return
            # ОТВЕТ НАЗЫВАЕТ САМ ДВИЖОК (меню(авто=…)), а не порядок кнопок.
            # Первый вариант — это то, что удобно ЧЕЛОВЕКУ, и в меню «не смог
            # перелистнуть» первым стоит «я перелистнул сам». Отвечая им, робот
            # врал: никто не листал, движок читал ту же страницу и спрашивал
            # снова — прогон крутился на одном месте.
            ключ = getattr(self.human, "авто", "") or ""
            if not ключ:
                # Движок не сказал, что безопасно, — врать не будем. Пропускаем
                # эту фирму: пропуск честен и всегда конечен.
                self._лог_поток(f"  🤖 {заголовок} → безопасного ответа нет, "
                                f"пропускаю ({фирма or '—'})")
                self.human.answer_menu("")
                return
            self._лог_поток(f"  🤖 {заголовок} → «{ключ}» ({фирма or '—'})")
            self.human.answer_menu(ключ)

        def слово(сообщение):
            if not self.самоход.is_set():
                self.очередь.put(("слово", сообщение))
                return
            # Гео берём ИЗ СНИМКА, а не из списка на экране: список — виджет.
            гео = (self._гео_прогона or [""])[0]
            новое = движок1.слово_из_запаса(гео, self._лог_поток) if гео else ""
            self._лог_поток(f"  🤖 нужно слово → «{новое or 'запас пуст, хватит'}»")
            self.human.answer_keyword(новое or движок1.СТОП_ДОБОРА)

        return HumanGate(ui_ask=спросить, ui_menu=меню, ui_keyword=слово)

    def _запустить(self, работа, после):
        self.стоп.clear()
        self.пауза.clear()
        self.human = self._шлюз()
        if self.самоход.is_set():
            self._лог("🤖 Автономный режим: вопросов не будет, "
                      "спорное пропускаю и иду дальше.", "важное")
            self._человек_вид(тема.ПАНЕЛЬ_ДОБОР, "Работаю сам",
                              "Автономный режим. Всё, на чём обычно спрашиваю, "
                              "пропускаю и записываю в лог.\n\n"
                              "Снять галочку можно прямо сейчас — следующий "
                              "вопрос будет твой.")

        def обёртка():
            итог, выгружать = None, False
            try:
                итог = работа(self.human)
                выгружать = True
            except AbortRun:
                self._лог_поток("Остановлено.")
                выгружать = True
            except Exception as e:
                self._лог_поток(f"ОШИБКА: {type(e).__name__}: {e}")
            finally:
                if выгружать and self.книга and self.лист:
                    try:
                        from выгрузка import выгрузить
                        выгрузить(self.книга, self.лист, self._лог_поток,
                                  мультигео=self.мульти)
                    except Exception as e:
                        self._лог_поток(f"⚠ в таблицу не выгрузилось: {e}")
                self.очередь.put(("конец", (после, итог)))

        self.поток = threading.Thread(target=обёртка, daemon=True)
        self.поток.start()

    def стоп_всё(self):
        self.стоп.set()
        self._лог("Останавливаю после текущей фирмы…", "важное")

    def _лог_поток(self, текст):
        self.очередь.put(("лог", (str(текст), "")))

    # ─────────────────────────── строка состояния ───────────────────────────
    #
    # ЧИТАЕМ ТОТ ЖЕ ЛОГ, что и так течёт мимо, а не заводим вторую дорогу из
    # движков в окно. Движков три (поиск, выписки, сайты), и протаскивать
    # через каждый ещё один канал ради надписи — это три места, где однажды
    # забудут его дёрнуть. Лог же пишется ВСЕГДА: без него не работает ничего.
    #
    # Что понимаем:
    #   «[12/50] Имя фирмы»          — сколько фирм пройдено из скольких
    #   «[3/19]  гео FR — строки …»  — какая страна по счёту в мультипрогоне
    #   «Гео CH. Ищу «hazel» …»      — страна и слово в Части 1
    #   «✔ …pdf», «✔ [7/50] …»       — сделано
    #   «✘ …», «⏭ пропускаю …»       — пропущено
    ШАБЛОН_ФИРМЫ = re.compile(r"^\[(\d+)/(\d+)\]\s+(?!гео\b)(.+)")
    ШАБЛОН_ГЕО2 = re.compile(r"^\[(\d+)/(\d+)\]\s+гео\s+([A-Z]{2})")
    ШАБЛОН_ГЕО1 = re.compile(r"^Гео\s+([A-Z]{2})\b")

    def _сбросить_статус(self, что: str = "", гео: str = "") -> None:
        """Начали новое дело — счёт с нуля, иначе он врёт от прошлого."""
        self._состояние = {"что": что, "гео": гео, "на": 0, "всего": 0,
                           "сделано": 0, "мимо": 0}
        self._показать_статус()

    def _статус_из_строки(self, строка: str) -> None:
        с = (строка or "").strip()
        сост = getattr(self, "_состояние", None)
        if сост is None or not с:
            return
        м = self.ШАБЛОН_ГЕО2.match(с) or self.ШАБЛОН_ГЕО1.match(с)
        if м:
            сост["гео"] = м.group(м.lastindex)
            # Новая страна — счёт фирм начинается заново.
            сост["на"] = сост["всего"] = 0
            return self._показать_статус()
        м = self.ШАБЛОН_ФИРМЫ.match(с)
        if м:
            сост["на"], сост["всего"] = int(м.group(1)), int(м.group(2))
            return self._показать_статус()
        if с.startswith("✔"):
            сост["сделано"] += 1
            return self._показать_статус()
        if с.startswith(("✘", "⏭", "⊘")):
            сост["мимо"] += 1
            return self._показать_статус()

    def _показать_статус(self) -> None:
        сост = getattr(self, "_состояние", None)
        if not hasattr(self, "статус"):
            return
        if not сост or not сост.get("что"):
            self.статус.configure(text=ПОКОЙ,
                                  foreground=тема.ТЕМА["muted"])
            return
        куски = [сост["что"]]
        if сост.get("гео"):
            куски.append(сост["гео"])
        if сост.get("всего"):
            куски.append(f"{сост['на']}/{сост['всего']}")
        куски.append(f"сделано {сост['сделано']}")
        if сост["мимо"]:
            куски.append(f"пропущено {сост['мимо']}")
        self.статус.configure(text="   ·   ".join(куски),
                              foreground=тема.ТЕМА["ink"])

    ПРЕДЕЛ_СТРОК_НА_ЭКРАНЕ = 4000

    def _файл_лога(self):
        """
        Лог прогона на диск. Открываем при первой записи, держим открытым.

        Зачем вообще. Новое окно писало ТОЛЬКО на экран, и это стоило двух
        вещей сразу: разбирать «что там было вчера» стало нечем, а статистика
        слов читает как раз файлы логи/лог_*.txt — то есть про всё, найденное
        новым окном, она не знала вовсе. Формат строк тот же, что у прежнего
        приложения: разборщик уже умеет их читать.
        """
        if getattr(self, "_лог_поток_файл", None) is None:
            try:
                пути.ЛОГИ.mkdir(parents=True, exist_ok=True)
                имя = f"лог_{datetime.now():%Y-%m-%d_%H-%M-%S}.txt"
                self._лог_поток_файл = open(пути.ЛОГИ / имя, "a",
                                            encoding="utf-8", buffering=1)
            except Exception:
                self._лог_поток_файл = False      # больше не пробуем
        return self._лог_поток_файл or None

    def _лог(self, текст, метка=""):
        строка = str(текст).rstrip()
        self.лог.insert("end", строка + "\n", метка or ())
        self.лог.see("end")
        # ЭКРАН НЕ КОПИМ БЕЗ КОНЦА. Прогон на 19 стран пишет десятки тысяч
        # строк, и виджет от этого тяжелеет до заметных подтормаживаний.
        # На диске остаётся всё, на экране — последнее.
        строк = int(self.лог.index("end-1c").split(".")[0])
        if строк > self.ПРЕДЕЛ_СТРОК_НА_ЭКРАНЕ:
            self.лог.delete("1.0", f"{строк - self.ПРЕДЕЛ_СТРОК_НА_ЭКРАНЕ}.0")
        ф = self._файл_лога()
        if ф:
            try:
                ф.write(строка + "\n")
            except Exception:
                pass

    def _разбор_очереди(self):
        try:
            while True:
                вид, данные = self.очередь.get_nowait()
                if вид == "лог":
                    текст, метка = данные if isinstance(данные, tuple) else (данные, "")
                    self._лог(текст, метка)
                    self._статус_из_строки(текст)
                elif вид == "счётчики":
                    self._показать_счётчики(данные)
                elif вид == "гео":
                    self._обновить_строку_гео(*данные)
                elif вид == "вызов":
                    # Рабочий поток просит что-то сделать С ВИДЖЕТАМИ. Делаем
                    # это ЗДЕСЬ — очередь разбирается в главном потоке, а Tk
                    # из чужого потока вешает окно намертво.
                    данные()
                elif вид == "человек":
                    self._вопрос(*данные)
                elif вид == "меню":
                    self._вопрос_меню(*данные)
                elif вид == "слово":
                    self._вопрос_слово(данные)
                elif вид == "отработано":
                    self._показать_отметку(данные)
                elif вид == "конец":
                    после, итог = данные
                    self._включить_шаги(поиск_идёт=False)
                    self._человек_покой()
                    if после:
                        после(итог)
        except queue.Empty:
            pass
        self.after(120, self._разбор_очереди)

    # ---- вопросы человеку ----

    def _вопрос(self, заголовок, текст, фирма):
        self._человек_вид(тема.ПАНЕЛЬ_ЧЕЛОВЕК, заголовок,
                          (f"Фирма: {фирма}\n\n" if фирма else "") + текст)
        self._чп_кнопка("✓  Продолжить", *тема.КН_УСПЕХ,
                        lambda: self._ответ(HumanChoice.CONTINUE))
        self._чп_повтор()
        self._чп_кнопка("⏭  Пропустить фирму", *тема.КН_НЕЙТРАЛЬ,
                        lambda: self._ответ(HumanChoice.SKIP))
        self._чп_кнопка("⏭  Пропустить страну", *тема.КН_ДЕЙСТВИЕ,
                        lambda: self._ответ(HumanChoice.SKIP_GEO))
        self._чп_кнопка("■  Стоп", *тема.КН_ОПАСНОСТЬ,
                        lambda: self._ответ(HumanChoice.ABORT))

