r"""
ПРИВЕСТИ ТАБЛИЦУ В СООТВЕТСТВИЕ С ТЕМ, ЧТО БЫЛО НА САМОМ ДЕЛЕ.

Три источника правды, и они не совпадают:
  · ЛОГИ прогонов — что мы пытались скачать, что получилось, под каким именем
    файл и ПОЧЕМУ не вышло;
  · ДИСК — что реально лежит сейчас (файл мог быть удалён руками или сброшен
    скриптом сбросить_гео);
  · ТАБЛИЦА — что человек видит.

Правило простое: **в таблице должно стоять то, что есть на диске сейчас.**
Лог объясняет причину, но не является доказательством наличия файла: по логам
скачано 387 фирм, а девятнадцати файлов на диске уже нет.

Что пишем в строку:
  файл есть          → «Файл выписки» = имя файла, «Номер в реестре», статус
                        «найдена»;
  файла нет, причина  → «Файл выписки» = причина словами («нет номера НДС»),
                        статус «нет выписки», а для ликвидированных и негодных
                        форм — «брак»;
  ничего не известно  → не трогаем вовсе.

Строки со статусом «отработано» не трогаем никогда: они уже уехали.

Запуск:
    .venv\Scripts\python.exe код\актуализировать_таблицу.py            — примерка
    .venv\Scripts\python.exe код\актуализировать_таблицу.py --писать   — применить
"""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common.пути import ВЫПИСКИ, КОРЕНЬ
from part2.core.matching import normalize

import разобрать_логи

# Причины, по которым фирма не годится в принципе, а не «сейчас не вышло».
БРАК = ("ликвидац", "in liquidation", "не active", "removed", "непригодна",
        "форма не подходит")


def файлы_на_диске() -> dict[str, Path]:
    в = ВЫПИСКИ
    return {p.name: p for p in в.rglob("*") if p.is_file()} if в.exists() else {}


def собрать_правки(log=print) -> list[dict]:
    из_логов = разобрать_логи.разобрать(log=log)
    диск = файлы_на_диске()

    from common import таблица
    log("")
    log("читаю таблицу…")
    правки, счёт = [], Counter()
    for л in таблица.всё():               # вся таблица одним запросом
        if л["скрыт"] or not л["строк"]:
            continue
        лист = л["имя"]
        гео = лист.split(".")[0].upper()
        строки = л["строки"]
        if not строки:
            continue
        шапка = строки[0]
        try:
            i_орг = шапка.index("Организация")
            i_файл = шапка.index("Файл выписки")
            i_стат = шапка.index("Статус")
            i_ном = шапка.index("Номер в реестре")
        except ValueError:
            continue
        # Номер строки, если он уже проставлен: правку лучше адресовать им,
        # а не именем — имя мы прочитали из этой же клетки, но с прошлого
        # чтения его могли поправить руками.
        i_ид = шапка.index("ID") if "ID" in шапка else -1
        for с in строки[1:]:
            орг = с[i_орг] if len(с) > i_орг else ""
            if not орг:
                continue
            если = с[i_стат] if len(с) > i_стат else ""
            if если == "отработано":
                continue
            знание = из_логов.get((гео, normalize(орг)))
            if not знание:
                счёт["в логах ничего нет"] += 1
                continue

            есть_файл = знание["файл"] and знание["файл"] in диск
            if есть_файл:
                надо = {"Файл выписки": знание["файл"], "Статус": "найдена"}
                if знание["номер"]:
                    надо["Номер в реестре"] = знание["номер"]
                счёт["выписка есть"] += 1
            elif знание["причина"]:
                низ = знание["причина"].lower()
                надо = {"Файл выписки": знание["причина"][:120],
                        "Статус": "брак" if any(б in низ for б in БРАК)
                                  else "нет выписки"}
                счёт["причина отказа"] += 1
            elif знание["файл"]:
                надо = {"Файл выписки": "скачивалась, файла на диске нет",
                        "Статус": "нет выписки"}
                счёт["файл пропал"] += 1
            else:
                continue

            сейчас = {"Файл выписки": с[i_файл] if len(с) > i_файл else "",
                      "Статус": если,
                      "Номер в реестре": с[i_ном] if len(с) > i_ном else ""}
            меняем = {к: v for к, v in надо.items() if сейчас.get(к, "") != v}
            if меняем:
                правки.append({"лист": лист, "орг": орг, "поля": меняем,
                               "ид": (с[i_ид] if 0 <= i_ид < len(с) else "")})
    log("")
    for к, n in счёт.most_common():
        log(f"   {к:26} {n:>5}")
    return правки


if __name__ == "__main__":
    правки = собрать_правки()
    print("")
    print(f"=== СТРОК К ПРАВКЕ: {len(правки)} ===")
    по_листам = Counter(п["лист"] for п in правки)
    for л, n in sorted(по_листам.items()):
        print(f"   {л:10} {n:>4}")
    print("")
    print("=== примеры ===")
    for п in правки[:10]:
        поля = ", ".join(f"{к}={v[:44]}" for к, v in п["поля"].items())
        print(f"   {п['лист']:8} {п['орг'][:38]:40} → {поля}")

    if "--писать" not in sys.argv:
        print("")
        print("Это ПРИМЕРКА, таблица не тронута.")
        raise SystemExit(0)

    from common import таблица
    о = таблица.обновить(правки)
    print("")
    print(f"   ✔ обновлено строк: {о['обновлено']}")
    if о["не_нашлось"]:
        print(f"   ⚠ не нашлось: {len(о['не_нашлось'])}")
        for с in о["не_нашлось"][:10]:
            print(f"      {с}")
