r"""
ПОЧИНКА ЗАПАСА СЛОВ: местные и английские — ВПЕРЕМЕШКУ.

История в два шага, и оба были ошибкой в свою сторону.

Шаг первый. Генератор складывал «англ + местные», а запас выдаёт строго по
порядку. До местных очередь не доходила НИКОГДА: сто английских впереди. Замер
08.09.2026 по живому файлу — в EE первые девяносто слов английские, а «teras,
vask, pronks, savi» лежали в хвосте нетронутыми. Отсюда и «2–3 фирмы на слово»:
английское слово в эстонском реестре ищет эстонские фирмы с английскими
названиями, а их там единицы.

Шаг второй. Поставили местные вперёд — и получили ту же беду зеркально:
английские не попробуются, пока не кончатся местные. А по ним выхлоп местами
выше, и узнать это можно только попробовав.

Правильно — ЧЕРЕДОВАТЬ: местное, английское, местное. Обе половины проверяются
с самого начала, и статистика выхлопа набирается по ним одновременно, а не по
очереди через неделю.

Скрипт раскладывает уже накопленный запас на две половины и сплетает их.
Выданные не трогаем — они отработали. Англоязычные страны пропускаем: там
«местных» нет, чередовать нечего.

Запуск:  .venv\Scripts\python.exe код\починить_слова.py
"""
from __future__ import annotations

import json
import shutil
import sys
import unicodedata
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common.пути import данные
from part1.слова_gemini import вперемешку

АНГЛОЯЗЫЧНЫЕ = {"UK", "US", "AU", "IE", "CA", "NZ"}


def местное(слово: str) -> bool:
    """
    Похоже ли слово на местное, а не английское.

    Признак надёжный ровно один — буквы за пределами латиницы: ü, ä, ő, ł, ą.
    Слова без них по виду не различить («teras» и «timber» одинаковы), для них
    работает второй признак — место в списке (см. разложить).
    """
    return any(ord(c) > 127
               for c in unicodedata.normalize("NFC", слово))


def разложить(свободные: list[str]) -> tuple[list[str], list[str]]:
    """
    Свободные слова → (местные, английские).

    Если диакритика есть — она и есть надёжная граница: всё до последнего
    такого слова считаем местным. Если её нет вовсе (эстонский и польский
    пишутся и латиницей), опираемся на порядок: прошлая починка увела местные
    в начало, поэтому делим пополам. Точность тут не критична — перемешивание
    всё равно даёт обеим половинам ход с первых слов.
    """
    места = [i for i, с in enumerate(свободные) if местное(с)]
    if not места:
        середина = len(свободные) // 2
        return свободные[:середина], свободные[середина:]
    граница = места[-1] + 1
    return свободные[:граница], свободные[граница:]


def починить(путь: Path | None = None, log=print) -> dict:
    путь = путь or данные("запас_слов.json")
    if not путь.exists():
        log(f"нет файла {путь} — чинить нечего")
        return {}
    запас = json.loads(путь.read_text(encoding="utf-8"))

    копия = путь.with_suffix(".json.до_перемешивания")
    shutil.copy2(путь, копия)
    log(f"копия: {копия.name}")

    итог = {}
    for гео, гнездо in sorted(запас.items()):
        свободные = гнездо.get("свободные") or []
        if гео.upper() in АНГЛОЯЗЫЧНЫЕ or len(свободные) < 4:
            log(f"  · {гео}: пропускаю ({len(свободные)} слов)")
            continue
        местные, англ = разложить(свободные)
        гнездо["свободные"] = вперемешку(местные, англ)
        итог[гео] = len(свободные)
        log(f"  ✔ {гео}: {len(свободные)} слов "
            f"({len(местные)} местных + {len(англ)} англ.) — "
            f"первые: {', '.join(гнездо['свободные'][:6])}")

    путь.write_text(json.dumps(запас, ensure_ascii=False, indent=1),
                    encoding="utf-8")
    log(f"готово: перемешано гео {len(итог)}")
    return итог


if __name__ == "__main__":
    починить()
