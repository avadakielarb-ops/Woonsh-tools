r"""
РАЗОВАЯ МИГРАЦИЯ: проставить статус по фактам, один раз на всю таблицу.

Зачем. Слово «найдена» значило две разные вещи. Часть 1 писала его про ФИРМУ
(нашли на dnb), Часть 2 — тем же словом про ВЫПИСКУ (реестр отдал документ).
Отличить одно от другого можно было только по колонке «Файл выписки», и
никакой счётчик не мог честно ответить, сколько фирм готово к проверке ботом.

Что делаем. Ставим ступень лестницы по ФАКТАМ строки, ничего не выдумывая:

    файл выписки лежит          → «выписка»
    в клетке причина отказа     → «нет выписки»
    ни файла, ни причины        → «найдена»

Закрытые ступени не трогаем вовсе: «годная», «отклонена», «брак»,
«отработано», «дубль» уже сказаны человеком или ботом, и переписывать их
фактами нельзя — факты о них ничего не знают.

Запуск:
    .venv\Scripts\python.exe код\статусы_по_лестнице.py            — показать
    .venv\Scripts\python.exe код\статусы_по_лестнице.py --писать   — проставить
"""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common.статусы import (ВЫПИСКА, ЗАКРЫТЫЕ, ГОДНАЯ, НАЙДЕНА, НЕТ_ВЫПИСКИ,
                            СПОРНАЯ, есть_выписка)


def разобрать(log=print) -> list[dict]:
    """Какие строки надо поправить. Ничего не пишет."""
    from common import таблица as т

    правки: list[dict] = []
    было = Counter()
    стало = Counter()
    for л in т.всё():
        if л["скрыт"] or not л["строк"] or not л["строки"]:
            continue
        ш = л["строки"][0]
        if "Организация" not in ш or "Статус" not in ш:
            continue
        iо, iс = ш.index("Организация"), ш.index("Статус")
        iф = ш.index("Файл выписки") if "Файл выписки" in ш else -1
        iи = ш.index("ID") if "ID" in ш else -1
        for с in л["строки"][1:]:
            def взять(i):
                return с[i].strip() if 0 <= i < len(с) and с[i] else ""

            орг = взять(iо)
            if not орг:
                continue
            статус = взять(iс).lower()
            было[статус or "(пусто)"] += 1
            # Сказанное человеком или ботом — не наше дело.
            if статус in ЗАКРЫТЫЕ or статус in (ГОДНАЯ, СПОРНАЯ):
                стало[статус] += 1
                continue
            файл = взять(iф)
            надо = (ВЫПИСКА if есть_выписка(файл)
                    else (НЕТ_ВЫПИСКИ if файл else НАЙДЕНА))
            стало[надо] += 1
            if надо != статус:
                правки.append({"лист": л["имя"], "орг": орг, "ид": взять(iи),
                               "поля": {"Статус": надо}})

    log("  было: " + ", ".join(f"{к}={n}" for к, n in было.most_common()))
    log("  стало:" + ", ".join(f" {к}={n}" for к, n in стало.most_common()))
    log(f"  поправить строк: {len(правки)}")
    return правки


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    правки = разобрать()
    if not правки:
        print("Всё уже по лестнице.")
        raise SystemExit(0)
    примеры = Counter(п["поля"]["Статус"] for п in правки)
    print()
    print("=== ЧТО ПРОСТАВИМ ===")
    for к, n in примеры.most_common():
        print(f"   {к:14} {n:>6}")
    if "--писать" not in sys.argv:
        print()
        print("Это ПРИМЕРКА, таблица не тронута. Проставить: --писать")
        raise SystemExit(0)
    from common import таблица as т
    о = т.обновить(правки)
    print()
    print(f"   ✔ обновлено строк: {о.get('обновлено', 0)} из {len(правки)}")
