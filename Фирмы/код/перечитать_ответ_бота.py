r"""
ПЕРЕЧИТАТЬ ОТВЕТ БОТА ПО ПРАВИЛУ и починить то, что записано неверно.

Зачем. 23.09.2026 ответ на пакет из 1645 имён был применён со сломанной
эхо-защитой: 421 фирму, которую бот прямо назвал дублем, записали ГОДНОЙ.
В логе это выглядело безобидно — «чужих дублей: 0, годных: 1599».

Правило, по которому считаем теперь (оно же в `разложить`):
    названа «добавлена»           → годная
    названа и так, и «уже есть»   → годная (имя ушло боту дважды)
    названа ТОЛЬКО «уже есть»     → отклонена, на «Недостойные», выписку снести
    не названа вовсе              → вердикта нет, статус не трогаем

Инструмент СЧИТАЕТ ЗАНОВО по паре «наряд + ответ» и сверяет с тем, что стоит
в таблице сейчас. Правит только расхождения.

Запуск:
    …\перечитать_ответ_бота.py <наряд.json> <ответ.txt>            — примерка
    …\перечитать_ответ_бота.py <наряд.json> <ответ.txt> --писать   — чинить

Примерка ничего не трогает и ничего не удаляет. С «--писать» выписки
отклонённых удаляются — это необратимо, поэтому сперва посмотри примерку.
"""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import json

import проверка_ботом as пб
from common.статусы import (ГОДНАЯ, ЗАКРЫТЫЕ, НАЙДЕНА, ВЫПИСКА, ОТКЛОНЕНА,
                            НЕДОСТОЙНЫЕ, есть_выписка)


def статус_без_вердикта(з: dict) -> str:
    """Куда вернуть строку, про которую бот ничего не сказал."""
    return ВЫПИСКА if есть_выписка(з.get("файл") or "") else НАЙДЕНА


def сейчас_в_таблице(ид: set[str]) -> dict[str, str]:
    """Статусы этих фирм в таблице — по всем листам, включая служебные."""
    from common import таблица as т

    где: dict[str, str] = {}
    for л in т.всё(служебные=True):
        стр = л.get("строки") or []
        if not стр:
            continue
        ш = [str(х or "").strip() for х in стр[0]]
        if "ID" not in ш or "Статус" not in ш:
            continue
        ки, кс = ш.index("ID"), ш.index("Статус")
        for с in стр[1:]:
            и = str(с[ки]).strip() if len(с) > ки else ""
            # ПЕРВАЯ НАЙДЕННАЯ СТРОКА — ТА, КОТОРУЮ ВИДИТ И ПРАВКА.
            # У фирмы есть близнец в «Реестре», и обновление попадает в первую
            # строку с этим ID. Смотреть надо туда же, иначе сверка покажет
            # расхождение там, где его нет.
            if и in ид and и not in где:
                где[и] = (str(с[кс]).strip().lower() if len(с) > кс else "")
    return где


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    доводы = [а for а in sys.argv[1:] if not а.startswith("--")]
    if len(доводы) < 2:
        print(__doc__)
        raise SystemExit(2)
    наряд, ответ_ф = Path(доводы[0]), Path(доводы[1])
    if not наряд.exists() or not ответ_ф.exists():
        print("Не нашёл наряд или ответ.")
        raise SystemExit(2)

    пакет = json.loads(наряд.read_text(encoding="utf-8"))
    ответ = ответ_ф.read_text(encoding="utf-8", errors="replace")
    р = пб.разложить(пакет, ответ, log=lambda с: print(с))
    print()

    надо: dict[str, str] = {}
    for з in р["годные"]:
        надо[з["ид"]] = ГОДНАЯ
    for з in р["отклонены"]:
        надо[з["ид"]] = ОТКЛОНЕНА
    for з in р["нет_ответа"]:
        надо[з["ид"]] = статус_без_вердикта(з)

    print("Читаю таблицу…")
    есть = сейчас_в_таблице(set(надо))
    по_ид = {з["ид"]: з for з in пакет}

    правки: dict[str, list[dict]] = {}
    совпало = Counter()
    for ид, нужен in надо.items():
        стоит = есть.get(ид, "")
        if стоит == нужен:
            совпало["уже верно"] += 1
            continue
        if стоит in ЗАКРЫТЫЕ and нужен != ОТКЛОНЕНА:
            # Строка уже закрыта чем-то другим (брак, отработано) — не трогаем.
            совпало["закрыта иначе"] += 1
            continue
        правки.setdefault(нужен, []).append(по_ид[ид])

    print()
    print("=== ЧТО НАДО ПОПРАВИТЬ ===")
    for нужен, список in sorted(правки.items()):
        было = Counter(есть.get(з["ид"], "(нет строки)") for з in список)
        print(f"  → {нужен}: {len(список)}")
        for б, n in было.most_common(4):
            print(f"       было «{б}»: {n}")
    for к, n in совпало.most_common():
        print(f"  · {к}: {n}")

    отклонить = правки.get(ОТКЛОНЕНА) or []
    файлы = пб.выписки_на_диске(отклонить) if отклонить else {}
    print(f"  · выписок отклонённых лежит на диске: {len(файлы)}")

    if "--писать" not in sys.argv:
        print()
        print("Это ПРИМЕРКА. Ничего не тронуто. Чинить: --писать")
        raise SystemExit(0)

    from common import таблица as т

    print()
    for нужен, список in sorted(правки.items()):
        о = т.обновить([{"лист": з["лист"], "орг": з["орг"], "ид": з["ид"],
                         "поля": {"Статус": нужен}} for з in список])
        print(f"  ☁ «{нужен}»: обновлено {о.get('обновлено', 0)} "
              f"из {len(список)}")

    if отклонить:
        ид = [з["ид"] for з in отклонить if з.get("ид")]
        п = т.перенести(НЕДОСТОЙНЫЕ, ид)
        print(f"  ☁ уехало на «{НЕДОСТОЙНЫЕ}»: {п.get('перенесено', 0)}")
        снесено = 0
        for з in отклонить:
            путь = файлы.get(з.get("файл") or "")
            if not путь:
                continue
            try:
                путь.unlink()
                снесено += 1
            except Exception as e:
                print(f"  ⚠ не удалилось {путь.name}: {type(e).__name__}")
        print(f"  · выписок удалено: {снесено}")

    # ВЕРДИКТ В ЖУРНАЛ — чтобы через неделю было видно, откуда статус.
    пб.записать_вердикт(р["годные"], ГОДНАЯ, log=print)
    пб.записать_вердикт(р["отклонены"], ОТКЛОНЕНА, log=print)
    путь = пб.дослать(р["нет_ответа"], наряд.stem, log=print)
    print()
    print("Готово.")
    if путь:
        print(f"Кого бот не назвал — лежат в {путь.name}. "
              "Отправлять их повторно нельзя: бот их уже завёл.")
