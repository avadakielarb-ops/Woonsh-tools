"""
СВЕСТИ СТАРЫЕ ПАПКИ ПРОГОНОВ В ОДНУ.

Было: каждый запуск делал свою папку с датой и временем —
    выписки/Мультигео 2026-08-25_17-37/LV/…
    выписки/Мультигео 2026-08-25_15-20/LV/…
За два дня их накопилось 56, и выписки одного листа лежали в пяти местах.

Стало:
    выписки/Мультигео/23-08/LV/…

Имя листа берём из книги, которая лежит внутри папки прогона
(«Мультигео 23-08.xlsx» → лист «23-08»); не нашли — из даты папки.

Запуск:
    .venv\\Scripts\\python.exe собрать_выписки.py            — показать, что будет
    .venv\\Scripts\\python.exe собрать_выписки.py --делать   — перенести

Файлы ПЕРЕМЕЩАЮТСЯ, не копируются. Одноимённые не затираются: к имени
добавляется « (2)», « (3)» — выписки разных прогонов на одну фирму бывают
разными, и молча терять их нельзя. Пустые старые папки удаляются.
"""
from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

ВЫПИСКИ = Path("выписки")
ЦЕЛЬ = ВЫПИСКИ / "Мультигео"
УЗОР = re.compile(r"^Мультигео[ _](\d{4}-\d{2}-\d{2})[_ ](\d{2}-\d{2})")


def имя_листа(папка: Path) -> str:
    """Лист, к которому относится прогон: из имени книги внутри папки."""
    for книга in папка.rglob("Мультигео *.xlsx"):
        m = re.search(r"Мультигео\s+(.+?)\.xlsx$", книга.name)
        if m:
            return m.group(1).strip()
    m = УЗОР.match(папка.name)
    if m:                                   # 2026-08-25 → 25-08
        год, месяц, день = m.group(1).split("-")
        return f"{день}-{месяц}"
    return "без-листа"


def свободное(путь: Path) -> Path:
    """Путь, который ещё не занят: «имя (2).pdf», «имя (3).pdf»…"""
    if not путь.exists():
        return путь
    for n in range(2, 200):
        новый = путь.with_name(f"{путь.stem} ({n}){путь.suffix}")
        if not новый.exists():
            return новый
    return путь.with_name(f"{путь.stem} (много){путь.suffix}")


def свести_книги(делать: bool) -> None:
    """
    Убрать Excel-копии из папок гео: книга должна быть ОДНА на лист.

    Каждое гео клало себе «Мультигео <лист>.xlsx» и «не_вышло.xlsx», а повторные
    прогоны добавляли «(2)» и «(3)». На 18 стран вышло 63 книги — чтобы увидеть
    результат, надо было открыть их все.

    Содержимое не собираем по кусочкам: полные данные и так лежат в рабочей
    книге «Мультигео <лист>.xlsx» в корне проекта, откуда движок их и читает.
    Копии в папках гео — просто выжимка, и их потеря ничего не стоит.
    """
    if not ЦЕЛЬ.exists():
        return
    лишние = [p for лист in ЦЕЛЬ.iterdir() if лист.is_dir()
              for гео in лист.iterdir() if гео.is_dir()
              for p in гео.glob("*.xlsx")]
    if not лишние:
        return
    print(f"\nExcel-копий внутри папок гео: {len(лишние)} — книга должна быть "
          "одна на лист")
    if not делать:
        for p in лишние[:5]:
            print("   ", p.relative_to(ЦЕЛЬ))
        print("   … (уберутся при запуске с --делать)")
        return
    for p in лишние:
        try:
            p.unlink()
        except Exception as e:
            print(f"   не смог убрать {p.name}: {e}")
    print(f"   убрано: {len(лишние)}. Полные данные — в рабочей книге "
          "«Мультигео <лист>.xlsx» в корне проекта.")


def main() -> int:
    делать = "--делать" in sys.argv
    if not ВЫПИСКИ.exists():
        print("папки «выписки» нет — нечего сводить")
        return 0

    старые = sorted(p for p in ВЫПИСКИ.iterdir()
                    if p.is_dir() and УЗОР.match(p.name))
    if not старые:
        print("старых папок с датой не нашёл — папки уже сведены")
        свести_книги(делать)        # книги чистим отдельно: они могли остаться
        return 0

    print(f"папок прогонов: {len(старые)}")
    по_листам: dict[str, int] = {}
    файлов = 0
    for папка in старые:
        # ПУСТУЮ ПАПКУ ДАЖЕ НЕ ИМЕНУЕМ. Иначе для прогона, где ничего не
        # скачалось, срабатывал запасной путь «взять дату из имени папки» —
        # и рядом с «23-08» заводилась пустая «25-08», хотя лист был один.
        if not any(p.is_file() for p in папка.rglob("*")):
            continue
        лист = имя_листа(папка)
        for источник in папка.rglob("*"):
            if источник.is_dir():
                continue
            относительный = источник.relative_to(папка)
            приёмник = свободное(ЦЕЛЬ / лист / относительный)
            файлов += 1
            по_листам[лист] = по_листам.get(лист, 0) + 1
            if делать:
                приёмник.parent.mkdir(parents=True, exist_ok=True)
                shutil.move(str(источник), str(приёмник))

    print(f"файлов к переносу: {файлов}")
    for лист, сколько in sorted(по_листам.items()):
        print(f"   выписки/Мультигео/{лист}/  ←  {сколько} файлов")

    if not делать:
        print("\nЭТО ПРОБНЫЙ ПРОГОН, ничего не тронуто.")
        print("Перенести: .venv\\Scripts\\python.exe собрать_выписки.py --делать")
        return 0

    # Убираем по отсутствию ФАЙЛОВ, а не «чего угодно»: после переноса внутри
    # остаётся каркас пустых папок по гео, и проверка `any(rglob("*"))`
    # считала его содержимым — пять папок так и остались висеть.
    убрано = 0
    for папка in старые:
        try:
            if not any(p.is_file() for p in папка.rglob("*")):
                shutil.rmtree(папка)
                убрано += 1
        except Exception as e:
            print(f"   не смог убрать {папка.name}: {e}")
    свести_книги(делать)
    print(f"\nГотово. Перенесено файлов: {файлов}, пустых папок убрано: {убрано}")
    осталось = [p.name for p in ВЫПИСКИ.iterdir()
                if p.is_dir() and УЗОР.match(p.name)]
    if осталось:
        print(f"Осталось непустых старых папок: {len(осталось)} — загляни в них:")
        for имя in осталось[:10]:
            print("   ", имя)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
