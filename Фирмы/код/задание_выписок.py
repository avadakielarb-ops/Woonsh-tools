r"""
ЗАДАНИЕ НА ВЫПИСКИ: «гео + сколько» вместо «книга + лист».

Как было и почему это неправильно. Кнопка «Скачать выписки» работала по КНИГЕ
и ЛИСТУ прошлого прогона. Человеку до них дела нет: он выбирает страну и
говорит, сколько надо. Хуже того, модель врала: фирмы страны лежат не в одном
листе, а где придётся — часть в «Мультигео», часть на листе гео, часть
добрана вчера, часть позавчера. «Лист» перестал быть ответом на вопрос «что
качать по Франции» ещё тогда, когда появился мультигео.

Правда теперь в ТАБЛИЦЕ: там все фирмы, их гео и их выписки. Значит и задание
надо собирать оттуда:

    выбрал гео и число  →  берём из таблицы фирмы этих стран БЕЗ выписки
                        →  складываем во временную книгу
                        →  Часть 2 работает как обычно, по колонке «Гео»
                        →  результат возвращаем в таблицу по НОМЕРУ фирмы

Временная книга — не хранилище, а наряд на работу: Часть 2 умеет читать и
писать только Excel, и переучивать её ради этого незачем. Живёт она в
«фирмы/задания», и по ней же видно, что именно качалось.
"""
from __future__ import annotations

from datetime import date
from pathlib import Path

from common import раскладка
from common.колонки import Шапка
from common.пути import КОРЕНЬ

# Раскладка листа задания — та же, что у таблицы (одна на весь проект).
# Часть 2 ищет колонки по заголовкам, поэтому перекладывать ничего не нужно.
КОЛОНКИ = раскладка.КОЛОНКИ
ДОКУМЕНТЫ = (".pdf", ".docx")
ПАПКА = КОРЕНЬ / "фирмы" / "задания"

# Строку с таким статусом качать не надо: она закрыта.
НЕ_КАЧАТЬ = {"отработано", "дубль", "брак"}


def есть_выписка(значение: str) -> bool:
    """
    В колонке «Файл выписки» лежит либо имя файла, либо ПРИЧИНА отказа.

    Различаем по расширению: «Altmer OU.pdf» — выписка, «ликвидирована» —
    причина. Путать нельзя: по причине качать надо заново, по файлу — нет.
    """
    з = (значение or "").strip().lower()
    return з.endswith(ДОКУМЕНТЫ)


def найти(гео: list[str], сколько: int | None = None, log=print,
          только_с_сайтом: bool | None = None) -> list[dict]:
    """
    Фирмы выбранных стран, у которых выписки ещё нет.

    сколько=None — все. только_с_сайтом: True — линия «с сайтом», False —
    «без сайта», None — обе.
    """
    from common import таблица as т

    нужны = {г.strip().upper() for г in (гео or []) if г and г.strip()}
    найдено: list[dict] = []
    for л in т.всё():
        if л["скрыт"] or not л["строк"] or not л["строки"]:
            continue
        строки = л["строки"]
        ш = строки[0]
        if "Организация" not in ш:
            continue
        н = {к: (ш.index(к) if к in ш else -1) for к in КОЛОНКИ}
        свой = л["имя"].split(".")[0].upper()
        for с in строки[1:]:
            def взять(поле: str) -> str:
                i = н.get(поле, -1)
                return с[i].strip() if 0 <= i < len(с) and с[i] else ""

            орг = взять("Организация")
            if not орг:
                continue
            г = (взять("Гео") or свой).upper()
            if нужны and г not in нужны:
                continue
            if взять("Статус").lower() in НЕ_КАЧАТЬ:
                continue
            if есть_выписка(взять("Файл выписки")):
                continue
            сайт = взять("Website")
            if только_с_сайтом is True and not сайт:
                continue
            if только_с_сайтом is False and сайт:
                continue
            найдено.append({поле: взять(поле) for поле in КОЛОНКИ} | {"Гео": г})
    найдено.sort(key=lambda з: (з["Гео"], з["Организация"]))
    if сколько:
        # Режем ПО КАЖДОЙ СТРАНЕ, а не по общему списку: «по 10 на страну»
        # это то, что человек имеет в виду, выбирая три страны и число.
        по_гео: dict[str, list] = {}
        for з in найдено:
            по_гео.setdefault(з["Гео"], []).append(з)
        найдено = [з for г in sorted(по_гео) for з in по_гео[г][:сколько]]
    log(f"  · к скачиванию: {len(найдено)} фирм"
        + (f" ({', '.join(f'{г}:{n}' for г, n in sorted(_по_гео(найдено).items()))})"
           if найдено else ""))
    return найдено


def _по_гео(строки: list[dict]) -> dict[str, int]:
    счёт: dict[str, int] = {}
    for з in строки:
        счёт[з["Гео"]] = счёт.get(з["Гео"], 0) + 1
    return счёт


def книга_задания(строки: list[dict], log=print) -> tuple[Path, str]:
    """Сложить наряд во временную книгу. Возвращает (книга, лист)."""
    from openpyxl import Workbook
    from openpyxl.styles import Font

    ПАПКА.mkdir(parents=True, exist_ok=True)
    метка = "-".join(sorted(_по_гео(строки))) or "пусто"
    имя = f"Выписки {метка} {date.today():%d-%m}.xlsx"
    путь = ПАПКА / имя
    лист = f"{date.today():%d-%m}"

    wb = Workbook()
    ws = wb.active
    ws.title = лист
    ws.append(КОЛОНКИ)
    for c in ws[1]:
        c.font = Font(bold=True)
    for i, з in enumerate(строки, start=1):
        ws.append([i if к == "№" else з.get(к, "") for к in КОЛОНКИ])
    for кол, ш in zip("ABCDEFGHIJKLMNOPQ", раскладка.ШИРИНЫ):
        ws.column_dimensions[кол].width = ш
    wb.save(путь)
    log(f"  · наряд: {путь.name}, лист «{лист}», строк {len(строки)}")
    return путь, лист


def вернуть_в_таблицу(книга: Path, лист: str, log=print) -> dict:
    """
    Отдать результат Части 2 обратно в таблицу — ПО НОМЕРУ ФИРМЫ.

    Именно по номеру: Часть 2 переименовывает фирму в название из реестра, и
    по имени строка в таблице уже не находится. Номер она не трогает.
    """
    from openpyxl import load_workbook

    from common import таблица as т

    wb = load_workbook(книга, read_only=True, data_only=True)
    ws = wb[лист] if лист in wb.sheetnames else wb[wb.sheetnames[0]]
    ш = Шапка(ws)
    iи, iф = ш.номер("ID"), ш.номер("Файл выписки")
    iн, iг = ш.номер("Номер в реестре"), ш.номер("Гео")
    iп = ш.номер("Платёжный профиль выписки")
    правки = []
    for с in ws.iter_rows(min_row=2, max_col=max(iи, iф, iн, iг, iп, 1),
                          values_only=True):
        def взять(i):
            return (str(с[i - 1]).strip() if i and i <= len(с) and с[i - 1]
                    else "")

        ид, файл = взять(iи), взять(iф)
        if not ид or not файл:
            continue
        поля = {"Файл выписки": файл}
        # Имя файла — это удача, а причина отказа — это «нет выписки». Одно
        # от другого отличаем по расширению, как и везде.
        поля["Статус"] = "найдена" if есть_выписка(файл) else "нет выписки"
        if взять(iн):
            поля["Номер в реестре"] = взять(iн)
        if взять(iп):
            поля["Платёжный профиль выписки"] = взять(iп)
        правки.append({"лист": взять(iг) or "", "орг": "", "ид": ид,
                       "поля": поля})
    wb.close()
    if not правки:
        log("  · возвращать в таблицу нечего")
        return {"обновлено": 0}
    о = т.обновить(правки)
    log(f"  ☁ в таблицу вернулось: {о.get('обновлено', 0)} из {len(правки)}")
    return о
