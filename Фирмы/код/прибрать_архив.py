r"""
ПРИБРАТЬ АРХИВ: каждая строка должна лежать там, где ей положено по статусу.

Архив копился при трёх разных правилах, и сейчас в нём вперемешку:

  «Отработано»   — отданное фармеру (так и должно быть),
                   плюс «нет выписки», «брак», «дубль», «найдена» — от старых
                   правил, когда лист был свалкой для всего закрытого;
  рабочие листы  — строки со статусом «отработано» и «отклонена», которые
                   пометили, но не увезли: связь оборвалась, окно закрыли.

Куда что должно ехать (правило одно, см. common/статусы.py):

    отработано              → «Отработано»
    отклонена, дубль, брак  → «Недостойные»
    нет выписки, найдена    → НА РАБОЧИЙ ЛИСТ СВОЕГО ГЕО

Последнее — не мелочь. «Нет выписки» значит «реестр отказал сегодня», а не
«фирма негодная»: завтра выписка может выйти. Пока такая строка лежит в
архиве, фирма для приложения мертва — её не покажут ни счётчики, ни наряд.

Запуск:
    .venv\Scripts\python.exe код\прибрать_архив.py            — показать
    .venv\Scripts\python.exe код\прибрать_архив.py --писать   — разложить
"""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common.статусы import (БРАК, ГОДНАЯ, ДУБЛЬ, ЗАКРЫТЫЕ, НАЙДЕНА,
                            НЕДОСТОЙНЫЕ, НЕТ_ВЫПИСКИ, ОТКЛОНЕНА, ОТРАБОТАНО,
                            ОТРАБОТАНО_ЛИСТ, СПОРНАЯ, ВЫПИСКА, есть_выписка)

АРХИВЫ = (ОТРАБОТАНО_ЛИСТ, НЕДОСТОЙНЫЕ)


def куда_надо(статус: str, гео: str, сайт: bool) -> str:
    """Лист, на котором строке место. Пусто — трогать не надо."""
    с = (статус or "").strip().lower()
    if с == ОТРАБОТАНО:
        return ОТРАБОТАНО_ЛИСТ
    if с in (ОТКЛОНЕНА, ДУБЛЬ, БРАК):
        return НЕДОСТОЙНЫЕ
    if с in (НАЙДЕНА, ВЫПИСКА, ГОДНАЯ, НЕТ_ВЫПИСКИ, СПОРНАЯ, ""):
        # Рабочий лист своей страны и своей линии. Мультигео сюда не годится:
        # туда кладёт только прогон, и вернуть строку именно в ту партию мы
        # уже не можем — да и незачем, работать с ней будут по стране.
        return f"{гео}" if сайт else f"{гео}.БС"
    return ""


# Причины отказа, которых БОЛЬШЕ НЕ СУЩЕСТВУЕТ: правило отменено 16–17.09.2026
# («фирма активна — берём, не берём только ликвидированных»). Строка с такой
# причиной — живая фирма, выброшенная зря; причину стираем, чтобы она не
# выглядела приговором, и фирма идёт на следующий круг за выпиской.
ПРОТУХШИЕ_ПРИЧИНЫ = ("не сданы годовые отчёты", "просрочка", "overdue",
                     "предупреждение об удалении", "уведомление об удалении",
                     "файла на диске нет")


def причина_протухла(значение: str) -> bool:
    н = (значение or "").lower()
    return any(п in н for п in ПРОТУХШИЕ_ПРИЧИНЫ)


def разобрать(log=print) -> dict:
    """Кого куда переставить и кому стереть протухшую причину."""
    from common import таблица as т

    переезды: dict[str, list[str]] = {}
    правки: list[dict] = []
    было = Counter()
    for л in т.всё(служебные=True):
        имя = л["имя"]
        if имя in ("Реестр", "Лог", "Слова") or not л["строки"]:
            continue
        ш = л["строки"][0]
        if "Организация" not in ш or "Статус" not in ш or "ID" not in ш:
            continue
        iо, iс, iи = ш.index("Организация"), ш.index("Статус"), ш.index("ID")
        iг = ш.index("Гео") if "Гео" in ш else -1
        iw = ш.index("Website") if "Website" in ш else -1
        свой = имя.split(".")[0].upper()
        for с in л["строки"][1:]:
            def в(i):
                return с[i].strip() if 0 <= i < len(с) and с[i] else ""

            if not в(iо):
                continue
            статус = в(iс).lower()
            ид = в(iи)
            гео = (в(iг) or свой).upper()
            надо = куда_надо(статус, гео, bool(в(iw)))
            в_архиве = имя in АРХИВЫ
            # Строка на месте? Для архива сверяем имя листа, для рабочих —
            # только факт «не в архиве»: раскладка по гео/линии исторически
            # гуляла, и гонять живые строки с листа на лист ради порядка
            # значит тронуть тысячи строк без пользы.
            if в_архиве and надо == имя:
                continue
            if not в_архиве and надо not in АРХИВЫ:
                continue
            if not надо or not ид:
                if в_архиве and not ид:
                    было[f"{имя}: {статус or '(пусто)'} без номера"] += 1
                continue
            было[f"{имя} → {надо}: {статус or '(пусто)'}"] += 1
            переезды.setdefault(надо, []).append(ид)
            # ВОЗВРАЩАЕМ В РАБОТУ — СТИРАЕМ ПРОТУХШУЮ ПРИЧИНУ. Иначе строка
            # приедет на рабочий лист с надписью «не сданы годовые отчёты» в
            # колонке файла: и глазу непонятно, и статус спорит с содержимым.
            iф = ш.index("Файл выписки") if "Файл выписки" in ш else -1
            если_файл = в(iф)
            if надо not in АРХИВЫ and причина_протухла(если_файл):
                правки.append({"лист": имя, "орг": в(iо), "ид": ид,
                               "поля": {"Статус": НАЙДЕНА, "Файл выписки": ""}})

    for к, n in было.most_common():
        log(f"   {к:52} {n:>5}")
    log(f"  · строк к переезду: {sum(len(v) for v in переезды.values())}")
    if правки:
        log(f"  · причин отменённых правил стираем: {len(правки)}")
    return {"переезды": переезды, "правки": правки}


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    print("Смотрю, что где лежит…")
    итог = разобрать()
    переезды, правки = итог["переезды"], итог["правки"]
    if not переезды and not правки:
        print("Всё на своих местах.")
        raise SystemExit(0)
    print()
    print("=== КУДА ПЕРЕЕДЕТ ===")
    for лист, ид in sorted(переезды.items()):
        print(f"   {лист:16} {len(ид):>5}")
    if "--писать" not in sys.argv:
        print()
        print("Это ПРИМЕРКА, таблица не тронута. Разложить: --писать")
        raise SystemExit(0)

    from common import таблица as т
    print()
    # ПРИЧИНУ СТИРАЕМ ДО ПЕРЕЕЗДА: правка ищет строку по номеру и листу, а
    # после переезда лист уже другой.
    if правки:
        о = т.обновить(правки)
        print(f"   ✔ протухших причин стёрто: {о.get('обновлено', 0)} "
              f"из {len(правки)}")
    всего = 0
    for лист, ид in sorted(переезды.items()):
        о = т.перенести(лист, ид)
        n = о.get("перенесено", 0)
        всего += n
        print(f"   ✔ {лист:16} перенесено {n} из {len(ид)}")
    print(f"   ✔ всего переехало: {всего}")
