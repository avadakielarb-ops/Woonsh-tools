r"""
ВЫХЛОП ПО СЛОВАМ: сколько какое слово принесло.

Зачем. Слово, давшее две фирмы, стоит ровно столько же, сколько давшее двести:
тот же заход на dnb, та же выдача, то же время. Разница только в результате, и
сейчас её никто не видит. Отсюда планирование заказа вслепую: «300 EE» — это
сто слов или пять, узнаёшь через сорок минут.

ЧТО СЧИТАЕМ по каждому слову и гео:
    найдено      — сколько фирм принесло слово (взято в лист)
    с выпиской   — сколько из них дошло до документа
    прогонов     — в скольких прогонах слово участвовало
Отношение «с выпиской / найдено» и есть настоящая цена слова.

ОТКУДА БЕРЁМ. Два источника, и оба нужны:
  · ЛОГИ прогонов — история за всё время. Слово видно в строке «ищу без
    правовой формы — «…»», а фирмы под ним идут следом до следующего слова.
    Это разгон: статистика появляется сразу, а не через неделю наблюдений.
  · КОЛОНКА «Слово» в таблице — точный источник для всего, что найдено после
    того, как Часть 1 научилась её заполнять.

Логи дают охват, колонка — точность. Где они спорят, верим колонке.

Запуск:
    .venv\Scripts\python.exe код\статистика_слов.py            — показать
    .venv\Scripts\python.exe код\статистика_слов.py --писать   — и в таблицу
"""
from __future__ import annotations

import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common.пути import КОРЕНЬ
from part2.core.matching import normalize
from part2.geos.registry import DRIVERS

ГЕО_ПО_НАЗВАНИЮ = {д.title: код for код, д in DRIVERS.items()}

# Шаблоны сняты с ЖИВЫХ логов, а не придуманы. Часть 1 пишет строку
# «Гео UK. Ищу «cobalt», нужно 70 фирм. Лист: 06-09 UK» — в ней сразу и гео,
# и слово, поэтому она главная. «🎲 Слово взято само» идёт до неё и гео тоже
# несёт — берём и её, чтобы не потерять прогоны, где первой строки нет.
ПОИСК = re.compile(r"^\s*Гео\s+(?P<гео>[A-Z]{2})\.\s*Ищу\s+«(?P<слово>[^»]+)»")
СЛОВО_САМО = re.compile(r"Слово взято само:\s*«(?P<слово>[^»]+)»\s*\((?P<гео>[A-Z]{2})\)")
ВЗЯЛ = re.compile(r"^\s*✔\s*\[\d+/\d+\]\s*(?P<имя>.+?)\s*—")
# Часть 2 отчитывается по гео листа, а не по слову: её строки нужны, чтобы
# понять, сколько из найденного дошло до выписки.
ЗАГОЛОВОК2 = re.compile(r"^(?P<страна>[^:]+):\s*\d+\s+фирм из листа")
СКАЧАНО = re.compile(r"^\s*✔\s*(?P<файл>.+?\.(?:pdf|docx))\s*\(")


class Копилка:
    """слово+гео → сколько нашлось, сколько с выпиской, в скольких прогонах."""

    def __init__(self):
        self.данные: dict[tuple[str, str], dict] = defaultdict(
            lambda: {"найдено": 0, "выписка": 0, "прогонов": 0})

    def нашлась(self, гео: str, слово: str, n: int = 1) -> None:
        if гео and слово:
            self.данные[(гео.upper(), слово.lower())]["найдено"] += n

    def выписка(self, гео: str, слово: str, n: int = 1) -> None:
        if гео and слово:
            self.данные[(гео.upper(), слово.lower())]["выписка"] += n

    def прогон(self, гео: str, слово: str) -> None:
        if гео and слово:
            self.данные[(гео.upper(), слово.lower())]["прогонов"] += 1

    def строки(self) -> list[list]:
        итог = []
        for (гео, слово), д in sorted(self.данные.items()):
            доля = (round(100 * д["выписка"] / д["найдено"])
                    if д["найдено"] else 0)
            итог.append([слово, гео, д["найдено"], д["выписка"], доля,
                         д["прогонов"]])
        return итог


def из_логов(папка: Path | None = None, log=print) -> Копилка:
    """
    Разобрать все логи: какое слово сколько принесло.

    Слово в логе живёт «до следующего»: строка «ищу …» открывает участок, и всё
    взятое дальше принадлежит ему, пока не встретится следующая такая строка.
    Способ грубый, но другого нет — в старых логах связи «фирма ↔ слово» не было.
    """
    папка = папка or (КОРЕНЬ / "логи")
    копилка = Копилка()
    файлы = sorted(папка.glob("лог_*.txt"))

    # ЧЕЙ ЭТО СЛОВО. Часть 2 качает выписки, ничего не зная о слове — она
    # работает по листу. Поэтому «сколько дошло до выписки» нельзя взять из
    # её строк напрямую. Зато можно связать через ИМЯ ФИРМЫ: Часть 1 пишет,
    # какие фирмы принесло слово, а разбор логов знает, у кого выписка есть.
    чьё: dict[str, tuple[str, str]] = {}      # нормализованное имя → (гео, слово)

    for ф in файлы:
        гео, слово = "", ""
        for строка in ф.read_text(encoding="utf-8", errors="replace").splitlines():
            m = ПОИСК.match(строка) or СЛОВО_САМО.search(строка)
            if m:
                гео = m.group("гео").upper()
                новое = m.group("слово").strip()
                if новое != слово:
                    слово = новое
                    копилка.прогон(гео, слово)
                continue
            m = ЗАГОЛОВОК2.match(строка)
            if m:
                # пошла Часть 2: слово тут ни при чём, гео берём из заголовка
                гео = ГЕО_ПО_НАЗВАНИЮ.get(m.group("страна").strip(), гео)
                слово = ""
                continue
            m = ВЗЯЛ.match(строка)
            if m and слово:
                копилка.нашлась(гео, слово)
                чьё.setdefault(normalize(m.group("имя")), (гео, слово))

    # теперь навешиваем выписки: у кого файл есть — тому слову и плюс
    try:
        import разобрать_логи
        сдиска = разобрать_логи.разобрать(папка, log=lambda s: None)
        для_выписок = 0
        for (гео_ф, ключ), з in сдиска.items():
            if not з.get("файл"):
                continue
            своё = чьё.get(ключ)
            if своё and своё[0] == гео_ф:
                копилка.выписка(своё[0], своё[1])
                для_выписок += 1
        log(f"  · выписок привязано к словам: {для_выписок}")
    except Exception as e:
        log(f"  · выписки к словам не привязались ({type(e).__name__})")

    log(f"логов прочитано: {len(файлы)}, слов с историей: "
        f"{len({с for _, с in копилка.данные})}")
    return копилка


# ЛИСТЫ, КОТОРЫЕ СЧИТАТЬ НЕЛЬЗЯ.
#  «Слова» — наш собственный отчёт. Считать его значит кормить статистику её
#           же выхлопом: из строки «pinnacle | UK | 4 | 0» получалось слово
#           «pinnacle» в несуществующем гео «СЛОВА».
#  «Реестр» — та же фирма, что и на рабочем листе, только вид сбоку. Учтёшь
#           оба — каждая фирма посчитается дважды.
#  «Лог»   — журнал событий, фирм там нет.
НЕ_СЧИТАТЬ = {"Слова", "Реестр", "Лог"}
# Листы, где страна лежит в колонке, а не в названии листа.
ГЕО_В_КОЛОНКЕ = {"Мультигео", "Отработано"}


def из_таблицы(log=print) -> Копилка:
    """Точный источник: колонка «Слово» на рабочих листах и в архиве."""
    from common import таблица as т

    копилка = Копилка()
    # Вся таблица одним запросом, вместе со служебными: «Отработано» тоже
    # хранит слово, и без него статистика теряет всё, что уже сделано.
    for л in т.всё(служебные=True):
        if not л["строк"] or л["имя"] in НЕ_СЧИТАТЬ:
            continue
        строки = л["строки"]
        if not строки or "Слово" not in строки[0]:
            continue
        ш = строки[0]
        iс = ш.index("Слово")
        iг = ш.index("Гео") if "Гео" in ш else -1
        iф = ш.index("Файл выписки") if "Файл выписки" in ш else -1
        свой = None if л["имя"] in ГЕО_В_КОЛОНКЕ else \
            л["имя"].split(".")[0].upper()
        for с in строки[1:]:
            слово = с[iс].strip() if iс < len(с) and с[iс] else ""
            if not слово:
                continue
            гео = свой or (с[iг].strip().upper() if 0 <= iг < len(с) else "")
            копилка.нашлась(гео, слово)
            файл = с[iф].strip() if 0 <= iф < len(с) else ""
            if файл.lower().endswith((".pdf", ".docx")):
                копилка.выписка(гео, слово)
    log(f"из таблицы: слов {len({с for _, с in копилка.данные})}")
    return копилка


def свести(log=print) -> Копилка:
    """
    Логи для охвата, таблица для точности. Где спорят — верим таблице.

    ЧТО ИМЕННО ЗАБИРАЕМ У ТАБЛИЦЫ. Только «найдено» и «с выпиской»: их она
    знает точно. «Прогонов» в таблице нет и быть не может — она хранит фирмы,
    а не запуски. Раньше строка таблицы затирала строку логов целиком, и
    прогоны обнулялись; после этого ни одно слово не считалось подозрительным
    (условие «участвовало в прогоне» переставало выполняться), и чистка
    работала вхолостую.
    """
    общая = из_логов(log=log)
    try:
        точная = из_таблицы(log=log)
    except Exception as e:
        log(f"  · таблица недоступна ({type(e).__name__}) — считаю по логам")
        return общая
    for ключ, д in точная.данные.items():
        было = общая.данные[ключ]
        было["найдено"] = д["найдено"]
        было["выписка"] = д["выписка"]
    return общая


def по_категориям(копилка: Копилка, log=print) -> list[list]:
    """
    Что дало каждое СМЫСЛОВОЕ ПОЛЕ: камни, птицы, ремёсла.

    Зачем отдельно от слов. По одному слову судить нельзя: «ice» дало десять
    фирм, «pinnacle» — ноль, и это может быть просто везение. А вот сорок слов
    одной категории против сорока другой — уже разговор: видно, где искать
    дальше, и следующую сотню можно просить с перекосом в то, что работает.

    Категория известна только словам, выданным после того, как запас научился
    её хранить. Старые идут как «(без категории)» — врать про них нечего.
    """
    from part1.запас import Запас

    буфер = Запас(log=lambda s: None)
    свод: dict[str, dict] = {}
    for (гео, слово), д in копилка.данные.items():
        кат = буфер.категория(гео, слово) or "(без категории)"
        з = свод.setdefault(кат, {"слов": 0, "найдено": 0, "выписка": 0})
        з["слов"] += 1
        з["найдено"] += д["найдено"]
        з["выписка"] += д["выписка"]
    итог = []
    for кат, з in свод.items():
        среднее = round(з["найдено"] / з["слов"], 1) if з["слов"] else 0
        итог.append([кат, з["слов"], з["найдено"], з["выписка"], среднее])
    return sorted(итог, key=lambda с: -с[4])


def выхлоп_по_гео(строки: list[list]) -> dict[str, float]:
    """
    Сколько фирм приносит ОДНО слово в каждой стране.

    Считаем по строкам сводки — тем самым, что лежат на листе «Слова», поэтому
    функция одинаково работает и с только что посчитанной копилкой, и с
    прочитанной из таблицы: формат один.

    В расчёт берём слово, если оно ЛИБО участвовало в прогоне, ЛИБО что-то
    принесло. Пустышка, съевшая прогон, — такая же часть цены, как удачное
    слово: без неё средний выхлоп завышен, и заказ на триста планируется по
    несуществующей скорости. А слово, которое ещё ни разу не пробовали, в
    среднее не попадает — истории у него нет.
    """
    сумма: dict[str, list[int]] = {}
    for с in строки:
        if len(с) < 6:
            continue
        _слово, гео, найдено, _выписка, _доля, прогонов = с[:6]
        try:
            найдено, прогонов = int(найдено or 0), int(прогонов or 0)
        except (TypeError, ValueError):
            continue
        if прогонов or найдено:
            сумма.setdefault(str(гео).upper(), []).append(найдено)
    return {гео: round(sum(н) / len(н), 1) for гео, н in сумма.items() if н}


def подозрительные(копилка: Копилка, гео: str = "", порог: int = 3) -> list[str]:
    """
    Слова, которые пора проверить у модели: были в деле, но принесли мало.

    «Мало» — меньше порога фирм при хотя бы одном прогоне. Слово, которое ещё
    не пробовали, сюда не попадает: пустая история и плохое слово — разные вещи.
    """
    итог = []
    for (г, слово), д in копилка.данные.items():
        if гео and г != гео.upper():
            continue
        if д["прогонов"] and д["найдено"] < порог:
            итог.append(слово)
    return sorted(set(итог))


def почистить_слова(копилка: Копилка, log=print, порог: int = 3) -> dict:
    """
    Замкнуть цикл: слабые слова проверить у модели и брак выбросить.

    Тут важно, ЧТО считать поводом для проверки. Не «мало нашлось» — по
    редкому слову фирмы есть, до них просто не дошли. Повод — слово УЖЕ
    участвовало в прогоне и всё равно принесло меньше порога. Дальше решает
    модель: выдуманное и служебное уходит навсегда, живое остаётся.

    ПОЧЕМУ ДВА КРУГА. Слово попадает в статистику только после того, как его
    выдали, а выданное в «свободные» уже не возвращается. Значит в том гео,
    где слово провалилось, выбрасывать нечего — там оно потрачено. Толк от
    проверки в другом: то же самое слово лежит нетронутым ещё в пяти странах.
    Поэтому:
      круг 1 — спрашиваем в том гео, где слово провалилось, и запоминаем брак
               (в «брак», чтобы генератор не придумал его заново);
      круг 2 — вердикт «нет» (слова не существует) перепроверяем в тех гео,
               где слово ещё свободно, и чистим уже там.
    Второй круг не берём на веру из первого: «нет» значит «нет в ЭТОМ языке и
    не английское». Польское слово, проверенное на чешском гео, получило бы
    «нет» — и мы вычистили бы его из Польши, где оно живое.
    """
    from part1 import слова_проверка
    from part1.запас import Запас

    буфер = Запас(log=log)
    итог: dict[str, list[str]] = {}
    выдуманные: set[str] = set()

    def записать(гео: str, вердикты: dict) -> None:
        """Брак — в запас, живое — в лог: решение видно целиком, а не наполовину."""
        брак = [с for с, з in вердикты.items()
                if з["вердикт"] in слова_проверка.БРАК]
        живые = [с for с, з in вердикты.items()
                 if з["вердикт"] not in слова_проверка.БРАК]
        if живые:
            log(f"  · оставляю живыми: {', '.join(живые)}")
        if not брак:
            return
        буфер.забраковать(гео, брак)
        итог.setdefault(гео, []).extend(брак)
        for с in брак:
            log(f"  ✘ {гео}: «{с}» — {вердикты[с]['вердикт']}: "
                f"{вердикты[с].get('почему', '')}")

    for гео in sorted({г for г, _ in копилка.данные}):
        плохие = подозрительные(копилка, гео, порог)
        # ПРО ЧТО УЖЕ СПРАШИВАЛИ, НЕ СПРАШИВАЕМ. Забракованное слово остаётся
        # в статистике навсегда — оно ведь и правда дало мало. Без этой строки
        # каждая чистка заново гоняла бы через модель один и тот же список.
        уже = {с.lower() for с in буфер._гнездо(гео).get("брак", [])}
        плохие = [с for с in плохие if с.lower() not in уже]
        if not плохие:
            continue
        log(f"{гео}: слабых слов {len(плохие)} — спрашиваю модель")
        вердикты = слова_проверка.проверить(гео, плохие, log=log)
        записать(гео, вердикты)
        выдуманные |= {с.lower() for с, з in вердикты.items()
                       if з["вердикт"] == "нет"}

    if not выдуманные:
        return итог

    # круг 2: те же слова там, где они ещё не потрачены
    for гео in sorted(буфер.данные):
        свободные = [с for с in буфер._гнездо(гео)["свободные"]
                     if с.lower() in выдуманные]
        if not свободные:
            continue
        log(f"{гео}: лежит {len(свободные)} слов, забракованных в других гео "
            f"— проверяю здесь")
        записать(гео, слова_проверка.проверить(гео, свободные, log=log))
    return итог


