"""
ОЧЕРЕДЬ ЗАДАНИЙ — заводишь список, уходишь, возвращаешься к результатам.

Задание = слово × страна × сколько + галочки ЭТАПОВ:
    собрать  (Часть 1) → сайты (Часть 3) → выписки (Часть 2)

Сегодня ставишь одну галочку и чинишь этап. Когда гео станут надёжными —
ставишь все три, и это уже конвейер в одну кнопку. Переделывать не придётся.

Почему этапы идут ФАЗАМИ, а не по одному заданию целиком: Часть 1 на десять
стран в ОДНОМ браузере быстрее и безопаснее, чем десять раз открыть и закрыть
(лишний повод для проверки бота). Поэтому сначала собираем всё, потом ищем
сайты, потом качаем выписки. Статус при этом считается по каждой строке
отдельно — перезапустить можно ровно одну.

Состояние лежит в «очередь.json» и пишется после каждого шага: прогон на десять
стран это часы, и после падения надо понимать, где ты был.
"""
from __future__ import annotations

import json
import os
from dataclasses import dataclass, field, asdict
from datetime import datetime, date
from pathlib import Path
from threading import Event

from common import пути
from common.пути import данные

ФАЙЛ_ОЧЕРЕДИ = данные("очередь.json")

# Этапы в порядке выполнения. Ключ — как хранится, подпись — как показывается.
ЭТАПЫ = [("собрать", "1. Собрать фирмы"),
         ("сайты",   "3. Найти сайты"),
         ("выписки", "2. Скачать выписки")]

ЖДЁТ, РАБОТАЕТ, ГОТОВО, ОШИБКА, ПРОПУЩЕНО, ОСТАНОВЛЕНО = (
    "ждёт", "работает", "готово", "ошибка", "пропущено", "остановлено")


@dataclass
class Задание:
    слово: str
    страна: str
    сколько: int = 10
    без_сайта: bool = False
    этапы: dict = field(default_factory=lambda: {"собрать": True,
                                                 "сайты": False,
                                                 "выписки": False})
    статус: str = ЖДЁТ
    взято: int = 0
    отсеяно: int = 0
    скачано: int = 0
    заметка: str = ""
    начато: str = ""
    закончено: str = ""

    @property
    def осталось(self) -> int:
        """
        Сколько ещё добрать. После падения посреди строки продолжаем с этого
        места, а не собираем всё заново: уже взятые фирмы забронированы в
        реестре, и повторный проход выдал бы ДРУГИЕ фирмы сверх нужного.
        """
        return max(0, int(self.сколько) - int(self.взято))

    @property
    def этапы_текст(self) -> str:
        вкл = [подпись.split(". ")[1] for ключ, подпись in ЭТАПЫ
               if self.этапы.get(ключ)]
        return " → ".join(вкл) if вкл else "— ничего —"


class Очередь:
    """Список заданий + история прогонов. Пишется на диск после каждого шага."""

    def __init__(self, path: Path = ФАЙЛ_ОЧЕРЕДИ, log=None):
        self.path = path
        self.log = log or (lambda s: None)
        self.задания: list[Задание] = []
        self.история: list[dict] = []
        self.файл_excel: str = f"Мультигео {date.today():%d-%m}.xlsx"
        self.лист: str = ""            # лист, созданный последним прогоном
        self.загрузить()

    # ---------- диск ----------

    def загрузить(self) -> None:
        if not self.path.exists():
            return
        try:
            д = json.loads(self.path.read_text(encoding="utf-8"))
        except Exception as e:
            # Очередь — не реестр: потеря списка заданий неприятна, но не
            # разрушительна. Поэтому не падаем, а начинаем с чистого листа.
            self.log(f"(очередь не прочиталась, начинаю пустую: {e})")
            return
        self.задания = [Задание(**з) for з in д.get("задания", [])]
        self.история = д.get("история", [])
        self.файл_excel = д.get("файл_excel", self.файл_excel)
        self.лист = д.get("лист", "")

    def сохранить(self) -> None:
        """Атомарно — по тем же причинам, что и реестр: смерть посреди записи."""
        д = {"задания": [asdict(з) for з in self.задания],
             "история": self.история[-500:],          # больше и не нужно
             "файл_excel": self.файл_excel,
             "лист": self.лист}
        врем = self.path.with_suffix(".tmp")
        врем.write_text(json.dumps(д, ensure_ascii=False, indent=1), encoding="utf-8")
        os.replace(врем, self.path)

    # ---------- правка списка ----------

    def добавить(self, з: Задание) -> None:
        self.задания.append(з)
        self.сохранить()

    def удалить(self, индекс: int) -> None:
        if 0 <= индекс < len(self.задания):
            self.задания.pop(индекс)
            self.сохранить()

    def сдвинуть(self, индекс: int, куда: int) -> int:
        """Переставить строку. Возвращает новый индекс."""
        новый = индекс + куда
        if 0 <= индекс < len(self.задания) and 0 <= новый < len(self.задания):
            self.задания[индекс], self.задания[новый] = \
                self.задания[новый], self.задания[индекс]
            self.сохранить()
            return новый
        return индекс

    def очистить_статусы(self) -> None:
        for з in self.задания:
            з.статус, з.взято, з.отсеяно, з.скачано = ЖДЁТ, 0, 0, 0
            з.заметка = з.начато = з.закончено = ""
        self.сохранить()

    # ---------- повторы и возобновление ----------

    def прошлые(self, слово: str, страна: str) -> list[dict]:
        """Что уже гонялось по этому слову и стране — для вопроса о повторе."""
        с, ст = слово.strip().lower(), страна.strip().lower()
        return [и for и in self.история
                if и.get("слово", "").lower() == с
                and и.get("страна", "").lower() == ст]

    def оборванные(self) -> list[int]:
        """
        Строки, оставшиеся в статусе «работает» — значит прогон не закрылся сам.
        Это и есть признак падения: при нормальном конце статус всегда меняется.
        """
        return [i for i, з in enumerate(self.задания) if з.статус == РАБОТАЕТ]

    def в_историю(self, з: Задание) -> None:
        self.история.append({
            "слово": з.слово, "страна": з.страна, "сколько": з.сколько,
            "взято": з.взято, "скачано": з.скачано,
            "без_сайта": з.без_сайта,
            "дата": datetime.now().strftime("%Y-%m-%d %H:%M"),
            "статус": з.статус,
        })


def прогон(оч: Очередь, human, log=print, stop: Event | None = None,
           pause: Event | None = None, только: int | None = None,
           на_изменение=None) -> dict:
    """
    Выполнить очередь. только=индекс — прогнать ровно одну строку.

    Импорты движков ВНУТРИ функции: окно очереди должно открываться быстро,
    а part2 тянет за собой все драйверы гео.
    """
    from part1 import engine as движок1
    from part2 import engine as движок2
    from part3 import поиск_сайтов as движок3

    номера = [только] if только is not None else list(range(len(оч.задания)))
    работа = [(i, оч.задания[i]) for i in номера if i < len(оч.задания)]
    if not работа:
        raise RuntimeError("В очереди нечего выполнять.")

    excel = Path(оч.файл_excel)

    def отметить(i: int, статус: str, **поля):
        з = оч.задания[i]
        з.статус = статус
        for k, v in поля.items():
            setattr(з, k, v)
        if статус in (ГОТОВО, ОШИБКА, ОСТАНОВЛЕНО):
            з.закончено = datetime.now().strftime("%H:%M")
        оч.сохранить()
        if на_изменение:
            на_изменение()

    # ── ФАЗА 1: собрать фирмы (один браузер на все строки) ────────────────────
    сбор = [(i, з) for i, з in работа if з.этапы.get("собрать") and з.осталось > 0]
    пропущен_сбор = [(i, з) for i, з in работа
                     if з.этапы.get("собрать") and з.осталось == 0]
    for i, з in пропущен_сбор:
        log(f"⏭ «{з.слово}» × {з.страна}: уже набрано {з.взято} из {з.сколько} — "
            "сбор пропущен")

    if сбор:
        for i, з in сбор:
            отметить(i, РАБОТАЕТ, начато=datetime.now().strftime("%H:%M"))
        задания = [{"слово": з.слово, "страна": з.страна,
                    "сколько": з.осталось, "без_сайта": з.без_сайта}
                   for _, з in сбор]

        def после_строки(н: int, итог: dict):
            i, з = сбор[н]
            ошибка = итог.get("ошибка", "")
            отметить(i,
                     ОШИБКА if ошибка else (ПРОПУЩЕНО if итог.get("пропущено") else ГОТОВО),
                     взято=з.взято + итог.get("взято", 0),
                     отсеяно=з.отсеяно + итог.get("отсеяно", 0),
                     заметка=ошибка)

        итог1 = движок1.run_задания(задания, excel, human, log=log, stop=stop,
                                    pause=pause, на_задание=после_строки)
        оч.лист = итог1.get("лист", оч.лист)
        оч.сохранить()

    # ── ФАЗА 2: найти сайты фирмам без сайта ─────────────────────────────────
    сайты = [(i, з) for i, з in работа if з.этапы.get("сайты")]
    if сайты and not (stop and stop.is_set()):
        log(f"\n{'═' * 52}")
        log("ЭТАП: поиск сайтов для фирм без сайта")
        log(f"{'═' * 52}")
        for i, з in сайты:
            if stop and stop.is_set():
                break
            try:
                движок3.run(excel, human, страна=з.страна, log=log,
                            stop=stop, pause=pause)
            except Exception as e:
                log(f"✘ поиск сайтов ({з.страна}): {type(e).__name__}: {e}")
                отметить(i, ОШИБКА, заметка=f"сайты: {e}")

    # ── ФАЗА 3: скачать выписки, по гео, с листа мультигео ────────────────────
    выписки = [(i, з) for i, з in работа if з.этапы.get("выписки")]
    if выписки and not (stop and stop.is_set()):
        log(f"\n{'═' * 52}")
        log("ЭТАП: скачивание выписок")
        log(f"{'═' * 52}")
        лист = оч.лист or ""
        if not лист:
            log("✘ неизвестен лист мультигео — сначала собери фирмы (этап 1)")
        else:
            # ОДНА папка «Мультигео», внутри по имени листа (см. engine.папка_листа)
            папка = движок2.папка_листа(пути.ВЫПИСКИ, лист)
            from part1.data.countries import to_code
            for i, з in выписки:
                if stop and stop.is_set():
                    break
                гео = to_code(з.страна)
                if гео not in движок2.DRIVERS:
                    log(f"⏭ {гео} — драйвер гео не написан, пропускаю")
                    отметить(i, ПРОПУЩЕНО, заметка=f"нет драйвера {гео}")
                    continue
                try:
                    итог2 = движок2.run(гео, excel, пути.ВЫПИСКИ, human, log=log,
                                        sheet=лист, stop=stop, pause=pause,
                                        фильтр_гео=гео, папка_прогона=папка)
                    отметить(i, ГОТОВО, скачано=итог2.get("скачано", 0))
                except Exception as e:
                    log(f"✘ выписки {гео}: {type(e).__name__}: {e}")
                    отметить(i, ОШИБКА, заметка=f"выписки: {e}")

    # ── в историю ────────────────────────────────────────────────────────────
    for i, з in работа:
        if з.статус in (ГОТОВО, ОШИБКА, ПРОПУЩЕНО):
            оч.в_историю(з)
    оч.сохранить()
    if на_изменение:
        на_изменение()

    взято = sum(оч.задания[i].взято for i, _ in работа)
    скачано = sum(оч.задания[i].скачано for i, _ in работа)
    return {"взято": взято, "скачано": скачано, "строк": len(работа),
            "файл": str(excel), "лист": оч.лист}
