r"""
ВЫГРУЗКА ПРОГОНА В ТАБЛИЦУ — то, что закрывает цепочку.

До неё приложение было набором деталей: Часть 1 писала в Excel, Часть 2 писала
в Excel, а в таблицу всё это попадало только когда руками запускали перенос.
Пользователь видел «оно что-то делает», а картины не было. Теперь прогон
закрывает за собой сам.

КОГДА. В конце прогона, один раз — так выбрал пользователь (вариант Б). По ходу
в таблицу не ходим вообще: прогон длится сорок минут, и терять его из-за
моргнувшей сети нельзя. Локальный Excel остаётся страховкой и пишется как раньше.

ЧТО ДЕЛАЕТ. Берёт ОДИН отработанный лист, раскладывает фирмы по трём корзинам
(с сайтом → лист гео, без сайта но с адресом → «<ГЕО>.БС», без адреса → только
в «Реестр») и синхронизирует:

  фирмы, которых в таблице ещё нет  → дописываем на лист + запись в «Реестр»;
  уже известные                     → обновляем «Файл выписки», «Номер в
                                      реестре», «Статус» — то есть результат
                                      Части 2 по ним.

Повторный запуск безопасен: он ничего не удваивает, потому что «уже известна»
определяется по «Реестру», а он один на всю таблицу — и лист гео, и «Мультигео»
считаются одной и той же фирмой.
"""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import перенос_в_таблицу as перенос
from common import раскладка


def _ключи_реестра(таблица, log) -> dict[str, str]:
    """
    Что таблица уже знает: {ключ: номер фирмы}. Один запрос вместо чтения
    сорока листов.

    Номер может быть пустым — у строк, заведённых до того, как номера
    появились. Тогда правка поедет по имени, как раньше; хуже не станет.
    """
    # ВЕСЬ лист, без вариантов: недобор здесь означает, что известная фирма
    # сойдёт за новую и ляжет в таблицу вторым экземпляром.
    строки = таблица.читать("Реестр", 20000, всё=True)
    if not строки:
        return {}
    шапка = строки[0]
    i = шапка.index("Ключ") if "Ключ" in шапка else 0
    iи = шапка.index("ID") if "ID" in шапка else -1
    ключи = {с[i].strip(): (с[iи].strip() if 0 <= iи < len(с) else "")
             for с in строки[1:] if len(с) > i and с[i].strip()}
    с_номером = sum(1 for з in ключи.values() if з)
    log(f"  · в таблице уже известно фирм: {len(ключи)}"
        + (f", из них с номером {с_номером}" if с_номером else ""))
    return ключи


def выгрузить(excel: Path, лист: str, log=print, мультигео: bool = False) -> dict:
    """
    Синхронизировать один лист с таблицей.

    мультигео=True — прогон шёл по нескольким странам сразу, и весь его улов
    ложится на ОДИН лист «Мультигео», а не растекается по странам. Так просил
    пользователь: заказ «10 EE + 10 FI + 10 AU» забирается из одного места, а
    не собирается по трём листам руками. Страна каждой строки видна в колонке
    «Гео», поэтому ничего не теряется, а «Реестр» по-прежнему один — фирма не
    попадёт в работу дважды, даже если завтра найдётся одиночным прогоном.
    """
    from common import пути
    from common import таблица as т

    # ПОЛИГОН В ТАБЛИЦУ НЕ ПИШЕТ. Рядом с рабочей копией живёт вторая, где
    # чинят гео и гоняют опыты. Если и она начнёт выгружать, в таблице
    # смешаются боевые фирмы и мусор проверок, и доверять ей станет нельзя.
    # Сам запрет стоит в клиенте таблицы; здесь — чтобы сказать об этом
    # по-человечески и не пугать исключением на ровном месте.
    if пути.это_полигон():
        log("  · это ПОЛИГОН — в таблицу ничего не пишу (так и задумано)")
        return {"полигон": True}

    if not т.настроена():
        log("  · таблица не настроена — выгрузку пропускаю "
            "(данные в Excel на месте)")
        return {"пропущено": True}

    log("Выгружаю в таблицу…")
    итог = перенос.собрать(log=lambda s: None,
                           только_книга=excel, только_лист=лист)
    фирмы = итог["фирмы"]
    if not фирмы:
        log("  · на листе нечего выгружать")
        return {"новых": 0, "обновлено": 0}

    известные = _ключи_реестра(т, log)

    # Заводим недостающие листы: гео могло появиться впервые.
    гео = sorted({г for г, _ in фирмы})
    т.создать(гео)

    новые: dict[str, list] = {}
    в_реестр: list[list] = []
    правки: list[dict] = []
    счёт = Counter()

    for (г, ключ), з in sorted(фирмы.items()):
        полный = f"{г}|{ключ}"
        if полный in известные:
            # Фирма уже в таблице — обновляем только результат Части 2.
            строка = з["строка"]
            поля = {}
            # ПО ИМЕНАМ, А НЕ ПО НОМЕРАМ. Позиции колонок менялись уже дважды,
            # и «строка[10]» каждый раз означало что-то другое — молча.
            файл = раскладка.взять(строка, "Файл выписки")
            номер_реестра = раскладка.взять(строка, "Номер в реестре")
            if файл:
                поля["Файл выписки"] = файл
                поля["Статус"] = "найдена"
            if номер_реестра:
                поля["Номер в реестре"] = номер_реестра
            if поля and з["лист"]:
                # НОМЕР ВПЕРЁД ИМЕНИ. К этому моменту Часть 2 уже могла
                # переименовать фирму в название из реестра, и по имени строка
                # в таблице не находится — результат прогона терялся молча.
                #
                # Свой номер (из книги) вернее: он писан в ту же строку, что
                # лежит в таблице. Нет его — берём из «Реестра»: там номера
                # проставлены разовой миграцией. Нет и там — поедем по имени.
                правки.append({"лист": з["лист"], "орг": з["орг"],
                               "ид": (з["ид"] if з.get("ид_из_книги")
                                      else известные.get(полный, "")),
                               "поля": поля})
                счёт["обновлено"] += 1
            continue
        if з["лист"]:
            # Куда класть: при мультипрогоне — всё в «Мультигео», иначе на лист
            # своей страны. Линия «без сайта» остаётся отдельной и там, и там.
            куда = ("Мультигео" if мультигео and not з["лист"].endswith(".БС")
                    else з["лист"])
            новые.setdefault(куда, []).append(з["строка"])
            счёт["новых"] += 1
        else:
            счёт["без адреса"] += 1
        в_реестр.append([полный, г, з["орг"],
                         "найдена" if з["лист"] else "без адреса",
                         раскладка.взять(з["строка"], "Дата"),
                         раскладка.взять(з["строка"], "Слово"),
                         з["откуда"], з["ид"]])

    for имя_листа in sorted(новые):
        n = т.дописать(имя_листа, новые[имя_листа])
        log(f"  ✔ {имя_листа}: +{n} фирм")
    if в_реестр:
        т.дописать("Реестр", в_реестр)
    if правки:
        о = т.обновить(правки)
        log(f"  ✔ обновлено строк: {о['обновлено']}")

    log(f"Таблица: новых {счёт['новых']}, обновлено {счёт['обновлено']}"
        + (f", без адреса {счёт['без адреса']}" if счёт["без адреса"] else ""))
    return dict(счёт)


if __name__ == "__main__":
    if len(sys.argv) < 3:
        print(r"Запуск: .venv\Scripts\python.exe код\выгрузка.py <книга.xlsx> <лист>")
        raise SystemExit(1)
    выгрузить(Path(sys.argv[1]), sys.argv[2])
