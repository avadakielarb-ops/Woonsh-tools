r"""
РАЗЛОЖИТЬ «Мультигео» ПО ЛИСТАМ СТРАН.

Зачем. Мультигеошный прогон кладёт весь заказ на один лист — партию видно
целиком, и это удобно, пока прогон идёт. Но накапливается там ВСЁ, и через
месяц лист страны показывает крохи, а основная масса лежит в общей куче.

Замер 23.09.2026: из 1645 фирм, ушедших боту, на листах стран лежало 602, а
1043 — на «Мультигео». Самый большой лист страны (PL) показывал 71 фирму с
сайтом, тогда как по счётчику их 90, а по AU — 232 против 18 на листе.
Человек смотрит в таблицу, видит десятки и не верит счётчикам, которые
считают ПО КОЛОНКЕ «Гео», а не по имени листа. Обе цифры верные, разрез
разный — и это хуже, чем если бы одна из них просто врала.

Что делает. Каждую строку «Мультигео» увозит на лист её страны — тот самый,
который открывают глазами. Лист создаётся, если его ещё нет.

Запуск:
    …\разложить_мультигео.py                 — примерка, ничего не трогает
    …\разложить_мультигео.py --писать        — разложить
    …\разложить_мультигео.py LV PL --писать  — только эти страны
"""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

ЛИСТ = "Мультигео"


def собрать_по_странам(нужны: set[str]) -> tuple[dict[str, list[str]], int]:
    """Номера фирм с «Мультигео», разложенные по колонке «Гео»."""
    from common import таблица as т

    по_гео: dict[str, list[str]] = {}
    без_гео = 0
    for л in т.всё(служебные=True):
        if л.get("имя") != ЛИСТ:
            continue
        стр = л.get("строки") or []
        if not стр:
            continue
        ш = [str(х or "").strip() for х in стр[0]]
        if "ID" not in ш or "Гео" not in ш:
            print("На «Мультигео» нет колонок ID или Гео — не берусь.")
            raise SystemExit(2)
        ки, кг = ш.index("ID"), ш.index("Гео")
        ко = ш.index("Организация") if "Организация" in ш else -1
        for с in стр[1:]:
            if 0 <= ко < len(с) and not str(с[ко]).strip():
                continue          # пустая строка-место, её переносить незачем
            и = str(с[ки]).strip() if len(с) > ки else ""
            г = (str(с[кг]).strip().upper() if len(с) > кг else "")
            if not и:
                continue
            if not г:
                без_гео += 1
                continue
            if нужны and г not in нужны:
                continue
            по_гео.setdefault(г, []).append(и)
    return по_гео, без_гео


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    нужны = {а.strip().upper() for а in sys.argv[1:] if not а.startswith("--")}

    print("Читаю «Мультигео»…")
    по_гео, без_гео = собрать_по_странам(нужны)
    всего = sum(len(v) for v in по_гео.values())
    if not всего:
        print("Переносить нечего.")
        raise SystemExit(0)

    print()
    print(f"=== РАЗЛОЖИМ {всего} СТРОК ===")
    for г, ид in sorted(по_гео.items(), key=lambda x: -len(x[1])):
        print(f"  {г:<6} {len(ид):>5}")
    if без_гео:
        # БЕЗ СТРАНЫ ПЕРЕНОСИТЬ НЕКУДА. Такую строку молча оставить на месте
        # честнее, чем свалить в случайный лист: её видно здесь и можно
        # разобрать руками.
        print(f"  · без колонки «Гео» — оставляю на месте: {без_гео}")

    if "--писать" not in sys.argv:
        print()
        print("Это ПРИМЕРКА, таблица не тронута. Разложить: --писать")
        raise SystemExit(0)

    from common import таблица as т

    print()
    перенесено = 0
    for г, ид in sorted(по_гео.items()):
        о = т.перенести(г, ид)
        n = о.get("перенесено", 0)
        перенесено += n
        print(f"  ☁ {г}: перенесено {n} из {len(ид)}")
    print()
    print(f"Всего перенесено: {перенесено} из {всего}")
    print("Теперь лист страны и счётчик показывают одно и то же.")
