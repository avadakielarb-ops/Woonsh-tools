"""
ГДЕ ЧТО ЛЕЖИТ — одно место на весь проект.

В корне остаётся только запускалка. Всё остальное разложено по четырём папкам,
и раскладка задана ЗДЕСЬ: чтобы переставить папку, правится одна строка, а не
десяток констант по всему коду.

    СТАРТ.bat          ← запуск, только он
    код/               весь Python: пакеты, окна, обслуживающие скрипты
    данные/            состояние: реестр броней, запас слов, исключения, ключи
    фирмы/             рабочие книги Excel (Мультигео и по странам)
    доки/              описания, заметки, сборка
    выписки/  логи/    результаты прогонов — на виду, их открывают чаще всего

Корень считаем от ЭТОГО файла, а не от текущей папки: приложение запускают и
из корня, и из «код», и собранным .exe — рабочая папка каждый раз разная,
а расположение файлов относительно проекта неизменно.
"""
from __future__ import annotations

from pathlib import Path

def _найти_корень() -> Path:
    """
    Корень проекта — папка, где лежит СТАРТ.bat.

    Ищем ПОДЪЁМОМ, а не отсчётом уровней: код уже переезжал (common лежал в
    корне, теперь в «код»), и жёсткое parent.parent пришлось бы править каждый
    раз. Признак корня — запускалка либо папка «данные» рядом.
    """
    тек = Path(__file__).resolve().parent
    for кандидат in [тек, *тек.parents]:
        if (кандидат / "СТАРТ.bat").exists() or (кандидат / "данные").is_dir():
            return кандидат
    return тек.parent.parent


КОРЕНЬ = _найти_корень()

КОД = КОРЕНЬ / "код"
ДАННЫЕ = КОРЕНЬ / "данные"
ФИРМЫ = КОРЕНЬ / "фирмы"
ДОКИ = КОРЕНЬ / "доки"
ЛОГИ = КОРЕНЬ / "логи"


def _хранилище_выписок() -> Path:
    """
    Где лежат выписки. ВНЕ ПАПКИ ПРИЛОЖЕНИЯ, если сказано в настройках.

    Зачем вынесли (16.09.2026). Выписки — сотни мегабайт документов, и они
    жили внутри проекта: «Фирмы» весили 1.9 ГБ, полигон ещё 1.8 ГБ, причём
    291 МБ в полигоне были точной копией того же самого. Папку приложения
    копируют, синхронизируют, кладут в архив — и каждый раз таскают этот вес
    за собой. Документы не код: им место снаружи, одной кучей на оба проекта.

    Путь задаётся файлом «данные/пути.json», ключ «выписки». Нет файла или
    ключа — остаётся прежнее место внутри проекта: настройка, которой нет,
    не должна ломать работающую установку.
    """
    import json
    try:
        свои = json.loads((ДАННЫЕ / "пути.json").read_text(encoding="utf-8"))
        путь = (свои.get("выписки") or "").strip()
        if путь:
            return Path(путь)
    except Exception:
        pass
    return КОРЕНЬ / "выписки"


ВЫПИСКИ = _хранилище_выписок()
ШАБЛОНЫ = ДАННЫЕ / "шаблоны"
ПРОФИЛЬ_БРАУЗЕРА = КОРЕНЬ / ".профиль_браузера"


def данные(имя: str) -> Path:
    """Файл состояния. Папку создаём сразу: писать в неё будут в любом случае."""
    ДАННЫЕ.mkdir(parents=True, exist_ok=True)
    return ДАННЫЕ / имя


def это_полигон() -> bool:
    """
    Это испытательная копия? Признак — файл «полигон» в папке данных.

    Правило «полигон в таблицу не пишет» спрашивают из двух мест: клиент
    таблицы (запрещает запись) и выгрузка (говорит об этом по-человечески).
    Держим ответ ЗДЕСЬ, одной функцией: два независимых чтения файла — это два
    места, где однажды забудут поправить, и одно из них промолчит. Заодно
    тестам есть что подменить: проверка клиента не должна зависеть от того, в
    какой из двух копий её запустили.
    """
    return (ДАННЫЕ / "полигон").exists()


def фирмы(имя: str) -> Path:
    ФИРМЫ.mkdir(parents=True, exist_ok=True)
    return ФИРМЫ / имя


def книги_мультигео() -> list[Path]:
    """Рабочие книги «Мультигео *.xlsx», свежие первыми."""
    ФИРМЫ.mkdir(parents=True, exist_ok=True)
    return sorted(ФИРМЫ.glob("Мультигео *.xlsx"),
                  key=lambda p: p.stat().st_mtime, reverse=True)
