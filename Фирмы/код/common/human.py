"""
ЧЕЛОВЕК В КОНТУРЕ.

Капча, логин, непонятная выдача — скрипт не гадает и не падает. Он останавливается
и зовёт человека. В приложении вопрос показывается ПАНЕЛЬЮ ВНУТРИ ОКНА (не отдельным
всплывающим окном). Если движок запущен из консоли — падаем в консольный режим.

Механика: HumanGate.ask() блокирует поток движка, пока UI не установит Event.
"""
from __future__ import annotations

from enum import Enum
from threading import Event
from typing import Callable, Optional


class HumanChoice(str, Enum):
    CONTINUE = "continue"
    SKIP = "skip"
    SKIP_GEO = "skip_geo"      # бросить всю страну, но прогон продолжить
    ABORT = "abort"


class AbortRun(Exception):
    """Человек нажал «Стоп» — прекращаем весь прогон."""


class SkipCompany(Exception):
    """Человек нажал «Пропустить» — бросаем текущую фирму."""


class SkipGeo(Exception):
    """
    Человек нажал «Пропустить страну» — бросаем ВСЮ страну, идём к следующей.

    Нужно в мультилисте: если гео залипло (реестр лежит, капча не кончается,
    сайт переделали), раньше выбор был только между «мучиться с этой страной»
    и «остановить весь прогон на 18 стран». Теперь можно бросить одну.
    """


def сохранить_excel(wb, path, human, log=print) -> None:
    """
    Сохранить книгу Excel. Файл открыт в Excel (PermissionError) — НЕ падаем:
    встаём на паузу и ждём человека (закрой файл → «Повторить»).
    """
    попыток = 0
    while True:
        try:
            wb.save(path)
            return
        except PermissionError:
            # БЕЗ ЧЕЛОВЕКА ПОВТОРЯЕМ НЕ ВЕЧНО. Автономный режим ответит
            # «повторить» столько раз, сколько спросишь, а закрывать Excel
            # некому — получился бы бесконечный круг вместо прогона.
            попыток += 1
            if попыток > 20:
                raise AbortRun("Excel-файл так и не закрыли (20 попыток)")
            выбор = human.меню(
                "Excel открыт — закрой файл",
                f"Не могу записать: файл открыт в Excel.\n{path}\n\n"
                "Закрой его в Excel и нажми «Повторить».",
                [("retry", "🔁 Повторить (я закрыл Excel)"),
                 ("stop",  "■ Остановить прогон")],
                авто="retry")
            if not выбор or выбор == "stop":
                raise AbortRun("Excel-файл не закрыт")
            log("Пробую записать снова…")


def подождать_паузу(pause, stop=None) -> None:
    """
    ПАУЗА на БЕЗОПАСНОЙ ТОЧКЕ. Движок зовёт это между фирмами: если человек
    нажал «Пауза», стоим тут, пока он не нажмёт «Возобновить». Так мы не рвём
    скачивание на полуслове и не сжигаем бронь.
    """
    import time
    while pause is not None and pause.is_set():
        if stop is not None and stop.is_set():
            raise AbortRun("остановлено")
        time.sleep(0.3)


class HumanGate:
    def __init__(self, ui_ask: Optional[Callable[[str, str, str], None]] = None,
                 ui_keyword: Optional[Callable[[str], None]] = None,
                 ui_menu: Optional[Callable[[str, str, list, str], None]] = None):
        """
        ui_ask(title, message, company)          — панель с «Продолжить/Пропустить/Стоп».
        ui_menu(title, message, варианты, company) — панель с ПРОИЗВОЛЬНЫМИ кнопками.
        Ответ приложение кладёт через answer()/answer_menu(). Нет UI → консоль.
        """
        self.ui_ask = ui_ask
        self.ui_keyword = ui_keyword
        self.ui_menu = ui_menu
        # Что отвечать без человека на ТЕКУЩИЙ вопрос — ставит сам
        # спрашивающий в меню(авто=…). Пусто — значит безопасного ответа нет.
        self.авто = ""
        self._keyword = ""
        self.log: list[str] = []          # что делали руками — попадёт в отчёт
        self._event = Event()
        self._choice = HumanChoice.SKIP
        self._menu_choice = ""
        # ПРИКАЗ — вмешательство ДО ТОГО, как движок сам о чём-то спросит.
        #
        # Панель с кнопками появляется, только когда движок решил спросить. А
        # просьба человека была ровно про другой случай: «он завис и не идёт
        # дальше и не показывает действия». Тогда нажимать нечего, и остаётся
        # убивать прогон целиком.
        #
        # Поэтому окно кладёт приказ сюда, а ЗАБИРАЕТ И ИСПОЛНЯЕТ ЕГО САМ
        # ДВИЖОК — в своём потоке, на ближайшей передышке. Иначе никак:
        # Playwright привязан к потоку, который его создал, и дёрнуть браузер
        # из окна значит сломать прогон вернее, чем он уже сломан.
        self._приказ = ""
        self._последний = ""      # что человек просил в прошлый раз
        # Повод ПОСЛЕДНЕГО вопроса. Нужен, чтобы по брошенному SkipCompany
        # отличить «фирмы нет в реестре» от обычного «пропустить».
        self.повод = ""

    # --- ручное управление: окно кладёт, движок забирает ---
    def приказать(self, ключ: str) -> str:
        """
        Окно: «сделай это, как только сможешь». Возвращает, что встало в
        очередь на самом деле, — окну есть что написать в лог.

        «ПОВТОРИТЬ» — САМОСТОЯТЕЛЬНАЯ КОМАНДА, а не «сделай то же, что в
        прошлый раз». Сперва я сделал вторым способом, и человек справедливо
        не понял: он нажимает «повторить последнее действие», а в логе
        «повторяю: Обновить страницу» — при том что ничего до этого не
        нажимал. Повторять надо то, на чём встал ДВИЖОК, а не то, что жал
        человек. Для прогона это одно и то же: перечитать страницу и пройти
        текущий шаг заново.
        """
        ключ = (ключ or "").strip()
        if ключ:
            self._последний = ключ
        self._приказ = ключ
        return ключ

    def забрать_приказ(self) -> str:
        """Движок: что просил человек. Забираем НАСОВСЕМ — приказ разовый."""
        п, self._приказ = self._приказ, ""
        return п

    def исполнить_приказ(self, br=None, log=None) -> bool:
        """
        Выполнить то, что человек нажал в «ручном управлении».

        Зовётся ИЗ ПОТОКА ДВИЖКА и часто — на каждой передышке. Живёт здесь, а
        не в движке, чтобы и драйверы могли позвать её из своих ожиданий, не
        импортируя движок по кругу.

        Возвращает True, если что-то сделали: вызывающий может перечитать
        страницу и попробовать снова.
        """
        приказ = self.забрать_приказ()
        if not приказ:
            return False
        скажи = log or (lambda *_: None)
        if приказ == "стоп":
            скажи("✋ ручное управление: стоп")
            raise AbortRun("остановлено человеком вручную")
        if приказ == "страна":
            скажи("✋ ручное управление: пропускаю страну")
            raise SkipGeo("страна пропущена человеком вручную")
        if приказ == "пропустить":
            скажи("✋ ручное управление: пропускаю фирму")
            raise SkipCompany("фирма пропущена человеком вручную")
        if приказ in ("обновить", "повторить"):
            скажи("✋ ручное управление: "
                  + ("повторяю последнее действие" if приказ == "повторить"
                     else "перечитываю страницу"))
            # И то и другое для прогона — одно: перечитать страницу и пройти
            # текущий шаг заново. Возвращаем True, и тот, кто ждал, повторяет.
            цель = br.перезагрузить if br is not None else self.перезагрузить
            if цель:
                цель(скажи)
            return True
        if приказ == "продолжить":
            скажи("✋ ручное управление: иду дальше")
            return True
        скажи(f"✋ ручное управление: не знаю приказа «{приказ}»")
        return False

    # --- вызывает приложение, когда человек нажал кнопку ---
    def answer(self, choice: HumanChoice) -> None:
        self._choice = choice
        self._event.set()

    def answer_menu(self, key: str) -> None:
        """Приложение передаёт ключ выбранной кнопки меню."""
        self._menu_choice = key or ""
        self._event.set()

    def answer_keyword(self, text: str) -> None:
        """Приложение передаёт введённое слово (или пусто = отмена)."""
        self._keyword = (text or "").strip()
        self._event.set()

    def ask_keyword(self, message: str) -> str:
        """
        Спросить у человека НОВОЕ СЛОВО для добора. Возвращает слово или "".
        Нет UI — консольный ввод.
        """
        if not self.ui_keyword:
            try:
                return input(message + "\nНовое слово (пусто = стоп): ").strip()
            except Exception:
                return ""
        self._event.clear()
        self._keyword = ""
        self.ui_keyword(message)
        self._event.wait()
        return self._keyword

    # --- глаза: их подставляет Browser, сам HumanGate про браузер не знает ---
    снимок = None       # снимок(повод) -> путь к PNG
    диагноз = None      # диагноз() -> объект с .код/.заголовок/.что_делать
    перезагрузить = None   # перезагрузить(log) -> bool, зовёт ТОЛЬКО движок

    def _обогатить(self, title: str, message: str) -> tuple[str, str]:
        """
        Перед вопросом посмотреть на страницу и дополнить сообщение.

        Симптом у разных бед один — «элемент не найден». Поэтому говорим, ЧТО
        на самом деле на экране (проверка бота, баннер, разлогинило, пусто), и
        прикладываем снимок. Без этого разбор поломки занимает час.
        Всё в try: диагностика НИКОГДА не должна ронять сам вопрос человеку.
        """
        хвост = []
        try:
            д = self.диагноз() if self.диагноз else None
            if д is not None and д.код != "неясно":
                title = f"{д.заголовок}"
                хвост.append("Что вижу на странице: " + д.заголовок.lower())
                хвост.append(д.что_делать)
        except Exception:
            pass
        try:
            путь = self.снимок(title) if self.снимок else ""
            if путь:
                хвост.append(f"📸 Снимок экрана: {путь}")
        except Exception:
            pass
        if хвост:
            message = message.rstrip() + "\n\n" + "\n\n".join(хвост)
        return title, message

    # --- вызывают драйверы ---
    def ask(self, title: str, message: str, company: str = "") -> HumanChoice:
        title, message = self._обогатить(title, message)
        self.log.append(f"{company or '—'}: {title}")
        if not self.ui_ask:
            return self._console(title, message, company)
        self._event.clear()
        self.ui_ask(title, message, company)
        self._event.wait()                 # ЖДЁМ человека, сколько понадобится
        return self._choice

    def меню(self, title: str, message: str,
             варианты: list[tuple[str, str]], company: str = "",
             авто: str = "") -> str:
        """
        Спросить человека с ПРОИЗВОЛЬНЫМИ кнопками.
        варианты — список (ключ, подпись кнопки). Возвращает ключ выбранной.
        Ждём ответа СКОЛЬКО УГОДНО — без таймаута.

        авто — что ответить, когда человека НЕТ (автономный режим). Спрашивающий
        называет это сам, и не зря: раньше автономный режим брал ПЕРВЫЙ вариант,
        а первым в меню «не смог перелистнуть» стоит «я перелистнул сам». Робот
        отвечал, что перелистнул, — хотя не листал никто. Движок читал ту же
        страницу, находил те же две фирмы дублями, снова не мог перелистнуть и
        снова спрашивал. Прогон крутился на одной странице часами (замер по
        логу 09.09.2026, Австрия). Порядок кнопок — дело удобства человека, и
        привязывать к нему поведение робота нельзя.
        """
        title, message = self._обогатить(title, message)
        self.авто = авто
        self.log.append(f"{company or '—'}: {title}")
        if not self.ui_menu:
            print("\n" + "=" * 60)
            print(f"ТРЕБУЕТСЯ ЧЕЛОВЕК: {title}")
            print(message)
            for i, (_, подпись) in enumerate(варианты, 1):
                print(f"  [{i}] {подпись}")
            print("=" * 60)
            while True:
                a = input("> ").strip()
                if a.isdigit() and 1 <= int(a) <= len(варианты):
                    return варианты[int(a) - 1][0]
        self._event.clear()
        self._menu_choice = ""
        self.ui_menu(title, message, варианты, company)
        self._event.wait()                 # ЖДЁМ человека, сколько понадобится
        return self._menu_choice

    def require(self, title: str, message: str, company: str = "") -> None:
        choice = self.ask(title, message, company)
        if choice is HumanChoice.SKIP:
            raise SkipCompany(title)
        if choice is HumanChoice.SKIP_GEO:
            raise SkipGeo(title)
        if choice is HumanChoice.ABORT:
            raise AbortRun(title)

    # --- типовые поводы ---
    def captcha(self, company: str = "") -> None:
        self.require("Капча", "Сайт показал капчу.\n"
                              "Реши её в окне браузера и нажми «Продолжить».", company)

    def login(self, site: str, company: str = "") -> None:
        self.require("Нужен вход в систему",
                     f"Сайт {site} требует авторизацию.\n"
                     "Залогинься в окне браузера и нажми «Продолжить».\n"
                     "Сессия сохранится — для следующих фирм логин не понадобится.", company)

    def choose(self, company: str, candidates: list[str],
               наш_адрес: str = "") -> None:
        """
        Выбор из нескольких кандидатов.

        НАШ АДРЕС показываем обязательно: без него вопрос «который из них?»
        неотвечаем — человек видит список чужих названий и не знает, с чем
        сравнивать. Ставим его ПЕРВОЙ строкой, до списка.
        """
        lines = "\n".join(f"  {i+1}. {c}" for i, c in enumerate(candidates[:10]))
        шапка = f"Наша фирма: {company}\n"
        if наш_адрес:
            шапка += f"Наш адрес:  {наш_адрес}\n"
        self.require("Неоднозначное совпадение",
                     f"{шапка}\nНайдено кандидатов: {len(candidates)}\n\n{lines}\n\n"
                     "Открой нужную фирму в браузере и нажми «Продолжить».\n"
                     "Подходящей нет — «Пропустить».", company)

    def нет_совпадений(self, company: str, наш_адрес: str,
                       кандидаты: list[str]) -> None:
        """
        Похожего не нашлось ни одним запросом — РЕШАЕТ ЧЕЛОВЕК, а не мы.

        Раньше в этом месте фирма выбрасывалась молча и вдобавок помечалась
        непригодной НАВСЕГДА. Но «ничего не нашлось» часто значит «не так
        спросили»: реестры пишут имена не как DnB. Цена ошибки — потерянная
        живая фирма, которую больше никогда не предложат. Поэтому спрашиваем.
        """
        шапка = f"Наша фирма: {company}\n"
        if наш_адрес:
            шапка += f"Наш адрес:  {наш_адрес}\n"
        # ПОМЕЧАЕМ ПОВОД ДО ВОПРОСА. В автономном режиме шлюз отвечает
        # «пропустить» сам, и наружу летит SkipCompany — по ней не отличить
        # «фирмы нет в реестре» от «человек нажал пропустить на другом
        # вопросе». А разница есть: первую надо отложить в ящик и переспросить
        # местное написание, вторую — не трогать.
        self.повод = "не нашёл"
        если_есть = ("\n\nЧто реестр показал (ничего похожего):\n"
                     + "\n".join(f"  {i+1}. {к}" for i, к in enumerate(кандидаты))
                     ) if кандидаты else "\n\nРеестр не показал вообще ничего."
        self.require(
            "Не нашёл фирму в реестре",
            шапка + "Пробовал полное имя, имя без правовой формы и по первым "
                    "словам — похожего нет." + если_есть +
            "\n\nПосмотри сам: нашёл — открой карточку в браузере и «Продолжить».\n"
            "Действительно нет — «Пропустить фирму».", company)

    def stuck(self, what: str, company: str = "") -> None:
        self.require("Скрипт застрял",
                     f"Не удалось выполнить шаг: {what}\n\n"
                     "Доведи его руками и нажми «Продолжить», либо «Пропустить».", company)

    def сайт_не_отвечает(self, гео: str, адрес: str, company: str = "") -> None:
        """
        Реестр не открылся — это лежащий сайт, а не наша поломка.

        Отдельный повод, потому что ответ на него другой. На «скрипт застрял»
        человек пытается доделать шаг руками; здесь делать нечего — сайта нет,
        и правильный ход почти всегда «пропустить страну». Так и пишем прямо:
        на австрийском gisa.gv.at это повторялось прогон за прогоном и каждый
        раз выглядело как ошибка скрипта.
        """
        self.require(
            f"Реестр {гео} не отвечает",
            f"Не открылась страница реестра:\n{адрес}\n\n"
            "Обычно это значит, что сайт лежит или закрыт для нас — со стороны "
            "скрипта тут делать нечего.\n\n"
            "• Открылся у тебя в браузере → «Продолжить»\n"
            "• Нет → «Пропустить всю страну», вернёмся к ней позже.", company)

    def _console(self, title: str, message: str, company: str) -> HumanChoice:
        print("\n" + "=" * 60)
        print(f"ТРЕБУЕТСЯ ЧЕЛОВЕК: {title}")
        if company:
            print(f"Фирма: {company}")
        print(message + "\n" + "=" * 60)
        while True:
            a = input("[1] продолжить  [2] пропустить  [3] стоп > ").strip()
            if a == "1":
                return HumanChoice.CONTINUE
            if a == "2":
                return HumanChoice.SKIP
            if a == "3":
                return HumanChoice.ABORT
