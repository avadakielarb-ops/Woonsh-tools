"""
ПЕРЕХОДНИК ПО ЗАГОЛОВКАМ: где на ЭТОМ листе нужная колонка.

Зачем. Код в нескольких местах знал номера наизусть: «Гео» — двенадцатая,
«Организация» — третья, «Файл выписки» — десятая. Пока лист один, это работает.
Но у пользователя 97 листов и ПЯТНАДЦАТЬ разных наборов колонок: где-то есть
«Штат», где-то «Название BG», где-то шапки нет вовсе. Любая вставленная колонка
сдвигает всё, что правее, и код молча пишет фирму в соседнюю ячейку. Молча —
это и есть худшее: ошибка всплывает через неделю в чужой выписке.

Теперь код не знает номеров. Он спрашивает: «где Организация?» — и получает
ответ ДЛЯ ЭТОГО ЛИСТА.

ПОЧЕМУ ЕСТЬ ЗАПАСНОЙ НОМЕР. Часть старых листов вообще без шапки (нашлось 23
таких) или с мусором в первой строке. Раньше код работал на них по номерам — и
работал верно. Поэтому `номер()` принимает запасной номер: не нашли заголовок —
ведём себя ровно как раньше. Так переход ничего не ломает: поведение меняется
ТОЛЬКО там, где заголовок есть и стоит не на своём историческом месте, то есть
ровно в том случае, ради которого всё и затевалось.

Запасной номер НЕ подставляется сам по себе — его передаёт вызывающий код,
и рядом видно, какое наследство он покрывает. Для «Гео» запасного нет намеренно:
на обычном листе этой колонки не существует, и выдумывать её нельзя.
"""
from __future__ import annotations

# Одно и то же поле в разных листах называли по-разному. Сравниваем в
# нормализованном виде: регистр, «ё», пробелы и знаки роли не играют.
СИНОНИМЫ: dict[str, tuple[str, ...]] = {
    "№": ("№", "n", "номер", "nn"),
    "Платёжный профиль": ("платежный профиль", "профиль",
                          "платежная информация", "payinfo"),
    "Организация": ("организация", "название", "компания", "фирма",
                    "name", "company"),
    "Адрес": ("адрес", "адрес line 1", "address", "street"),
    "Город": ("город", "city"),
    "Индекс": ("индекс", "почтовый индекс", "zip", "postcode", "post code"),
    "Штат": ("штат", "область", "регион", "state", "region"),
    "Website": ("website", "сайт", "вебсайт", "веб-сайт", "web"),
    "Номер в реестре": ("номер в реестре", "рег номер", "регистрационный номер",
                        "reg number", "registry number"),
    "Файл выписки": ("файл выписки", "выписка", "файл"),
    "Платёжный профиль выписки": ("платежный профиль выписки",
                                  "профиль выписки", "адрес по выписке"),
    "Гео": ("гео", "geo", "страна", "country"),
    # Колонки, появившиеся позже. Без них переходник отвечал «такой колонки
    # нет» на заголовок, который прямо стоит в шапке, и код молча уезжал на
    # запасной номер — то есть ровно та беда, ради которой переходник и писан.
    "Слово": ("слово", "по слову", "keyword", "word"),
    "ID": ("id", "ид", "номер фирмы"),
}


def нормализовать(значение) -> str:
    """
    Заголовок к сравнимому виду: «Платёжный  Профиль» → «платежныйпрофиль».

    Убираем всё, кроме букв и цифр: в шапках встречались неразрывные пробелы,
    двойные пробелы и висящие двоеточия — на глаз одинаково, для сравнения нет.
    «№» оставляем: это единственный знак, который сам по себе означает колонку.
    """
    т = str(значение or "").strip().lower().replace("ё", "е")
    return "".join(с for с in т if с.isalnum() or с == "№")


_ПО_СИНОНИМУ = {нормализовать(с): канон
                for канон, синонимы in СИНОНИМЫ.items()
                for с in синонимы}
# само каноническое имя тоже считается синонимом самого себя
_ПО_СИНОНИМУ.update({нормализовать(к): к for к in СИНОНИМЫ})


class Шапка:
    """
    Карта «канонический заголовок → номер колонки» для одного листа.

    Строится ОДИН раз при открытии листа: читать первую строку на каждое
    обращение — это тысячи лишних чтений на прогоне в сто пятьдесят фирм.
    """

    ШИРИНА = 40        # дальше сорокового столбца шапки не встречалось

    def __init__(self, ws, ширина: int | None = None):
        self.лист = getattr(ws, "title", "?")
        self._номера: dict[str, int] = {}
        self._сырые: dict[str, int] = {}
        предел = min(ширина or self.ШИРИНА, self.ШИРИНА)
        # ЧИТАЕМ ЧЕРЕЗ iter_rows, а не ws.cell: книгу открывают и в режиме
        # read_only (там cell() недоступен), и обычным. Через iter_rows шапка
        # читается одинаково в обоих, иначе половина проверок молча получала бы
        # пустую карту и уезжала на запасные номера.
        строка = next(ws.iter_rows(min_row=1, max_row=1), ())
        for c, ячейка in enumerate(строка, 1):
            if c > предел:
                break
            н = нормализовать(getattr(ячейка, "value", None))
            if not н:
                continue
            self._сырые.setdefault(н, c)
            канон = _ПО_СИНОНИМУ.get(н)
            # ПЕРВОЕ вхождение выигрывает: если человек продублировал колонку,
            # работаем с той, что левее — она и есть исходная.
            if канон and канон not in self._номера:
                self._номера[канон] = c

    # ---------- чтение ----------

    def есть(self, имя: str) -> bool:
        return имя in self._номера

    def номер(self, имя: str, запасной: int = 0) -> int:
        """
        Номер колонки. Не нашли заголовок — запасной (0 = «нет такой»).

        Запасной передаёт вызывающий код: это его историческое поведение,
        а не догадка переходника.
        """
        return self._номера.get(имя, запасной)

    def нужен(self, имя: str, запасной: int = 0) -> int:
        """То же, но без колонки работать нельзя — говорим об этом внятно."""
        н = self.номер(имя, запасной)
        if not н:
            есть = ", ".join(sorted(self._сырые)) or "(шапки нет)"
            raise RuntimeError(
                f"На листе «{self.лист}» нет колонки «{имя}».\n"
                f"Что нашёл в шапке: {есть}")
        return н

    def все(self) -> dict[str, int]:
        return dict(self._номера)

    def ширина(self) -> int:
        """Самая правая занятая колонка шапки (0 — шапки нет)."""
        return max(self._сырые.values(), default=0)
