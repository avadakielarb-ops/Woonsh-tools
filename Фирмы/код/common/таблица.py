"""
ДВЕРЬ В GOOGLE ТАБЛИЦУ. Тонкий клиент к скрипту таблицы (доки/таблица_скрипт.js).

ПОЧЕМУ ЧЕРЕЗ APPS SCRIPT, А НЕ ЧЕРЕЗ SHEETS API. Sheets API требует сервисного
аккаунта в Google Cloud, JSON-ключа на диске и упирается в квоту ~60 записей в
минуту. Скрипт, привязанный к таблице, работает от имени владельца, пишет
пачками за один вызов и не требует ни облачного проекта, ни ключей на диске.
У пользователя весь остальной парк (ВуншПунш, бот) и так на Apps Script.

ПОЧЕМУ ТОЛЬКО stdlib. Ради одного POST тянуть requests незачем — в проекте уже
есть тот же подход в part1/слова_gemini.py.

РЕЖИМ РАБОТЫ — вариант Б, выбранный пользователем: прогон пишет ЛОКАЛЬНО и
только в конце выгружает пачкой сюда. Поэтому здесь нет ни ретраев на каждую
строку, ни фонового потока: одна выгрузка, один ответ, понятная ошибка.
Побочный эффект, о котором договорились: пока прогон идёт, таблица не меняется.

АДРЕС И КЛЮЧ НЕ В КОДЕ. Они лежат в данные/ключи.json, который в .gitignore:
URL развёртывания открыт «для всех», то есть сам по себе является паролем.
"""
from __future__ import annotations

import json
import time
import urllib.error
import urllib.parse
import urllib.request

from common import пути
from common.пути import данные

ФАЙЛ_КЛЮЧЕЙ = данные("ключи.json")
ТАЙМАУТ = 120          # Apps Script на большой пачке думает секунды, не мгновенно

# ПОЛИГОН В ТАБЛИЦУ НЕ ПИШЕТ — правило пользователя, и держать его надо в
# ОДНОМ месте. Раньше запрет стоял в выгрузке, но выгрузка не единственная,
# кто пишет: есть и разовые скрипты, и статистика слов, и раздача номеров.
# Проверять в каждом — значит однажды завести новый и забыть.
#
# Признак полигона — файл «полигон» в папке данных: он есть только там.
# ЧТО МЕНЯЕТ ТАБЛИЦУ. Полигону это запрещено — он работает на копии кода, но
# таблица у него та же, живая. «перенести», «дубли_строк» и «убрать_строки»
# тут раньше не значились, хотя переносят и УДАЛЯЮТ строки: список собирали
# по именам действий, а эти появились позже и остались мимо.
ПИШУЩИЕ = {"создать", "дописать", "отработать", "обновить", "сортировать",
           "слова", "ид", "порядок", "перенести", "переставить",
           "дубли_строк", "убрать_строки", "статусы"}


class НетДоступа(RuntimeError):
    """Не настроен адрес/ключ таблицы, либо скрипт не отвечает как надо."""


def настройки(path=ФАЙЛ_КЛЮЧЕЙ) -> tuple[str, str]:
    """(адрес, ключ) из ключи.json. utf-8-sig — PowerShell пишет файлы с BOM."""
    try:
        д = json.loads(path.read_text(encoding="utf-8-sig"))
    except FileNotFoundError:
        raise НетДоступа(f"нет файла {path}") from None
    except Exception as e:
        raise НетДоступа(f"{path} не читается: {e}") from e
    адрес = (д.get("таблица_url") or "").strip()
    ключ = (д.get("таблица_ключ") or "").strip()
    if not адрес or not ключ:
        raise НетДоступа(
            f"в {path} нужны «таблица_url» и «таблица_ключ».\n"
            "URL — из «Развернуть → Управление развёртываниями», "
            "ключ — строка ФИРМЫ_КЛЮЧ из скрипта таблицы.")
    return адрес, ключ


def настроена() -> bool:
    """Есть ли вообще настройки. Нужна, чтобы приложение не падало без них."""
    try:
        настройки()
        return True
    except НетДоступа:
        return False


def _разобрать(сырое: str) -> dict:
    """
    Ответ скрипта. Он обязан быть JSON; HTML означает беду, и её надо назвать.

    Три типовые беды, каждую видно по телу ответа, и каждая лечится по-разному —
    поэтому разбираем их отдельно, а не «скрипт не ответил».
    """
    низ = (сырое or "")[:600].lower()
    if "accounts.google.com" in низ or "signin" in низ:
        raise НетДоступа(
            "развёртывание требует входа. Открой «Управление развёртываниями» → "
            "карандаш → «У кого есть доступ: Все» → Развернуть.")
    if "doget" in низ and ("not found" in низ or "не знайдено" in низ
                           or "не найдена" in низ):
        raise НетДоступа(
            "в скрипте таблицы нет doGet — вставь доки/таблица_скрипт.js "
            "и переразверни НОВОЙ ВЕРСИЕЙ.")
    try:
        return json.loads(сырое)
    except Exception:
        raise НетДоступа(f"скрипт ответил не JSON: {(сырое or '')[:200]}") from None


def _вызов(действие: str, тело: dict | None = None, тайм: int = ТАЙМАУТ) -> dict:
    """
    Один вызов скрипта. Данные шлём POST-ом: длина GET-адреса ограничена, а
    пачка строк туда не влезет.

    Про редирект. Apps Script отвечает на POST перекладкой на
    script.googleusercontent.com, и urllib идёт туда уже GET-ом. Это НОРМАЛЬНО:
    запрос скрипт отработал на первом шаге, по второму адресу лежит готовый
    ответ. Ломается только если выключить следование редиректам.
    """
    if действие in ПИШУЩИЕ and пути.это_полигон():
        raise НетДоступа(
            f"это ПОЛИГОН — писать в таблицу ему нельзя (действие «{действие}»). "
            "Так задумано: иначе в таблице смешаются боевые фирмы и мусор "
            "проверок, и доверять ей станет нельзя.")
    адрес, ключ = настройки()
    полное = dict(тело or {})
    полное.update({"action": действие, "key": ключ})
    запрос = urllib.request.Request(
        адрес, data=json.dumps(полное, ensure_ascii=False).encode("utf-8"),
        method="POST", headers={"Content-Type": "application/json"})

    # ПОВТОРЯЕМ ПРИ ОБРЫВЕ СЕТИ. Замер 08.09.2026: чтение таблицы упало на
    # середине с RemoteDisconnected — просто моргнула связь. Для выгрузки в
    # конце прогона это недопустимо: сорок минут работы нельзя терять из-за
    # одного разорванного соединения. Ошибки САМОГО скрипта (нет ключа, нет
    # листа) не повторяем — они от повтора не исправятся.
    последняя: Exception | None = None
    for попытка in range(3):
        try:
            with urllib.request.urlopen(запрос, timeout=тайм) as r:
                ответ = _разобрать(r.read().decode("utf-8", "replace"))
            break
        except urllib.error.HTTPError as e:
            ответ = _разобрать(e.read().decode("utf-8", "replace"))
            break
        except НетДоступа:
            raise
        except Exception as e:
            последняя = e
            if попытка < 2:
                time.sleep(2 * (попытка + 1))
    else:
        raise НетДоступа(
            f"таблица недоступна после трёх попыток: "
            f"{type(последняя).__name__}: {последняя}") from последняя
    if not ответ.get("ok"):
        raise НетДоступа(f"скрипт отказал: {ответ.get('ошибка') or ответ}")
    return ответ


# ---------- то, что вызывает приложение ----------

def пинг() -> dict:
    """Живо ли соединение. Возвращает имя таблицы и число листов."""
    return _вызов("ping", тайм=45)


def схема() -> list[dict]:
    """Все листы: имя, скрыт ли, сколько строк, что в шапке."""
    return _вызов("схема", тайм=60)["листы"]


def читать(лист: str, сколько: int = 50, всё: bool = False) -> list[list[str]]:
    """
    Первые строки листа как есть — вместе с шапкой.

    всё=True — «мне нужен весь лист, неполный ответ не годится». Тогда обрезка
    поднимается ошибкой. Так проверяется единственное место, где недобор
    смертелен: список известных фирм. Замер 09.09.2026 — скрипт молча отдавал
    первые 500 строк «Реестра» из 2793, и всё, что дальше, каждый прогон
    считал новым и дописывал второй раз.
    """
    ответ = _вызов("читать", {"лист": лист, "сколько": сколько})
    if всё and ответ.get("обрезано"):
        raise НетДоступа(
            f"лист «{лист}» не влез в один ответ (просили {сколько} строк). "
            "Читать частями скрипт пока не умеет — увеличь потолок в _фЧитать.")
    return ответ["строки"]


def всё(листы: list[str] | None = None, служебные: bool = False,
        сколько: int = 20000) -> list[dict]:
    """
    ВСЯ таблица одним запросом: [{имя, скрыт, строк, строки}, …].

    Строки идут вместе с шапкой, как у «читать», — разбор на местах не
    меняется. Замер 10.09.2026: обход по листу за раз стоил 137 секунд
    (схема 23 с + 43 листа по 2,6). Одним запросом — секунды.

    служебные=False по умолчанию: «Реестр» и «Отработано» нужны не всем, а
    весят тысячи строк. Кому надо — просит явно.
    """
    о = _вызов("всё", {"листы": list(листы or []), "служебные": служебные,
                       "сколько": сколько}, тайм=300)
    if о.get("обрезано"):
        raise НетДоступа(
            f"таблица не влезла в один ответ (просили {сколько} строк на лист). "
            "Читай частями через «читать».")
    return о["листы"]


def создать(гео: list[str] | None = None) -> dict:
    """
    Завести недостающие листы. Существующие не трогает — можно звать повторно.
    гео — коды стран; на каждый заводится «EE» и «EE.БС».
    """
    return _вызов("создать", {"гео": list(гео or [])})


def лист_слов(строки: list[list]) -> int:
    """
    Записать сводку выхлопа по словам. Лист «Слова» перезаписывается ЦЕЛИКОМ.

    Это картина, а не журнал: дописывание оставило бы одно слово в пяти
    строках с разными цифрами, и верной была бы только последняя.
    """
    return _вызов("слова", {"строки": строки}, тайм=180).get("записано", 0)


def проставить_ид(листы: list[str] | None = None,
                  реестр: dict[str, str] | None = None) -> dict:
    """
    Выдать постоянные номера строкам, у которых их ещё нет.

    Повторный вызов безопасен: уже выданные номера не трогаются. Считает и
    пишет сам скрипт — гонять две с половиной тысячи строк туда-обратно ради
    одной колонки незачем.

    реестр — {'EE|ALTMER ENERGY': 'EE-7QK4M2'}: чем связать строки «Реестра» с
    их номерами на листах. Карту считает Python, потому что ключ реестра
    построен на НОРМАЛИЗОВАННОМ имени, а правила нормализации есть только тут.
    """
    тело: dict = {"листы": list(листы or [])}
    if реестр:
        тело["реестр"] = реестр
    return _вызов("ид", тело, тайм=300)


def переставить(листы: list[str] | None = None) -> dict:
    """
    Привести колонки листов к нынешней раскладке.

    Нужно после того, как порядок колонок изменился: скрипт кладёт строку
    слева направо, и в лист со старым порядком данные лягут мимо — адрес в
    город. Двигаются ДАННЫЕ по заголовкам, а не колонки; чужие колонки, если
    человек их добавил, уезжают в конец, а не теряются.
    """
    return _вызов("переставить", {"листы": list(листы or [])}, тайм=300)


def статусы() -> dict:
    """
    Обновить выпадающий список статусов на всех листах таблицы.

    Правило проверки данных живёт В ТАБЛИЦЕ и ставится один раз, при заведении
    листа. Добавили в лестницу ступень — сорок листов всё ещё требуют старый
    набор, и запись падает с «в ячейке A24 нарушены правила проверки данных».
    """
    return _вызов("статусы", {}, тайм=300)


def дубли_строк(примерка: bool = True) -> dict:
    """
    Убрать строки-близнецы: одна фирма записана дважды под ОДНИМ номером.

    Беда не только в лишнем месте. Правка находит ТОЛЬКО ПЕРВУЮ строку с
    нужным номером, и вторая навсегда остаётся такой, какой записалась.
    Нашлось это так: дозапись платёжек отчиталась «389 из 389», а 389 строк
    AU.БС остались пустыми — у них был тот же номер, что у соседей выше.

    примерка=True — только посчитать. Строки удаляются насовсем, поэтому
    сначала смотрим.
    """
    return _вызов("дубли_строк", {"примерка": bool(примерка)}, тайм=300)


def убрать_строки(лист: str, ид: list[str], примерка: bool = True,
                  пачка: int = 200) -> dict:
    """
    Убрать С ЭТОГО ЛИСТА строки с такими номерами фирм.

    Нужно там, где «дубли_строк» бессилен: тот чистит повторы ВНУТРИ листа и
    оставляет первую строку, а межлистовой близнец — случай, где лишнюю
    выбирают по смыслу, а не по порядку. Замер 23.09.2026: 729 фирм лежали и
    на «Мультигео», и на листе своей страны, 1265 лишних строк; правка
    статуса попадала в одну из них, вторая оставалась со старой.

    По умолчанию ПРИМЕРКА — удаление строк необратимо.
    """
    итог = {"убрано": 0, "примерка": примерка}
    for i in range(0, len(ид), пачка):
        о = _вызов("убрать_строки",
                   {"лист": лист, "ид": ид[i:i + пачка],
                    "примерка": bool(примерка)}, тайм=300)
        итог["убрано"] += о.get("убрано", 0)
    return итог


def перенести(куда: str, ид: list[str], пачка: int = 200) -> dict:
    """
    Перенести строки на другой лист ПО НОМЕРАМ ФИРМ.

    Нужно, когда строки легли не туда: заново эти фирмы уже не найдутся — они
    помечены в «Реестре» как виденные. Ищем строго по ID: имя повторяется,
    номер нет.
    """
    итог = {"перенесено": 0, "листы": []}
    for i in range(0, len(ид), пачка):
        о = _вызов("перенести", {"куда": куда, "ид": ид[i:i + пачка]}, тайм=300)
        итог["перенесено"] += о.get("перенесено", 0)
        итог["листы"] += list(о.get("листы") or [])
    return итог


def сортировать(лист: str, по: list[str] | None = None) -> int:
    """
    Отсортировать лист: по умолчанию гео, потом организация.
    Освобождённые места (строки без организации) уходят вниз.
    """
    о = _вызов("сортировать",
               {"лист": лист, "по": по or ["Гео", "Организация"]}, тайм=180)
    return о.get("отсортировано", 0)


def отработать(отметки: list[dict], дата: str = "", пачка: int = 200,
               сохранять_статус: bool = False) -> dict:
    """
    Убрать фирмы с рабочих листов на скрытый «Отработано».

    отметки — [{'лист': 'UK', 'орг': 'BRONZE LAND LTD', 'ид': 'UK-7QK4M2'}, …].
    «ид» необязателен, но если он есть — ищут по нему: имя фирмы могло
    поменяться, номер не меняется никогда. Строка уезжает целиком:
    отработанное не мешает в работе, но помнится, иначе следующий прогон
    найдёт ту же фирму заново.

    сохранять_статус — НЕ помечать «отработано», а оставить как есть. Нужно
    для «якорей»: ликвидированных, ненайденных, с красным флагом. Они тоже
    должны исчезнуть из работы, но пометить их отработанными значит соврать —
    завтра не отличишь «сделали» от «не годится».

    Пачками, потому что скрипт удаляет строки по одной, а это самая долгая
    операция в Таблицах.
    """
    итог = {"помечено": 0, "не_нашлось": []}
    for i in range(0, len(отметки), пачка):
        о = _вызов("отработать", {"отметки": отметки[i:i + пачка], "дата": дата,
                                  "сохранять_статус": сохранять_статус})
        итог["помечено"] += о.get("помечено", 0)
        итог["не_нашлось"] += о.get("не_нашлось", [])
    return итог


def обновить(правки: list[dict], пачка: int = 150) -> dict:
    """
    Поправить отдельные клетки существующих строк.

    правки — [{'лист': 'EE', 'орг': 'Altmer Energy OU', 'ид': 'EE-7QK4M2',
               'поля': {'Файл выписки': 'Altmer Energy OÜ.pdf'}}, …]
    Меняются ТОЛЬКО названные колонки: остальное человек мог править руками.

    «ид» необязателен и ищется первым. Пример выше — как раз тот случай, ради
    которого номер и заводился: в листе имя с dnb («OU»), а Часть 2 знает имя
    из реестра («OÜ»), и по имени такая строка не находится.

    Пачки мельче, чем при дописывании: скрипт трогает клетки по одной, а это
    в Таблицах на порядок медленнее, чем запись блоком.
    """
    итог = {"обновлено": 0, "не_нашлось": []}
    for i in range(0, len(правки), пачка):
        о = _вызов("обновить", {"правки": правки[i:i + пачка]})
        итог["обновлено"] += о.get("обновлено", 0)
        итог["не_нашлось"] += о.get("не_нашлось", [])
    return итог


def порядок() -> list[str]:
    """Разложить вкладки по алфавиту, служебные — в конец."""
    return _вызов("порядок", тайм=180).get("порядок", [])


def дописать(лист: str, строки: list[list], пачка: int = 400) -> int:
    """
    Дописать строки в конец листа. Возвращает, сколько добавили.

    Режем на пачки: у Apps Script один вызов ограничен шестью минутами, и
    полторы тысячи строк одним куском — верный способ поймать таймаут ровно в
    тот момент, когда прогон уже отработал и результат ещё не сохранён.
    """
    всего = 0
    for i in range(0, len(строки), пачка):
        кусок = строки[i:i + пачка]
        if not кусок:
            continue
        всего += _вызов("дописать", {"лист": лист, "строки": кусок}).get("добавлено", 0)
    return всего
