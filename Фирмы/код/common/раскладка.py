r"""
РАСКЛАДКА РАБОЧЕГО ЛИСТА — ОДНА НА ВЕСЬ ПРОЕКТ.

Список колонок был написан в четырёх местах: скрипт таблицы, перенос, живая
дозапись, наряд на выписки. Пока он не менялся, это сходило с рук. Но стоило
переставить одну колонку — и четыре копии разъезжаются, а строки начинают
ложиться мимо: адрес в город, сайт в номер реестра. Молча.

Здесь список ОДИН, и рядом — способ обращаться к полю ПО ИМЕНИ. Позиции в
коде больше не пишем: «строка[10]» переживает ровно до первой перестановки,
и понять, что сломалось, потом невозможно.
"""
from __future__ import annotations

# ПОРЯДОК ЗНАЧИМ: строки уходят в таблицу списком, и скрипт кладёт их слева
# направо. «Платёжный профиль выписки» стоит ТРЕТЬИМ по прямой просьбе
# пользователя: это то, что он копирует в работу каждый день, и лазить за ним
# в двенадцатую колонку — лишнее движение на каждой фирме.
КОЛОНКИ = [
    "Статус",                      # A  выпадающий список
    "№",                           # B  сходится с локальным Excel
    "Платёжный профиль выписки",   # C  ← то, что берут в работу
    "Платёжный профиль",           # D  как его дал dnb
    "Организация",                 # E
    "Адрес",                       # F
    "Город",                       # G
    "Индекс",                      # H
    "Штат",                        # I  только US/AU
    "Website",                     # J
    "Номер в реестре",             # K  заполняет Часть 2
    "Файл выписки",                # L  имя файла ЛИБО причина отказа
    "Гео",                         # M
    "Дата",                        # N
    "Слово",                       # O  по какому слову найдена
    "Исходное с dnb",              # P  НЕ перезаписывается никогда
    "ID",                          # Q  постоянный номер фирмы
]

# Ширины столбцов — в том же порядке, чтобы не разъезжались вместе с ним.
ШИРИНЫ = [110, 45, 320, 320, 260, 220, 130, 90, 120, 200, 130, 240,
          60, 90, 110, 320, 100]

_НОМЕР = {имя: i for i, имя in enumerate(КОЛОНКИ)}


def номер(поле: str) -> int:
    """Место колонки в строке. Нет такой — внятная ошибка, а не тихий сдвиг."""
    if поле not in _НОМЕР:
        raise KeyError(f"нет колонки «{поле}». Есть: {', '.join(КОЛОНКИ)}")
    return _НОМЕР[поле]


def взять(строка: list, поле: str, иначе: str = "") -> str:
    """Значение поля ПО ИМЕНИ. Короче строка — отдаём «иначе», не падаем."""
    i = номер(поле)
    if i >= len(строка) or строка[i] is None:
        return иначе
    return str(строка[i]).strip()


def собрать(значения: dict) -> list:
    """Строка для таблицы из словаря «имя колонки → значение»."""
    return [значения.get(имя, "") for имя in КОЛОНКИ]
