"""
СТАТУС = СТУПЕНЬ ЛЕСТНИЦЫ, и ничего больше. Одно место на весь проект.

Лестница фирмы:

    найдена  →  выписка  →  годная  →  отработано
                    ↘ нет выписки (реестр отказал, но фирма жива)
                    ↘ отклонена   (бот сказал «уже есть»)
                    ↘ брак        (форма не годится, ликвидирована)
                    ↘ спорная     (не смогли выбрать сами)

ПОЧЕМУ ПРИШЛОСЬ РАЗВОДИТЬ. В колонке «Статус» лежали вперемешку ступень
(«отработано») и причина отказа («брак», «дубль», «нет выписки»), а лист
«Отработано» отвечал сразу на два несовместимых вопроса: «фирму отдали» и
«фирма не годится». Замер 16.09.2026: 321 строка архива — 248 отданных,
54 без выписки, 12 брака, 6 дублей и одна случайная. Посчитать выработку по
такому листу нельзя, вернуть фирму в работу тоже.

ЧТО ГДЕ ЛЕЖИТ. Живое остаётся на листе гео — в том числе «нет выписки»:
сегодня реестр молчал, завтра отдаст, и уводить такую строку в архив рано.
Уезжают только два конца: отданное — на «Отработано», непригодное — на
«Недостойные».

«дубль» — прежнее написание «отклонена». Старые строки его сохраняют, новые
не пишут: смысл один, а два слова про одно — это два места, где однажды
забудут поправить.
"""
from __future__ import annotations

ДОКУМЕНТЫ = (".pdf", ".docx")

НАЙДЕНА = "найдена"          # фирма есть, выписки нет
ВЫПИСКА = "выписка"          # файл скачан, бот его не видел
ГОДНАЯ = "годная"            # бот подтвердил — можно брать в работу
НЕТ_ВЫПИСКИ = "нет выписки"  # реестр отказал; причина рядом, в «Файле выписки»
СПОРНАЯ = "спорная"          # сами выбрать не смогли, человек не смотрел
ОТКЛОНЕНА = "отклонена"      # бот сказал «уже есть»
ДУБЛЬ = "дубль"              # прежнее написание «отклонена»
БРАК = "брак"                # форма не годится, ликвидирована — навсегда
ОТРАБОТАНО = "отработано"    # ушла фармеру

# Лист-архив для каждого из двух концов.
ОТРАБОТАНО_ЛИСТ = "Отработано"
НЕДОСТОЙНЫЕ = "Недостойные"

# Живые ступени: строка лежит на листе своего гео и участвует в работе.
ЖИВЫЕ = {НАЙДЕНА, ВЫПИСКА, ГОДНАЯ, НЕТ_ВЫПИСКИ, СПОРНАЯ, ""}

# Закрытые: фирма из оборота вышла, спрашивать про неё больше нечего.
ЗАКРЫТЫЕ = {ОТКЛОНЕНА, ДУБЛЬ, БРАК, ОТРАБОТАНО}

# НЕ ВЫДАВАТЬ ФАРМЕРУ: закрытые плюс «нет выписки». Строка без выписки в
# работу не годится — отдавать нечего, — но и занимать место, которое должно
# уйти под замену, она не должна.
НЕ_ВЫДАВАТЬ = ЗАКРЫТЫЕ | {НЕТ_ВЫПИСКИ}

# НЕ СПРАШИВАТЬ БОТА ПОВТОРНО: закрытые и уже подтверждённые. «Нет выписки»
# спрашивать можно — это линия «без выписок».
НЕ_СПРАШИВАТЬ_БОТА = ЗАКРЫТЫЕ | {ГОДНАЯ}

# Порядок для выпадающего списка в таблице — он же порядок лестницы.
# Тот же список живёт в Код.js (ФИРМЫ_СТАТУСЫ) — сверяет тест_статус.
ВСЕ = [НАЙДЕНА, ВЫПИСКА, ГОДНАЯ, НЕТ_ВЫПИСКИ, СПОРНАЯ,
       ОТКЛОНЕНА, БРАК, ОТРАБОТАНО, ДУБЛЬ]


def есть_выписка(значение: str) -> bool:
    """
    В колонке «Файл выписки» лежит либо имя файла, либо ПРИЧИНА отказа.

    Различаем по расширению: «Altmer OU.pdf» — выписка, «ликвидирована» —
    причина. Путать нельзя: по причине качать надо заново, по файлу — нет.
    """
    return (значение or "").strip().lower().endswith(ДОКУМЕНТЫ)


def ступень(статус: str, файл: str = "") -> str:
    """
    Ступень строки — по статусу, а если его не проставили, то по фактам.

    Старые строки статуса не несут вовсе либо несут «найдена» и при скачанной
    выписке: Часть 1 писала «найдена» про ФИРМУ, Часть 2 тем же словом про
    ВЫПИСКУ. Пока миграция не прошла, читаем по факту наличия файла.
    """
    с = (статус or "").strip().lower()
    if с in ЗАКРЫТЫЕ:
        return ДУБЛЬ if с == ДУБЛЬ else с
    if с in (ГОДНАЯ, СПОРНАЯ, НЕТ_ВЫПИСКИ):
        return с
    return ВЫПИСКА if есть_выписка(файл) else НАЙДЕНА


def можно_в_работу(статус: str) -> bool:
    """Фирму можно отдавать фармеру? Только после подтверждения ботом."""
    return (статус or "").strip().lower() == ГОДНАЯ
