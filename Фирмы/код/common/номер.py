r"""
ПОСТОЯННЫЙ НОМЕР ФИРМЫ.

ЗАЧЕМ. Сегодня строка в таблице ищется по «Организации» — посимвольно. Это
работает ровно до первого расхождения, а расхождения неизбежны и законны:

  · Часть 2 берёт имя из РЕЕСТРА, а в листе лежит имя с dnb. «Altmer Energy OU»
    и «Altmer Energy OÜ» — одна фирма, но не одна строка;
  · человек поправил имя руками, убрал лишний пробел, дописал форму;
  · фирма переехала с листа гео в «Мультигео» или в «Отработано».

Каждый такой случай выпадает в «не_нашлось», и результат Части 2 просто не
доезжает до таблицы. Номер снимает вопрос: он присваивается один раз при
появлении фирмы и больше не меняется НИКОГДА, что бы ни случилось с именем.

ПОЧЕМУ НЕ ХЭШ ОТ ИМЕНИ. Хэш кажется удобнее — считается где угодно, одинаково
и без сговора. Но он умирает ровно там, где нужен: имя поменялось — поменялся
и хэш, то есть «постоянный» номер перестаёт быть постоянным именно в тот
момент, ради которого затевался.

ПОЧЕМУ НЕ СКВОЗНАЯ НУМЕРАЦИЯ. «Фирма №2511» требует, чтобы кто-то один знал
последний выданный номер. У нас пишут и приложение, и скрипт таблицы, и
разовые переносы — согласовывать счётчик между ними значит однажды выдать один
номер двум фирмам. Случайный номер такого места не имеет.

ВИД: «EE-7QK4M2» — гео и шесть знаков. Гео впереди не для машины, а для
человека: в логе «не нашлось EE-7QK4M2» сразу видно, чья это строка.

Алфавит без похожих знаков (0/O, 1/I/L): номер иногда переписывают глазами.
"""
from __future__ import annotations

import secrets

АЛФАВИТ = "23456789ABCDEFGHJKMNPQRSTUVWXYZ"       # без 0 O 1 I L
ДЛИНА = 6


def новый(гео: str = "", занятые: set[str] | None = None) -> str:
    """
    Свежий номер. занятые — уже выданные, чтобы не совпасть.

    Совпадение и без проверки почти невероятно (31⁶ — это 887 миллионов на
    несколько тысяч фирм), но «почти» тут ни к чему: список занятых у нас и
    так на руках — «Реестр» читается перед каждой выгрузкой.
    """
    занятые = занятые or set()
    п = (гео or "").strip().upper()[:2]
    for _ in range(50):
        хвост = "".join(secrets.choice(АЛФАВИТ) for _ in range(ДЛИНА))
        номер = f"{п}-{хвост}" if п else хвост
        if номер not in занятые:
            return номер
    # 50 подряд занятых — это не совпадение, а сломанный список занятых.
    raise RuntimeError("не смог выдать свободный номер фирмы")


def похож(значение: str) -> bool:
    """Похоже ли это на наш номер. Нужно, чтобы отличить его от мусора в клетке."""
    з = (значение or "").strip().upper()
    if "-" in з:
        гео, _, хвост = з.partition("-")
        if len(гео) != 2 or not гео.isalpha():
            return False
    else:
        хвост = з
    return len(хвост) == ДЛИНА and all(с in АЛФАВИТ for с in хвост)
