СЛУЖЕБНЫЕ_ЛИСТЫ = {"Лог", "Без сайта", "Нашли сайт"}


def _найти_столбец(ws, заголовок: str) -> int:
    """Номер столбца по заголовку в строке 1. Нет такого — 0. Ничего не создаёт."""
    return Шапка(ws).номер(заголовок)


def разбор_листа(excel: Path, sheet: str) -> list[dict]:
    """
    ОЦЕНКА ЛИСТА до старта: какие страны и на КАКИХ СТРОКАХ лежат.

    Возвращает блоки подряд идущих строк одной страны, в порядке листа:
      [{"гео": "FR", "первая": 2, "последняя": 11, "строки": [2..11]}, …]
    Обычно на страну один блок, но если Часть 1 писала в файл дважды, страна
    может встретиться несколькими кусками — тогда блоков будет несколько,
    и это видно в логе.
    """
    wb = load_workbook(excel, read_only=True)
    try:
        ws = wb[sheet]
        строки = ws.iter_rows(min_row=1, values_only=False)
        шапка = next(строки, None)
        if шапка is None:
            return []
        к = next((i for i, я in enumerate(шапка, 1) if я.value == ГЕО), 0)
        if not к:
            return []
        блоки: list[dict] = []
        for номер, r in enumerate(строки, start=2):
            з = str(r[к - 1].value or "").strip().upper() if len(r) >= к else ""
            if not з:
                continue
            if блоки and блоки[-1]["гео"] == з and блоки[-1]["последняя"] == номер - 1:
                блоки[-1]["последняя"] = номер
                блоки[-1]["строки"].append(номер)
            else:
                блоки.append({"гео": з, "первая": номер, "последняя": номер,
                              "строки": [номер]})
        return блоки
    finally:
        wb.close()


def мультилисты(excel: Path) -> list[str]:
    """
    Листы файла, с которыми Часть 2 умеет работать в режиме мультилиста —
    то есть те, у которых в шапке есть колонка «Гео». По остальным страну
    определять не по чему.
    """
    wb = load_workbook(excel, read_only=True)
    try:
        годные = []
        for имя in wb.sheetnames:
            if имя in СЛУЖЕБНЫЕ_ЛИСТЫ:
                continue
            шапка = next(wb[имя].iter_rows(min_row=1, max_row=1), ())
            if any((я.value or "") == ГЕО for я in шапка):
                годные.append(имя)
        return годные
    finally:
        wb.close()


def гео_на_листе(excel: Path, sheet: str) -> list[str]:
    """Страны листа в порядке первого появления."""
    порядок: list[str] = []
    for б in разбор_листа(excel, sheet):
        if б["гео"] not in порядок:
            порядок.append(б["гео"])
    return порядок


def _проверить_гео(excel: Path, sheet: str, гео: str, ожидалось: list[int],
                   папка: Path, итог: dict, log) -> list[str]:
    """
    ПРОВЕРКА ПОСЛЕ СТРАНЫ: то ли качали и туда ли положили.

    Сверяем три вещи:
      1) сколько строк этой страны на листе  vs  сколько взял прогон;
      2) сколько строк получили «Файл выписки» — и все ли они этой страны;
      3) сколько файлов реально лежит в папке страны.
    Возвращает список замечаний (пусто — всё сошлось).
    """
    замечания: list[str] = []
    wb = load_workbook(excel, read_only=True)
    try:
        ws = wb[sheet]
        ш = Шапка(ws)
        к_гео = ш.номер(ГЕО)
        к_файл = ш.номер("Файл выписки", СТОЛБЕЦ_ФАЙЛ)
        заполнено, чужие = 0, []
        for r in ws.iter_rows(min_row=2, min_col=1, max_col=max(к_гео, к_файл)):
            файл = r[к_файл - 1].value if len(r) >= к_файл else None
            з = str(r[к_гео - 1].value or "").strip().upper() if к_гео else ""
            if файл and з == гео.upper():
                заполнено += 1
                if r[0].row not in ожидалось:
                    чужие.append(r[0].row)
    finally:
        wb.close()

    файлов = len([p for p in папка.glob("*.pdf")]) if папка.exists() else 0
    взято = итог.get("всего", 0)
    скачано = итог.get("скачано", 0)

    log(f"  ПРОВЕРКА {гео}:")
    log(f"    строк на листе: {len(ожидалось)} "
        f"(строки {min(ожидалось)}–{max(ожидалось)})" if ожидалось else
        f"    строк на листе: 0")
    log(f"    прогон взял в работу: {взято}, скачал: {скачано}")
    log(f"    строк с проставленной выпиской: {заполнено}")
    log(f"    файлов в {папка.name}: {файлов}")

    if ожидалось and взято != len(ожидалось):
        замечания.append(f"{гео}: на листе {len(ожидалось)} строк, "
                         f"а в работу взято {взято}")
    if чужие:
        замечания.append(f"{гео}: выписка проставлена в строках вне блока страны: "
                         f"{чужие[:10]}")
    if файлов < скачано:
        замечания.append(f"{гео}: скачано {скачано}, а файлов в папке {файлов}")
    # Колонка «Файл выписки» помнит и ПРОШЛЫЕ прогоны. Если она заполнена, а в
    # папке ЭТОГО прогона пусто — говорить «сходится» нельзя: именно так проверка
    # отрапортовала «✔» на прогоне, где не скачалось вообще ничего.
    if заполнено and файлов == 0:
        замечания.append(
            f"{гео}: в {заполнено} строках стоит имя файла, но в папке этого "
            "прогона ни одного PDF — имена остались от прошлых прогонов")
    if ожидалось and скачано == 0:
        замечания.append(f"{гео}: не скачано НИ ОДНОЙ выписки из {len(ожидалось)}")
    for з in замечания:
        log(f"    ⚠ {з}")
    if not замечания:
        log("    ✔ сходится")
    return замечания


def run_мультилист(excel: Path, sheet: str, out_dir: Path, human: HumanGate,
                   log=print, stop: Event | None = None,
                   pause: Event | None = None,
                   только_недостающие: bool = True,
                   только_гео: list[str] | None = None,
                   мультигео: bool | None = None) -> dict:
    """
    ОДИН запуск на весь мультилист: на листе лежат все страны сразу, страна
    каждой строки стоит в колонке «Гео».

    Идём странами по очереди: для каждой берём её строки и её драйвер. Гео не
    угадывается и не берётся из имени листа — только из колонки «Гео», поэтому
    перепутать страну нельзя. Драйвера для страны нет — она пропускается с
    пометкой, остальные качаются.

    только_гео — работать НЕ ПО ВСЕМУ ЛИСТУ, а по названным странам. Нужно
    ровно то, чего ждёт человек: выбрал в списке Францию — качается Франция.
    Без этого выбор страны просто не учитывался, лист шёл с начала, и на
    «скачать выписки по Франции» приложение принималось за Австрию.
    """
    # --- 1. ОЦЕНКА: что вообще на листе и в каком порядке это делать ---
    блоки = разбор_листа(excel, sheet)
    нужны = {г.strip().upper() for г in (только_гео or []) if г and г.strip()}
    if нужны and блоки:
        было = len(блоки)
        блоки = [б for б in блоки if (б["гео"] or "").upper() in нужны]
        log(f"Беру только {', '.join(sorted(нужны))}: "
            f"{len(блоки)} блоков из {было}")
        if not блоки:
            raise RuntimeError(
                f"На листе «{sheet}» нет строк стран "
                f"{', '.join(sorted(нужны))}. Проверь, тот ли лист выбран.")
    if not блоки:
        # Не просто «нельзя», а КУДА идти: подсказываем листы этого файла,
        # на которых колонка «Гео» есть.
        годные = [и for и in мультилисты(excel) if и != sheet]
        подсказка = ("\nВ этом файле подходят листы: " + ", ".join(f"«{и}»" for и in годные)
                     if годные else
                     "\nВ этом файле мультилистов нет вовсе — возьми файл "
                     "«Мультигео <дата>.xlsx», который делает Часть 1.")
        raise RuntimeError(
            f"На листе «{sheet}» нет заполненной колонки «{ГЕО}» — "
            "по чему определять страну.\n"
            "Такой лист делает Часть 1 в режиме «Мультигео»." + подсказка)

    строки_гео: dict[str, list[int]] = {}
    for б in блоки:
        строки_гео.setdefault(б["гео"], []).extend(б["строки"])
    порядок = list(dict.fromkeys(б["гео"] for б in блоки))

    # РЕЖИМ: одна страна или несколько. От него зависит, куда лягут файлы —
    # «выписки/FR/<дата>» или «выписки/Мультигео/<дата>/FR». Зовущий может
    # сказать прямо; не сказал — считаем по числу стран в работе.
    это_мультигео = (len(порядок) > 1 if мультигео is None else bool(мультигео))
    log(f"Режим: {'мультигео' if это_мультигео else порядок[0] if порядок else '—'}"
        f" — выписки лягут "
        + ("в «Мультигео/<дата>/<ГЕО>»" if это_мультигео
           else "в папку страны"))

    log(f"РАЗБОР ЛИСТА «{sheet}»")
    for б in блоки:
        сколько = len(б["строки"])
        диапазон = (f"строки {б['первая']}–{б['последняя']}" if сколько > 1
                    else f"строка {б['первая']}")
        есть = "" if б["гео"] in DRIVERS else "   ⏭ драйвера нет"
        log(f"   {диапазон:<20} {б['гео']:<6} {сколько} фирм{есть}")
    # страна кусками — не ошибка, но человек должен это видеть
    for гео, строки in строки_гео.items():
        кусков = sum(1 for б in блоки if б["гео"] == гео)
        if кусков > 1:
            log(f"   ⚠ {гео} лежит {кусков} кусками — обработаю все его строки разом")

    без_драйвера = [г for г in порядок if г not in DRIVERS]
    рабочие = [г for г in порядок if г in DRIVERS]
    log(f"\n   Порядок работы: {' → '.join(рабочие) if рабочие else '—'}")
    for г in без_драйвера:
        log(f"   ⏭ {г} — драйвер гео не написан, пропущу "
            f"({len(строки_гео[г])} строк)")
    if not рабочие:
        raise RuntimeError("Ни для одной страны с листа нет драйвера. Нечего качать.")

    # --- 2. ПАПКА ПРОГОНА — ПО РЕЖИМУ, а не по имени листа ---
    # Мультигео: «Мультигео/<дата>», внутри страны. Одна страна: её же папка.
    # Несколько стран НЕ мультигео — общей папки нет вовсе, каждая идёт к себе;
    # тогда для сводки берём ту, куда лягут книги.
    папка_прогона = папка_книг(out_dir, sheet,
                               рабочие[0] if (not это_мультигео
                                              and len(рабочие) == 1) else "",
                               это_мультигео)
    log(f"\n   Выписки → "
        + (f"{папка_прогона}  (внутри по папке на страну)" if это_мультигео
           else f"{папка_прогона}" if len(рабочие) == 1
           else "в папку каждой страны отдельно") + "\n")

    итоги: list[dict] = []
    все_замечания: list[str] = []
    for н, гео in enumerate(рабочие, 1):
        if stop and stop.is_set():
            log("Остановлено — оставшиеся страны пропущены.")
            break
        ожидалось = sorted(строки_гео[гео])
        log(f"\n{'─' * 52}")
        log(f"[{н}/{len(рабочие)}]  гео {гео} — строки "
            f"{ожидалось[0]}–{ожидалось[-1]} ({len(ожидалось)} фирм)")
        log(f"{'─' * 52}")
        try:
            итог = run(гео, excel, out_dir, human, log=log, sheet=sheet,
                       stop=stop, pause=pause, фильтр_гео=гео,
                       папка_прогона=папка_прогона,
                       только_недостающие=только_недостающие,
                       мультигео=это_мультигео)
            итоги.append({"гео": гео, **итог})
            # --- 3. ПРОВЕРКА: те ли строки, туда ли легли выписки ---
            # Папку спрашиваем У САМОГО ПРОГОНА: он один знает, куда положил
            # (мог уйти в добор, в прежнюю папку страны). Считать её заново —
            # значит проверять пустое место и обвинять прогон в потере файлов.
            все_замечания += _проверить_гео(
                excel, sheet, гео, ожидалось,
                Path(итог.get("папка") or (папка_прогона / гео)), итог, log)
        except SkipGeo as e:
            # Бросили ОДНУ страну — прогон продолжается со следующей.
            # Причина важна: «уже скачано» и «человек пропустил» — разные вещи,
            # и в сводке их надо различать, иначе непонятно, что доделывать.
            причина = str(e)
            само = "уже скачан" in причина
            log(f"⏭ гео {гео}: {причина}")
            итоги.append({"гео": гео, "скачано": 0, "всего": len(ожидалось),
                          "ошибка": "уже было скачано" if само
                                    else "пропущено человеком"})
            continue
        except AbortRun:
            # «Стоп» — это стоп ВСЕГО прогона, а не одной страны.
            log("■ Остановлено — оставшиеся страны не тронуты.")
            итоги.append({"гео": гео, "скачано": 0, "всего": 0,
                          "ошибка": "остановлено"})
            break
        except Exception as e:
            log(f"✘ гео {гео}: {type(e).__name__}: {e}")
            итоги.append({"гео": гео, "скачано": 0, "всего": 0,
                          "ошибка": f"{type(e).__name__}: {e}"})

    log(f"\n{'═' * 52}")
    log(f"СВОДКА ПО ЛИСТУ «{sheet}»")
    log(f"{'═' * 52}")
    скачано = всего = 0
    for и in итоги:
        скачано += и.get("скачано", 0)
        всего += и.get("всего", 0)
        пометка = ("  ⚠ " + и["ошибка"]) if и.get("ошибка") else ""
        строки = sorted(строки_гео.get(и["гео"], []))
        где = f"строки {строки[0]}–{строки[-1]}" if строки else "—"
        log(f"  {и['гео']:<6} {где:<16} скачано {и.get('скачано', 0):>3} "
            f"из {и.get('всего', 0):>3}{пометка}")
    for г in без_драйвера:
        log(f"  {г:<6} {'':<16} ⏭ пропущено — драйвер гео не написан")
    log(f"\nИТОГО скачано {скачано} из {всего}.")
    прибрать_пустые(папка_прогона, log)

    # СКОЛЬКО МЕСТ ОСВОБОДИЛОСЬ. Прогон сам вычищает фирмы, оказавшиеся
    # ликвидированными, с негодной формой или ненайденными. Без этой строки
    # человек не знает, что в листе появились дыры, и не идёт добирать замену —
    # а лист тихо худеет от прогона к прогону.
    from part2 import дубликаты as _дуб
    свободно = {}
    for г in порядок:
        n = len(_дуб.свободные_места(excel, sheet, г))
        if n:
            свободно[г] = n
    if свободно:
        свод = ", ".join(f"{г} {n}" for г, n in sorted(свободно.items()))
        log(f"\n⬜ ОСВОБОДИЛОСЬ МЕСТ: {sum(свободно.values())}  ({свод})")
        log("   Это фирмы, которые ликвидированы, с негодной формой или не "
            "нашлись в реестре.")
        log("   Нажми «🔁 Замена» → «Заменить дубликаты» — Часть 1 доберёт их "
            "сама, вставлять ничего не надо.")
    log(f"Папка прогона: {папка_прогона}")
    if все_замечания:
        log(f"\n⚠ ЗАМЕЧАНИЯ ПРОВЕРКИ ({len(все_замечания)}):")
        for з in все_замечания:
            log(f"   • {з}")
    else:
        log("✔ Проверки пройдены: строки и выписки разложены по своим странам.")
    return {"скачано": скачано, "всего": всего, "гео": итоги,
            "без_драйвера": без_драйвера, "папка": str(папка_прогона),
            "замечания": все_замечания}


def _собрать_еик(ws, фирмы, wb, excel: Path, human: HumanGate, log,
                 stop: Event | None, pause: Event | None) -> None:
    """
    БОЛГАРИЯ, ЭТАП 1: проставить ЕИК всем фирмам разом, одной сессией hithorizons.

    Почему отдельным этапом, а не по ходу скачивания: hithorizons за Cloudflare,
    и метаться между ним и реестром на каждой фирме — верный способ получить бан.
    Сначала собираем все номера, потом идём качать.

    ЕИК пишется в колонку «ЕИК» и оттуда же читается при повторных прогонах —
    второй раз сайт не тревожим. Ячейку, заполненную руками, НЕ трогаем.
    Не нашли или несколько кандидатов — оставляем пусто: драйвер тогда пойдёт
    старым путём (по кириллице) и при нужде позовёт человека. Взять чужой номер
    хуже, чем не взять никакого.
    """
    from part2.geos import hithorizons as hh

    к_еик = _столбец(ws, "ЕИК", 14)
    # ЕИК ИЩЕМ И В «НОМЕРЕ В РЕЕСТРЕ» — ЭТО ОН И ЕСТЬ.
    #
    # Колонка «ЕИК» живёт только внутри книги прогона, а наряд каждый раз
    # НОВЫЙ: в нём этой колонки нет вовсе. Поэтому номер, добытый вчера на
    # hithorizons, назавтра считался неизвестным — и всё начиналось сызнова,
    # а если hithorizons не отвечал, драйвер падал на поиск по кириллице.
    # Ровно на это и жаловался человек: «получали код, чтобы потом искать по
    # имени». При этом номер лежит в таблице с первого же скачивания: для
    # Болгарии «Номер в реестре» — это и есть ЕИК (UIC, 9 или 13 цифр).
    к_номер = Шапка(ws).номер("Номер в реестре")

    def _еик(строка: int) -> str:
        for к in (к_еик, к_номер):
            if not к:
                continue
            з = re.sub(r"\D", "", str(ws.cell(row=строка, column=к).value or ""))
            if len(з) in (9, 13):
                return з
        return ""

    нужны = []
    из_таблицы = 0
    for row, c in фирмы:
        готовый = _еик(row)
        if готовый:
            c.extra["eik"] = готовый
            # Кладём обратно в свою колонку: следующий проход этой же книги
            # найдёт его сразу, не перечитывая «Номер в реестре».
            if not str(ws.cell(row=row, column=к_еик).value or "").strip():
                ws.cell(row=row, column=к_еик).value = готовый
                из_таблицы += 1
        else:
            нужны.append((row, c))

    уже = len(фирмы) - len(нужны)
    if уже:
        log(f"BG: ЕИК уже известен у {уже} фирм — их не ищу заново"
            + (f" (из них {из_таблицы} взяты из «Номера в реестре»)"
               if из_таблицы else "") + ".")
    if not нужны:
        return

    log(f"\nBG ЭТАП 1: ищу ЕИК на hithorizons для {len(нужны)} фирм "
        "(потом одним заходом качаю выписки)")
    нашли = спорных = 0
    with Browser(profile="BG", human=human, log=log) as br:
        for i, (row, c) in enumerate(нужны, 1):
            if stop and stop.is_set():
                log("BG: остановлено — остальные ЕИК не искал.")
                break
            подождать_паузу(pause, stop)
            log(f"  [{i}/{len(нужны)}] {c.name}")
            try:
                находки = hh.искать(br, c.name, log=log)
            except AbortRun:
                raise
            except Exception as e:
                log(f"    ✘ {type(e).__name__}: {e}")
                находки = []
            одна = hh.подобрать(c.name, находки)
            if одна:
                ws.cell(row=row, column=к_еик, value=одна.еик)
                c.extra["eik"] = одна.еик
                нашли += 1
                log(f"    ✔ ЕИК {одна.еик}  ({одна.имя[:44]})")
            else:
                спорных += 1
                if not находки:
                    log("    ⚠ на hithorizons не нашлось — пойду по кириллице")
                else:
                    log(f"    ⚠ {len(находки)} похожих, однозначно не выбрать — "
                        "пойду по кириллице:")
                    for н in находки[:3]:
                        log(f"        • {н.имя[:44]}  ЕИК {н.еик}  {н.адрес[:24]}")
            if i % 10 == 0:
                сохранить_excel(wb, excel, human, log)   # не терять сделанное
            if i < len(нужны):
                hh.пауза()
    сохранить_excel(wb, excel, human, log)
    log(f"BG ЭТАП 1 готов: ЕИК найден у {нашли} из {len(нужны)}, "
        f"спорных {спорных}.\n")


def _обновить_свод(путь: Path, geo: str, заголовки: list[str],
                   строки: list[list], ширины: list[int], перенос: int | None = None):
    """
    ОДИН файл на весь лист вместо копии в каждой стране.

    Было: каждое гео клало себе «Мультигео 23-08.xlsx» и «не_вышло.xlsx», а при
    повторных прогонах рядом появлялись «(2)» и «(3)». В папке листа набралось
    63 книги на 18 стран — чтобы собрать результат, надо было открыть их все.

    Стало: одна книга на лист. Строки ЭТОГО гео заменяются, чужие остаются на
    месте — поэтому добор одной страны не стирает работу по остальным, а
    повторный прогон той же страны не плодит дубли.
    """
    from openpyxl import Workbook, load_workbook
    чужие: list[list] = []
    if путь.exists():
        try:
            стар = load_workbook(путь)
            лист = стар[стар.sheetnames[0]]
            for р in лист.iter_rows(min_row=2, values_only=True):
                if р and str(р[0] or "").strip().upper() != geo.upper():
                    чужие.append(list(р))
            стар.close()
        except Exception:
            чужие = []          # книга битая — перезапишем с нуля, не падая

    wb = Workbook()
    ws = wb.active
    ws.title = "Свод"
    ws.append(заголовки)
    for c in ws[1]:
        c.font = Font(bold=True)
    for р in чужие + строки:
        ws.append(р)
    for i, ш in enumerate(ширины):
        ws.column_dimensions[chr(ord("A") + i)].width = ш
    if перенос is not None:
        for р in ws.iter_rows(min_row=2, min_col=перенос + 1, max_col=перенос + 1):
            for c in р:
                c.alignment = Alignment(wrap_text=True, vertical="top")
    путь.parent.mkdir(parents=True, exist_ok=True)
    wb.save(путь)
    return len(чужие) + len(строки)


def _не_вышло(results, geo: str, out_dir: Path):
    """
    Обратная связь для Части 1: кого добрать взамен.

    ОДНА книга на весь лист. Строки этого гео заменяются, чужие остаются:
    добор одной страны не должен стирать список по остальным.
    """
    плохие = [r for r in results if r.status is not Status.OK]
    p = Path(out_dir) / "не_вышло.xlsx"
    строки = [[geo, r.company.name, RU[r.status], r.reason] for r in плохие]
    if not строки and not p.exists():
        return None
    _обновить_свод(p, geo, ["Гео", "Фирма", "Что случилось", "Причина"],
                   строки, [8, 42, 30, 50])
    return p if строки else None


