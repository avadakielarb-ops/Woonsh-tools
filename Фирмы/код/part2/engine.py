# ВЫБОР ФИРМЫ ЖИВЁТ В ЯДРЕ — part2/core/matching.py, функция `выбрать`.
# До 20.10.2026 здесь была вторая копия правил (_подобрать, _подтверждён,
# _противоречит, свой список «улица»-слов), и они с ядром отвечали по-разному
# на одну и ту же выдачу: британская фирма с точным уникальным именем
# отклонялась здесь из-за адреса бухгалтера — и тут же бралась там, где адреса
# не было вовсе.

def _имена(c) -> list[str]:
    """Наше имя и его написания от модели (см. part2/местные_имена.py)."""
    extra = getattr(c, "extra", None) or {}
    # Болгария: реестр знает фирму кириллицей («"АББЕКС" ЕООД»), а имя DnB —
    # латиница («ABBEX LTD EOOD»). Болгарское имя у нас уже есть — сравниваем
    # и с ним, иначе найденная фирма «не совпадала» (живой прогон 20.10.2026).
    return [c.name, *extra.get("написания", []),
            *([extra["bg_name"]] if extra.get("bg_name") else [])]


def _подобрать(c, адрес1: str, cands: list):
    """Однозначный кандидат по правилам ядра или None."""
    return выбрать(_имена(c), адрес1, c.zip_code, cands)[0]


def статус_не_прочитан(причина: str) -> bool:
    """
    «статус: —», «статус не aktywna (—)» и подобное — это НЕ СМОГ ПРОЧИТАТЬ,
    а вовсе не «статус плохой».

    Драйверы пишут так, когда поле пустое: страница не догрузилась, висела
    капча, сайт отдал заглушку. Выбрасывать фирму за это нельзя — именно так
    молча терялись ЖИВЫЕ фирмы: 13 штук за прогон в Словении и Хорватии,
    плюс BLUE ICE в Польше. Пустой статус = повод переспросить, а не отказ.
    """
    т = (причина or "").strip().lower().rstrip(".")
    return (not т) or т.endswith("—") or т.endswith("(—)") or т == "статус:"


МАКС_КАРТОЧЕК = 5          # сколько карточек открываем ради адреса


def _форма_вперёд(имя: str) -> str:
    """
    «MEGA STAR SIA» → «SIA "MEGA STAR"». ТОЛЬКО ДЛЯ ЛАТВИИ.

    Латвийский реестр ищет по ТОЧНОМУ официальному написанию: форма спереди и
    название в кавычках. Живой замер: «MEGA STAR SIA» — 0 результатов,
    «MEGA STAR» — 0, а `SIA "MEGA STAR"` находит фирму первой строкой.

    Раньше этот запрос слали ВСЕМ странам, и чешский или британский реестр
    честно искал строку с кавычками — ещё один пустой запрос на фирму.
    Форму не угадываем: берём ту, что уже стоит в конце имени.
    """
    слова = (имя or "").strip().split()
    if len(слова) < 2:
        return ""
    хвост = слова[-1].strip('.,"«»')
    if хвост.lower() != "sia":
        return ""
    основа = " ".join(слова[:-1]).strip(' ,"«»')
    return f'SIA "{основа}"' if основа else ""


def запросы_для(c, geo: str = "", сам_режет_форму: bool = False) -> list[str]:
    """
    Чем искать фирму в реестре — по порядку, без повторов.

      1) написания от модели: реестровое (с местными буквами), латиницей;
      2) имя как в DnB;
      3) Латвия — ещё `SIA "…"` (см. `_форма_вперёд`);
      4) имя без правовой формы — если драйвер не режет её сам.

    УПРОЩЕНИЙ «ПЕРВЫЕ ДВА СЛОВА», «ПЕРВОЕ СЛОВО» БОЛЬШЕ НЕТ (решение
    пользователя 20.10.2026: «с упрощёнными запросами перебор»). «AQUA» вместо
    «AQUA-360 SIA» — не упрощение, а массовый поиск: тысяча чужих фирм на
    десятке страниц, нашей среди них может не быть вовсе.
    """
    # Обрезанное DnB имя ищем без «...» и недописанного слова (см. без_обреза).
    варианты = [без_обреза(в) for в in [*_имена(c)[1:], c.name]]
    if (geo or "").upper() == "LV":
        варианты.append(_форма_вперёд(c.name))
    if not сам_режет_форму:
        варианты.append(без_формы(без_обреза(c.name)))
    вышло, видели = [], set()
    for в in варианты:
        в = (в or "").strip()
        if len(в) >= 2 and в.casefold() not in видели:
            видели.add(в.casefold())
            вышло.append(в)
    return вышло


def _пауза_между_запросами(geo: str, первый: bool) -> None:
    """
    Не стучать в реестр очередью. Чешский реестр блокирует частые запросы
    («не палиться, что работает питон» — просьба пользователя 19.10.2026):
    ему пауза перед каждым поиском, остальным — между запросами одной фирмы.
    """
    import random
    import time
    if (geo or "").upper() == "CZ":
        time.sleep(random.uniform(2.0, 5.0))
    elif not первый:
        time.sleep(random.uniform(1.0, 3.0))


def _стабильная(cand) -> bool:
    """
    Можно ли вернуться к этому кандидату ПОЗЖЕ, после ухода со страницы.

    У части гео ref — это номер или ссылка (вернуться легко). У Финляндии там
    живой Locator со страницы выдачи: уйдёшь — он протухнет. Такие карточки
    щупать нельзя, иначе потеряем и выбор, и место.
    """
    return isinstance(cand.ref, (str, int)) and str(cand.ref) not in ("", "HUMAN")


def _уточнить_по_адресу(d, c, адрес1: str, кандидаты: list, log) -> list:
    """
    ЭТАП 2 каскада: адресов в выдаче нет — идём смотреть их В КАРТОЧКАХ.

    Зачем. Выдача многих реестров показывает только названия, и когда их
    несколько, выбрать не из чего: человеку показывали список чужих имён без
    единой зацепки. Поэтому открываем до пяти карточек, забираем оттуда адрес
    и сверяем с нашим.

    Совпал ровно один — он и есть ответ, человека не тревожим.
    Не совпал никто (или совпало несколько) — возвращаем кандидатов С
    ДОБЫТЫМИ АДРЕСАМИ: пусть человек решает, но уже глядя на адреса.

    Карточки только «стабильные» (см. _стабильная): к остальным не вернуться.
    """
    щупаем = [k for k in кандидаты if _стабильная(k)][:МАКС_КАРТОЧЕК]
    if not адрес1 or len(щупаем) < 2:
        return кандидаты

    log(f"  · адресов в выдаче нет — смотрю карточки ({len(щупаем)} шт.)")
    найденные: dict[str, str] = {}
    for k in щупаем:
        try:
            d.open(k)
            d.page.wait_for_timeout(600)
            d.check(c)                      # часть драйверов заполняет адрес тут
            адрес = (d.данные_реестра() or {}).get("адрес", "")
            if адрес:
                найденные[str(k.ref)] = адрес
                log(f"      {k.name[:34]:34} → {адрес[:44]}")
        except AbortRun:
            raise
        except Exception:
            continue                        # карточка не открылась — не беда

    if not найденные:
        return кандидаты

    подходят = [k for k in кандидаты
                if str(k.ref) in найденные
                and адрес_сходится(адрес1, найденные[str(k.ref)], c.zip_code)]
    # Возвращаемся на выдачу: карточки мы уже полистали, состояние надо вернуть.
    try:
        свежие = d.search(c)
    except Exception:
        свежие = кандидаты
    по_ref = {str(k.ref): k for k in свежие}

    if len(подходят) == 1:
        нужный = подходят[0]
        log(f"  ✔ выбрал по адресу из карточки: {нужный.name[:40]}")
        return [по_ref.get(str(нужный.ref), нужный)]

    # Не решили сами — отдаём человеку, но уже С АДРЕСАМИ.
    обогащённые = []
    for k in свежие:
        адрес = найденные.get(str(k.ref), k.address)
        обогащённые.append(Candidate(name=k.name, address=адрес, ref=k.ref,
                                     url=getattr(k, "url", ""),
                                     aliases=getattr(k, "aliases", ())))
    if подходят:
        log(f"  · по адресу подошли {len(подходят)} — решает человек")
    return обогащённые


def _выбрать_фирму(d, c, адрес1: str, human, log):
    """
    Найти и выбрать нужную фирму. Возвращает Candidate (в т.ч. «HUMAN» —
    человек открыл карточку сам).

    Каждый запрос из `запросы_для` — со своей выдачей, листаем до
    МАКС_СТРАНИЦ. Выбрали — сразу выходим. Не выбрали ни одним запросом —
    решает человек: «не нашёл» (ничего похожего) или «выбери» (список).
    КАЖДЫЙ ЗАПРОС ПИШЕТСЯ В ЛОГ, и пустой тоже: раньше пустые молчали, и по
    логу нельзя было понять, чем вообще искали.
    """
    geo = getattr(d, "code", "")
    имена = _имена(c)
    запросы = запросы_для(c, geo, getattr(d, "сам_режет_форму", False))
    if getattr(d, "один_запрос", False):
        запросы = запросы[:1]
    все: list = []
    from copy import copy
    for n, запрос in enumerate(запросы):
        _пауза_между_запросами(geo, первый=(n == 0))
        c2 = copy(c)
        c2.name = запрос
        try:
            кандидаты = d.search(c2) or []
        except (AbortRun, SkipCompany, SkipGeo):
            raise
        except Exception as e:
            log(f"  · запрос «{запрос}» не прошёл: {type(e).__name__}")
            continue
        log(f"  · запрос «{запрос}» — {len(кандидаты)} шт.")
        этого: list = []
        страница = 1
        while кандидаты:
            этого.extend(кандидаты)
            m, почему = выбрать(имена, адрес1, c.zip_code, кандидаты)
            if m is not None:
                log(f"  ✔ {почему}"
                    + (f" (страница {страница})" if страница > 1 else "")
                    + f": {m.name[:60]}")
                return m
            if страница >= МАКС_СТРАНИЦ or not d.следующая_страница():
                break
            страница += 1
            log(f"  …ищу на странице {страница}")
            кандидаты = d.кандидаты_страницы()
        if страница > 1:
            # полные тёзки бывают на разных страницах — смотрим их вместе
            m, почему = выбрать(имена, адрес1, c.zip_code, этого)
            if m is not None:
                log(f"  ✔ {почему}: {m.name[:60]}")
                return m
        все.extend(этого)

    # ТЁЗКИ БЕЗ АДРЕСОВ В ВЫДАЧЕ — сходим за адресами в карточки. Только для
    # полных тёзок: адрес различает одинаковые имена, но не выбирает фирму
    # с другим именем (DnB часто держит адрес бухгалтера, правда — в реестре).
    from part2.core.matching import _ключи_кандидата, без_повторов
    ключи = {ключ_имени(и) for и in имена} - {""}
    тёзки = без_повторов([k for k in все if _ключи_кандидата(k) & ключи])
    if len(тёзки) > 1 and not any((k.address or "").strip() for k in тёзки):
        тёзки = _уточнить_по_адресу(d, c, адрес1, тёзки, log)
        if len(тёзки) == 1:
            return тёзки[0]
        m, _ = выбрать(имена, адрес1, c.zip_code, тёзки)
        if m is not None:
            return m
        все = тёзки + [k for k in все if k not in тёзки]

    # Убираем повторы: разные запросы часто приносят одних и тех же.
    from part2.core.matching import без_повторов
    список = без_повторов(все)
    if список:
        # По логу должно быть видно, КОГО показал реестр и почему не взяли:
        # без этого «нашёл слово в слово, а пишет "нет совпадения"» не разобрать.
        _, почему = выбрать(имена, адрес1, c.zip_code, список)
        log(f"  · сам не выбрал ({почему}); в выдаче: "
            + "; ".join(f"{k.name[:40]}" + (f" [{k.address[:30]}]" if k.address else "")
                        for k in список[:4])
            + (f" … ещё {len(список) - 4}" if len(список) > 4 else ""))

    # ЧЕЛОВЕК. Даже если ничего похожего: решение «фирмы в реестре нет»
    # принимает человек, а не мы за него.
    if не_похожи(c, адрес1, список):
        log("  · похожего не нашлось ни одним запросом — спрашиваю человека")
        return _спросить_и_принять(
            c, адрес1, [f"{k.name} — {k.address or 'адрес не показан'}"
                        for k in список[:8]], human, log)
    return pick(c.name, адрес1 or c.address, список, human,
                имена=имена[1:], индекс=c.zip_code)


def _спросить_и_принять(c, адрес1: str, кандидаты: list, human, log):
    """
    «Не нашёл» → спросить человека и ПОВЕРИТЬ ЕГО ОТВЕТУ.

    Здесь был позорный баг. Окно говорило человеку: «нашёл — открой карточку в
    браузере и Продолжить». Человек находил MEGA STAR SIA руками, открывал
    карточку, жал «Продолжить» — а код возвращал None ВНЕ ЗАВИСИМОСТИ от ответа,
    с комментарием «человек нажал Пропустить». Фирма уходила в «не нашлась»,
    хотя человек только что показал её пальцем. Ровно та же обида, что и с
    перескоком: сделал всё правильно, а прогон сделал вид, что не заметил.

    Как правильно: «Пропустить» бросает SkipCompany внутри require(), сюда мы
    после него не возвращаемся. Значит если вернулись — человек нажал
    «Продолжить», и на экране открыта нужная карточка.
    """
    human.нет_совпадений(c.name, адрес1, кандидаты)
    log("  · человек нашёл фирму сам — беру карточку с его вкладки")
    return Candidate(name=c.name, address=адрес1, ref="HUMAN")


def _принять_от_человека(d, br, c, выбор, human, log, попыток: int = 3) -> None:
    """
    Человек нажал «Продолжить» — ЗАБРАТЬ У НЕГО КАРТОЧКУ, а не бросить фирму.

    Что было. Ядро сразу спрашивало `d.карточка_открыта()` и при первом же
    «нет» бросало SkipCompany БЕЗ ЕДИНОЙ СТРОКИ В ЛОГЕ. Причин «нет» было
    три, и все — наши, не человека:
      · карточка открылась в НОВОЙ вкладке, а драйвер читал старую;
      · страница ещё грузилась (Латвия: «нажало скачать до прогрузки»);
      · драйвер берёт номер из URL, а тот меняется через миг после клика.
    Человек делал всё правильно, а прогон отвечал молчаливым прыжком к
    следующей фирме. Ноль из десяти по пяти странам подряд.

    Что теперь. Идём на вкладку человека, даём странице встать, снимаем данные.
    Не вышло — говорим В ЛОГ и СПРАШИВАЕМ ЕЩЁ РАЗ, а не решаем за него.
    Сдаёмся только после трёх попыток, и тоже вслух.
    """
    for попытка in range(1, попыток + 1):
        br.вкладка_человека(log)
        try:
            d.page.wait_for_load_state("domcontentloaded", timeout=5000)
        except Exception:
            pass
        try:
            d.open(выбор)                    # драйвер снимает номер/имя с карточки
        except (AbortRun, SkipCompany, SkipGeo):
            raise
        except Exception as e:
            log(f"  · не смог снять данные с карточки: {type(e).__name__}: {e}")
        # ПРОЧИТАТЬ КАРТОЧКУ, А ПОТОМ СПРАШИВАТЬ, ВИДНА ЛИ ОНА.
        #
        # Здесь была тихая поломка на все гео. `карточка_открыта()` спрашивает
        # `номер()`, а `номер()` почти у каждого драйвера возвращает ПОЛЕ,
        # которое заполняет `check()` — и только он. В этом месте `check()` ещё
        # не звали (ядро зовёт его строкой ниже), поле пустое, и ответ «карточки
        # не вижу» был предрешён. Человек открывал нужную карточку, жал
        # «Продолжить» — и получал «Не вижу карточку фирмы» трижды подряд, после
        # чего фирму выбрасывали. Живой случай 12.09: Швейцария, AQUA AG,
        # карточка открыта на zefix.ch/.../firm/518110.
        #
        # `open()` тут помочь не может: при выборе человеком у большинства гео
        # он сразу возвращается — мы УЖЕ на нужной странице, идти некуда.
        # Читает страницу только `check()`, его и зовём. Ответ выбрасываем:
        # годность фирмы решает ядро ниже, нам нужен факт «карточка прочиталась».
        try:
            d.check(c)
        except (AbortRun, SkipCompany, SkipGeo):
            raise
        except Exception as e:
            log(f"  · карточка не прочиталась: {type(e).__name__}: {e}")
        if d.карточка_открыта():
            log(f"  · принял карточку от человека (номер {d.номер() or '—'})")
            return
