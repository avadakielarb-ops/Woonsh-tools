def прибрать_пустые(папка: Path, log=print) -> int:
    """
    Убрать пустые папки гео после прогона.

    Гео, из которого ничего не скачалось, оставляет пустой каталог. Их
    накапливается по одному на каждую неудачную страну, и в папке листа
    начинается тот же бардак, ради избавления от которого её и заводили.
    """
    убрано = 0
    try:
        for под in sorted(Path(папка).iterdir()):
            if под.is_dir() and not any(p.is_file() for p in под.rglob("*")):
                под.rmdir()
                убрано += 1
    except Exception:
        return убрано
    if убрано:
        log(f"  · убрал {убрано} пустых папок гео (оттуда ничего не скачалось)")
    return убрано


def состав_прогона(excel: Path, sheet: str | None = None,
                   фильтр_гео: str | None = None) -> list[dict]:
    """
    ЧТО пойдёт в работу: имя + гео + строка, без единого захода в браузер.

    Нужно окну «Список фирм и исключения»: до сих пор единственным способом
    узнать состав прогона было запустить его и читать лог по одной фирме.

    Имя берём так же, как боевой разбор: сперва «паспорт» из колонки B, и
    только если его нет — колонка C. Иначе список показывал бы устаревшие
    имена, а прогон работал по другим.
    """
    wb = load_workbook(excel, read_only=True, data_only=True)
    ws = wb[sheet] if sheet and sheet in wb.sheetnames else wb[wb.sheetnames[0]]
    к_гео = _найти_столбец(ws, "Гео")
    итог: list[dict] = []
    for r in ws.iter_rows(min_row=2, max_col=max(12, к_гео or 12)):
        гео = ""
        if к_гео:
            гео = str(ws.cell(row=r[0].row, column=к_гео).value or "").strip().upper()
        if фильтр_гео and гео and гео != фильтр_гео.upper():
            continue
        имя = ""
        профиль = r[1].value
        if профиль and str(профиль).strip():
            имя = _разобрать_блок_B(str(профиль), гео or (фильтр_гео or ""))[0]
        if not имя and len(r) > 2 and r[2].value:
            имя = str(r[2].value).strip()
        if имя:
            итог.append({"строка": r[0].row, "гео": гео, "имя": имя})
    wb.close()
    return итог


