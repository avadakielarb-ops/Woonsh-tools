def папка_листа(out_dir: Path, sheet: str) -> Path:
    """
    ОДНА ПАПКА НА ПАРТИЮ, внутри — страны, и там же книга:

        выписки/07-09/EE/…pdf
                     /PL/…pdf
                     /Мультигео 07-09.xlsx

    ПОЧЕМУ ПЕРЕДЕЛАНО (жалоба 08.09.2026). Было две разные схемы: одиночное гео
    уходило в «выписки/UK/2026-09-07_21-03_53шт», а прогон с листа — в
    «выписки/Мультигео/0709/UK». Из-за этого запуск ОДНОЙ страны с листа
    мультигео оказывался внутри «Мультигео», книгу приходилось искать там же,
    а рядом лежали «Мультигео/Мультигео/23-08» и три разных стиля имён.
    Теперь схема одна и та же всегда, уровня «Мультигео» больше нет.

    ПОЧЕМУ ИМЯ ЛИСТА, А НЕ СЕГОДНЯШНЯЯ ДАТА. Партия — это лист, а качать её
    могут на другой день: лист «23-08» вполне добирается 25-го. По сегодняшней
    дате партия расползлась бы на две папки, и собрать её стало бы нечем.
    У листов имена и так по дате («07-09», «23-08 PL»), так что папка выходит
    ровно «по дате», как и просили.

    ПАПКУ ЗДЕСЬ НЕ СОЗДАЁМ. Создаёт тот, кто в неё пишет, — иначе неудачный
    запуск оставляет пустышку. Их накопилось шесть штук (DK, HU, PL и три
    датированные), и каждую приходилось открывать, чтобы понять, что она пустая.

    Пустое имя листа — «без-листа»: честно и заметно, в отличие от подставленной
    даты, которая выглядит правдой.
    """
    чистый = (sheet or "").strip()
    имя = safe_name(чистый) if чистый else "без-листа"
    return Path(out_dir) / имя


def дата_партии(sheet: str) -> str:
    """
    Дата партии для имени папки: из имени листа, если она там есть.

    «21-07 EE» → 21-07. Сегодняшнюю подставляем только когда взять неоткуда:
    лист «23-08» могут добирать 25-го, и по сегодняшней дате одна партия
    расползлась бы на две папки.
    """
    m = re.match(r"^\s*(\d{2})[-. ]?(\d{2})", (sheet or "").strip())
    return f"{m.group(1)}-{m.group(2)}" if m else f"{datetime.now():%d-%m}"


def папка_гео(out_dir: Path, sheet: str, geo: str,
              мультигео: bool = False) -> Path:
    """
    Куда складывать выписки. Раскладка по РЕЖИМУ ПРОГОНА:

        выписки/EE/21-07/…            качали одну страну
        выписки/EE.БС/21-07/…         линия «без сайта»
        выписки/Мультигео/09-09/EE/…  качали несколько стран разом

    Режим определяет ТОТ, КТО ЗАПУСКАЛ, а не устройство листа. Это важно:
    задание на одну Францию собирается в тот же мультилист (у него есть
    колонка «Гео»), но человек качал ФРАНЦИЮ — и файлы обязаны лечь в «FR»,
    а не в «Мультигео». Замер 10.09.2026: семь французских выписок ушли в
    «Мультигео\10-09», и найти их можно было, только зная внутреннее
    устройство наряда.

    В мультигео страна остаётся ПОДПАПКОЙ: партия лежит вместе, но внутри
    разобрана по странам, а не свалена в кучу.
    """
    г = (geo or "без-гео").upper()
    if мультигео:
        return Path(out_dir) / ПАПКА_МУЛЬТИГЕО / дата_партии(sheet) / г
    # линия «без сайта» лежит отдельно — как и лист в таблице
    верх = f"{г}.БС" if (sheet or "").lower().startswith("без сайта") else г
    return Path(out_dir) / верх / дата_партии(sheet)


def папка_книг(out_dir: Path, sheet: str, geo: str = "",
               мультигео: bool = False) -> Path:
    """
    Где лежат КНИГИ прогона («Выписки FR 10-09.xlsx», «не_вышло.xlsx»).

    Рядом с выписками, а не отдельной кучей:

        выписки/FR/10-09/…            качали одну страну — книга там же
        выписки/Мультигео/09-09/…     партия — книга над странами партии

    ПОЧЕМУ ПРИШЛОСЬ ПРАВИТЬ. Книги клались в «выписки/<имя листа>», а лист
    наряда зовётся просто датой — и в корне выписок завелись папки «09-09» и
    «10-09» с одной книгой внутри, похожие на папки гео. Найти книгу
    французского прогона можно было только зная, как называется лист наряда.
    Замер 10.09.2026: две таких папки, обе пустые по выпискам.

    Гео не назвали и это не мультигео (старые вызовы из очереди и app) —
    отдаём прежнюю «выписки/<лист>»: ломать их незачем.
    """
    if мультигео:
        return Path(out_dir) / ПАПКА_МУЛЬТИГЕО / дата_партии(sheet)
    if geo:
        return папка_гео(out_dir, sheet, geo)
    return папка_листа(out_dir, sheet)


def прежние_папки(out_dir: Path, sheet: str, geo: str) -> list[Path]:
    """
    Где выписки этой страны могли лежать ДО смены раскладки.

    Нужно, чтобы добор ложился РЯДОМ с уже скачанным, а не заводил вторую
    кучу. Порядок — от новой схемы к старым; отдаём только непустые.
    """
    г = (geo or "").upper()
    места = [папка_гео(out_dir, sheet, г),
             # прежняя раскладка мультигео: «Мультигео/<лист>/<ГЕО>» и
             # «Мультигео/<лист>» без страны — так лежит уже скачанное
             Path(out_dir) / ПАПКА_МУЛЬТИГЕО / safe_name((sheet or "").strip()) / г,
             Path(out_dir) / ПАПКА_МУЛЬТИГЕО / safe_name((sheet or "").strip()),
             Path(out_dir) / ПАПКА_МУЛЬТИГЕО / дата_партии(sheet)]
    старые = Path(out_dir) / г
    if старые.is_dir():
        места += sorted((p for p in старые.glob("*") if p.is_dir()), reverse=True)
        места.append(старые)
    живые = []
    for м in места:
        if м.is_dir() and any(p.is_file() for p in м.iterdir()) and м not in живые:
            живые.append(м)
    return живые


def _разобрать_блок_B(блок: str, geo: str):
    """
    Разобрать вставленный блок колонки B на имя/адрес/город/индекс/сайт.
    Формат (как делает Часть 1):
        Название
        Address: <полный адрес>
        Website: <сайт>
    Строки могут идти и через перевод строки, и в одну строку.
    """
    import re
    from part1.data.address_rules import разобрать
    текст = блок.replace("\r", "\n")
    # имя = всё до "Address:"
    m_addr = re.search(r"Address:\s*(.+?)(?:\n|Website:|$)", текст, re.I | re.S)
    m_web = re.search(r"Website:\s*(\S+)", текст, re.I)
    имя = re.split(r"Address:", текст, flags=re.I)[0].strip().strip("\n").strip()
    имя = re.sub(r"\s+", " ", имя)
    сырой_адрес = m_addr.group(1).strip() if m_addr else ""
    сырой_адрес = re.sub(r"\s+", " ", сырой_адрес)
    сайт = m_web.group(1).strip() if m_web else ""
    r = разобрать(сырой_адрес, geo) if сырой_адрес else None
    return (имя,
            (r.улица if r else сырой_адрес),
            (r.город if r else ""),
            (r.индекс if r else ""),
            сайт)


def _столбец(ws, заголовок: str, ширина: int | None = None) -> int:
    """
    Найти столбец по заголовку в строке 1 или создать новый в конце (жирным).

    Ищем ПЕРЕХОДНИКОМ, а не точным сравнением строк. Раньше лист с колонкой
    «Адрес по выписке» не признавался за «Платёжный профиль выписки», и рядом
    создавалась вторая колонка того же смысла — так и набежало пятнадцать
    разных шапок на девяносто семь листов.
    """
    from openpyxl.utils import get_column_letter
    найден = Шапка(ws).номер(заголовок)
    if найден:
        return найден
    последний = 0
    for c in range(1, 40):
        v = ws.cell(row=1, column=c).value
        if v not in (None, ""):
            последний = c
    нов = последний + 1
    ячейка = ws.cell(row=1, column=нов, value=заголовок)
    ячейка.font = Font(bold=True)
    # ширина: заданная или по длине заголовка (чтобы название колонки не сжималось)
    ws.column_dimensions[get_column_letter(нов)].width = ширина or (len(заголовок) + 4)
    return нов


def _лист(wb, geo: str, sheet: str | None):
    """ДЫРА №2: страна зашита в имя листа («13-07 CZ») — не перепутаем гео."""
