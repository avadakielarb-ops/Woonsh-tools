"""
ЗАМЕНА ДУБЛИКАТОВ — фирм, которые уже где-то использовались.

Хозяин выгружает список названий, проверяет его на своей стороне и возвращает
те, что брать нельзя. Дальше нужно не просто их выкинуть, а ЗАМЕНИТЬ: место в
листе должно остаться за той же страной, иначе после нескольких чисток вместо
десяти фирм на гео останется три.

Поэтому строка не удаляется. У неё стирают данные фирмы (C..H, номер, файл,
платёжный профиль), а «№» и «Гео» остаются — получается СВОБОДНОЕ МЕСТО, куда
Часть 1 положит замену. Порядок блоков по странам не ломается, и проверка
«строки 122–131» продолжает сходиться.

Старая выписка тоже уходит: держать PDF фирмы, которой в листе больше нет, —
верный способ потом принять его за результат.
"""
from __future__ import annotations

from pathlib import Path

from openpyxl import load_workbook

from common.колонки import Шапка
from part2.исключения import Исключения

# ИСТОРИЧЕСКИЕ НОМЕРА. Раньше они были единственной правдой:
# 1 № · 2 Платёжный профиль · 3 Организация · 4 Адрес · 5 Город · 6 Индекс
# 7 Штат · 8 Website · 9 Номер в реестре · 10 Файл выписки
# 11 Платёжный профиль выписки · 12 Гео
# Теперь колонки ищутся по ЗАГОЛОВКУ, а эти числа остались запасным вариантом
# для листов без шапки — их у пользователя два десятка, и они рабочие.
ЗАПАСНОЙ_ГЕО = 12
ЗАПАСНОЙ_ИМЯ = 3
ЗАПАСНОЙ_ФАЙЛ = 10
ГЕО_ЗАГОЛОВОК = "Гео"


def _столбцы(ws) -> tuple[int, int, int]:
    """Номера «Гео», «Организация», «Файл выписки» для ЭТОГО листа."""
    ш = Шапка(ws)
    return (ш.номер(ГЕО_ЗАГОЛОВОК, ЗАПАСНОЙ_ГЕО),
            ш.номер("Организация", ЗАПАСНОЙ_ИМЯ),
            ш.номер("Файл выписки", ЗАПАСНОЙ_ФАЙЛ))


def найти(excel: Path, sheet: str, имена: list[str]) -> dict:
    """
    Сопоставить присланные названия со строками листа.

    Возвращает {'нашли': [{'строка','гео','имя','файл'}], 'не_нашли': [имена]}.
    Сравнение — ключом из «Исключений»: регистр, диакритика и знаки не важны,
    правовая форма важна. Так «BLUE ICE Sp. z o.o.» найдёт «BLUE ICE SP Z O O»,
    но не тронет бельгийскую «Blue Ice».
    """
    ключи = {}
    for имя in имена:
        имя = (имя or "").strip()
        if имя:
            ключи.setdefault(Исключения.ключ(имя), имя)

    wb = load_workbook(excel, data_only=True)
    ws = wb[sheet] if sheet in wb.sheetnames else wb[wb.sheetnames[0]]
    к_гео, к_имя, к_файл = _столбцы(ws)
    нашли, встречены = [], set()
    for r in ws.iter_rows(min_row=2, max_col=к_гео):
        имя = str(ws.cell(row=r[0].row, column=к_имя).value or "").strip()
        к = Исключения.ключ(имя)
        if not к or к not in ключи:
            continue
        встречены.add(к)
        нашли.append({
            "строка": r[0].row,
            "гео": str(ws.cell(row=r[0].row, column=к_гео).value or "").strip().upper(),
            "имя": имя,
            "файл": str(ws.cell(row=r[0].row, column=к_файл).value or "").strip(),
        })
    wb.close()
    return {"нашли": нашли,
            "не_нашли": [и for к, и in ключи.items() if к not in встречены]}


def освободить(excel: Path, sheet: str, строки: list[dict],
               папка_выписок: Path | None = None, log=print) -> dict:
    """
    Очистить найденные строки и убрать их выписки. Возвращает сводку по гео.

    Excel сохраняем ОДИН раз в конце: книга большая, а сохранение на каждую
    строку — это минуты на ровном месте.
    """
    if not строки:
        return {}
    wb = load_workbook(excel)
    ws = wb[sheet] if sheet in wb.sheetnames else wb[wb.sheetnames[0]]
    # Стираем ВСЁ, кроме «№» и «Гео»: место должно остаться за этой страной,
    # а всё остальное — данные ушедшей фирмы. Раньше здесь был список номеров,
    # и колонка, добавленная позже («Название BG», «Адрес по выписке»), в него
    # не попадала — от старой фирмы оставался хвост в новой строке.
    # Гео ищем БЕЗ запасного номера: нет колонки — значит и беречь нечего,
    # а «двенадцатая на всякий случай» уберегла бы чужие данные от очистки.
    беречь = Шапка(ws).номер(ГЕО_ЗАГОЛОВОК)
    чистить = [c for c in range(2, ws.max_column + 1) if c != беречь]
    по_гео: dict[str, int] = {}
    удалено = 0
    for с in строки:
        for col in чистить:
            ws.cell(row=с["строка"], column=col).value = None
        по_гео[с["гео"] or "--"] = по_гео.get(с["гео"] or "--", 0) + 1
        if папка_выписок and с["файл"]:
            путь = Path(папка_выписок) / (с["гео"] or "") / с["файл"]
            try:
                if путь.exists():
                    путь.unlink()
                    удалено += 1
            except Exception as e:
                log(f"   не смог убрать {путь.name}: {e}")
    wb.save(excel)
    wb.close()
    if удалено:
        log(f"   старых выписок убрано: {удалено}")
    return по_гео


def свободные_места(excel: Path, sheet: str, гео: str) -> list[int]:
    """
    Строки этого гео, где имя пустое, — туда Часть 1 положит замену.

    Ищем именно по пустой «Организации»: строка с «№» и «Гео», но без фирмы —
    это и есть освобождённое место.
    """
    wb = load_workbook(excel, data_only=True)
    ws = wb[sheet] if sheet in wb.sheetnames else wb[wb.sheetnames[0]]
    к_гео, к_имя, _ = _столбцы(ws)
    места = []
    for r in ws.iter_rows(min_row=2, max_col=к_гео):
        г = str(ws.cell(row=r[0].row, column=к_гео).value or "").strip().upper()
        имя = str(ws.cell(row=r[0].row, column=к_имя).value or "").strip()
        if г == (гео or "").upper() and not имя:
            места.append(r[0].row)
    wb.close()
    return места
