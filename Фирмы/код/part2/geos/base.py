"""
Контракт гео-драйвера.

Любая страна — это один файл в geos/, который умеет ровно три вещи:
    search()   — найти фирму в реестре и вернуть кандидатов
    check()    — проверить статус (активна? нет красных предупреждений?)
    fetch()    — получить документ (скачать / напечатать / заполнить шаблон)

Всё остальное — браузер, каскад матчинга, вызов человека, переименование файла,
отчёт — делает ядро. Добавить новую страну = написать ~40 строк, а не новый скрипт.
"""
from __future__ import annotations

from abc import ABC, abstractmethod
from pathlib import Path

from common.browser import Browser
from common.human import HumanGate
from part2.core.matching import Candidate
from part2.core.models import Company


class GeoDriver(ABC):
    code: str = ""          # "CZ"
    title: str = ""         # "Чехия"
    url: str = ""           # входная страница реестра

    # Как получаем документ: "download" | "print" | "template"
    method: str = "download"

    # Как ядру строить запросы (см. engine.запросы_для):
    #   сам_режет_форму — драйвер сам ищет без правовой формы, и отдельный
    #     запрос «без формы» был бы повтором того же поиска;
    #   один_запрос — драйвер ищет НЕ по c.name (Болгария — своим кириллическим
    #     именем), и любой второй запрос дал бы ту же выдачу.
    сам_режет_форму: bool = False
    один_запрос: bool = False

    # ЛОГ ЕСТЬ ВСЕГДА, даже у драйвера, собранного в обход __init__.
    # Проверки создают драйверы через object.__new__ (браузер им не нужен), и
    # любая строка `self.log(...)` в драйвере роняла такую проверку с
    # AttributeError. staticmethod — не для красоты: обычная функция в
    # атрибуте класса стала бы методом и получила бы self первым аргументом.
    log = staticmethod(print)

    def __init__(self, br: Browser, human: HumanGate):
        self.br = br
        self.human = human
        self.log = print          # движок подменит на лог прогона (self.log = log)

    @property
    def page(self):
        """
        ТЕКУЩАЯ вкладка браузера, а не запомненная при создании драйвера.

        Раньше было `self.page = br.page` один раз в __init__. Стоило человеку
        открыть карточку в новой вкладке (или сайту сделать это за него), как
        драйвер продолжал читать СТАРУЮ страницу: номер не находился, статус
        был пустой, «человек не открыл карточку». Свойство всегда отдаёт то,
        с чем браузер работает сейчас, — включая вкладку, на которую он
        перешёл вслед за человеком (`Browser.вкладка_человека`).
        """
        return self.br.page

    @abstractmethod
    def search(self, c: Company) -> list[Candidate]:
        """Открыть реестр, вбить имя, вернуть список кандидатов из выдачи."""

    @abstractmethod
    def open(self, cand: Candidate) -> None:
        """Открыть карточку выбранной фирмы."""

    def check(self, c: Company) -> tuple[bool, str]:
        """Проверка статуса на карточке. (годна?, причина отказа)."""
        return True, ""

    @abstractmethod
    def fetch(self, c: Company, dest: Path) -> Path:
        """Положить готовый документ по пути dest."""

    # ДЫРА №8: официальный номер фирмы (IČO, KRS, orgnr, CVR, KVK...).
    # Часть 2 достаёт его из реестра и ВПИСЫВАЕТ ОБРАТНО в Excel — он становится
    # постоянным ключом фирмы (имя может смениться, номер — нет).
    номер_regex: str = r"\b(\d[\d\s./-]{5,})\b"

    def номер(self) -> str:
        """Номер со страницы фирмы. Гео может переопределить под свой формат."""
        import re
        try:
            m = re.search(self.номер_regex, self.page.inner_text("body"))
            return m.group(1).strip() if m else ""
        except Exception:
            return ""

    def карточка_открыта(self) -> bool:
        """
        ДЫРА №7: после «Продолжить» человек мог НЕ открыть карточку.
        Прежде чем качать — убеждаемся, что на странице есть карточка фирмы.

        СПРАШИВАЕМ ТРИ РАЗНЫХ ИСТОЧНИКА, а не один. Раньше здесь стояло
        `bool(self.номер())`, и этого было мало: почти каждый драйвер
        переопределяет `номер()` так, что тот отдаёт ПОЛЕ, заполняемое внутри
        `check()`. Пока `check()` не отработал — поле пустое; а если он вышел
        раньше времени (статус не тот, страница не догрузилась), оно пустое и
        после. Человек открывал нужную карточку и трижды получал «Не вижу
        карточку фирмы», после чего фирму выбрасывали. Живой случай 12.09:
        Швейцария, AQUA AG, карточка открыта на zefix.ch/…/firm/518110.

        Порядок: номер драйвера → признак карточки самого гео (у CH это
        «/firm/» в адресе) → общее правило «на странице есть длинный номер».
        Любого хватает: мы отвечаем на вопрос «человек показал карточку?», и
        в спорном случае верить человеку правильнее, чем выбрасывать фирму.
        """
        if self.номер():
            return True
        свой = getattr(self, "на_карточке", None)
        if callable(свой):
            try:
                if свой():
                    return True
            except Exception:
                pass
        return bool(GeoDriver.номер(self))

    def extra_fields(self) -> dict:
        """Доп-поля гео (напр. FR: siren/siret). По умолчанию пусто."""
        return {}

    def данные_реестра(self) -> dict:
        """
        ДАННЫЕ ФИРМЫ ИЗ РЕЕСТРА (с открытой карточки) — то, чему верим и по чему
        подаём в Google Ads. Ядро пишет их в колонку «Платёжный профиль выписки»
        и сверяет адрес с Частью 1.

        Ключи (все необязательны):
            имя, адрес, город, индекс, штат, меняли_имя (bool)
        Пусто = гео ещё не реализовало метод (колонка останется пустой).
        """
        return {}

    # ---- пагинация выдачи (для многолюдных запросов вроде «Heat») ----
    # Ядро ищет фирму ПО АДРЕСУ Части 1 и, если на текущей странице её нет,
    # листает выдачу дальше. Гео без пагинации оставляют значения по умолчанию.

    def следующая_страница(self) -> bool:
        """Перейти на следующую страницу выдачи. True — перешли, False — больше нет."""
        return False

    def кандидаты_страницы(self) -> list:
        """Собрать кандидатов с ТЕКУЩЕЙ страницы выдачи (после следующая_страница)."""
        return []
