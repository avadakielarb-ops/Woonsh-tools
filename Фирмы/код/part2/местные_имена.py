"""
НАПИСАНИЯ ДО ПРОГОНА: как фирма записана в реестре своей страны.

Беда простая и общая. DnB даёт имя латиницей и без диакритики: «A.L Timber
Components OU». В реестре та же фирма — «A.L Timber Components OÜ», и это
разные строки для любого поиска. Так же живут чешское «s.r.o.» с длинными
именами, словенские «š/č/ž», латышские «ķ/ļ/ņ», венгерские «ő/ű». Фирма есть,
а найти её нечем.

КАК БЫЛО ДО 20.10.2026: «ящик ненайденных». Фирму искали по имени DnB, потом
упрощёнными запросами (без формы, первые слова), не нашли — откладывали, а
после страны спрашивали модель и проходили ещё раз. На фирму уходило до семи
запросов в реестр, и время съедали именно угадывания.

КАК ТЕПЕРЬ (решение пользователя 20.10.2026): весь список страны ДО прогона
уходит в модель пачками, ответ — два написания на фирму:
  · «реестр»   — как она стоит в государственном реестре, с местными буквами;
  · «латиница» — то же латиницей, как пишут по-английски.
Ищем сразу ими, и фирма находится с первого запроса.

ПО ОДНОЙ СТРАНЕ — правило пользователя: «чтобы не запутывать апи». Ответы
кладём в кэш: второй прогон той же страны модель не зовёт.
"""
from __future__ import annotations

import json
from pathlib import Path

from part1.слова_gemini import спросить_любой

# Ответ строго по схеме: модель любит добавлять пояснения, а нам нужен список.
СХЕМА = {
    "type": "ARRAY",
    "items": {
        "type": "OBJECT",
        "properties": {
            "было": {"type": "STRING"},
            "реестр": {"type": "STRING"},
            "латиница": {"type": "STRING"},
        },
        "required": ["было", "реестр", "латиница"],
    },
}

# ПРАВОВУЮ ФОРМУ НЕ ПРОСИМ ДОПИСЫВАТЬ. Первая версия промпта звала её «обычной
# для этой страны», и модель прилежно вешала «Oy» на каждое имя: «ANVIL MUSIC
# PRODUCTIONS» → «Anvil Music Productions Oy» (живая проверка 15.10.2026, 4 из
# 5 имён). Пользы ноль: драйверы ищут по имени БЕЗ формы. А вред есть: имя,
# изменившееся только хвостом, выглядит «исправленным».
ПРОМПТ = """Ты знаешь, как названия фирм пишутся в официальных реестрах {страна}.

Вот {сколько} названий так, как их записал международный справочник DnB —
латиницей и обычно без местных букв. Мы будем искать эти фирмы в
государственном реестре {страна}.

Для каждого названия верни два написания:
• «реестр» — под которым фирма стоит в реестре {страна}: с местными буквами;
• «латиница» — то же название обычной латиницей, как его пишут по-английски.

Правила:
• меняй ТОЛЬКО написание, не придумывай других фирм и не переводи слова;
• восстанавливай диакритику ({примеры});
• правовую форму НЕ ДОБАВЛЯЙ, если её в названии не было;
• правовую форму, которая БЫЛА, поправь на местную (OU → OÜ, Ltd → Oy);
• не уверен — верни название без изменений в оба поля;
• «было» — название ровно как в списке, символ в символ;
• ответ строго списком, без пояснений.

Названия:
{список}"""

# СТРАНЫ, ГДЕ СПРАШИВАТЬ НЕЧЕГО. Имена там пишутся обычной латиницей, без
# диакритики и без своей правовой формы: «BRONZE WING TRADING LTD» в реестре
# записано ровно так же, как в DnB. Модель на таком списке честно отвечает
# «без изменений» на всё — запрос ради запроса.
#
# ПЕРЕЧИСЛЯЕМ ЯВНО, а не «у кого нет подсказки». Подсказки нет и у новой
# страны, которой её просто ещё не написали, — и там написания нужны.
БЕЗ_МЕСТНЫХ = {"AU", "UK", "GB", "US", "IE", "NZ", "CA"}

# Чем именно отличается местное написание — подсказка модели по стране.
ПОДСКАЗКИ = {
    "EE": "OU → OÜ, а → ä, о → ö, у → ü, õ",
    "CZ": "s.r.o., á é í ó ú ů č ď ě ň ř š ť ž",
    "SK": "s.r.o., á ä č ď é í ĺ ľ ň ó ô ŕ š ť ú ý ž",
    "SI": "d.o.o., s.p., č š ž",
    "HR": "d.o.o., j.d.o.o., č ć đ š ž",
    "LV": "SIA, ā č ē ģ ī ķ ļ ņ š ū ž",
    "LT": "UAB, ą č ę ė į š ų ū ž",
    "PL": "sp. z o.o., ą ć ę ł ń ó ś ź ż",
    "HU": "Kft., Zrt., á é í ó ö ő ú ü ű",
    "FI": "Oy, ä ö å",
    "SE": "AB, å ä ö",
    "NO": "AS, æ ø å",
    "DK": "ApS, A/S, æ ø å",
    "DE": "GmbH, ä ö ü ß",
    "AT": "GmbH, ä ö ü ß",
    "CH": "GmbH, AG, Sàrl, ä ö ü é è",
    "FR": "SAS, SARL, à â ç é è ê î ô û",
    "BE": "BV, SRL, é è ê ï",
    "NL": "B.V., ë ï é",
    "BG": "ООД, ЕООД, АД — кириллица",
    "RO": "S.R.L., ă â î ș ț",
}

ПАЧКА = 80          # имён в одном запросе: больше — модель начинает терять строки


def _файл_кэша() -> Path:
    from common import пути
    return пути.ДАННЫЕ / "имена_реестра.json"


def _прочитать_кэш(путь: Path) -> dict:
    try:
        return json.loads(путь.read_text(encoding="utf-8"))
    except Exception:
        return {}


def _записать_кэш(путь: Path, кэш: dict) -> None:
    try:
        путь.parent.mkdir(parents=True, exist_ok=True)
        временный = путь.with_suffix(".tmp")
        временный.write_text(json.dumps(кэш, ensure_ascii=False, indent=1),
                             encoding="utf-8")
        временный.replace(путь)
    except Exception:
        pass                       # кэш — удобство, не условие работы


def _страна(гео: str) -> str:
    # НАЗЫВАЕМ СТРАНУ ПО ИМЕНИ, А НЕ КОДОМ. С «реестрах FI» модель путалась:
    # на финское «Aqua Team OU» вернула эстонское «OÜ» вместо «Oy» (живая
    # проверка 15.10.2026).
    try:
        from part1.data.countries import CODE_TO_NAME
        return f"{CODE_TO_NAME.get(гео, гео)} ({гео})"
    except Exception:
        return гео


def _спросить_пачку(гео: str, имена: list[str], log, api_key) -> dict[str, dict]:
    промпт = ПРОМПТ.format(
        страна=_страна(гео), сколько=len(имена),
        примеры=ПОДСКАЗКИ.get(гео, "местные буквы этой страны"),
        список="\n".join(f"- {и}" for и in имена))
    # Температура низкая намеренно: нужно ОДНО правильное написание.
    сырое = спросить_любой(промпт, api_key, схема=СХЕМА, температура=0.2, log=log)
    пары = json.loads(сырое)
    свои = {и.casefold(): и for и in имена}
    вышло: dict[str, dict] = {}
    for п in пары if isinstance(пары, list) else []:
        п = п or {}
        исходное = свои.get(str(п.get("было", "")).strip().casefold())
        if not исходное:
            continue                           # чужое имя в ответе не берём
        вышло[исходное] = {"реестр": str(п.get("реестр", "")).strip(),
                           "латиница": str(п.get("латиница", "")).strip()}
    return вышло


def написания(гео: str, имена: list[str], log=print, api_key: str | None = None,
              кэш_путь: Path | None = None) -> dict[str, list[str]]:
    """
    {имя DnB → [другие написания]} для всей страны — ДО прогона.

    В списке только НОВОЕ: написание, совпавшее с исходным, искать незачем.
    Пусто — модель не помогла или спрашивать нечего; прогон идёт по имени DnB.
    Модель молчит — не беда, прогон не падает.
    """
    гео = (гео or "").upper()
    имена = [и for и in dict.fromkeys((и or "").strip() for и in имена) if и]
    if not имена or гео in БЕЗ_МЕСТНЫХ:
        return {}
    путь = кэш_путь or _файл_кэша()
    кэш = _прочитать_кэш(путь)
    нет = [и for и in имена if f"{гео}|{и}" not in кэш]
    if нет:
        log(f"  · {гео}: спрашиваю у модели реестровое написание {len(нет)} фирм "
            f"(из кэша {len(имена) - len(нет)})")
    спрошено = 0
    for i in range(0, len(нет), ПАЧКА):
        пачка = нет[i:i + ПАЧКА]
        try:
            ответ = _спросить_пачку(гео, пачка, log, api_key)
        except Exception as e:
            log(f"  · модель не подсказала написание ({type(e).__name__}: "
                f"{str(e)[:60]}) — ищу по имени DnB")
            break
        for и in пачка:
            # Пропавшее в ответе имя тоже кладём (пустым): иначе каждый прогон
            # спрашивал бы его снова и снова.
            кэш[f"{гео}|{и}"] = ответ.get(и, {"реестр": "", "латиница": ""})
        спрошено += len(пачка)
        _записать_кэш(путь, кэш)

    итог: dict[str, list[str]] = {}
    for и in имена:
        з = кэш.get(f"{гео}|{и}") or {}
        новые = [в for в in dict.fromkeys((з.get("реестр", ""), з.get("латиница", "")))
                 if в and в.casefold() != и.casefold()]
        if новые:
            итог[и] = новые
    if спрошено or итог:
        log(f"  · {гео}: другое написание есть у {len(итог)} из {len(имена)}")
    return итог
