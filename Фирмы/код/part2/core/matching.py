def normalize(name: str) -> str:
    """
    КЛЮЧ ХРАНЕНИЯ: «DIAMOND SHINE Kft.» и «Diamond Shine kft» → «diamond shine».

    НЕ МЕНЯТЬ. По нему записаны журнал бота (ключ_журнала), отпечатки реестра
    фирм и колонка «Ключ» листа «Реестр». Другой ответ на то же имя — и всё
    записанное станет «новым»: фирмы уйдут боту второй раз.

    ДЛЯ СРАВНЕНИЯ ИМЁН НЕ ГОДИТСЯ: формы режет где угодно, а не с краёв, и
    обратные кавычки/амперсанды оставляет как есть. Сравнение — `ключ_имени`.
    """
    s = unicodedata.normalize("NFKD", name or "")
    s = "".join(c for c in s if not unicodedata.combining(c))
    s = s.lower()
    for a, b in (("ł", "l"), ("ø", "o"), ("đ", "d"), ("ð", "d"),
                 ("ħ", "h"), ("ß", "ss")):
        s = s.replace(a, b)
    s = re.sub(r"[.,\"'()\-/]", " ", s)
    s = re.sub(r"\s+", " ", s).strip()
    for form in sorted(LEGAL_FORMS, key=len, reverse=True):
        s = re.sub(rf"(^|\s){re.escape(form)}(\s|$)", " ", s)
    s = re.sub(r"\s+", " ", s).strip()
    сл = s.split()
    полов = len(сл) // 2
    if полов and сл[:полов] == сл[полов:]:
        s = " ".join(сл[:полов])
    return s


