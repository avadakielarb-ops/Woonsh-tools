"""
Каскад сопоставления (одинаковый для ВСЕХ гео — так решили):

    1) ИМЯ: точное совпадение ключа имени (с учётом реестрового написания);
    2) несколько полных тёзок → различаем по АДРЕСУ;
    3) всё ещё не уверены → зовём ЧЕЛОВЕКА.

Правило существует, чтобы никогда не скачать выписку не на ту фирму.

АДРЕС — ВТОРОСТЕПЕННЫЙ ПРИЗНАК (правило пользователя 20.10.2026: «адрес с dnb
может не биться с адресом фирмы по выписке, а мы ориентируемся на выписку»).
DnB часто держит адрес бухгалтера или старый офис, реестр — юридический. Так
что адрес:
  • НЕ ВЫБИРАЕТ фирму, когда имя не совпало;
  • НЕ ОТКЛОНЯЕТ фирму с совпавшим именем — кроме имён из одного слова
    («ICE», «ONE»): такие тёзки разбросаны по всей стране;
  • различает ПОЛНЫХ тёзок, когда их несколько.

До 20.10.2026 сравнений адреса было пять, и на одну пару они отвечали по-
разному: одна «подтверждено», другая «не похоже», третья «нечего сравнивать —
похоже». Теперь сверка одна (`адрес_сходится`), и у неё три ответа.
"""
