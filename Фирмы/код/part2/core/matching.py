def токены_адреса(s: str) -> set[str]:
    """
    Значимые слова адреса: буквенные ≥3 букв ИЛИ числа ≥4 цифр (индекс),
    без слов-типов улицы. Диакритику складываем: реестры и DnB пишут её как
    попало, и «Järve» без точек не должно стать другим словом.
    """
    т = unicodedata.normalize("NFKD", s or "")
    т = "".join(c for c in т if not unicodedata.combining(c)).lower()
    for a, b in (("ł", "l"), ("ø", "o"), ("đ", "d"), ("ß", "ss"), ("ħ", "h")):
        т = т.replace(a, b)
    return set(re.findall(r"[a-zа-яё]{3,}|\d{4,}", т)) - АДРЕС_СТОП


def адрес_сходится(наш: str, их: str, индекс: str = "") -> bool | None:
    """
    ЕДИНСТВЕННАЯ сверка адреса. Три ответа:

      True  — сходится: наш индекс буквально в их адресе, ИЛИ ≥2 общих
              значимых слова, ИЛИ их короткий адрес целиком внутри нашего;
      False — спорит: с обеих сторон по ≥2 значимых слова и ни одного общего;
      None  — НЕ ЗНАЕМ: адреса нет, он скудный или совпало одно слово.

    «Не знаем» — не «похоже» и не «чужая». Раньше пустой адрес считался
    похожим, и фирма «подтверждалась» адресом, которого никто не видел.
    """
    if not (их or "").strip() or not ((наш or "").strip() or (индекс or "").strip()):
        return None
    if индекс and индекс.strip().lower() in их.lower():
        return True
    p, r = токены_адреса(наш), токены_адреса(их)
    if len(p & r) >= 2:
        return True
    if r and p and r <= p:
        return True
    if len(p) >= 2 and len(r) >= 2 and not (p & r):
        return False
    return None


def _лучший_по_адресу(наш: str, кандидаты: list):
    """
    Из нескольких ПОЛНЫХ ТЁЗОК выбрать явно лучшего по адресу — или никого.

    FR «CRYSTAL» ×2 в Aulnay-sous-Bois: индекс и город есть у обоих, решает
    улица. Победитель — кто набрал ≥3 значимых слова и оторвался от второго
    минимум на два.
    """
    наши = токены_адреса(наш)
    if len(наши) < 3 or len(кандидаты) < 2:
        return None
    счёт = sorted(((len(наши & токены_адреса(k.address or "")), k) for k in кандидаты),
                  key=lambda x: x[0], reverse=True)
    if счёт[0][0] >= 3 and счёт[0][0] - счёт[1][0] >= 2:
        return счёт[0][1]
    return None


# ── ИМЯ ────────────────────────────────────────────────────────────────────

@dataclass
class Candidate:
    """Строка из выдачи реестра."""
    name: str
    address: str = ""
    url: str = ""
    ref: object = None      # что угодно: locator, id, номер — драйверу виднее
    aliases: tuple = ()     # прежние имена (UK: «Matching previous names») — запасной матч


def имена_родня(наше: str, чужое: str) -> bool:
    """
    Похожи ли имена настолько, чтобы это могла быть та же фирма.

    Считаем роднёй, если общих значимых слов БОЛЬШЕ половины меньшего имени:
    «Packaged Ice» и «Gala Ice» по одному «ice» — не родня. Для имён из двух
    слов требуются оба.
    """
    a = set(ключ_имени(наше).split())
    b = set(ключ_имени(чужое).split())
    if not a or not b:
        return False
    общие = a & b
    меньшее = min(len(a), len(b))
    return len(общие) >= (меньшее + 2) // 2


def _ключи_кандидата(k) -> set[str]:
    return {ключ_имени(и) for и in (k.name, *getattr(k, "aliases", ())) if и}


def родня(наши_имена, k) -> bool:
    """Похож ли кандидат на какое-нибудь из наших написаний (с его прежними именами)."""
    имена = [наши_имена] if isinstance(наши_имена, str) else list(наши_имена)
    return any(имена_родня(н, и) for н in имена if н
               for и in (k.name, *getattr(k, "aliases", ())) if и)


def без_повторов(кандидаты: list) -> list:
    """
    Одна фирма — один кандидат. Повторы схлопываем по номеру в реестре (ref),
    а где номера нет — по имени и адресу.

    Иначе одна и та же фирма становилась «двумя тёзками» и выбор сдавался:
    её приносили два запроса подряд, или реестр сам показывал её дважды (ABR
    — под юридическим и торговым именем с одним ABN). Со стороны это и
    выглядело как «нашёл слово в слово — и пишет, что совпадения нет».
    """
    видели, вышло = set(), []
    for k in кандидаты:
        ref = k.ref
        if isinstance(ref, (str, int)) and str(ref) not in ("", "HUMAN"):
            метка = ("ref", str(ref))
        elif isinstance(ref, dict) and ref.get("bid"):
            метка = ("ref", str(ref["bid"]))
        else:
            метка = (ключ_имени(k.name), (k.address or "").strip().lower())
        if метка not in видели:
            видели.add(метка)
            вышло.append(k)
    return вышло


def выбрать(имена, адрес: str, индекс: str, кандидаты: list):
    """
    ЕДИНСТВЕННЫЙ ВЫБОР ФИРМЫ ИЗ ВЫДАЧИ. Возвращает (кандидат | None, почему).

    имена — наше имя и его написания (реестровое от модели, латиницей): фирма
    совпала, если её ключ равен ключу ЛЮБОГО из них.

      1) ровно один точный — берём; адрес может только ОТВЕТИТЬ «спорит» для
         имени из одного слова (тёзки «ICE» по всей стране);
      2) точных несколько — различаем адресом (подтверждён ровно один или
         один явно лучший);
      3) точных нет, но в выдаче ОДНА фирма и она родня нашему имени из ≥2
         слов — это она: реестр показал одну карточку («одна карточка» раньше
         считалась «пусто»), а имя пишется чуть иначе («Aqua Team» → «Aqua
         Team Services»). Адрес и тут может только возразить.
    Иначе None — решает человек.
    """
    имена = [имена] if isinstance(имена, str) else [и for и in имена if и]
    # Обрезанное имя сравниваем без огрызка: «… KOMANDYTOWA [ W...» иначе
    # не совпадёт ни с чем.
    имена = [без_обреза(и) if обрезано(и) else и for и in имена] + \
            [и for и in имена if обрезано(и)]
    ключи = {ключ_имени(и) for и in имена if not обрезано(и)} - {""}
    кандидаты = без_повторов(кандидаты or [])
    if not кандидаты or not ключи:
        return None, "выдача пуста"
    главное = ключ_имени(имена[0])
    одно_слово = len(главное.split()) <= 1

    # Сперва по ТЕКУЩЕМУ имени, и только если никого — по прежним (UK: у
    # переименованной фирмы старое имя бывает текущим у другой).
    точные = [k for k in кандидаты if ключ_имени(k.name) in ключи]
    if not точные:
        точные = [k for k in кандидаты if _ключи_кандидата(k) & ключи]
    if len(точные) == 1:
        k = точные[0]
        if одно_слово and адрес_сходится(адрес, k.address, индекс) is False:
            return None, "имя из одного слова, а адрес спорит"
        return k, "точное имя"
    if len(точные) > 1:
        # ИМЯ ВМЕСТЕ С ФОРМОЙ — тоже имя, и сильнее адреса. ABR, живая проверка
        # 20.10.2026: наша «ANVIL ADVISORY PTY LTD» и чужое торговое имя
        # «Anvil Advisory» с другим ABN — без формы ключи равны, и фирма,
        # найденная слово в слово, уходила в «неоднозначное совпадение».
        # Так в прогоне 19.10 пропали 36 австралийских фирм из 100.
        полные = {полное_имя(и) for и in имена}
        с_формой = [k for k in точные if полное_имя(k.name) in полные]
        if len(с_формой) == 1:
            return с_формой[0], "тёзки, совпало вместе с правовой формой"
        подтв = [k for k in точные if адрес_сходится(адрес, k.address, индекс)]
        if len(подтв) == 1:
            return подтв[0], "тёзки, различил адресом"
        лучший = _лучший_по_адресу(адрес, подтв or точные)
        if лучший is not None:
            return лучший, "тёзки, различил улицей"
        return None, f"полных тёзок {len(точные)}, адрес не различает"

    # ОБРЕЗАННОЕ ИМЯ («… JANISZEWSKI DA...») целиком не совпадёт ни с чем —
    # сравниваем по НАЧАЛУ: реестровое имя должно начинаться с того, что DnB
    # успел написать. Ровно одна такая фирма — она.
    начала = [ключ_имени(без_обреза(и)) for и in имена if обрезано(и)]
    начала = [н for н in начала if len(н.split()) >= 2]
    if начала:
        по_началу = [k for k in кандидаты
                     if any(ключ_имени(k.name).startswith(н) for н in начала)]
        if len(по_началу) == 1:
            return по_началу[0], "имя обрезано, совпало начало"

    if len(кандидаты) == 1 and not одно_слово and родня(имена, кандидаты[0]):
        k = кандидаты[0]
        if адрес_сходится(адрес, k.address, индекс) is False:
            return None, "одна похожая фирма, но адрес спорит"
        return k, "одна похожая фирма в выдаче"
    return None, "точного имени нет"


def pick(ours_name: str, ours_addr: str, candidates: list[Candidate],
         human: HumanGate, имена=(), индекс: str = "") -> Candidate:
    """Выбор с человеком в конце: сам не выбрал — показываем список."""
    if not candidates:
        raise LookupError("в реестре ничего не найдено")
    k, _ = выбрать([ours_name, *имена], ours_addr, индекс, candidates)
    if k is not None:
        return k
    if len(candidates) == 1:
        один = candidates[0]
        human.choose(ours_name,
                     [f"{один.name} — {один.address or '(адрес не показан)'}"
                      + ("" if родня([ours_name, *имена], один)
                         else "   ← имя не похоже на наше")],
                     наш_адрес=ours_addr)
    else:
        # Показываем и НАШ адрес, и адрес каждого кандидата — иначе выбирать
        # не из чего: список чужих названий без точки отсчёта.
        human.choose(ours_name,
                     [f"{c.name} — {c.address or '(адрес не показан в выдаче)'}"
                      for c in candidates],
                     наш_адрес=ours_addr)
    # Человек сам открыл нужную карточку в браузере; драйвер продолжит с текущей
    # страницы. Возвращаем маркер "выбрано руками".
    return Candidate(name=ours_name, address=ours_addr, ref="HUMAN")
