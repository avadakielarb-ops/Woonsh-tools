r"""
ВЫХЛОП ПО СЛОВАМ: сколько фирм принесло каждое слово и каких именно.

Слово — это поисковый запрос, которым Часть 1 прочёсывает dnb.com. Слова
разные: одно тащит сотни фирм без сайта и почти ни одной с сайтом, другое
наоборот. До сих пор мы этого не видели и гоняли всё подряд.

ОТКУДА ДАННЫЕ. Из самой таблицы: в каждой строке стоит колонка «Слово» —
то, по которому фирма нашлась. Замер 23.09.2026: 15710 строк со словом,
287 разных слов, 345 пар «гео + слово». Ничего копить и заводить не нужно,
всё уже записано.

ДВЕ ЛИНИИ СУДИМ ПО-РАЗНОМУ. Для «с сайтом» важна ДОЛЯ: слово, давшее 2
фирмы с сайтом из 274, — тупизм, сколько его ни гоняй. Для «без сайта»
важен объём: там сайт и не нужен.

ПОЧЕМУ ДОЛЯ, А НЕ ЧИСЛО. Слова гоняли разное количество раз, и по
абсолютному числу выходило бы, что редкое слово плохое, — а оно просто
молодое. Доля сравнивает честно. Распределение долей (выборка от 30 фирм,
23.09.2026): нижние 10% слов — ниже 1%, четверть — ниже 2,3%, медиана 5,5%.
Отсюда и порог по умолчанию.
"""
from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common.статусы import ГОДНАЯ, ОТКЛОНЕНА

# Листы, чьё имя НЕ говорит о стране: там гео берут из колонки.
ОБЩИЕ_ЛИСТЫ = {"Мультигео", "Недостойные", "Отработано"}

# «РЕЕСТР» НЕ СЧИТАЕМ. Там лежит по строке на КАЖДУЮ виденную фирму — 10712
# штук, со словом и без колонки «Website». Посчитай его — и каждая фирма
# учтётся дважды, причём второй раз как «без сайта»: у эстонского «velvet»
# выходило 4 с сайтом и 4 без, хотя на деле все четыре с сайтом. Доля
# схлопывалась ровно вдвое, и слова выглядели тупее, чем есть.
МИМО = {"Реестр", "Слова", "Лог"}

# Сколько фирм должно быть найдено словом, прежде чем о нём можно судить.
# Меньше — это не «плохое слово», а «мало гоняли»: разница принципиальная,
# и путать её значит выбрасывать хорошие слова, не дав им поработать.
МИНИМУМ = 30

# Доля фирм с сайтом, ниже которой слово для этой линии бесполезно.
ПОРОГ_САЙТА = 0.02


def пусто() -> dict:
    return {"сайт": 0, "бс": 0, "годн": 0, "откл": 0}


def собрать(гео: list[str] | None = None, log=print) -> dict[str, dict[str, dict]]:
    """
    {гео: {слово: {сайт, бс, годн, откл, всего, доля}}} — по всей таблице.
    """
    from common import таблица as т

    нужны = {г.strip().upper() for г in (гео or []) if г and г.strip()}
    сырое: dict[tuple[str, str], dict] = defaultdict(пусто)
    строк = 0
    for л in т.всё(служебные=True):
        if (л.get("имя") or "") in МИМО:
            continue
        стр = л.get("строки") or []
        if not стр:
            continue
        ш = [str(х or "").strip() for х in стр[0]]
        if "Слово" not in ш or "Организация" not in ш:
            continue
        кс, ко = ш.index("Слово"), ш.index("Организация")
        кw = ш.index("Website") if "Website" in ш else -1
        кг = ш.index("Гео") if "Гео" in ш else -1
        кст = ш.index("Статус") if "Статус" in ш else -1
        свой = (None if л["имя"] in ОБЩИЕ_ЛИСТЫ
                else л["имя"].split(".")[0].upper())
        for с in стр[1:]:
            if not (ко < len(с) and str(с[ко]).strip()):
                continue
            слово = str(с[кс]).strip().lower() if кс < len(с) else ""
            if not слово:
                continue
            г = свой or (str(с[кг]).strip().upper() if 0 <= кг < len(с) else "")
            if not г or (нужны and г not in нужны):
                continue
            д = сырое[(г, слово)]
            есть_сайт = 0 <= кw < len(с) and str(с[кw]).strip()
            д["сайт" if есть_сайт else "бс"] += 1
            ст = (str(с[кст]).strip().lower() if 0 <= кст < len(с) else "")
            if ст == ГОДНАЯ:
                д["годн"] += 1
            elif ст == ОТКЛОНЕНА:
                д["откл"] += 1
            строк += 1

    итог: dict[str, dict[str, dict]] = defaultdict(dict)
    for (г, слово), д in сырое.items():
        всего = д["сайт"] + д["бс"]
        итог[г][слово] = dict(д, всего=всего,
                              доля=(д["сайт"] / всего if всего else 0.0))
    log(f"  · выхлоп: {строк} строк, слов {sum(len(v) for v in итог.values())}, "
        f"стран {len(итог)}")
    return dict(итог)


def тупые(по_словам: dict[str, dict], линия: str,
          порог: float = ПОРОГ_САЙТА, минимум: int = МИНИМУМ) -> list[str]:
    """
    Слова, бесполезные ДЛЯ ЭТОЙ ЛИНИИ.

    Для «сайт» — те, у кого доля фирм с сайтом ниже порога. Для «бс» тупых
    не бывает: там сайт не нужен, и любое слово, дающее объём, годится;
    возвращаем пустой список, чтобы вызывающему не приходилось об этом
    помнить.

    Слова с выборкой меньше «минимума» не судим вовсе — см. МИНИМУМ.
    """
    if линия != "сайт":
        return []
    плохие = [слово for слово, д in по_словам.items()
              if д["всего"] >= минимум and д["доля"] < порог]
    return sorted(плохие, key=lambda с: по_словам[с]["доля"])


def строки_отчёта(по_словам: dict[str, dict], линия: str = "сайт",
                  порог: float = ПОРОГ_САЙТА,
                  минимум: int = МИНИМУМ) -> list[tuple]:
    """Готовые строки для показа: (слово, сайт, бс, доля, годн, приговор)."""
    плохие = set(тупые(по_словам, линия, порог, минимум))
    ключ = ((lambda д: -д["доля"]) if линия == "сайт"
            else (lambda д: -д["бс"]))
    строки = []
    for слово in sorted(по_словам, key=lambda с: ключ(по_словам[с])):
        д = по_словам[слово]
        if д["всего"] < минимум:
            приговор = "мало данных"
        elif слово in плохие:
            приговор = "тупое"
        else:
            приговор = ""
        строки.append((слово, д["сайт"], д["бс"], д["доля"], д["годн"],
                       приговор))
    return строки


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    коды = [а for а in sys.argv[1:] if not а.startswith("--")]
    линия = "бс" if "--без-сайта" in sys.argv else "сайт"
    выхлоп = собрать(коды or None)
    for г in sorted(выхлоп):
        print()
        print(f"=== {г} · линия «{линия}» ===")
        print(f"  {'слово':<18}{'с сайтом':>9}{'без сайта':>11}"
              f"{'доля':>8}{'годных':>8}  приговор")
        for слово, сайт, бс, доля, годн, приговор in строки_отчёта(
                выхлоп[г], линия):
            print(f"  {слово:<18}{сайт:>9}{бс:>11}{доля*100:>7.1f}%"
                  f"{годн:>8}  {приговор}")
