r"""
ВТОРОЙ ПУТЬ ЛИНИИ «БЕЗ САЙТА»: искать фирмы ПРЯМО В РЕЕСТРЕ, минуя dnb.

Зачем. Для линии «без сайта» сайт фирме не нужен — нужны имя, адрес и выписка.
А всё это есть в самом госреестре. Идти за этим на dnb бессмысленно: он медленный,
за Cloudflare, и отдаёт как раз то, что мы потом всё равно перепроверяем в реестре.

Как это возможно без новых драйверов. У каждого гео уже есть `search(Company)` —
он вбивает ИМЯ в поиск реестра и разбирает выдачу. Реестры ищут по ЧАСТИ имени,
поэтому если подать не имя, а СЛОВО («aurora»), тот же код вернёт все фирмы, у
которых это слово в названии. Ничего нового писать не нужно — меняется только
то, что мы вводим в поле.

Что отсеиваем сразу:
  · без адреса — такая фирма бесполезна обеим линиям (правило пользователя);
  · уже использованные — по общему реестру, чтобы не выдать второй раз;
  · повторы внутри прогона.

Проверку «жива ли фирма» здесь НЕ делаем: она живёт в Части 2, на карточке, и
дублировать её значит открывать каждую карточку дважды.
"""
from __future__ import annotations

import re
from threading import Event

from common.browser import Browser
from common.human import AbortRun, HumanGate
from part1.models import Firm
from part1.registry import LocalFileRegistry, отпечаток
from part2.core.models import Company
from part2.geos.registry import DRIVERS


МАКС_СТРАНИЦ = 10      # страниц выдачи на одно слово; дальше — следующее слово


def умеет(гео: str) -> bool:
    """Есть ли у гео драйвер реестра — только с ним этот путь возможен."""
    return (гео or "").upper() in DRIVERS


def по_слову(имя: str, слово: str) -> bool:
    """
    Правда ли фирма найдена ПО ЭТОМУ слову.

    Реестры ищут по-разному, и оба перекоса нашлись на живом прогоне
    09.09.2026:
      · Польша по «amber» вернула 30 записей, среди них VISION SHIPPING,
        CHINT POLAND, A&K KRUJA — слова в названии нет вовсе (ищет ещё по
        каким-то своим полям);
      · Эстония по «ice» вернула «13July Services», «1Office Group» — слово
        нашлось ВНУТРИ другого («Serv-ice-s»), к названию отношения не имея.

    Поэтому требуем: слово стоит в НАЧАЛЕ какого-нибудь слова названия.
    «Ice Tower» и «AMBER SZCZECIN» проходят, «Services» и «1Office» — нет.
    Чужие записи не отбрасывать нельзя: они лягут в лист как добыча слова,
    и статистика выхлопа начнёт врать вслед за листом.
    """
    слово = (слово or "").strip().lower()
    if not слово:
        return True
    куски = re.split(r"[^0-9a-zA-Zа-яёА-ЯЁäöüõåæøßčšžćłńśźżāēīūģķļņáéíóúñ]+",
                     (имя or "").lower())
    return any(к.startswith(слово) for к in куски if к)


def искать(гео: str, слова: list[str], сколько: int, human: HumanGate,
           log=print, stop: Event | None = None, pause: Event | None = None,
           испробованы: list[str] | None = None) -> list[Firm]:
    """
    Набрать `сколько` фирм из реестра гео по списку слов.

    Возвращает Firm без сайта — их пишут на лист «Без сайта» тем же кодом,
    что и находки dnb, поэтому дальше всё работает как обычно.

    испробованы — сюда складываем слова, до которых РЕАЛЬНО дошли. Нужного
    числа фирм обычно хватает на втором-третьем слове, остальные так и не
    пробовались: их вызывающий вернёт в запас. Пустое слово и слово-неудача —
    разные вещи, и по числу находок их не различить.
    """
    гео = (гео or "").upper()
    if not умеет(гео):
        log(f"✘ {гео}: драйвера реестра нет — этим путём искать нечем")
        return []

    драйвер = DRIVERS[гео]
    реестр = LocalFileRegistry(log=log)
    найдено: list[Firm] = []
    видели: set[str] = set()

    log(f"{драйвер.title}: ищу в реестре напрямую, слов {len(слова)}, "
        f"нужно {сколько}")
    with Browser(profile=гео, human=human, log=log) as br:
        for слово in слова:
            if len(найдено) >= сколько or (stop and stop.is_set()):
                break
            if pause:
                while pause.is_set() and not (stop and stop.is_set()):
                    br.page.wait_for_timeout(500)
            if испробованы is not None:
                испробованы.append(слово)
            d = драйвер(br, human)
            d.log = log
            try:
                кандидаты = list(d.search(Company(row=0, name=слово)) or [])
                # ЛИСТАЕМ ВЫДАЧУ. Первая страница — двадцать строк, и на ней
                # поиск кончался: прогон 19.10 просил 100 фирм, а набрал 14 с
                # одного слова, хотя у Companies House на «aspen» страниц
                # десятки. Листаем, пока не наберём или страницы не кончатся.
                страниц = 1
                while (len(найдено) + len(кандидаты) < сколько * 2
                       and страниц < МАКС_СТРАНИЦ and d.следующая_страница()):
                    страниц += 1
                    кандидаты += list(d.кандидаты_страницы() or [])
            except AbortRun:
                raise
            except Exception as e:
                log(f"  ✘ «{слово}»: {type(e).__name__}: {str(e)[:90]}")
                continue

            взято, мимо = 0, 0
            for к in кандидаты:
                if len(найдено) >= сколько:
                    break
                имя = (к.name or "").strip()
                адрес = (к.address or "").strip()
                if not имя:
                    continue
                if not по_слову(имя, слово):
                    мимо += 1
                    continue
                if not адрес or адрес.strip().lower() == имя.lower():
                    # Правило пользователя: без адреса фирма не нужна вовсе.
                    # Адрес, равный имени, — это не адрес, а сбой разбора
                    # карточки (ловилось на «1Office Tallinn OÜ»).
                    continue
                fp = отпечаток(имя, гео, "", "")
                if fp in видели:
                    continue
                видели.add(fp)
                # «Свободна» — значит не бронировалась, не использовалась и не
                # помечена непригодной. Один вопрос вместо трёх проверок.
                if not реестр.свободна(fp):
                    continue
                # ПЛАТЁЖКА БЕЗ САЙТА — БЕЗ СТРОКИ «Website». Пустая строка
                # «Website:» в блоке, который человек копирует руками, — это
                # мусор, который он потом стирает. У этой линии сайта нет по
                # определению, и обещать его нечем.
                найдено.append(Firm(
                    name=имя, country=гео, address=адрес, слово=слово,
                    payment_profile=f"{имя}\nAddress: {адрес}"))
                взято += 1
            log(f"  · «{слово}»: в выдаче {len(кандидаты)}"
                + (f" ({страниц} стр.)" if страниц > 1 else "") + f", взял {взято}"
                + (f", мимо слова {мимо}" if мимо else "")
                + f", всего {len(найдено)} из {сколько}")

    log(f"Из реестра набрано: {len(найдено)}")
    return найдено
