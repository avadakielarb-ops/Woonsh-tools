def _ещё_раз_тот_же(dnb, keyword: str, country: str, human, log) -> bool:
    """
    Повторить ТОТ ЖЕ поиск — прежде чем поверить, что слово пустое.

    Пустая таблица значит одно из двух: слово редкое (тогда всё честно) или мы
    затупили — страница не догрузилась, фильтр страны не встал, выдача ещё
    рисуется. Отличить нельзя, а цена ошибки разная: бросив слово зря, мы
    теряем его НАВСЕГДА (повторно оно не предложится), даже если за ним стояло
    десять страниц фирм.

    Поэтому переспрашиваем сайт один раз. Появились строки — работаем дальше.
    """
    log(f"  · пусто по «{keyword}» — переспрашиваю сайт (мог не догрузиться)")
    try:
        if _искать_и_проверить(dnb, keyword, country, human, log) != ОК:
            return False
        строки = dnb.rows()
    except AbortRun:
        raise
    except Exception as e:
        log(f"    · повтор не вышел: {type(e).__name__}")
        return False
    if строки:
        log(f"    ✔ на повторе {len(строки)} фирм — слово живое, продолжаю")
        return True
    return False


def слово_из_запаса(country: str, log=print, линия: str = "") -> str:
    """
    Следующее слово для добора — из запаса, без участия человека.

    Порядок: буфер (то, что нагенерил Gemini) → просим Gemini пополнить →
    встроенный словарь. Уже отработанные по этой стране и «слабые» (дали меньше
    трёх фирм) не предлагаются — см. part1/слова.

    линия — «сайт» или «бс». Слово, признанное тупым ДЛЯ ЭТОЙ линии, не
    предлагается: эстонское «tamm» нашло 108 фирм и ровно одну с сайтом.
    Для другой линии оно остаётся в обороте — там оно из лучших.

    Пустая строка означает «слов больше нет», и только тогда добор кончается.
    """
    try:
        from part1 import слова as словарь
        from part1.запас import Запас
        from part1.data.countries import to_code
    except Exception:
        return ""
    гео = (to_code(country) or country or "").upper()
    буфер = Запас(log=lambda s: None)

    if not буфер.свободно(гео):
        log(f"  · запас слов для {гео} пуст — прошу у Gemini")
        try:
            from part1 import слова_gemini as ген
            катег: dict = {}
            новые = ген.сгенерировать(гео, 100,
                                      исключить=буфер.все_известные(гео),
                                      log=log, категории=катег)
            буфер.пополнить(гео, новые, катег)
        except Exception as e:
            log(f"  · Gemini не помог ({type(e).__name__}) — беру из словаря")

    взято = словарь.предложить(гео, 1, [], буфер=буфер, линия=линия)
    if not взято:
        log(f"  · слов для {гео} больше не осталось")
        return ""
    log(f"  🎲 Слово из запаса: «{взято[0]}» (осталось {буфер.свободно(гео)})")
    return взято[0]


def run(keyword: str, country: str, count: int, excel: Path,
        human: HumanGate, log=print, stop: Event | None = None,
        pause: Event | None = None, искать_без_сайта: bool = False,
        лист: str | None = None, свободные: list[int] | None = None,
        авто_слова: bool = False, дозапись=None,
        ускоренно: bool = False) -> dict:
    """
    Одна страна — как было раньше. искать_без_сайта — собрать фирмы БЕЗ сайта.

    лист + свободные — режим ЗАМЕНЫ ДУБЛИКАТОВ: пишем в УЖЕ СУЩЕСТВУЮЩИЙ лист и
    в конкретные его строки, освобождённые от использованных фирм. Без этого
    замена уехала бы на новый лист с сегодняшней датой (лист «23-08», а сегодня
    25-е), Часть 2 продолжила бы читать старый — и фирма выпала бы из работы.
    """
    reg = LocalFileRegistry(log=log)
    writer = ExcelWriter(excel, to_code(country), human,
                         только_без_сайта=искать_без_сайта,
                         мульти=bool(лист), лист=лист)
    if свободные:
        writer.свободные_места(свободные)
        log(f"Замена ляжет в строки: {', '.join(map(str, свободные))}")
    with Browser(profile="dnb", human=human, log=log) as br:
        dnb = DnB(br, human, log)
        try:
            return _по_стране(dnb, keyword, country, count, writer,
                              human, reg, log, stop, pause, искать_без_сайта,
                              авто_слова=авто_слова, дозапись=дозапись,
                              ускоренно=ускоренно)
        finally:
            if дозапись:
                дозапись.сбросить()


def run_задания(задания: list[dict], excel: Path, human: HumanGate, log=print,
                stop: Event | None = None, pause: Event | None = None,
                на_задание=None) -> dict:
    """
    ОБЩИЙ движок для очереди: список заданий, у каждого СВОЁ слово и количество.

    задание = {"слово": str, "страна": str, "сколько": int, "без_сайта": bool}

    Один браузер и один writer на всю пачку — всё ложится в ОДИН лист с датой,
    страна каждой строки в колонке «Гео» (см. run_мультигео). Открывать браузер
    заново под каждую строку очереди было бы и медленно, и лишний повод для
    проверки бота.

    на_задание(индекс, итог) — обратный вызов после каждой строки, чтобы окно
    очереди красило статус сразу, а не после всего прогона.
    """
    reg = LocalFileRegistry(log=log)
    итоги: list[dict] = []
    # Датированный лист не нужен, только если ВСЕ строки ищут фирмы без сайта.
    все_без_сайта = bool(задания) and all(з.get("без_сайта") for з in задания)
    writer = ExcelWriter(excel, "", human, мульти=True,
                         только_без_сайта=все_без_сайта)
    log(f"ОЧЕРЕДЬ: {len(задания)} заданий.  Файл: {excel}, лист «{writer.sheet_name}»\n")

    with Browser(profile="dnb", human=human, log=log) as br:
        dnb = DnB(br, human, log)
        for н, з in enumerate(задания):
            if stop and stop.is_set():
                log("Остановлено — оставшиеся задания пропущены.")
                break
            слово, страна = з["слово"], з["страна"]
            сколько, без = int(з["сколько"]), bool(з.get("без_сайта"))
            что = " (БЕЗ САЙТА)" if без else ""
            log(f"\n{'─' * 52}")
            log(f"[{н + 1}/{len(задания)}]  «{слово}» × {страна} × {сколько}{что}")
            log(f"{'─' * 52}")
            try:
                итог = _по_стране(dnb, слово, страна, сколько, writer,
                                  human, reg, log, stop, pause, без)
            except SkipGeo:
                # «Пропустить страну» в очереди = бросить это задание, идти дальше.
                # Без отдельной ветки оно попало бы в общий except ниже и легло
                # бы в сводку как ошибка, хотя это осознанное решение человека.
                log(f"⏭ «{слово}» × {страна} пропущено человеком")
                итог = {"взято": 0, "отсеяно": 0, "лист": writer.sheet_name,
                        "пропущено": True, "ошибка": "пропущено человеком"}
                итоги.append({**з, **итог})
                if на_задание:
                    на_задание(н, итоги[-1])
                continue
            except AbortRun:
                итог = {"взято": 0, "отсеяно": 0, "лист": writer.sheet_name,
                        "пропущено": True, "ошибка": "остановлено"}
                итоги.append({**з, **итог})
                if на_задание:
                    на_задание(н, итоги[-1])
                raise
            except Exception as e:
                log(f"✘ {страна}: {type(e).__name__}: {e}")
                итог = {"взято": 0, "отсеяно": 0, "лист": writer.sheet_name,
                        "пропущено": True, "ошибка": f"{type(e).__name__}: {e}"}
            итоги.append({**з, **итог})
            if на_задание:
                на_задание(н, итоги[-1])

    всего = sum(и["взято"] for и in итоги)
    log(f"\n{'═' * 52}")
    log("СВОДКА ОЧЕРЕДИ")
    log(f"{'═' * 52}")
    for и in итоги:
        ошибка = и.get("ошибка", "")
        пометка = ("  ⚠ " + ошибка) if ошибка else (
            "  ⏭ пропущено" if и.get("пропущено") else "")
        log(f"  «{и['слово']}» × {и['страна']:<16} взято {и['взято']:>3}, "
            f"отсеяно {и['отсеяно']:>3}{пометка}")
    log(f"\nИТОГО взято: {всего}.  Файл: {excel}, лист «{writer.sheet_name}»")
    return {"задания": итоги, "всего": всего, "файл": str(excel),
            "лист": writer.sheet_name}


def run_мультигео(keyword: str, страны: list[str], count: int, excel: Path,
                  human: HumanGate, log=print, stop: Event | None = None,
                  pause: Event | None = None, искать_без_сайта: bool = False,
                  авто_слова: bool = False, лист: str | None = None,
                  сколько_по_гео: dict[str, int] | None = None,
                  дозапись=None, ускоренно: bool = False) -> dict:
    """
    Один браузер, страны по очереди, count фирм на каждую — всё в ОДИН ЛИСТ.

    авто_слова НЕ ЗАБЫВАТЬ ПЕРЕДАВАТЬ. Здесь этого параметра не было вовсе, и
    автономный прогон на 19 странах шёл по «человеческой» ветке: страницы
    кончились — вопрос человеку. Отвечал за него робот, и отвечал первой
    кнопкой — «я перелистнул сам». Прогон часами читал одну и ту же страницу
    Австрии (лог 09.09.2026). Мультигео — как раз тот случай, ради которого
    автономность и заводили: девятнадцать стран подряд никто не досидит.

    Лист называется датой («23-08»), страны идут подряд, нумерация сквозная,
    а страна каждой строки стоит в колонке «Гео». Именно по этой колонке
    работает Часть 2: один запуск на весь лист, драйвер берётся построчно.
    Фирмы без сайта уходят на лист «Без сайта» — тоже с пометкой гео.

    Одна страна упала — прогон НЕ рушится: пишем причину и идём к следующей.
    В конце — сводка.
    """
    reg = LocalFileRegistry(log=log)
    итоги: list[dict] = []
    # ЛИСТ МОЖНО ЗАДАТЬ — это ПРОДОЛЖЕНИЕ прерванного прогона. По дате завёлся
    # бы новый лист, и добранные фирмы легли бы отдельно от вчерашних.
    writer = ExcelWriter(excel, "", human, мульти=True,
                         только_без_сайта=искать_без_сайта, лист=лист)
    что = "фирм БЕЗ САЙТА" if искать_без_сайта else "фирм"
    log(f"МУЛЬТИГЕО: {len(страны)} стран по {count} {что} — " + ", ".join(страны))
    log(f"Слово: «{keyword}».  Файл: {excel}, лист «{writer.sheet_name}»\n")

    with Browser(profile="dnb", human=human, log=log) as br:
        dnb = DnB(br, human, log)
        for н, страна in enumerate(страны, 1):
            if stop and stop.is_set():
                log("Остановлено — оставшиеся страны пропущены.")
                break
            # СКОЛЬКО ЕЩЁ НУЖНО по этой стране. При продолжении прерванного
            # прогона часть уже лежит в листе, и просить снова полную сотню
            # значит переработать вдвое.
            # Ключом может быть и название («Austria»), и код («AT») — зовущий
            # думает кодами, движок названиями, и подгонять это к одному виду
            # ради одного словаря незачем.
            надо = count if сколько_по_гео is None else int(
                сколько_по_гео.get(страна,
                                   сколько_по_гео.get(to_code(страна), count)))
            log(f"\n{'─' * 52}")
            log(f"[{н}/{len(страны)}]  {страна}"
                + (f"  (осталось добрать {надо})" if надо != count else ""))
            log(f"{'─' * 52}")
            if надо <= 0:
                log("  · уже набрано — пропускаю")
                итоги.append({"страна": страна, "взято": 0, "отсеяно": 0,
                              "лист": writer.sheet_name, "пропущено": True,
                              "ошибка": "уже набрано"})
                continue
            # ПРОГРЕСС ОТДЕЛЬНО ОТ ВОЗВРАТА. Страна может кончиться
            # исключением, и тогда возврата не будет — а сделанное уже лежит в
            # книге. Раньше сводка печатала в таких случаях ноль и врала.
            прогресс = {"взято": 0, "отсеяно": 0, "лист": writer.sheet_name}
            try:
                итог = _по_стране(dnb, keyword, страна, надо, writer,
                                  human, reg, log, stop, pause, искать_без_сайта,
                                  авто_слова=авто_слова, прогресс=прогресс,
                                  ускоренно=ускоренно,
                                  дозапись=дозапись)
                итоги.append({"страна": страна, **итог})
            except SkipGeo:
                log(f"⏭ {страна} пропущена человеком "
                    f"(успела взять {прогресс['взято']}) — иду к следующей")
                итоги.append({"страна": страна, **прогресс, "пропущено": True,
                              "ошибка": "пропущено человеком"})
                continue
            except AbortRun:
                итоги.append({"страна": страна, **прогресс, "пропущено": True,
                              "ошибка": "остановлено"})
                raise
            except Exception as e:
                log(f"✘ {страна}: {type(e).__name__}: {e} "
                    f"(успела взять {прогресс['взято']})")
                итоги.append({"страна": страна, **прогресс, "пропущено": True,
                              "ошибка": f"{type(e).__name__}: {e}"})
                # БРАУЗЕРА БОЛЬШЕ НЕТ — продолжать нечем. Раньше каждая из
                # оставшихся стран честно пыталась открыть страницу и падала
                # с той же ошибкой: одиннадцать одинаковых строк в сводке
                # вместо одной внятной.
                if "TargetClosed" in type(e).__name__ or "has been closed" in str(e):
                    log("Браузер закрыт — останавливаю прогон, "
                        "оставшиеся страны не трогаю.")
                    break
            finally:
                # Что накопилось по стране — в таблицу, не дожидаясь конца.
                if дозапись:
                    дозапись.сбросить()

    log(f"\n{'═' * 52}")
    log("СВОДКА МУЛЬТИГЕО")
    log(f"{'═' * 52}")
    всего = 0
    for и in итоги:
        всего += и["взято"]
        ошибка = и.get("ошибка", "")
        пометка = ("  ⚠ " + ошибка) if ошибка else (
            "  ⏭ пропущена" if и.get("пропущено") else "")
        log(f"  {и['страна']:<18} взято {и['взято']:>3}, "
            f"отсеяно {и['отсеяно']:>3}{пометка}")
    log(f"\nИТОГО взято: {всего}.  Файл: {excel}, лист «{writer.sheet_name}»")
    if искать_без_сайта:
        log("Дальше: Часть 3 → этот файл → найдёт сайты этим фирмам поиском.")
    else:
        log("Дальше: Часть 2 → этот файл → галочка «Мультилист» → выбрать лист "
            f"«{writer.sheet_name}». Гео возьмётся из колонки «Гео».")
    return {"страны": итоги, "всего": всего, "файл": str(excel),
            "лист": writer.sheet_name}
