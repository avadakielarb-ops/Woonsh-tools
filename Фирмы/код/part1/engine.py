# ТРИ ИСХОДА ПОИСКА, и путать их нельзя — лечатся они по-разному.
ОК = "ок"            # выдача есть и она из нужной страны — можно писать
ПУСТО = "пусто"      # фирм по этому слову нет — нужно ДРУГОЕ СЛОВО
ЧУЖАЯ = "чужая"      # фирмы есть, но не той страны — нужен человек


def _искать_и_проверить(dnb: DnB, keyword: str, country: str,
                        human: HumanGate, log) -> str:
    """
    Поиск + ОБЯЗАТЕЛЬНОЕ подтверждение страны. Возвращает ОК / ПУСТО / ЧУЖАЯ.

    Проверяем по строкам выдачи: чип фильтра может остаться от предыдущей страны
    и соврать, а колонка Country/Region — нет. Не сошлось — сначала пробуем
    переискать сами, потом зовём человека. Молча писать не в тот лист нельзя.

    ПОЧЕМУ ТРИ ИСХОДА, А НЕ «ДА/НЕТ». Пустая выдача и чужая страна — разные
    беды. Пока ответ был булевым, «по слову ничего не нашлось» приходило тем
    же «нет», что и «фильтр страны съехал», и лечилось тоже одинаково —
    пропуском страны. Австрия так потеряла 80 фирм на ровном месте.
    """
    имя = to_name(country)

    def пусто() -> bool:
        """Выдача пуста? Считаем СЫРЫЕ строки, разбор тут ни при чём."""
        считалка = getattr(dnb, "строк_в_таблице", None)
        return not (считалка() if считалка else len(dnb.rows()))

    # БЫСТРЫЙ ПУТЬ: если по этой стране уже искали, слово меняется переходом по
    # адресу — 4 секунды вместо 30. Не вышло (пусто, страна уехала, разметка
    # сменилась) — молча идём длинным путём, он всегда рабочий.
    if dnb.сменить_слово(keyword, country):
        ок, пояснение = dnb.страна_выдачи_совпадает(имя)
        if ок:
            log(f"  ✔ страна подтверждена по выдаче: {пояснение}")
            return ОК
    # СТРАНЫ НЕТ В ПОДСКАЗКЕ — ЗНАЧИТ ПО СЛОВУ В НЕЙ ФИРМ НЕТ. dnb показывает
    # страны с числом найденного («Austria (502)»), и отсутствие строки — это
    # ответ, а не сбой. Человека звать не за чем: выбирать не из чего.
    if not dnb.search(keyword, country):
        log(f"  · по слову «{keyword}» страна «{имя}» не предложена — "
            f"фирм нет, нужно другое слово")
        return ПУСТО
    переискали = False
    while True:
        ок, пояснение = dnb.страна_выдачи_совпадает(имя)
        if ок:
            log(f"  ✔ страна подтверждена по выдаче: {пояснение}")
            return ОК

        # ПУСТАЯ ВЫДАЧА — ЭТО ПРО СЛОВО, А НЕ ПРО СТРАНУ. Проверка страны
        # смотрит, какая доля строк из нужной страны; когда строк нет вовсе,
        # доля тоже ноль — и «нет фирм по слову» выглядело как «страна не
        # подтвердилась». Австрия 09.09.2026: слово «Schwalbe» ничего не нашло,
        # и прогон БРОСИЛ страну на 20 фирмах из 100, хотя в запасе оставалось
        # 83 слова. Отвечать тут надо новым словом, а не пропуском страны.
        if пусто():
            if not переискали:
                переискали = True
                log("  · пусто — повторяю поиск с нуля")
                if not dnb.search(keyword, country):
                    log(f"  · страна «{имя}» и на повторе не предложена")
                    return ПУСТО
                continue
            log(f"  · по слову «{keyword}» в «{имя}» фирм нет — нужно другое")
            return ПУСТО

        log(f"  ⚠ выдача не похожа на «{имя}»: {пояснение}")
        if not переискали:
            переискали = True
            log("  · повторяю поиск с нуля")
            if not dnb.search(keyword, country):
                return ПУСТО
            continue

        выбор = human.меню(
            "Страна не подтвердилась",
            f"Искали «{имя}», но выдача на неё не похожа:\n{пояснение}\n\n"
            "Если записать сейчас — фирмы попадут НЕ В ТОТ лист.\n"
            "Поправь фильтр страны в браузере и выбери, что делать.",
            [("проверить",  "🔍  Я поправил — проверь ещё раз"),
             ("заново",     "🔄  Переискать с нуля"),
             ("пропустить", "⏭  Пропустить эту страну"),
             ("стоп",       "■  Остановить прогон")], имя,
            # Без человека фильтр страны поправить некому: «проверить» и
            # «заново» дадут ту же неподтверждённую выдачу по кругу. Страну
            # бросаем — в мультигео это стоит одной страны, а не прогона.
            авто="пропустить")

        if выбор == "стоп" or not выбор:
            raise AbortRun("остановлено")
        if выбор == "пропустить":
            # Не пишем «страна пропущена»: решает это ВЫЗЫВАЮЩИЙ. Он сначала
            # попробует другое слово — по редкому слову в нужной стране фирм
            # может не быть, а в соседних они есть, и выдача тогда выглядит
            # чужой. Страну бросаем, только если чужая приходит подряд.
            log(f"  ⚠ выдача не из «{имя}» — по этому слову писать нечего")
            return ЧУЖАЯ
        if выбор == "заново":
            dnb.search(keyword, country)


def _по_стране(dnb: DnB, keyword: str, country: str, count: int,
               writer: ExcelWriter, human: HumanGate, reg: LocalFileRegistry, log,
               stop: Event | None, pause: Event | None,
               искать_без_сайта: bool = False, авто_слова: bool = False,
               прогресс: dict | None = None, дозапись=None,
               ускоренно: bool = False) -> dict:
    """
    Собрать count фирм по ОДНОЙ стране в готовом браузере.

    авто_слова=True — АВТОМАТИЧЕСКИЙ ДОБОР, без единого вопроса человеку.
    Слово кончилось, дало ноль фирм или страницы кончились — сами берём
    следующее из запаса и идём дальше, пока не наберём count. Так работает
    замена дубликатов: там семь стран подряд, и дёргать человека на каждое
    слово (а слова часто дают одну-две фирмы) — это часы вместо минут.
    writer уже открыт: в мультирежиме он ОДИН на все страны (общий лист),
    поэтому перед каждой страной ему просто переставляют гео.

    искать_без_сайта=True — ОБРАТНАЯ задача: нужны как раз фирмы БЕЗ сайта
    (их потом дожимает Часть 3 поиском сайта). Фирмы с сайтом тогда отсеиваются,
    найденные пишутся на лист «Без сайта» и в реестр НЕ бронируются — сайта у них
    нет, использовать их для Google Ads пока нельзя.

    ускоренно=True — НЕ ДОЧИТЫВАТЬ ПУСТОЕ СЛОВО ДО КОНЦА. Слово, на котором
    страница за страницей нет ни одной годной фирмы, дальше её не даст: у dnb
    выдача отсортирована по совпадению, и хвост всегда хуже головы. Цена
    прочёсывания видна по цифрам — на десять фирм С САЙТОМ приходится под три
    сотни без сайта. Правило: пустая ПЕРВАЯ страница закрывает слово сразу,
    дальше — две пустые подряд. Работает только вместе с авто_слова: закрыть
    слово можно лишь тогда, когда есть чем его заменить.
    """
    # СПИСОК СЛОВ через запятую: «аква, хет, хит» — ищем по очереди.
    слова = [s.strip() for s in (keyword or "").split(",") if s.strip()] or [keyword]
    индекс = 0
    keyword = слова[0]

    code = to_code(country)
    writer.гео = code                 # чем помечать строки в колонке «Гео»
    взято = отсеяно = 0

    # СЧЁТЧИК НАРУЖУ. Страна может кончиться исключением (браузер закрыли,
    # сайт лёг), и тогда возврата не будет вовсе — а сводка печатала ноль,
    # хотя фирмы уже лежали в книге. Замер 09.09.2026: Бельгия отчиталась
    # «взято 0» при полусотне записанных строк. Отчитываться надо тем, что
    # реально сделано, поэтому счётчик живёт в словаре вызывающего.
    прогресс = прогресс if прогресс is not None else {}
    прогресс.setdefault("взято", 0)
    прогресс.setdefault("отсеяно", 0)

    def посчитать() -> None:
        прогресс["взято"], прогресс["отсеяно"] = взято, отсеяно
        прогресс["лист"] = writer.sheet_name
    # защита от ДУБЛЕЙ внутри прогона: DnB показывает одну фирму дважды, а ключ
    # реестра из таблицы и с карточки не совпадает — ловим сами
    виденные_url: set[str] = set()      # карточки, уже открытые в этом прогоне
    взятые_ключи: set[str] = set()      # уже взятые фирмы (имя + сайт)

    if len(слова) > 1:
        log(f"Слова для добора ({len(слова)}): " + ", ".join(f"«{s}»" for s in слова))
    что = "фирм БЕЗ САЙТА" if искать_без_сайта else "фирм"
    log(f"Гео {code}. Ищу «{keyword}», нужно {count} {что}. Лист: {writer.sheet_name}")

    # СМЕНА СЛОВА в автоматическом режиме. Возвращает False, когда слов больше
    # нет или сменили слишком много раз — тогда честно заканчиваем.
    сменено = 0
    ПРЕДЕЛ_СМЕН = 40
    # Сколько слов подряд с чужой страной значат, что дело не в словах.
    ПРЕДЕЛ_ЧУЖИХ = 3

    # СТРАХОВКА ОТ ВЕЧНОГО КРУГА. Если выдача не сменилась, значит страницу не
    # перелистнули — кто бы что об этом ни сказал. Раньше выхода из этого не
    # было: движок спрашивал «не смог перелистнуть», в ответ приходило «я
    # перелистнул сам», он перечитывал ту же страницу, находил те же фирмы
    # дублями — и по кругу, часами (лог 09.09.2026, Австрия, 19 стран).
    # Считаем подряд идущие ОДИНАКОВЫЕ страницы: три — и слово закрыто.
    прежняя_страница: tuple = ()
    повторов_страницы = 0
    ПРЕДЕЛ_ПОВТОРОВ = 3
    # Сколько строк на ПОЛНОЙ странице. 25 — замер по всем логам: 105 страниц
    # ровно по 25 и ни одной больше. Держим как нижнюю границу, но если dnb
    # когда-нибудь начнёт показывать больше — запомним увиденное и поверим ему,
    # а не константе.
    полная_страница = ПОЛНАЯ_СТРАНИЦА
    # УСКОРЕННЫЙ РЕЖИМ: сколько страниц подряд не дали ни одной годной фирмы и
    # какая по счёту страница слова сейчас читается. Счётчики сбрасываются при
    # смене слова — иначе новое слово наследует приговор старого.
    пустых_подряд = 0
    страница_слова = 0

    def сменить_слово_само() -> bool:
        """
        Взять из запаса слово, по которому ЕСТЬ выдача. True — нашли такое.

        ПУСТОЕ СЛОВО — НЕ ПОВОД ОСТАНОВИТЬСЯ. По слову может не быть ни одной
        фирмы в этой стране, и это обычное дело, а не поломка: берём следующее
        и пробуем снова, пока слова не кончатся. Раньше пустая выдача
        возвращалась общим отказом и стоила целой страны — Австрия ушла с 20
        фирмами из 100, имея 83 слова в запасе.
        """
        nonlocal keyword, сменено, пустых_подряд, страница_слова
        # НОВОЕ СЛОВО — ЧИСТЫЙ СЧЁТ. Иначе оно унаследует пустые страницы
        # предыдущего и будет закрыто, не успев ничего показать.
        пустых_подряд = 0
        страница_слова = 0
        чужих_подряд = 0
        while True:
            if сменено >= ПРЕДЕЛ_СМЕН:
                log(f"  · сменил уже {сменено} слов — останавливаюсь, "
                    f"чтобы не крутиться")
                return False
            нов = слово_из_запаса(country, log,
                                  линия="бс" if искать_без_сайта else "сайт")
            if not нов:
                return False
            сменено += 1
            keyword = нов
            итог = _искать_и_проверить(dnb, keyword, country, human, log)
            if итог == ОК:
                return True
            if итог == ЧУЖАЯ:
                # ЧУЖАЯ СТРАНА ТОЖЕ БЫВАЕТ ПРО СЛОВО. По редкому слову в
                # нужной стране фирм нет, а в соседних есть — dnb показывает
                # их, и выдача выглядит «не той страной». Пробуем другое слово.
                # Но если чужая приходит ПОДРЯД — дело уже не в словах, а в
                # фильтре страны, и перебирать запас дальше значит сжечь его
                # впустую.
                чужих_подряд += 1
                if чужих_подряд >= ПРЕДЕЛ_ЧУЖИХ:
                    log(f"  · {чужих_подряд} слова подряд дали чужую страну — "
                        f"дело не в словах, а в фильтре страны")
                    return False
                continue
            чужих_подряд = 0        # ПУСТО — счётчик чужих ни при чём

    def не_добрали() -> bool:
        """
        Перейти к СЛЕДУЮЩЕМУ слову. True — слов больше нет, страну заканчиваем.

        Вынесено отдельно, потому что приходить сюда надо двумя путями:
        страница оказалась последней (тогда вопросов не задаём вовсе) и человек
        сам выбрал «страницы кончились». Раньше добор жил внутри разбора
        ответа на вопрос — и попасть в него, не задав вопроса, было нельзя.
        """
        nonlocal keyword, индекс
        if авто_слова:
            if сменить_слово_само():
                return False
            log(f"Слова кончились. Итого взято {взято} из {count}.")
            return True

        # ПУСТОЕ СЛОВО НЕ ЗАКАНЧИВАЕТ СТРАНУ и здесь: спрашиваем следующее,
        # пока человек не скажет «хватит» или слова не кончатся.
        while True:
            if индекс + 1 < len(слова):
                следующее = слова[индекс + 1]
                подтв = human.меню(
                    "Перейти к следующему слову?",
                    f"Набрал {взято} из {count}. Слово «{keyword}» отработано.\n"
                    f"Следующее в списке: «{следующее}».",
                    [("да",      f"▶  Да, искать «{следующее}»"),
                     ("другое",  "✍  Ввести другое слово"),
                     ("стоп",    "■  Закончить прогон")],
                    авто="да")
                if подтв == "стоп" or not подтв:
                    log(f"Остановлено. Итого взято {взято}.")
                    return True
                if подтв == "да":
                    индекс += 1
                    keyword = слова[индекс]
                    log(f"Добор по слову из списка: «{keyword}»")
                    # добор — это НОВЫЙ поиск, страну подтверждаем заново
                    итог = _искать_и_проверить(dnb, keyword, country, human, log)
                    if итог == ОК:
                        return False
                    if итог == ЧУЖАЯ:
                        return True
                    continue                 # ПУСТО — просим следующее слово

            новое = human.ask_keyword(
                f"Набрал {взято} из {count}. Слово «{keyword}» отработано.\n"
                "Впиши своё слово — или просто нажми «Искать ещё», "
                "и я возьму следующее из запаса.")
            if новое == СТОП_ДОБОРА:
                log(f"Добор остановлен человеком. Итого взято {взято}.")
                return True
            if not новое:
                # ПУСТО = «бери сам». Запас уже настроен, и заставлять человека
                # придумывать слово на каждый добор — та же ручная работа, от
                # которой уходим. Пустое поле больше не значит «закончить»:
                # для этого есть отдельная кнопка «Хватит».
                новое = слово_из_запаса(
                    country, log, линия="бс" if искать_без_сайта else "сайт")
            if not новое:
                log(f"Добор завершён. Итого взято {взято}.")
                return True
            keyword = новое
            log(f"Добор по новому слову: «{keyword}»")
            итог = _искать_и_проверить(dnb, keyword, country, human, log)
            if итог == ОК:
                return False
            if итог == ЧУЖАЯ:
                return True
            log(f"  · по «{keyword}» фирм нет — беру следующее")

    if _искать_и_проверить(dnb, keyword, country, human, log) != ОК:
        # И пусто, и чужая страна лечатся одинаково — ДРУГИМ СЛОВОМ. Добор сам
        # разберётся, где предел: слова кончились, или чужая идёт подряд и
        # значит дело уже не в словах.
        if не_добрали():
            return {"взято": 0, "отсеяно": 0, "лист": writer.sheet_name,
                    "пропущено": True}

    while взято < count:
        if stop and stop.is_set():
            raise AbortRun("остановлено")
        строки = dnb.rows()
        if not строки:
            # ПУСТАЯ ВЫДАЧА — обычное дело для редкого слова, а не поломка.
            # Но ПЕРЕД тем как бросить слово, ПЕРЕСПРАШИВАЕМ САЙТ. Пустая
            # таблица бывает и от затупа: страница не догрузилась, фильтр
            # страны не встал. Бросить в этот момент хорошее слово с десятком
            # страниц — потерять его навсегда: повторно оно не предложится.
            if авто_слова:
                if _ещё_раз_тот_же(dnb, keyword, country, human, log):
                    continue
                log(f"  · по «{keyword}» пусто и на повторе — беру следующее")
                if сменить_слово_само():
                    continue
                log(f"Слова кончились. Итого взято {взято} из {count}.")
                break
            human.stuck("на странице нет строк выдачи — проверь, открылась ли таблица")
            break

        # ПОСЛЕДНЯЯ ЛИ ЭТО СТРАНИЦА — видно по числу строк, и спрашивать об
        # этом некого. Неполная страница означает, что дальше ничего нет:
        # листать нечего, «Next» либо отсутствует, либо ничего не сделает.
        # Раньше движок всё равно жал «Next», не мог, звал человека — и на
        # странице из ДВУХ фирм («Falter», Австрия) начинался вечный круг.
        # Считаем СЫРЫЕ строки: разобранных всегда столько же или меньше.
        считалка = getattr(dnb, "строк_в_таблице", None)
        сырых = (считалка() if считалка else 0) or len(строки)
        полная_страница = max(полная_страница, сырых)
        страница_последняя = сырых < полная_страница

        # Та же самая страница, что и в прошлый заход?
        отпечаток_страницы = tuple(f.url or f.name for f in строки)
        if отпечаток_страницы == прежняя_страница:
            повторов_страницы += 1
            if повторов_страницы >= ПРЕДЕЛ_ПОВТОРОВ:
                log(f"  ⚠ выдача не меняется {повторов_страницы} раза подряд — "
                    f"страницу перелистнуть не выходит, слово «{keyword}» закрываю")
                повторов_страницы = 0
                прежняя_страница = ()
                if авто_слова and сменить_слово_само():
                    continue
                log(f"Итого взято {взято} из {count}.")
                break
        else:
            повторов_страницы = 0
        прежняя_страница = отпечаток_страницы

        log(f"На странице {len(строки)} фирм")
        страница_слова += 1
        было_взято = взято

        for f in строки:
            if взято >= count:
                break
            if stop and stop.is_set():
                raise AbortRun("остановлено")
            подождать_паузу(pause, stop)      # безопасная точка: между фирмами

            # ЭТАЖ 1 — по строке таблицы, БЕЗ открытия карточки (дёшево)
            ok, why = этаж_1(f, code, reg)
            if not ok:
                отсеяно += 1
                writer.отсев(Rejected(f.name, f.industry, "", why))
                log(f"  ✘ {f.name} — {why}")
                continue

            # дубль по карточке — второй раз её не открываем
            if f.url in виденные_url:
                log(f"  ✘ {f.name} — дубль в выдаче")
                continue
            виденные_url.add(f.url)

            # ЭТАЖ 2 — открываем карточку ради сайта и адреса (дорого)
            try:
                полная = dnb.enrich_website(f, code)
            except SkipCompany:
                continue

            if искать_без_сайта:
                # ОБРАТНЫЙ режим: сайт есть — мимо, нет сайта — то, что нужно
                if полная.website:
                    отсеяно += 1
                    log(f"  ✘ {полная.name} — есть сайт, а ищем без сайта")
                    continue
                if not writer.без_сайта(полная):
                    log(f"  ✘ {полная.name} — уже есть в листе «Без сайта»")
                    continue
                взято += 1
                посчитать()
                if дозапись:
                    дозапись.добавить(полная, code, keyword,
                                      getattr(writer, "последний_ид", ""),
                                      без_сайта=True)
                адрес = полная.address or полная.city or ""
                log(f"  ✔ [{взято}/{count}] {полная.name} — {адрес}")
                continue

            if not полная.website:
                # нет сайта — в основной лист не берём, но сохраняем в «Без сайта»
                # (организация + адрес — пригодится для будущей функции)
                writer.без_сайта(полная)
                отсеяно += 1
                log(f"  ✘ {f.name} — нет сайта (записал в лист «Без сайта»)")
                continue

            # дубль по сути (та же фирма другой строкой выдачи)
            ключ = f"{полная.name.strip().lower()}|{полная.website.strip().lower()}"
            if ключ in взятые_ключи:
                отсеяно += 1
                log(f"  ✘ {полная.name} — дубль (уже взята в этом прогоне)")
                continue
            взятые_ключи.add(ключ)

            # бронируем ОБА ключа: с карточки и из таблицы выдачи — иначе
            # та же фирма на другой странице снова пройдёт этаж 1
            reg.забронировать(отпечаток(полная.name, code, полная.zip_code, полная.city))
            reg.забронировать(отпечаток(f.name, code, f.zip_code, f.city))
            # ЧЕМ НАШЛИ — в строку. Слово меняется по ходу прогона (автодобор),
            # поэтому пишем текущее прямо перед записью, а не в начале.
            writer.слово = keyword
            writer.фирма(полная)
            взято += 1
            посчитать()
            if дозапись:
                дозапись.добавить(полная, code, keyword,
                                  getattr(writer, "последний_ид", ""))
            log(f"  ✔ [{взято}/{count}] {полная.name} — {полная.website}")

        # СТРАНИЦА ДОЧИТАНА — отдаём накопленное в таблицу. Не по одной фирме:
        # каждый запрос стоит секунды, а страница это сразу 25 строк.
        if дозапись:
            дозапись.сбросить()
        посчитать()

        if взято >= count:
            break

        # УСКОРЕННЫЙ РЕЖИМ: СЛОВО НЕ ДАЁТ — БЕРЁМ СЛЕДУЮЩЕЕ.
        #
        # Выдача dnb отсортирована по совпадению с запросом, поэтому хвост
        # всегда хуже головы: если голова пустая, дочитывать десять страниц
        # незачем. Цена прочёсывания видна по цифрам прогонов — на десять фирм
        # С САЙТОМ приходится под три сотни без сайта.
        #
        # Порог разный по счёту страницы. Первая пустая закрывает слово сразу:
        # это самая показательная страница, и если в ней нет ничего, дальше не
        # будет тем более. Со второй требуем ДВЕ пустые подряд — одна случайная
        # страница из дублей и «уже использованных» ещё ничего не значит.
        if взято == было_взято:
            пустых_подряд += 1
        else:
            пустых_подряд = 0
        предел_пустых = 1 if страница_слова == 1 else 2
        if ускоренно and авто_слова and пустых_подряд >= предел_пустых:
            log(f"  ⚡ «{keyword}»: {пустых_подряд} "
                f"{'страница' if пустых_подряд == 1 else 'страницы'} подряд "
                f"без годных фирм — не дочитываю, беру следующее слово")
            if сменить_слово_само():
                continue
            log(f"Слова кончились. Итого взято {взято} из {count}.")
            break

        # СТРАНИЦА НЕПОЛНАЯ — значит она ПОСЛЕДНЯЯ. Слово отработано, и
        # выяснять это через «Next» и вопрос человеку незачем: ответ уже
        # известен из числа строк.
        if страница_последняя:
            log(f"  · строк на странице {сырых} из {полная_страница} — "
                f"последняя. Слово «{keyword}» отработано ({взято} из {count})")
            if не_добрали():
                break
            continue

        # Листаем дальше. Не вышло — НЕ гадаем «затуп или фирмы кончились»,
        # а даём человеку ВЫБОР (ждём сколько нужно, без таймаута).
        конец = False
        while not dnb.next_page():
            # АВТОМАТИЧЕСКИ: страницы кончились — значит слово отработано,
            # берём следующее. Человека не трогаем вовсе.
            if авто_слова:
                log(f"  · страницы по «{keyword}» кончились "
                    f"({взято} из {count}) — беру следующее слово")
                if сменить_слово_само():
                    break                      # читаем выдачу нового слова
                log(f"Слова кончились. Итого взято {взято} из {count}.")
                конец = True
                break
            # В лог прогона это писать НАДО: без записи потом не понять, сколько
            # раз тебя дёргали и на чём. Раньше вопрос жил только в окне.
            log("  ⚠ не смог перелистнуть страницу — спрашиваю человека")
            выбор = human.меню(
                "Не смог перелистнуть страницу",
                f"Набрал {взято} из {count} по слову «{keyword}».\n"
                "Кнопку «Next» нажать не вышло — либо затуп, либо страницы "
                "кончились.\n\nЧто делаем?",
                [("перелистнул", "📄  Я перелистнул сам — читай эту страницу"),
                 ("ещё",         "🔄  Попробуй перелистнуть ещё раз"),
                 ("слово",       "🔍  Страницы кончились — новое слово (добор)"),
                 ("стоп",        "■  Остановить прогон")],
                # БЕЗ ЧЕЛОВЕКА — «слово». Ни «перелистнул», ни «ещё» тут не
                # годятся: первое утверждает действие, которого не было, второе
                # повторяет то, что уже не вышло. Оба крутят прогон на месте.
                авто="слово")

            if выбор == "стоп" or not выбор:
                raise AbortRun("остановлено")
            if выбор == "перелистнул":
                log("    · человек перелистнул сам — читаю текущую страницу")
                break                       # читаем строки текущей страницы
            if выбор == "ещё":
                log("    · пробую перелистнуть ещё раз")
                continue                    # ещё раз пробуем сами
            # «слово» — ДОБОР, тот же самый, что и на последней странице.
            конец = не_добрали()
            break
        if конец:
            break

    log(f"\nГотово. Взято {взято}, отсеяно {отсеяно}. Файл: {writer.path}")
    return {"взято": взято, "отсеяно": отсеяно, "лист": writer.sheet_name,
            "пропущено": False}


