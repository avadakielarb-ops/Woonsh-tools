"""
БУФЕР СЛОВ — что нагенерил Gemini и что из этого ещё не потрачено.

Зачем отдельным файлом, а не «сгенерировал и сразу в очередь»: генерация стоит
запроса и секунд, а очередь заполняется пачками по восемнадцать стран. Держим
запас на диске — тогда кнопка «Сгенерировать задания» работает мгновенно и
офлайн, а к Gemini ходим редко и большими порциями (по сотне на гео).

Слово живёт в двух состояниях: «свободно» и «выдано». Выданное не возвращается
никогда: даже если задание из очереди удалили, слово уже могло отработать —
а повтор выдаст те же забронированные фирмы, то есть сожжённый прогон.

Формат:
    {"PL": {"свободные": ["amber", …], "выданные": ["granite", …],
            "обновлено": "2026-08-25 14:02"}, …}
"""
from __future__ import annotations

import json
import os
from datetime import datetime
from pathlib import Path

from common.пути import данные

ФАЙЛ = данные("запас_слов.json")


class Запас:
    def __init__(self, path: Path = ФАЙЛ, log=None):
        self.path = Path(path)
        self.log = log or (lambda s: None)
        self.данные: dict[str, dict] = {}
        self.загрузить()

    # ---------- диск ----------

    def загрузить(self) -> None:
        if not self.path.exists():
            return
        try:
            self.данные = json.loads(self.path.read_text(encoding="utf-8"))
        except Exception as e:
            # Запас — не реестр: потеря неприятна, но не разрушительна.
            # Начинаем с пустого, а старый файл оставляем рядом для разбора.
            self.log(f"(запас слов не прочитался, начинаю пустой: {e})")
            try:
                self.path.replace(self.path.with_suffix(".битый"))
            except Exception:
                pass
            self.данные = {}

    def сохранить(self) -> None:
        """Атомарно: смерть посреди записи не должна оставить огрызок."""
        врем = self.path.with_suffix(".tmp")
        врем.write_text(json.dumps(self.данные, ensure_ascii=False, indent=1),
                        encoding="utf-8")
        os.replace(врем, self.path)

    # ---------- работа ----------

    # БРАК БЫВАЕТ ДВУХ РОДОВ, И ПУТАТЬ ИХ НЕЛЬЗЯ.
    #
    # «брак» — слова, которых не существует: модель проверила и сказала, что
    # в названиях фирм такого не встречается. Оно бесполезно везде.
    #
    # «брак_сайт» / «брак_бс» — слова НАСТОЯЩИЕ, но бесполезные для одной
    # линии. Эстонское «tamm» нашло 108 фирм и ровно одну с сайтом: под
    # «с сайтом» гонять его — время на ветер, под «без сайта» это одно из
    # лучших слов, что у нас есть. Выбросить его совсем значило бы потерять
    # сотню фирм ради экономии на другой линии.
    ЛИНИИ = ("сайт", "бс")

    def _ключ_брака(self, линия: str) -> str:
        return "брак_сайт" if (линия or "").lower() == "сайт" else "брак_бс"

    def _гнездо(self, гео: str) -> dict:
        г = (гео or "").upper()
        return self.данные.setdefault(
            г, {"свободные": [], "выданные": [], "обновлено": ""})

    def свободно(self, гео: str) -> int:
        return len(self._гнездо(гео)["свободные"])

    def все_известные(self, гео: str) -> set[str]:
        """Всё, что этот запас когда-либо знал по стране — и своё, и потраченное."""
        г = self._гнездо(гео)
        было = ({с.lower() for с in г["свободные"]}
                | {с.lower() for с in г["выданные"]}
                # брак тоже помним: иначе выброшенное слово сгенерируется снова
                | {с.lower() for с in г.get("брак", [])})
        # И ОТБРАКОВАННОЕ ПО ЛИНИИ — тоже. Слово осталось в обороте для
        # другой линии; предложи его модель заново как «новое», и мы получим
        # дубль, который вдобавок уже признан негодным.
        for линия in self.ЛИНИИ:
            было |= {с.lower() for с in г.get(self._ключ_брака(линия), [])}
        return было

    def брак_линии(self, гео: str, линия: str) -> list[str]:
        """Слова, признанные бесполезными для этой линии."""
        return list(self._гнездо(гео).get(self._ключ_брака(линия), []))

    def забраковать_для(self, гео: str, слова: list[str], линия: str) -> int:
        """
        Слово настоящее, но для ЭТОЙ линии бесполезно.

        В отличие от `забраковать`, из «свободных» НЕ вынимаем: другая линия
        продолжит им пользоваться. Отсев происходит при выдаче — см. `взять`.
        """
        if (линия or "").lower() not in self.ЛИНИИ:
            raise ValueError(f"линия «{линия}» не бывает")
        г = self._гнездо(гео)
        список = г.setdefault(self._ключ_брака(линия), [])
        было = len(список)
        for с in слова:
            if с and с.lower() not in {х.lower() for х in список}:
                список.append(с)
        if len(список) != было:
            self.сохранить()
        return len(список) - было

    def вернуть_в_оборот(self, гео: str, слова: list[str], линия: str) -> int:
        """Передумали: слово снова годится для этой линии."""
        г = self._гнездо(гео)
        список = г.get(self._ключ_брака(линия)) or []
        убрать = {с.lower() for с in слова}
        было = len(список)
        г[self._ключ_брака(линия)] = [с for с in список
                                      if с.lower() not in убрать]
        if len(г[self._ключ_брака(линия)]) != было:
            self.сохранить()
        return было - len(г[self._ключ_брака(линия)])

    def забраковать(self, гео: str, слова: list[str]) -> int:
        """
        Выбросить слова НАВСЕГДА: модель проверила и сказала, что это брак —
        такого слова нет либо в названиях фирм оно не встречается.

        Кладём в отдельный список «брак», а не удаляем молча. Во-первых, оно
        помнится и не сгенерируется заново. Во-вторых, глядя в файл, видно,
        почему запас похудел, — иначе это выглядит как потеря данных.

        РЕДКОЕ СЛОВО СЮДА НЕ ПОПАДАЕТ. «Дало мало» и «плохое» — разные вещи:
        по редкому слову фирмы есть, до них просто не дошли.
        """
        г = self._гнездо(гео)
        брак = г.setdefault("брак", [])
        плохие = {с.lower() for с in слова}
        было = len(г["свободные"])
        г["свободные"] = [с for с in г["свободные"] if с.lower() not in плохие]
        for с in слова:
            if с not in брак:
                брак.append(с)
        self.сохранить()
        return было - len(г["свободные"])

    def пополнить(self, гео: str, слова: list[str],
                  категории: dict[str, str] | None = None) -> int:
        """
        Добавить новые слова. Возвращает, сколько реально добавилось.

        категории — {слово: «камни»}. Храним отдельной картой, а не меняя
        списки на объекты: списки читает половина проекта, и переделка ради
        одного поля сломала бы всё разом. Карта живёт рядом и никому не мешает.
        """
        г = self._гнездо(гео)
        было = self.все_известные(гео)
        новые = []
        for с in слова:
            с = (с or "").strip()
            if с and с.lower() not in было:
                новые.append(с)
                было.add(с.lower())
        г["свободные"].extend(новые)
        if категории:
            карта = г.setdefault("категории", {})
            for с in новые:
                к = категории.get(с.lower())
                if к:
                    карта[с.lower()] = к
        г["обновлено"] = datetime.now().strftime("%Y-%m-%d %H:%M")
        self.сохранить()
        return len(новые)

    def категория(self, гео: str, слово: str) -> str:
        """Из какого смыслового поля слово. Пусто — из старого запаса."""
        return self._гнездо(гео).get("категории", {}).get(
            (слово or "").strip().lower(), "")

    def взять(self, гео: str, сколько: int, кроме: set[str] | None = None,
              линия: str = "") -> list[str]:
        """
        Выдать слова и СРАЗУ пометить выданными.

        Помечаем до прогона, а не после: между заполнением очереди и запуском
        может пройти час, и второй клик по кнопке обязан получить другое.

        линия — «сайт» или «бс». Отбракованное для неё пропускаем, но в
        «свободных» оставляем: другая линия им ещё воспользуется.
        """
        кроме = {с.lower() for с in (кроме or set())}
        if (линия or "").lower() in self.ЛИНИИ:
            кроме |= {с.lower() for с in self.брак_линии(гео, линия)}
        г = self._гнездо(гео)
        выдать, остаток = [], []
        for с in г["свободные"]:
            if len(выдать) < сколько and с.lower() not in кроме:
                выдать.append(с)
            else:
                остаток.append(с)
        if выдать:
            г["свободные"] = остаток
            г["выданные"].extend(выдать)
            self.сохранить()
        return выдать

    def вернуть(self, гео: str, слова: list[str]) -> None:
        """Вернуть невостребованное (задание не добавилось) обратно в свободные."""
        г = self._гнездо(гео)
        for с in слова:
            if с in г["выданные"]:
                г["выданные"].remove(с)
                г["свободные"].insert(0, с)
        self.сохранить()

    def сводка(self) -> str:
        if not self.данные:
            return "запас пуст"
        части = [f"{г}:{len(д['свободные'])}"
                 for г, д in sorted(self.данные.items()) if д["свободные"]]
        return ", ".join(части) if части else "запас израсходован"
