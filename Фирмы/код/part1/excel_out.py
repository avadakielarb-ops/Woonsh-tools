"""
Запись в Excel. Пишем и сохраняем ПОСЛЕ КАЖДОЙ фирмы.
Страна — в имени листа («19-07 FR»), чтобы Часть 2 не перепутала гео.

Колонки:
  A №  |  B Платёжный профиль  |  C Организация  |  D Адрес  |  E Город
  F Индекс  |  G Штат  |  H Website  |  I Номер в реестре  |  J Файл выписки
  K Платёжный профиль выписки  |  (L Гео — только мультилист)
  далее Слово и ID
Имя фирмы — ЦЕЛИКОМ как на карточке (без обрезки). H и I... то есть I и J заполняет Часть 2.

Хвостовые колонки дописывались по мере надобности и стоят в конце намеренно:
Часть 2 разбирает A..K по фиксированным местам, и вставка в середину сдвинула
бы всё. Сами эти колонки ищутся по ЗАГОЛОВКУ, поэтому их порядок роли не играет.
"""
from __future__ import annotations

from datetime import date
from pathlib import Path

from openpyxl import Workbook, load_workbook
from openpyxl.styles import Font, Alignment, PatternFill

from common.колонки import Шапка
# Именно функцией, а не модулем: в «фирма()» уже есть своя переменная «номер»
# (порядковый номер строки), и модуль с тем же именем она бы перекрыла.
from common.номер import новый as новый_номер

from .models import Firm, Rejected

КОЛОНКИ = ["№", "Платёжный профиль", "Организация", "Адрес", "Город",
           "Индекс", "Штат", "Website", "Номер в реестре", "Файл выписки",
           "Платёжный профиль выписки"]        # K — заполняет Часть 2 из реестра
КОЛОНКИ_ЛОГА = ["Дата", "Название", "Отрасль", "Сайт", "Причина отсева"]
КОЛОНКИ_БЕЗ_САЙТА = ["Организация", "Адрес", "Город", "Индекс"]

# МУЛЬТИЛИСТ: все страны на ОДНОМ листе, страна — в колонке «Гео».
# Колонка добавлена В КОНЕЦ намеренно: A..K уже разобраны Частью 2 по фиксированным
# местам (профиль — B, номер — I, файл — J). Вставь «Гео» в начало — всё поедет.
# Часть 2 ищет её по ЗАГОЛОВКУ, а не по номеру, так что позиция роли не играет.
ГЕО = "Гео"

# ПО КАКОМУ СЛОВУ НАЙДЕНА. Без этой колонки статистики выхлопа не бывает:
# слово нигде не связано с фирмой, и «сколько дало слово aurora» посчитать
# неоткуда. Стоит ПОСЛЕДНЕЙ — старые листы без неё читаются переходником
# как раньше, ничего не съезжает.
СЛОВО = "Слово"

# ПОСТОЯННЫЙ НОМЕР. Рождается здесь, вместе с фирмой, и дальше едет с ней
# везде: в таблицу, в архив «Отработано», в правки от Части 2. Заводить его
# позже поздно — к тому времени фирму уже ищут по имени, а именно имя и
# меняется (Часть 2 подставляет название из реестра вместо названия с dnb).
ИД = "ID"
ГОЛУБОЙ = PatternFill(start_color="DDEBF7", end_color="DDEBF7", fill_type="solid")


def имя_листа(гео: str = "", мульти: bool = False,
              лист: str | None = None) -> str:
    """
    Как будет называться лист прогона. Одно правило на всех.

    Нужно и писарю, и тем, кто должен знать имя ДО начала прогона (закладка
    «продолжить с места остановки»). Второе место, считающее имя по своей
    формуле, однажды посчитало бы иначе — и продолжение ушло бы в другой лист.
    """
    if лист and лист.strip():
        return лист.strip()
    return (f"{date.today():%d-%m}" if мульти
            else f"{date.today():%d-%m} {(гео or '').upper()}")


class ExcelWriter:
    """
    Обычный режим: один лист на страну, имя «23-08 PL».
    мульти=True:   ОДИН лист с датой («23-08»), страна в колонке «Гео»,
                   страны идут подряд, нумерация сквозная.
    """

    def __init__(self, path: Path, country_code: str, human=None,
                 мульти: bool = False, только_без_сайта: bool = False,
                 лист: str | None = None):
        self.path = path
        self.human = human
        self.мульти = мульти
        self.гео = (country_code or "").upper()
        # Гео в листе «Без сайта» нужно и в мультигео, и в режиме «ищем без сайта»:
        # там весь смысл — собирать фирмы ПО СТРАНАМ, иначе потом не разобрать.
        self._гео_в_без_сайта = мульти or только_без_сайта
        self.wb = load_workbook(path) if path.exists() else Workbook()
        if not path.exists():
            self.wb.remove(self.wb.active)

        if только_без_сайта:
            # режим «ищем фирмы БЕЗ сайта»: основной лист не нужен, всё уходит
            # на «Без сайта». Пустой датированный лист не плодим.
            self.sheet_name = "Без сайта"
            self.ws = None
            начальный_n = 0
        else:
            # ЛИСТ МОЖНО ЗАДАТЬ ЯВНО. Нужно для замены дубликатов: работаем с
            # листом «23-08», хотя сегодня 25-е. По дате мы бы завели НОВЫЙ лист,
            # замена легла бы в него, а Часть 2 продолжила читать старый — фирма
            # исчезла бы из работы совсем.
            база = имя_листа(self.гео, мульти, лист)
            if (лист or мульти) and база in self.wb.sheetnames:
                # ДОПИСЫВАЕМ в сегодняшний лист, а не плодим «23-08 (2)».
                # Это важно для возобновления после падения: иначе добранные
                # фирмы легли бы на НОВЫЙ лист, Часть 2 пошла бы по нему и не
                # увидела тех, что собрались до обрыва. Нумерация продолжается.
                self.sheet_name = база
                self.ws = self.wb[база]
                начальный_n = self.ws.max_row - 1
            else:
                имя, i = база, 2
                while имя in self.wb.sheetnames:
                    имя = f"{база} ({i})"
                    i += 1
                self.sheet_name = имя
                self.ws = self.wb.create_sheet(имя)
                колонки = self._подписи()
                self.ws.append(колонки)
                for c in self.ws[1]:
                    c.font = Font(bold=True)
                ширины = ([5, 50, 34, 30, 16, 12, 16, 26, 18, 30, 50]
                          + ([8] if мульти else []) + [14, 12])
                for col, w in zip("ABCDEFGHIJKLMN", ширины):
                    self.ws.column_dimensions[col].width = w
                if мульти:
                    # колонку «Гео» подсвечиваем — по ней работает Часть 2
                    self.ws.cell(row=1, column=колонки.index(ГЕО) + 1).fill = ГОЛУБОЙ
                начальный_n = 0

        self.log = self.wb["Лог"] if "Лог" in self.wb.sheetnames else self.wb.create_sheet("Лог")
        if self.log.max_row == 1 and self.log["A1"].value is None:
            self.log.append(КОЛОНКИ_ЛОГА)
            for c in self.log[1]:
                c.font = Font(bold=True)
        # что уже лежит в «Без сайта» — чтобы не писать одну фирму дважды
        # (у них нет сайта, значит и брони в реестре нет: дубли ловим здесь)
        self._без_сайта_ключи: set[str] = set()
        if "Без сайта" in self.wb.sheetnames:
            for имя, _адрес, город, *_ in self.wb["Без сайта"].iter_rows(
                    min_row=2, max_col=4, values_only=True):
                if имя:
                    self._без_сайта_ключи.add(
                        f"{str(имя).strip().lower()}|{str(город or '').strip().lower()}")

        # Нумерация продолжается, если дописываем в уже существующий лист.
        self.n = начальный_n
        self.save()

    def свободные_места(self, строки: list[int]) -> None:
        """
        Куда класть фирмы ВМЕСТО дописывания в конец.

        После чистки дубликатов в листе остаются строки с «№» и «Гео», но без
        фирмы. Замена обязана лечь именно туда: блоки стран идут подряд, и если
        добранную польскую фирму дописать в самый низ, за словенские строки, то
        и «строки 152–161» в отчёте перестанут сходиться, и мультилист пойдёт
        по листу не в том порядке.
        """
        self._свободные = list(строки)

    def фирма(self, f: Firm) -> None:
        свободная = None
        if getattr(self, "_свободные", None):
            свободная = self._свободные.pop(0)
        if свободная is None:
            self.n += 1
            номер = self.n
        else:
            номер = self.ws.cell(row=свободная, column=1).value or self.n
        строка = [номер, f.payment_profile, f.name, f.address, f.city,
                  f.zip_code, f.state, f.website, "", ""]
        if self.мульти:
            строка += ["", self.гео]        # K пустая (её пишет Часть 2), L — гео
        else:
            строка += [""]                  # K пустая — «Платёжный профиль выписки»
        # ПО КАКОМУ СЛОВУ НАЙДЕНА — предпоследней колонкой. Ставит движок перед
        # записью; без неё выхлоп слова посчитать неоткуда.
        # Номер запоминаем: его спрашивает живая дозапись в таблицу, чтобы
        # строка там и строка в книге были ОДНОЙ фирмой, а не двумя.
        self.последний_ид = новый_номер(self.гео)
        строка += [getattr(self, "слово", ""), self.последний_ид]
        if свободная is None:
            self.ws.append(строка)
            куда = self.ws.max_row
        else:
            # ЗАМЕНА ЛОЖИТСЯ В ЧУЖОЙ ЛИСТ. Лист мог быть создан раньше и иметь
            # свой набор колонок — тогда запись «по порядку слева» раскладывает
            # фирму мимо: адрес в город, сайт в номер реестра. Пишем по
            # ЗАГОЛОВКАМ, а порядок остаётся запасным вариантом для листов,
            # где шапки нет.
            куда = свободная
            подписи = self._подписи()
            for i, знач in enumerate(строка, start=1):
                подпись = подписи[i - 1] if i <= len(подписи) else ""
                self.ws.cell(row=куда, column=self._шапка().номер(подпись, i),
                             value=знач)
        self.ws.cell(row=куда, column=self._шапка().номер("Платёжный профиль", 2)) \
            .alignment = Alignment(wrap_text=True, vertical="top")
        if self.мульти:
            self.ws.cell(row=куда,
                         column=self._шапка().номер(ГЕО, 12)).fill = ГОЛУБОЙ
        self.save()

    def _подписи(self) -> list[str]:
        """Заголовки листа этого режима — они же порядок значений в строке."""
        return КОЛОНКИ + ([ГЕО] if self.мульти else []) + [СЛОВО, ИД]

    def _шапка(self) -> Шапка:
        """Карта колонок листа. Считаем один раз: лист за прогон не меняется."""
        if getattr(self, "_шапка_кэш", None) is None:
            self._шапка_кэш = Шапка(self.ws)
        return self._шапка_кэш

    def отсев(self, r: Rejected) -> None:
        self.log.append([f"{date.today():%d-%m-%Y}", r.name, r.industry, r.website, r.reason])
        self.save()

    def без_сайта(self, f: Firm) -> bool:
        """
        Фирма без сайта → лист «Без сайта» (организация + адрес). Его читает Часть 3.
        В мультирежиме туда же пишем гео — иначе потом не понять, чья это фирма.

        Дубли не пишем: этих фирм в реестре нет (сайта нет — бронировать нечего),
        поэтому повторные прогоны находили бы их снова и снова. Возвращает True,
        если строка действительно добавлена.
        """
        подписи = (КОЛОНКИ_БЕЗ_САЙТА
                   + ([ГЕО] if self._гео_в_без_сайта else []) + [СЛОВО, ИД])
        if "Без сайта" not in self.wb.sheetnames:
            л = self.wb.create_sheet("Без сайта")
            л.append(подписи)
            for c in л[1]:
                c.font = Font(bold=True)
            for col, w in zip("ABCDEFG", [44, 44, 20, 12, 8, 14, 12]):
                л.column_dimensions[col].width = w
        л = self.wb["Без сайта"]
        # ЛИСТ МОГ БЫТЬ ЗАВЕДЁН РАНЬШЕ — до того, как появились «Слово» и «ID».
        # Дописывать значения в безымянные колонки нельзя: их потом никто не
        # прочитает, а перенос ищет строго по заголовку. Дошиваем шапку.
        шапка = [(c.value or "") for c in л[1]]
        for подпись in подписи:
            if подпись not in шапка:
                шапка.append(подпись)
                я = л.cell(row=1, column=len(шапка), value=подпись)
                я.font = Font(bold=True)

        ключ = f"{(f.name or '').strip().lower()}|{(f.city or '').strip().lower()}"
        if ключ in self._без_сайта_ключи:
            return False
        self._без_сайта_ключи.add(ключ)
        self.последний_ид = новый_номер(self.гео)
        значения = {"Организация": f.name, "Адрес": f.address, "Город": f.city,
                    "Индекс": f.zip_code, ГЕО: self.гео,
                    СЛОВО: getattr(f, "слово", "") or getattr(self, "слово", ""),
                    ИД: self.последний_ид}
        строка = л.max_row + 1
        for i, подпись in enumerate(шапка, start=1):
            if подпись in значения:
                л.cell(row=строка, column=i, value=значения[подпись])
        self.save()
        return True

    def save(self) -> None:
        if self.human is not None:
            from common.human import сохранить_excel
            сохранить_excel(self.wb, self.path, self.human)
            return
        try:
            self.wb.save(self.path)
        except PermissionError:
            raise RuntimeError("Excel-файл открыт в Excel — закрой его, иначе я не могу писать")
