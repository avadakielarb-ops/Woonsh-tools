r"""
ПРИБРАТЬ ВЫПИСКИ: одна папка на гео и режим, дата — сегодняшняя.

Что накопилось. Правила раскладки менялись трижды, и на диске лежат все три
разом: «выписки/UK/2026-09-07_21-03_53шт», «выписки/Мультигео/23-08/PL»,
«выписки/21-07 EE», «выписки/Интересный заказ». Одна страна разбросана по
пяти местам, и ответить, где выписка конкретной фирмы, можно только обходом
всего дерева.

Что делаем. Раскладываем ВСЁ по нынешнему правилу:

    выписки/<ГЕО>/<дата>/…              обычные
    выписки/Мультигео/<дата>/<ГЕО>/…    то, что лежало в мультигео-партиях

Гео берём НЕ ИЗ ПАПКИ, а из ТАБЛИЦЫ — по имени файла. Папка врёт: файл мог
уехать не туда ещё при скачивании (так семь французских выписок оказались в
«Мультигео»), а таблица знает, чья это фирма. Не нашли в таблице — оставляем
на месте и говорим об этом: молча выбрасывать чужой труд нельзя.

Запуск:
    .venv\Scripts\python.exe код\прибрать_выписки.py            — показать
    .venv\Scripts\python.exe код\прибрать_выписки.py --писать   — и разложить
"""
from __future__ import annotations

import shutil
import sys
from collections import Counter
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import пути
from part2.core.matching import normalize

ВЫПИСКИ = пути.ВЫПИСКИ
ДОКУМЕНТЫ = (".pdf", ".docx")
КНИГИ = (".xlsx", ".xls")
МУЛЬТИГЕО = "Мультигео"
АРХИВ_КНИГ = "Книги прогонов"

# ПАПКИ, КОТОРЫЕ НАЗВАЛ ЧЕЛОВЕК, — НЕ ТРОГАЕМ. «Интересный заказ/Франция»,
# «…/Мадяры ебучие» собраны руками под конкретный заказ, и разложить их по
# гео значит стереть единственное, что о них известно. Машинная раскладка
# полезна ровно до тех пор, пока не спорит с ручной.
СВОИ_ПАПКИ = {"интересный заказ"}


def из_таблицы(log=print) -> tuple[dict, dict]:
    """
    Две карты по всей таблице:
      по файлу — {нормализованное имя файла → (гео, лист)};
      по фирме — {нормализованное имя фирмы → (гео, лист, ид, файл)}.

    Вторая нужна для файлов, которых таблица не знает. Их много: выписки
    качались с июля, а колонку «Файл выписки» научились заполнять позже, и
    сотня документов лежит на диске, числясь ненайденной. Имя файла Часть 2
    даёт по имени фирмы из реестра, поэтому по нему фирма и находится.
    """
    from common import таблица as т

    по_файлу: dict[str, tuple[str, str]] = {}
    по_фирме: dict[str, tuple[str, str, str, str]] = {}
    for л in т.всё(служебные=True):
        if not л["строк"] or not л["строки"]:
            continue
        # «Реестр» пропускаем: он не рабочий лист, а память «видели/не видели».
        # Те же фирмы лежат и на своих листах, а у части строк «Гео» пустое —
        # и имя листа подставлялось как страна, отчего в примерке появилась
        # папка «РЕЕСТР» на 26 файлов.
        if л["имя"] in ("Реестр", "Лог", "Слова"):
            continue
        ш = л["строки"][0]
        if "Гео" not in ш or "Организация" not in ш:
            continue
        iф = ш.index("Файл выписки") if "Файл выписки" in ш else -1
        iг, iо = ш.index("Гео"), ш.index("Организация")
        iи = ш.index("ID") if "ID" in ш else -1
        свой = л["имя"].split(".")[0].upper()
        for с in л["строки"][1:]:
            def взять(i):
                return с[i].strip() if 0 <= i < len(с) and с[i] else ""

            гео = взять(iг).upper() or свой
            файл, орг, ид = взять(iф), взять(iо), взять(iи)
            if файл.lower().endswith(ДОКУМЕНТЫ):
                по_файлу.setdefault(normalize(Path(файл).stem), (гео, л["имя"]))
            if орг:
                # КЛЮЧ С ГЕО, И ЭТО ОБЯЗАТЕЛЬНО. normalize срезает правовую
                # форму, поэтому эстонская «AQUA Invest OÜ» и хорватская
                # «AQUA INVEST d.o.o.» превращаются в одно «aqua invest».
                # Без страны в ключе примерка предложила вписать эстонскую
                # выписку хорватской фирме — и так же тихо это сделала бы.
                по_фирме.setdefault((гео, normalize(орг)),
                                    (гео, л["имя"], ид, файл))
    log(f"  · в таблице выписок числится: {len(по_файлу)}, "
        f"фирм всего: {len(по_фирме)}")
    return по_файлу, по_фирме


def мультигео_ли(путь: Path) -> bool:
    """Файл лежал в мультигео-партии? Смотрим по пути, а не гадаем."""
    return МУЛЬТИГЕО.lower() in (ч.lower() for ч in путь.relative_to(ВЫПИСКИ).parts)


def гео_из_пути(путь: Path) -> str:
    """
    Подсказка о стране из папки: «выписки/FR/…», «Мультигео/23-08/PL/…».

    Только подсказка, не приговор: папка врёт (семь французских выписок
    лежали в «Мультигео»). Но для разведения однофамильцев её хватает —
    в чужой стране файл не окажется.
    """
    for ч in reversed(путь.relative_to(ВЫПИСКИ).parts[:-1]):
        кусок = ч.split()[-1] if " " in ч else ч
        if len(кусок) == 2 and кусок.isalpha():
            return кусок.upper()
    return ""


def своя_папка(путь: Path) -> bool:
    """Файл лежит в папке, которую собрал человек под свой заказ?"""
    части = [ч.lower() for ч in путь.relative_to(ВЫПИСКИ).parts[:-1]]
    return any(ч in СВОИ_ПАПКИ for ч in части)


def разобрать(log=print) -> dict:
    """Что куда переедет и что вписать в таблицу. Ничего не двигает."""
    по_файлу, по_фирме = из_таблицы(log)
    план: list[tuple[Path, Path]] = []
    правки: list[dict] = []
    ничьи: list[Path] = []
    живые: set[Path] = set()        # папки, где после уборки лежат выписки
    сегодня = f"{date.today():%d-%m}"

    for п in sorted(ВЫПИСКИ.rglob("*")):
        if not п.is_file() or п.suffix.lower() not in ДОКУМЕНТЫ:
            continue
        if своя_папка(п):
            continue
        ключ = normalize(п.stem)
        своё = по_файлу.get(ключ)
        if своё:
            гео, лист = своё
        else:
            лист = ""
            # ТАБЛИЦА НЕ ЗНАЕТ ЭТОТ ФАЙЛ, но фирму может знать: имя файла
            # Часть 2 берёт из реестра. Нашли — заодно впишем файл в строку,
            # иначе выписка так и останется невидимой для приложения.
            #
            # Ищем ТОЛЬКО в стране, на которую указывает папка. Без этого
            # эстонская «AQUA Invest OÜ» находилась хорватской «AQUA INVEST
            # d.o.o.»: normalize срезает правовую форму, и остаётся одно имя.
            подсказка = гео_из_пути(п)
            фирма = по_фирме.get((подсказка, ключ)) if подсказка else None
            if not фирма and not подсказка:
                # Папка страны не назвала — берём совпадение, только если оно
                # ЕДИНСТВЕННОЕ на всю таблицу. Иначе гадать не станем.
                свои = [з for (г, к), з in по_фирме.items() if к == ключ]
                фирма = свои[0] if len(свои) == 1 else None
            if not фирма:
                # ТАБЛИЦА НЕ ЗНАЕТ НИ ФАЙЛ, НИ ФИРМУ — но папка называет страну,
                # и этого хватает, чтобы файл лёг к своим. Раньше такие
                # оставались на месте «до выяснения», и по стране выходило не
                # одна папка, а пять: «FR», «FR/2026-07-27_16-00_1шт», ещё две
                # датированные и корень. Замер 10.09.2026: 43 файла в пяти
                # местах. Выяснять там нечего: это выписки июльских прогонов,
                # когда колонки «Файл выписки» ещё не было.
                if not подсказка:
                    ничьи.append(п)
                    continue
                гео, лист = подсказка, ""
            else:
                гео, лист, ид, было = фирма
                if не_выписка(было) and лист != "Отработано":
                    правки.append({"лист": лист, "орг": "", "ид": ид,
                                   "поля": {"Файл выписки": п.name,
                                            "Статус": "найдена"}})
        # ВЫПИСКИ ОТРАБОТАННЫХ — ОТДЕЛЬНО. Фирма уже роздана; её документ не
        # должен лежать среди свободных, иначе завтра непонятно, что можно
        # выдавать. Но и выбрасывать нельзя — это история заказов.
        if лист == "Отработано":
            куда = ВЫПИСКИ / "Отработано" / гео
        elif мультигео_ли(п):
            куда = ВЫПИСКИ / МУЛЬТИГЕО / сегодня / гео
        else:
            куда = ВЫПИСКИ / гео / сегодня
        цель = куда / п.name
        живые.add(куда)
        if цель != п:
            план.append((п, цель))

    книги = разложить_книги(живые)
    log(f"  · файлов на диске разобрано: {len(план) + len(ничьи)}")
    log(f"  · переедет: {len(план)}, впишем в таблицу: {len(правки)}, "
        f"останется на месте: {len(ничьи)}")
    log(f"  · книг прогонов в архив: {len(книги)}")
    return {"план": план, "правки": правки, "ничьи": ничьи, "книги": книги}


def разложить_книги(живые: set[Path]) -> list[tuple[Path, Path]]:
    """
    Книги прогонов («не_вышло.xlsx», «Мультигео 23-08.xlsx») — в один архив.

    Книга рядом с выписками своего прогона полезна. Книга в папке, из которой
    выписки уже уехали, — только повод эту папку держать: после уборки таких
    осталось двадцать, и в дереве они выглядят как живые партии.

    Правило простое: книга остаётся там, где лежат ВЫПИСКИ этого прогона.
    Все прочие уходят в «Книги прогонов», имя получая от своей папки, чтобы
    десять «не_вышло.xlsx» не затёрли друг друга.
    """
    книги: list[tuple[Path, Path]] = []
    for п in sorted(ВЫПИСКИ.rglob("*")):
        if not п.is_file() or п.suffix.lower() not in КНИГИ:
            continue
        if своя_папка(п) or п.parent in живые or АРХИВ_КНИГ in п.parts:
            continue
        откуда = п.parent.relative_to(ВЫПИСКИ).as_posix().replace("/", " ") \
            if п.parent != ВЫПИСКИ else "корень"
        книги.append((п, ВЫПИСКИ / АРХИВ_КНИГ / f"{откуда} — {п.name}"))
    return книги


def не_выписка(значение: str) -> bool:
    """В клетке не имя файла: пусто или причина отказа."""
    return not (значение or "").strip().lower().endswith(ДОКУМЕНТЫ)


def выполнить(план: list[tuple[Path, Path]], log=print) -> int:
    """Переложить файлы. Ничего не затираем: тёзка ложится рядом как «(2)»."""
    перенесено = двойников = 0
    for откуда, куда in план:
        try:
            куда.parent.mkdir(parents=True, exist_ok=True)
            if куда.exists():
                if куда.stat().st_size == откуда.stat().st_size:
                    откуда.unlink()          # тот же файл, второй экземпляр
                    перенесено += 1
                    continue
                # ДРУГОЙ ФАЙЛ С ТЕМ ЖЕ ИМЕНЕМ — та же фирма, скачанная дважды
                # (реестр перевыпустил выписку, или прогон повторили). Оба
                # нужны, оба чужого не затирают: кладём рядом с «(2)».
                #
                # Раньше такой файл ОСТАВАЛСЯ на месте — и ради девяти
                # штук жили четыре старые папки, а «одна папка на гео»
                # переставало быть правдой.
                куда = свободное_имя(куда)
                двойников += 1
                log(f"  · {откуда.name}: та же фирма скачана дважды — "
                    f"второй файл лёг как «{куда.name}»")
            shutil.move(str(откуда), str(куда))
            перенесено += 1
        except Exception as e:
            log(f"  ✘ {откуда.name}: {type(e).__name__}: {e}")
    прибрать_пустые(log)
    return перенесено


def свободное_имя(цель: Path) -> Path:
    """«Фирма.pdf» занят — вернуть «Фирма (2).pdf», «(3)» и так далее."""
    n = 2
    while (п := цель.with_name(f"{цель.stem} ({n}){цель.suffix}")).exists():
        n += 1
    return п


def прибрать_пустые(log=print) -> int:
    """Убрать каталоги, из которых всё вынесли."""
    убрано = 0
    for п in sorted(ВЫПИСКИ.rglob("*"), key=lambda x: -len(x.parts)):
        if п.is_dir():
            try:
                if not any(п.iterdir()):
                    п.rmdir()
                    убрано += 1
            except Exception:
                pass
    if убрано:
        log(f"  · убрано пустых папок: {убрано}")
    return убрано


