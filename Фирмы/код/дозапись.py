r"""
ЖИВАЯ ДОЗАПИСЬ В ТАБЛИЦУ — фирмы появляются там ПО ХОДУ прогона.

Как было и почему меняем. Прогон писал только в локальную книгу, а в таблицу
выгружал ОДИН раз в самом конце. Пока он идёт — а идёт он часами — в таблице
пусто, и понять «сколько уже есть» можно было только заглянув в Excel. Хуже
того: прогон, прерванный до конца (закрыли окно, упал браузер), не выгружал
ничего вовсе.

ПОЧЕМУ НЕ ПО ОДНОЙ ФИРМЕ. Каждая запись — это запрос к скрипту таблицы, 2–4
секунды. На заказе в 1900 фирм это больше часа чистого ожидания, то есть
прогон удлинился бы вдвое. Поэтому копим ПАЧКОЙ и сбрасываем после каждой
страницы выдачи (это 25 фирм) и после каждой страны. В таблице фирмы
появляются через минуту-другую после находки, а не через четыре часа.

ОШИБКА СЕТИ НЕ РОНЯЕТ ПРОГОН. Не сбросилось — строки остаются в пачке и уедут
со следующей. Локальная книга пишется как раньше и остаётся страховкой: она
и есть источник правды, таблица — витрина.
"""
from __future__ import annotations

from datetime import date

from common import номер as _номер
from common import раскладка
from part2.core.matching import normalize


class Дозапись:
    """
    Копилка строк для таблицы. Живёт один прогон.

    лист — куда класть фирмы С САЙТОМ («Мультигео» или гео).
    Фирмы без сайта уходят на «<ГЕО>.БС» — их лист считается по гео строки.
    """

    ПАЧКА = 25          # столько строк на странице выдачи dnb

    # ЛИСТ МУЛЬТИГЕО В ТАБЛИЦЕ ЗОВЁТСЯ ТАК ВСЕГДА — и это НЕ имя листа книги.
    # В книге лист называется датой («09-09»), и если передать его сюда, вся
    # дозапись будет молча биться о «нет листа 09-09»: строки не уедут ни разу,
    # а в логе будет только «в таблицу не дописалось».
    ЛИСТ_МУЛЬТИГЕО = "Мультигео"

    def __init__(self, лист: str = "", log=print, мультигео: bool = False):
        self.лист = лист or self.ЛИСТ_МУЛЬТИГЕО
        self.log = log
        self.мультигео = мультигео
        self.пачка: list[dict] = []
        self.известные: set[str] = set()
        self.заведены: set[str] = set()
        self.всего = 0
        self.живая = True          # выключается, если таблица недоступна
        self._готова = False

    # ---------- подготовка ----------

    def _подготовить(self) -> None:
        """Один раз за прогон: узнать, что таблица уже знает."""
        if self._готова:
            return
        self._готова = True
        try:
            from common import таблица as т
            if not т.настроена():
                self.живая = False
                self.log("  · таблица не настроена — пишу только в книгу")
                return
            строки = т.читать("Реестр", 20000, всё=True)
            if строки:
                ш = строки[0]
                i = ш.index("Ключ") if "Ключ" in ш else 0
                self.известные = {с[i].strip() for с in строки[1:]
                                  if len(с) > i and с[i].strip()}
            self.log(f"  · таблица на связи, известных фирм {len(self.известные)}")
        except Exception as e:
            self.живая = False
            self.log(f"  · таблица недоступна ({type(e).__name__}) — "
                     f"пишу только в книгу, выгружу в конце")

    # ---------- накопление ----------

    def добавить(self, f, гео: str, слово: str, ид: str,
                 без_сайта: bool = False) -> None:
        """Запомнить фирму. Сама запись — в «сбросить»."""
        if not self.живая:
            return
        self._подготовить()
        if not self.живая:
            return
        гео = (гео or "").upper()
        ключ = f"{гео}|{normalize(f.name)}"
        if ключ in self.известные:
            return                      # уже в таблице, второй раз не пишем
        self.известные.add(ключ)
        профиль = getattr(f, "payment_profile", "") or ""
        свой_ид = ид or _номер.новый(гео)
        # ПО ИМЕНАМ КОЛОНОК, а не по порядку: порядок задаёт раскладка, и
        # список позиций здесь разъехался бы с ней при первой же перестановке.
        строка = раскладка.собрать({
            "Статус": "найдена",
            "Платёжный профиль": профиль,
            "Организация": f.name,
            "Адрес": f.address or "",
            "Город": f.city or "",
            "Индекс": f.zip_code or "",
            "Штат": f.state or "",
            "Website": f.website or "",
            "Платёжный профиль выписки": профиль,
            "Гео": гео,
            "Дата": f"{date.today():%d-%m}",
            "Слово": слово or "",
            "Исходное с dnb": профиль,
            "ID": свой_ид,
        })
        куда = (f"{гео}.БС" if без_сайта
                else (self.лист if self.мультигео else гео))
        self.пачка.append({"лист": куда, "ключ": ключ, "гео": гео,
                           "орг": f.name, "строка": строка,
                           "слово": слово or "", "ид": свой_ид})
        if len(self.пачка) >= self.ПАЧКА:
            self.сбросить()

    # ---------- запись ----------

    def сбросить(self) -> int:
        """
        Отправить накопленное. Возвращает, сколько строк ушло.

        Не получилось — строки ОСТАЮТСЯ в пачке: уедут со следующим сбросом
        или, в самом конце, обычной выгрузкой. Терять их нельзя.
        """
        if not self.живая or not self.пачка:
            return 0
        try:
            from common import таблица as т
            гео_новые = {з["гео"] for з in self.пачка} - self.заведены
            if гео_новые:
                т.создать(sorted(гео_новые))
                self.заведены |= гео_новые
            по_листам: dict[str, list] = {}
            for з in self.пачка:
                по_листам.setdefault(з["лист"], []).append(з["строка"])
            ушло = 0
            for имя, строки in sorted(по_листам.items()):
                ушло += т.дописать(имя, строки)
            т.дописать("Реестр", [
                [з["ключ"], з["гео"], з["орг"], "найдена",
                 f"{date.today():%d-%m}", з["слово"], "прогон", з["ид"]]
                for з in self.пачка])
            self.всего += ушло
            self.log(f"  ☁ в таблицу дописано {ушло} "
                     f"(всего за прогон {self.всего})")
            self.пачка.clear()
            return ушло
        except Exception as e:
            self.log(f"  ⚠ в таблицу не дописалось ({type(e).__name__}: "
                     f"{str(e)[:70]}) — строки жду до следующего раза")
            return 0
