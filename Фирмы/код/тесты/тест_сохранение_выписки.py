"""
Сохранение скачанного файла: пустышка НЕ должна пройти за выписку.

Разбор 08.09.2026. Прогон Эстонии отчитался «✔ скачано» 87 раз, а в папке
лежали файлы ПО НУЛЮ БАЙТ — содержимое (по 170 КБ) осталось в «Загрузках»
браузера. Причина: мы подключаемся к обычному Chrome (иначе Cloudflare не
пускает на dnb), для Playwright такой браузер «удалённый», и передача через
save_as на настоящих выписках не доезжает. На мелких файлах проходит — потому
и не поймали сразу.

Пустая выписка ХУЖЕ отсутствующей: в таблице она выглядит готовой.
Поэтому проверяем три вещи:
  1. обычный случай — файл сохранён, оригинал убран;
  2. save_as отдал пустышку — забираем файл из папки загрузок сами;
  3. взять неоткуда — БРОСАЕМ ошибку, а не пишем «скачано».
"""
import sys
import tempfile
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from common.browser import Browser

ошибок = 0


def проверить(что, условие, пояснение=""):
    global ошибок
    ошибок += not условие
    print(f"   {'✔' if условие else '✘'} {что}" + (f" — {пояснение}" if пояснение else ""))


class ФейкЗагрузка:
    """Как Playwright: save_as пишет столько байт, сколько ему велели."""

    def __init__(self, содержимое: bytes, имя="выписка.pdf", папка=None):
        self.содержимое = содержимое
        self.suggested_filename = имя
        self.убрана = False
        self.папка = папка

    def save_as(self, путь):
        Path(путь).write_bytes(self.содержимое)

    def delete(self):
        self.убрана = True
        if self.папка:
            п = Path(self.папка) / self.suggested_filename
            if п.exists():
                п.unlink()


print("=== 1. Обычный случай: файл сохранён, оригинал убран ===")
with tempfile.TemporaryDirectory() as врем:
    цель = Path(врем) / "гео" / "ФИРМА.pdf"
    з = ФейкЗагрузка("%PDF-1.4 настоящая выписка".encode("utf-8"))
    Browser.сохранить(з, цель)
    проверить("файл на месте", цель.exists() and цель.stat().st_size > 0,
              f"{цель.stat().st_size} байт")
    проверить("папка создалась сама", цель.parent.is_dir())
    проверить("оригинал убран", з.убрана)

print()
print("=== 2. save_as отдал пустышку — забираем из папки загрузок ===")
with tempfile.TemporaryDirectory() as врем:
    загрузки = Path(врем) / "Downloads"
    загрузки.mkdir()
    (загрузки / "выписка.pdf").write_bytes(b"%PDF-1.4 " + b"x" * 5000)
    было = Browser.папка_загрузок
    Browser.папка_загрузок = staticmethod(lambda: загрузки)
    try:
        цель = Path(врем) / "гео" / "ФИРМА.pdf"
        з = ФейкЗагрузка(b"", папка=загрузки)          # save_as пишет 0 байт
        строки = []
        Browser.сохранить(з, цель, log=строки.append)
        проверить("файл всё равно получен",
                  цель.exists() and цель.stat().st_size > 5000,
                  f"{цель.stat().st_size} байт")
        проверить("сказано вслух, откуда взяли",
                  any("Загрузок" in с for с in строки),
                  строки[-1] if строки else "(молча)")
    finally:
        Browser.папка_загрузок = было

print()
print("=== 3. Взять неоткуда — ошибка, а не мнимый успех ===")
with tempfile.TemporaryDirectory() as врем:
    пусто = Path(врем) / "Downloads"
    пусто.mkdir()
    было = Browser.папка_загрузок
    Browser.папка_загрузок = staticmethod(lambda: пусто)
    try:
        цель = Path(врем) / "гео" / "ФИРМА.pdf"
        з = ФейкЗагрузка(b"")
        try:
            Browser.сохранить(з, цель)
            проверить("должно было бросить ошибку", False)
        except RuntimeError as e:
            проверить("бросили ошибку с внятным текстом", "пуст" in str(e),
                      str(e)[:60])
        проверить("оригинал НЕ убран — вдруг пригодится", not з.убрана)
    finally:
        Browser.папка_загрузок = было

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
