"""
Архив: каждая строка лежит там, где ей место по статусу.

Лист «Отработано» копился при трёх правилах и стал свалкой всего закрытого:
на 22.09.2026 в нём было 248 отданных, 54 «нет выписки», 12 брака, 12 дублей
и 15 просто «найдена». Посчитать по такому листу выработку нельзя, а фирма,
попавшая туда по временной причине, для приложения мертва — её не покажет ни
счётчик, ни наряд.

Правило одно: отданное → «Отработано», непригодное → «Недостойные», ВСЁ
ЖИВОЕ (в том числе «нет выписки») → на рабочий лист своего гео и своей линии.

И отдельно: 42 из тех 54 были отсеяны по правилу, которое мы ОТМЕНИЛИ
(«не сданы годовые отчёты», «просрочка»). Такую причину стираем — иначе
строка приедет в работу с приговором в колонке файла.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import прибрать_архив as па

ошибок = 0


def проверить(что, вышло, ждём):
    global ошибок
    ладно = вышло == ждём
    ошибок += not ладно
    print(f"   {'✔' if ладно else '✘'} {что}"
          + ("" if ладно else f": вышло {вышло!r}, ждали {ждём!r}"))


print("=== 1. Куда какой статус ===")
проверить("отданное", па.куда_надо("отработано", "EE", True), "Отработано")
проверить("бот отклонил", па.куда_надо("отклонена", "EE", True), "Недостойные")
проверить("старое слово «дубль»", па.куда_надо("дубль", "EE", True),
          "Недостойные")
проверить("брак", па.куда_надо("брак", "EE", True), "Недостойные")

print()
print("=== 2. Живое возвращается НА СВОЙ ЛИСТ, а не в архив ===")
# «Нет выписки» — это «реестр отказал сегодня», а не «фирма негодная».
проверить("нет выписки, с сайтом", па.куда_надо("нет выписки", "UK", True), "UK")
проверить("нет выписки, без сайта", па.куда_надо("нет выписки", "UK", False),
          "UK.БС")
проверить("найдена", па.куда_надо("найдена", "EE", False), "EE.БС")
проверить("выписка есть", па.куда_надо("выписка", "FR", True), "FR")
проверить("годная", па.куда_надо("годная", "FR", True), "FR")
проверить("пустой статус — тоже живая", па.куда_надо("", "PL", True), "PL")

print()
print("=== 3. Причины отменённых правил опознаются ===")
for причина in ("красный флаг: не сданы годовые отчёты",
                "есть просрочка (overdue)",
                "красный флаг: предупреждение об удалении",
                "скачивалась, файла на диске нет"):
    проверить(f"«{причина[:34]}»", па.причина_протухла(причина), True)

print()
print("=== 4. Настоящие причины НЕ стираем ===")
for причина in ("ликвидирована", "нет статуса EN ACTIVITÉ",
                "форма не подходит для Google Ads", "Altmer Energy OU.pdf"):
    проверить(f"«{причина[:34]}»", па.причина_протухла(причина), False)

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
