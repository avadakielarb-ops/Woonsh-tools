"""
Клиент Google Таблицы — без сети. Подменяем urlopen и проверяем поведение.

Главное здесь — НЕ «умеет ли слать POST», а понятные ошибки. Настройка
таблицы делается руками один раз, и ошибиться можно ровно тремя способами:
не открыть доступ, не вставить скрипт, не переразвернуть. Каждая должна
называться своим именем, иначе человек будет искать причину наугад.
"""
import io
import json
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import common.таблица as т

ошибок = 0


class Ответ(io.BytesIO):
    """Заглушка urlopen: отдаёт заданное тело."""
    def __enter__(self): return self
    def __exit__(self, *a): return False


def подменить(тело: str, запомнить: list | None = None):
    def urlopen(запрос, timeout=None):
        if запомнить is not None:
            запомнить.append(json.loads(запрос.data.decode("utf-8")))
        return Ответ(тело.encode("utf-8"))
    т.urllib.request.urlopen = urlopen


def проверить(что, условие, пояснение=""):
    global ошибок
    ошибок += not условие
    print(f"   {'✔' if условие else '✘'} {что}" + (f" — {пояснение}" if пояснение else ""))


# настройки берём не из настоящего ключи.json: тест не должен зависеть от того,
# настроил пользователь таблицу или нет, и уж точно не должен туда лезть
т.настройки = lambda path=None: ("https://script.google.com/macros/s/ТЕСТ/exec",
                                 "ключ-теста")
# И НЕ ЗАВИСИМ ОТ КОПИИ. Тот же тест гоняется и в полигоне, а полигону писать
# в таблицу запрещено — без этой подмены половина проверок падала бы там на
# запрете, хотя проверяют они разбор ответов, а не права. Сам запрет проверяем
# отдельно, ниже, включая признак руками.
т.пути.это_полигон = lambda: False

print("=== 1. Нормальный ответ разбирается ===")
подменить(json.dumps({"ok": True, "таблица": "Фирмы", "листов": 4},
                     ensure_ascii=False))
о = т.пинг()
проверить("пинг вернул имя таблицы", о.get("таблица") == "Фирмы", о.get("таблица"))

print()
print("=== 2. Не открыт доступ — говорим ИМЕННО это ===")
подменить("<html><head><base href='https://accounts.google.com/v3/signin/'>")
try:
    т.пинг()
    проверить("должно было отказать", False)
except т.НетДоступа as e:
    проверить("названа причина «нужен вход»", "доступ" in str(e).lower()
              or "вход" in str(e).lower(), str(e).splitlines()[0][:70])

print()
print("=== 3. Скрипт не вставлен — говорим ИМЕННО это ===")
подменить("<html><body>Помилка Функцію сценарію doGet не знайдено</body></html>")
try:
    т.пинг()
    проверить("должно было отказать", False)
except т.НетДоступа as e:
    проверить("названа причина «нет doGet»", "doGet" in str(e),
              str(e).splitlines()[0][:70])

print()
print("=== 4. Скрипт вернул отказ — показываем его текст ===")
подменить(json.dumps({"ok": False, "ошибка": "нет ключа"}, ensure_ascii=False))
try:
    т.пинг()
    проверить("должно было отказать", False)
except т.НетДоступа as e:
    проверить("текст отказа виден", "нет ключа" in str(e), str(e)[:60])

print()
print("=== 5. Большая выгрузка режется на пачки ===")
отправленное: list = []
подменить(json.dumps({"ok": True, "добавлено": 400}), отправленное)
строки = [[f"строка {i}"] for i in range(1000)]
т.дописать("EE", строки, пачка=400)
размеры = [len(з["строки"]) for з in отправленное]
проверить("вызовов три", len(отправленное) == 3, f"{len(отправленное)}")
проверить("пачки 400/400/200", размеры == [400, 400, 200], f"{размеры}")
проверить("ключ и действие уходят всегда",
          all(з.get("key") and з.get("action") == "дописать" for з in отправленное))

print()
print("=== 6. Пустая выгрузка сеть не дёргает ===")
отправленное.clear()
т.дописать("EE", [])
проверить("вызовов ноль", len(отправленное) == 0, f"{len(отправленное)}")

print()
print("=== 7. Обрыв сети — повторяем, а не теряем прогон ===")
попыток = {"n": 0}


def рваная(запрос, timeout=None):
    попыток["n"] += 1
    if попыток["n"] < 3:
        raise ConnectionError("RemoteDisconnected")
    return Ответ(json.dumps({"ok": True, "таблица": "Фирмы"}).encode("utf-8"))


т.urllib.request.urlopen = рваная
т.time.sleep = lambda _s: None          # тест не должен ждать по-настоящему
try:
    о = т.пинг()
    проверить("со третьей попытки получилось", о.get("таблица") == "Фирмы",
              f"попыток {попыток['n']}")
except Exception as e:
    проверить("должно было получиться", False, f"{type(e).__name__}")

попыток["n"] = 0


def всегда_рвётся(запрос, timeout=None):
    попыток["n"] += 1
    raise ConnectionError("RemoteDisconnected")


т.urllib.request.urlopen = всегда_рвётся
try:
    т.пинг()
    проверить("должно было отказать", False)
except т.НетДоступа as e:
    проверить("сдались после трёх и сказали внятно",
              "трёх попыток" in str(e) and попыток["n"] == 3,
              f"попыток {попыток['n']}")

print()
print("=== 8. Обрезанный ответ на «дай весь лист» — это ошибка, а не тишина ===")
подменить(json.dumps({"ok": True, "строки": [["Ключ"], ["EE|A"]],
                      "обрезано": True}, ensure_ascii=False))
строки = т.читать("Реестр", 20000)
проверить("без «всё» отдаёт что дали", len(строки) == 2, f"{len(строки)}")
try:
    т.читать("Реестр", 20000, всё=True)
    проверить("должно было отказать", False)
except т.НетДоступа as e:
    проверить("сказано, что лист не влез", "не влез" in str(e), str(e)[:60])

print()
print("=== 9. Полигон в таблицу не пишет ===")
отправленное.clear()
подменить(json.dumps({"ok": True, "добавлено": 1}), отправленное)
т.пути.это_полигон = lambda: True
try:
    т.дописать("EE", [["фирма"]])
    проверить("должно было отказать", False)
except т.НетДоступа as e:
    проверить("запись остановлена", "ПОЛИГОН" in str(e), str(e)[:60])
проверить("в сеть ничего не ушло", len(отправленное) == 0, f"{len(отправленное)}")
подменить(json.dumps({"ok": True, "строки": [["Ключ"]]}), отправленное)
try:
    т.читать("EE", 10)
    проверить("читать полигону можно", True)
except т.НетДоступа as e:
    проверить("читать полигону можно", False, str(e)[:60])
т.пути.это_полигон = lambda: False

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
