"""
Написания ДО прогона: модель говорит, как фирма записана в реестре.

DnB даёт имя латиницей и без диакритики — «A.L Timber Components OU», — а в
реестре та же фирма записана «…OÜ». Для любого поиска это разные строки:
фирма есть, а найти её нечем. То же с чешским «Babice vychod» против «Babice
východ» и латышским «Kiegelis» против «Ķieģelis».

Решение пользователя 20.10.2026: весь список страны — в модель ДО прогона,
ответ — реестровое написание и латиница; искать сразу ими. Прежний «ящик»
(искать упрощёнными запросами, отложить, спросить после страны, пройти ещё
раз) съедал больше всего времени.
"""
import json
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import part2.местные_имена as ми

ошибок = 0


def проверить(что, вышло, ждём):
    global ошибок
    ладно = вышло == ждём
    ошибок += not ладно
    print(f"   {'✔' if ладно else '✘'} {что}"
          + ("" if ладно else f": вышло {вышло!r}, ждали {ждём!r}"))


настоящий = ми.спросить_любой
ответы: dict = {}
запросы: list = []


def подделка(промпт, api_key=None, схема=None, температура=1.3, log=print):
    запросы.append(промпт)
    return ответы.get("json", "[]")


тихо = lambda *a: None
папка = Path(tempfile.mkdtemp())


def кэш(имя):
    return папка / f"{имя}.json"


ми.спросить_любой = подделка
try:
    print("=== 1. Разбираем ответ модели ===")
    ответы["json"] = json.dumps([
        {"было": "A.L Timber Components OU", "реестр": "A.L. Timber Components OÜ",
         "латиница": "A.L. Timber Components OU"},
        {"было": "Aqua Invest OU", "реестр": "Aqua Invest OÜ",
         "латиница": "Aqua Invest OU"},
    ])
    карта = ми.написания("EE", ["A.L Timber Components OU", "Aqua Invest OU"],
                         log=тихо, кэш_путь=кэш("1"))
    проверить("обе подсказки взяты", len(карта), 2)
    # Совпавшее с исходным написание искать незачем: мы и так ищем им.
    проверить("Aqua: только новое написание", карта.get("Aqua Invest OU"),
              ["Aqua Invest OÜ"])
    проверить("A.L: оба новых", карта.get("A.L Timber Components OU"),
              ["A.L. Timber Components OÜ", "A.L. Timber Components OU"])

    print()
    print("=== 2. Без изменений — не подсказка; чужое имя не берём ===")
    ответы["json"] = json.dumps([
        {"было": "HEAT AND COOL", "реестр": "HEAT AND COOL", "латиница": "Heat and Cool"},
        {"было": "ЧУЖАЯ ФИРМА", "реестр": "Čužaja", "латиница": "Cuzaja"},
        {"было": "Kiegelis SIA", "реестр": "Ķieģelis SIA", "латиница": "Kiegelis SIA"},
    ])
    карта = ми.написания("LV", ["HEAT AND COOL", "Kiegelis SIA"], log=тихо,
                         кэш_путь=кэш("2"))
    проверить("осталась одна", карта, {"Kiegelis SIA": ["Ķieģelis SIA"]})

    print()
    print("=== 3. КЭШ: второй прогон модель не зовёт ===")
    запросы.clear()
    ещё = ми.написания("LV", ["HEAT AND COOL", "Kiegelis SIA"], log=тихо,
                       кэш_путь=кэш("2"))
    проверить("ответ тот же", ещё, {"Kiegelis SIA": ["Ķieģelis SIA"]})
    проверить("модель не спрашивали", len(запросы), 0)

    print()
    print("=== 4. Модель молчит — прогон идёт по имени DnB ===")
    def падать(*a, **к):
        raise RuntimeError("503")

    ми.спросить_любой = падать
    проверить("пустая карта", ми.написания("EE", ["Aqua Invest OU"], log=тихо,
                                            кэш_путь=кэш("4")), {})
    # И кэш не засорён пустышкой: в следующий раз спросим снова.
    проверить("в кэш не легло", кэш("4").exists(), False)

    print()
    print("=== 5. Пачки: длинный список уходит частями ===")
    ми.спросить_любой = подделка
    запросы.clear()
    ответы["json"] = "[]"
    ми.написания("CZ", [f"Firma {i} s.r.o." for i in range(ми.ПАЧКА + 5)],
                 log=тихо, кэш_путь=кэш("5"))
    проверить("два запроса", len(запросы), 2)

    print()
    print("=== 6. В промпте страна словом, подсказка по буквам, два поля ===")
    запросы.clear()
    ми.написания("CZ", ["Babice vychod s.r.o."], log=тихо, кэш_путь=кэш("6"))
    промпт = запросы[0] if запросы else ""
    проверить("страна названа словом", "Czech" in промпт or "Чех" in промпт, True)
    проверить("подсказка по буквам", "s.r.o." in промпт, True)
    проверить("само имя в списке", "Babice vychod s.r.o." in промпт, True)
    проверить("просим реестр и латиницу",
              "«реестр»" in промпт and "«латиница»" in промпт, True)
    # Первая версия звала форму «обычной для страны», и модель вешала «Oy» на
    # каждое имя: «ANVIL MUSIC PRODUCTIONS» → «… Oy», 4 из 5.
    проверить("форму не дописывать", "НЕ ДОБАВЛЯЙ" in промпт, True)
finally:
    ми.спросить_любой = настоящий

print()
print("=== 7. ГДЕ СПРАШИВАТЬ НЕЧЕГО — НЕ СПРАШИВАЕМ ===")
запросы.clear()
ми.спросить_любой = подделка
try:
    for г in ("UK", "US", "AU"):
        проверить(f"{г}: пусто", ми.написания(г, ["BRONZE WING TRADING LTD"],
                                               log=тихо, кэш_путь=кэш("7")), {})
    проверить("модель не дёрнули ни разу", len(запросы), 0)
finally:
    ми.спросить_любой = настоящий
# Перечислены ЯВНО: отключать по «нет подсказки» нельзя — подсказки нет и у
# новой страны, которой её просто ещё не написали.
проверить("список явный", "UK" in ми.БЕЗ_МЕСТНЫХ and "EE" not in ми.БЕЗ_МЕСТНЫХ,
          True)

print()
print("=== 8. Прогон спрашивает ДО браузера, ящика больше нет ===")
import inspect

from part2 import engine as дв

источник = inspect.getsource(дв.run)
проверить("написания спрашиваются", "написания(geo" in источник, True)
проверить("и раньше, чем открыт браузер",
          источник.index("написания(geo") < источник.index("with Browser("), True)
проверить("ящика нет", "ящик" in источник.replace("«ящика»", ""), False)
проверить("написание доходит до запроса",
          "написания" in inspect.getsource(дв._имена), True)

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
