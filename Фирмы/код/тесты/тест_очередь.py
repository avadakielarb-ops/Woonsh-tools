import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import shutil
from pathlib import Path
from очередь import (Задание, Очередь, ЖДЁТ, РАБОТАЕТ, ГОТОВО, ОШИБКА)

песочница = Path("_песочница_очередь")
shutil.rmtree(песочница, ignore_errors=True)
песочница.mkdir()
файл = песочница / "очередь.json"

print("=== 1. Заводим очередь ===")
оч = Очередь(файл)
оч.добавить(Задание("heat", "France", 10))
оч.добавить(Задание("auto", "Poland", 10,
                    этапы={"собрать": True, "сайты": False, "выписки": True}))
оч.добавить(Задание("pump", "Germany", 15, без_сайта=True))
for i, з in enumerate(оч.задания, 1):
    print(f"   {i}. «{з.слово}» × {з.страна} × {з.сколько}  |  {з.этапы_текст}")

print()
print("=== 2. Состояние переживает перезапуск ===")
оч2 = Очередь(файл)
print("   заданий после перечитывания:", len(оч2.задания))
print("   вторая строка:", оч2.задания[1].слово, оч2.задания[1].страна,
      "| этапы:", оч2.задания[1].этапы_текст)

print()
print("=== 3. Возобновление с точностью до фирмы ===")
оч2.задания[0].статус = РАБОТАЕТ
оч2.задания[0].взято = 4          # успели взять 4 из 10 и упали
оч2.сохранить()
оч3 = Очередь(файл)
оборв = оч3.оборванные()
print("   оборванных строк:", оборв, "(ждём [0])")
з = оч3.задания[оборв[0]]
print(f"   «{з.слово}» × {з.страна}: взято {з.взято} из {з.сколько} → "
      f"добрать осталось {з.осталось}")
if з.осталось != 6:
    print("   ✘ ПЛОХО: должно быть 6")
else:
    print("   ✔ добираем 6, а не все 10 заново")

print()
print("=== 4. Повтор: история помнит цифры ===")
з.статус = ГОТОВО
з.взято = 10
оч3.в_историю(з)
оч3.сохранить()
оч4 = Очередь(файл)
прошлые = оч4.прошлые("heat", "France")
print("   найдено записей в истории:", len(прошлые))
if прошлые:
    п = прошлые[-1]
    print(f"   «heat» × France уже гонялось {п['дата']}, взято {п['взято']} из {п['сколько']}")
print("   по чужому слову:", len(оч4.прошлые("другое", "France")), "(ждём 0)")

print()
print("=== 5. Порядок строк ===")
print("   до :", [з.слово for з in оч4.задания])
оч4.сдвинуть(2, -1)
print("   после сдвига 3-й вверх:", [з.слово for з in оч4.задания])
оч4.удалить(0)
print("   после удаления первой:", [з.слово for з in оч4.задания])

print()
print("=== 6. Сброс статусов ===")
оч4.задания[0].статус = ОШИБКА
оч4.задания[0].взято = 3
оч4.очистить_статусы()
print("   статус:", оч4.задания[0].статус, "| взято:", оч4.задания[0].взято)

print()
print("=== 7. Битый файл очереди не роняет приложение ===")
файл.write_text("{мусор", encoding="utf-8")
сообщения = []
оч5 = Очередь(файл, log=сообщения.append)
print("   заданий:", len(оч5.задания), "(пустая, но живая)")
print("   сообщение:", сообщения[0] if сообщения else "нет")

shutil.rmtree(песочница, ignore_errors=True)
print()
print("песочница убрана")
