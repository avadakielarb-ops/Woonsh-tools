"""
Уборка выписок: одна папка на гео и режим, и ничего не потеряно.

Скрипт двигает чужой труд по диску, поэтому проверяем не «разложилось ли», а
четыре правила, каждое из которых уже нарушалось на живых данных:

  1. однофамильцы из разных стран НЕ путаются (эстонская «AQUA Invest OÜ» и
     хорватская «AQUA INVEST d.o.o.» после normalize — одно имя);
  2. файл, которого таблица не знает, идёт по стране ИЗ ПАПКИ, а не остаётся
     лежать пятой кучей;
  3. папки, названные человеком, не трогаем вовсе;
  4. тёзка с другим содержимым ложится рядом как «(2)», а не затирает.
"""
import sys
from pathlib import Path
from tempfile import mkdtemp

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import прибрать_выписки as у

ошибок = 0


def проверить(что, вышло, ждём):
    global ошибок
    ладно = вышло == ждём
    ошибок += not ладно
    print(f"   {'✔' if ладно else '✘'} {что}"
          + ("" if ладно else f": вышло {вышло!r}, ждали {ждём!r}"))


# --- хранилище, как оно выглядело до уборки: три схемы разом ---
корень = Path(mkdtemp())
у.ВЫПИСКИ = корень / "выписки"


def положить(отн: str, тело: bytes = b"%PDF"):
    п = у.ВЫПИСКИ / отн
    п.parent.mkdir(parents=True, exist_ok=True)
    п.write_bytes(тело)
    return п


эст = положить("EE/21-07/AQUA Invest OU.pdf", b"%PDF estonia")
хорв = положить("HR/23-08/AQUA INVEST d.o.o..pdf", b"%PDF croatia")
июльский = положить("FR/AQUA D OC.pdf")                 # таблица о нём не знает
партия = положить("Мультигео/23-08/PL/GRANITE.pdf")
ручная = положить("Интересный заказ/Франция/PIZZA.pdf")
книга = положить("UK/2026-07-22_17-30_10шт/не_вышло.xlsx", b"PK")
двойник = положить("NL/2026-07-28/Terra Preta B.V..pdf", b"%PDF first")
двойник2 = положить("NL/старое/Terra Preta B.V..pdf", b"%PDF other, longer")

# Таблица знает про две одноимённые фирмы в разных странах и про голландскую.
у.из_таблицы = lambda log=print: (
    {},
    {("EE", "aqua invest"): ("EE", "EE", "EE-1", ""),
     ("HR", "aqua invest"): ("HR", "HR", "HR-1", ""),
     ("PL", "granite"): ("PL", "Мультигео", "PL-1", ""),
     ("NL", "terra preta"): ("NL", "NL", "NL-1", "")},
)

итог = у.разобрать(log=lambda *a: None)
куда = {о: ц for о, ц in итог["план"]}
сегодня = __import__("datetime").date.today().strftime("%d-%m")

print("=== 1. Однофамильцы остаются каждый в своей стране ===")
проверить("эстонская → EE", куда[эст], у.ВЫПИСКИ / "EE" / сегодня / эст.name)
проверить("хорватская → HR", куда[хорв], у.ВЫПИСКИ / "HR" / сегодня / хорв.name)

print()
print("=== 2. Файл не из таблицы идёт по стране из папки ===")
проверить("июльский FR → FR", куда[июльский],
          у.ВЫПИСКИ / "FR" / сегодня / июльский.name)
проверить("никто не остался на месте", итог["ничьи"], [])

print()
print("=== 3. Режим сохраняется: партия остаётся партией ===")
проверить("мультигео → Мультигео/<дата>/PL", куда[партия],
          у.ВЫПИСКИ / "Мультигео" / сегодня / "PL" / партия.name)

print()
print("=== 4. Папки человека не трогаем ===")
проверить("«Интересный заказ» не в плане", ручная in куда, False)

print()
print("=== 5. Книги прогонов — в архив, одной кучей ===")
книги = {о: ц for о, ц in итог["книги"]}
проверить("книга уехала в архив", книга in книги, True)
проверить("имя хранит прежнюю папку", книги[книга].name,
          "UK 2026-07-22_17-30_10шт — не_вышло.xlsx")

print()
print("=== 6. Тёзка с другим содержимым не затирает ===")
у.выполнить(итог["план"] + итог["книги"], log=lambda *a: None)
цель = у.ВЫПИСКИ / "NL" / сегодня
лежит = sorted(p.name for p in цель.iterdir())
проверить("оба файла на месте", лежит,
          ["Terra Preta B.V. (2).pdf", "Terra Preta B.V..pdf"])
всего = len([p for p in у.ВЫПИСКИ.rglob("*") if p.is_file()])
проверить("ни один файл не пропал", всего, 8)

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
