"""
ВЫБРАЛ СТРАНУ — РАБОТАЕМ ПО НЕЙ.

Что случилось 10.09.2026. На мультилисте лежат все страны сразу. Человек
выбрал в списке Францию и нажал «Скачать выписки» — приложение принялось за
Австрию: оно шло по листу с начала, а выбор страны просто терялся. То же с
«Списком для бота»: отдавался весь лист, ответ бота накрывал чужие страны, и
замены освобождали строки Австралии и Чехии.

Причина была в моей же правке: мультилист определяется по КНИГЕ (иначе одним
драйвером качали бы все страны подряд), и вместе с этим выбор страны перестал
на что-либо влиять. Одно не отменяет другого: режим — по книге, объём работы —
по выбору.
"""
import sys
from pathlib import Path
from tempfile import mkdtemp

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from openpyxl import Workbook

from part2.engine import разбор_листа, run_мультилист

ошибок = 0

# лист как после мультипрогона: три страны подряд
книга = Path(mkdtemp()) / "Мультигео.xlsx"
wb = Workbook()
ws = wb.active
ws.title = "09-09"
ws.append(["№", "Платёжный профиль", "Организация", "Адрес", "Город", "Индекс",
           "Штат", "Website", "Номер в реестре", "Файл выписки",
           "Платёжный профиль выписки", "Гео"])
н = 0
for гео, сколько in (("AT", 3), ("FR", 2), ("AU", 4)):
    for i in range(сколько):
        н += 1
        ws.append([н, "профиль", f"{гео} FIRMA {i}", "ул. 1", "Город", "00000",
                   "", "site.example", "", "", "", гео])
wb.save(книга)

print("=== 1. Разбор листа видит все три страны ===")
блоки = разбор_листа(книга, "09-09")
по_гео = {б["гео"]: len(б["строки"]) for б in блоки}
if по_гео != {"AT": 3, "FR": 2, "AU": 4}:
    ошибок += 1
    print(f"   ✘ разобралось не так: {по_гео}")
else:
    print(f"   ✔ {по_гео}")

print()
print("=== 2. Выбрана Франция — берётся Франция, а не первая по списку ===")
# Дальше движок полез бы в браузер, поэтому ловим его на первом же шаге:
# нам важно, ЧТО он собрался делать, а не как скачает.
взято = {}


class Стоп(RuntimeError):
    pass


import part2.engine as дв

настоящий = дв.run


def перехват(гео, excel, out_dir, human, log=print, sheet=None, **к):
    # run() получает не список строк, а «фильтр_гео»: строки он отбирает сам,
    # по колонке «Гео». Значит проверять надо именно фильтр.
    взято["гео"] = гео
    взято["фильтр"] = к.get("фильтр_гео")
    raise Стоп("дальше не надо")


дв.run = перехват
try:
    run_мультилист(книга, "09-09", Path(mkdtemp()), None,
                   log=lambda s: None, только_гео=["FR"])
except Стоп:
    pass
except Exception as e:
    ошибок += 1
    print(f"   ✘ упало иначе: {type(e).__name__}: {e}")
finally:
    дв.run = настоящий

if взято.get("гео") != "FR":
    ошибок += 1
    print(f"   ✘ взялся за «{взято.get('гео')}», а выбрана была FR")
elif взято.get("фильтр") != "FR":
    ошибок += 1
    print(f"   ✘ фильтр «{взято.get('фильтр')}» — строки возьмутся не те")
else:
    print("   ✔ FR и фильтр FR — Австрию не тронул")

print()
print("=== 3. Без выбора — весь лист, как и раньше ===")
взято.clear()
дв.run = перехват
try:
    run_мультилист(книга, "09-09", Path(mkdtemp()), None, log=lambda s: None)
except Стоп:
    pass
except Exception:
    pass
finally:
    дв.run = настоящий
if взято.get("гео") not in ("AT", "AU", "FR"):
    ошибок += 1
    print(f"   ✘ не начал вовсе: {взято}")
else:
    print(f"   ✔ пошёл по всему листу, начав с «{взято['гео']}»")

print()
print("=== 4. Выбрана страна, которой на листе нет — говорим прямо ===")
try:
    run_мультилист(книга, "09-09", Path(mkdtemp()), None,
                   log=lambda s: None, только_гео=["PL"])
    ошибок += 1
    print("   ✘ промолчал и что-то сделал")
except RuntimeError as e:
    if "PL" not in str(e):
        ошибок += 1
        print(f"   ✘ сообщение не про PL: {str(e)[:70]}")
    else:
        print(f"   ✔ «{str(e).splitlines()[0][:66]}»")

print()
print("ошибок:", ошибок)
