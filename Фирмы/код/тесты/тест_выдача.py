"""
Выдача: файлы ПЕРЕЕЗЖАЮТ в папку выдачи, а не копируются.

Выписка отдана в работу — значит из хранилища она ушла. Иначе завтра не
понять, что уже роздано, а что лежит свободным: те же файлы числятся и
выданными, и доступными.

И в книгу выдачи идёт платёжка ИЗ ВЫПИСКИ (имя и адрес из реестра), а не с
dnb: в работу уходит именно она.
"""
import sys
from pathlib import Path
from tempfile import mkdtemp

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import окно as о
from common import пути

ошибок = 0

# --- хранилище выписок, как оно выглядит на диске ---
корень = Path(mkdtemp())
выписки = корень / "выписки"
(выписки / "FR" / "10-09").mkdir(parents=True)
(выписки / "Мультигео" / "09-09" / "EE").mkdir(parents=True)
файл_фр = выписки / "FR" / "10-09" / "COOL-HEAT SERVICES SAS.pdf"
файл_ее = выписки / "Мультигео" / "09-09" / "EE" / "Altmer Energy OU.pdf"
файл_фр.write_bytes(b"%PDF-1.4 fr")
файл_ее.write_bytes(b"%PDF-1.4 ee")
оставшийся = выписки / "Мультигео" / "09-09" / "EE" / "Другая OU.pdf"
оставшийся.write_bytes(b"%PDF-1.4 other")

# ПОДМЕНЯЕМ ИМЕННО ХРАНИЛИЩЕ, а не корень проекта. С 16.09.2026 выписки живут
# ВНЕ папки приложения (Downloads\Выписки), путь задаётся «данные/пути.json» и
# считается один раз при импорте. Подмена корня на него уже не влияет — и
# проверка молча пошла бы работать с боевой папкой.
настоящее_хранилище = пути.ВЫПИСКИ
настоящий_корень = пути.КОРЕНЬ
пути.ВЫПИСКИ = выписки
# КОРЕНЬ тоже подменяем: от него считается ПАПКА ВЫДАЧИ. Забыть его — значит
# на каждом прогоне проверок создавать настоящую папку выдачи в проекте
# (так и вышло: «выдачи/16-09_11-50_EE-FR_3шт»). Проверка не должна оставлять
# следов в рабочих папках.
пути.КОРЕНЬ = корень


class Окошко:
    """Только то, что нужно методу: лог и сам метод."""
    _лог = lambda self, *a, **к: None
    _собрать_папку = о.Окно._собрать_папку


взяли = [
    {"орг": "COOL-HEAT SERVICES SAS", "гео": "FR",
     "файл": "COOL-HEAT SERVICES SAS.pdf",
     "платёжка": "COOL-HEAT SERVICES SAS\nAddress: 6 RUE DERRIERE L'HATE"},
    {"орг": "Altmer Energy OU", "гео": "EE", "файл": "Altmer Energy OU.pdf",
     "платёжка": "Altmer Energy OÜ\nAddress: Tartu mnt 1"},
    {"орг": "БЕЗ ВЫПИСКИ OU", "гео": "EE", "файл": "ликвидирована",
     "платёжка": "БЕЗ ВЫПИСКИ OU"},
]

try:
    папка = Окошко()._собрать_папку(взяли, ["FR", "EE"])
finally:
    пути.ВЫПИСКИ = настоящее_хранилище
    пути.КОРЕНЬ = настоящий_корень

print("=== 1. Файлы переехали, а не скопировались ===")
if файл_фр.exists() or файл_ее.exists():
    ошибок += 1
    print(f"   ✘ остались в хранилище: "
          f"{[п.name for п in (файл_фр, файл_ее) if п.exists()]}")
elif not (папка / файл_фр.name).exists() or not (папка / файл_ее.name).exists():
    ошибок += 1
    print(f"   ✘ в выдаче нет: {sorted(p.name for p in папка.iterdir())}")
else:
    print(f"   ✔ обе выписки в «{папка.name}», в хранилище их больше нет")

print()
print("=== 2. Чужие файлы не тронуты ===")
if not оставшийся.exists():
    ошибок += 1
    print("   ✘ унесли лишний файл")
else:
    print("   ✔ «Другая OU.pdf» на месте")

print()
print("=== 3. Опустевшие папки убраны, непустые оставлены ===")
пустая = выписки / "FR" / "10-09"
непустая = выписки / "Мультигео" / "09-09" / "EE"
if пустая.exists():
    ошибок += 1
    print(f"   ✘ пустая папка осталась: {пустая}")
elif not непустая.exists():
    ошибок += 1
    print("   ✘ убрали папку, в которой ещё есть файлы")
else:
    print("   ✔ пустая «FR/10-09» убрана, «Мультигео/09-09/EE» осталась")

print()
print("=== 4. В книге выдачи — платёжка ИЗ ВЫПИСКИ ===")
from openpyxl import load_workbook

wb = load_workbook(папка / "платёжки.xlsx")
ws = wb.active
строки = [[c.value for c in r] for r in ws.iter_rows(min_row=2)]
профили = {с[2]: с[3] for с in строки}
статусы = {с[2]: с[5] for с in строки}
if "Altmer Energy OÜ" not in (профили.get("Altmer Energy OU") or ""):
    ошибок += 1
    print(f"   ✘ платёжка не из выписки: {профили.get('Altmer Energy OU')!r}")
elif статусы.get("БЕЗ ВЫПИСКИ OU") != "выписки не было":
    ошибок += 1
    print(f"   ✘ фирма без выписки помечена как {статусы.get('БЕЗ ВЫПИСКИ OU')!r}")
else:
    print("   ✔ платёжка из выписки, фирма без файла помечена честно")
wb.close()

print()
print("=== 5. Текстовый список платёжек рядом ===")
текст = (папка / "платёжки.txt").read_text(encoding="utf-8")
if "Altmer Energy OÜ" not in текст or "COOL-HEAT" not in текст:
    ошибок += 1
    print(f"   ✘ в тексте не все: {текст[:80]!r}")
else:
    print("   ✔ все три платёжки в «платёжки.txt»")

print()
print("ошибок:", ошибок)
