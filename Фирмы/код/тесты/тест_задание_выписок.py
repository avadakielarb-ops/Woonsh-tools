о = зв.вернуть_в_таблицу(книга, "10-09", log=lambda s: None)
правки = {п["ид"]: п["поля"] for п in отправлено.get("правки", [])}
if о.get("обновлено") != 2:
    ошибок += 1
    print(f"   ✘ вернулось {о.get('обновлено')} правок, а надо две")
elif правки.get("EE-A1", {}).get("Статус") != "найдена":
    ошибок += 1
    print(f"   ✘ скачанная не «найдена»: {правки.get('EE-A1')}")
elif правки.get("EE-A2", {}).get("Статус") != "нет выписки":
    ошибок += 1
    print(f"   ✘ причина отказа не «нет выписки»: {правки.get('EE-A2')}")
elif "EE-A3" in правки:
    ошибок += 1
    print("   ✘ нетронутую строку тоже отправили")
else:
    print("   ✔ файл → «найдена», причина → «нет выписки», "
          "нетронутая не отправлена")
    print(f"     адресовано по номерам: {sorted(правки)}")

