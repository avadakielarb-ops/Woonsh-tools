"""
«Гео → сколько → поехали»: наряд на выписки собирается из ТАБЛИЦЫ.

Кнопка работала по книге и листу прошлого прогона, и это было неправильно по
существу: фирмы одной страны лежат не в одном листе, а где придётся — часть в
«Мультигео», часть на листе гео, часть добрана вчера. «Лист» перестал быть
ответом на вопрос «что качать по Франции» ещё тогда, когда появился мультигео.

Проверяем то, на чём это ломается: берём ли ТЕХ, кого надо, и не берём ли
лишних — уже скачанных, отработанных и закрытых по причине.
"""
import sys
import types
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

КОЛОНКИ = ["Статус", "№", "Платёжный профиль", "Организация", "Адрес", "Город",
           "Индекс", "Штат", "Website", "Номер в реестре", "Файл выписки",
           "Платёжный профиль выписки", "Гео", "Дата", "Слово",
           "Исходное с dnb", "ID"]


def строка(орг, гео, файл="", статус="", сайт="site.example", ид=None):
    з = {"Статус": статус, "№": "", "Платёжный профиль": "профиль",
         "Организация": орг, "Адрес": "ул. 1", "Город": "Город",
         "Индекс": "00000", "Штат": "", "Website": сайт,
         "Номер в реестре": "", "Файл выписки": файл,
         "Платёжный профиль выписки": "", "Гео": гео, "Дата": "10-09",
         "Слово": "проба", "Исходное с dnb": "", "ID": ид or f"{гео}-{орг[:4]}"}
    return [з[к] for к in КОЛОНКИ]


ТАБЛИЦА = [
    {"имя": "Мультигео", "скрыт": False, "строк": 6, "строки": [КОЛОНКИ] + [
        строка("EE ГОДНАЯ 1", "EE"),
        строка("EE УЖЕ ЕСТЬ", "EE", файл="EE УЖЕ ЕСТЬ.pdf"),
        строка("EE ЛИКВИД", "EE", файл="ликвидирована"),
        строка("EE ОТРАБОТАНА", "EE", статус="отработано"),
        строка("FR ГОДНАЯ", "FR"),
        строка("FR ДУБЛЬ", "FR", статус="дубль"),
    ]},
    {"имя": "EE.БС", "скрыт": False, "строк": 2, "строки": [КОЛОНКИ] + [
        строка("EE БЕЗ САЙТА", "EE", сайт=""),
        строка("EE БС С ВЫПИСКОЙ", "EE", сайт="", файл="есть.docx"),
    ]},
    {"имя": "Слова", "скрыт": True, "строк": 1, "строки": [["Слово", "Гео"]]},
]

поддельная = types.ModuleType("common.таблица")
поддельная.всё = lambda листы=None, служебные=False, сколько=20000: [
    л for л in ТАБЛИЦА if служебные or not л["скрыт"]]
отправлено = {}
поддельная.обновить = lambda правки, пачка=150: (
    отправлено.setdefault("правки", правки), {"обновлено": len(правки)})[1]
sys.modules["common.таблица"] = поддельная

import задание_выписок as зв

ошибок = 0

print("=== 1. Берём только тех, кому выписка нужна ===")
строки = зв.найти(["EE"], None, log=lambda s: None)
имена = sorted(з["Организация"] for з in строки)
ждём = ["EE БЕЗ САЙТА", "EE ГОДНАЯ 1", "EE ЛИКВИД"]
if имена != ждём:
    ошибок += 1
    print(f"   ✘ взяли {имена}")
    print(f"     а надо  {ждём}")
else:
    print(f"   ✔ {имена}")
    print("     скачанная, отработанная — мимо; «ликвидирована» это ПРИЧИНА, "
          "а не файл, её пробуем снова")

print()
print("=== 2. Гео решает: FR — это FR ===")
фр = [з["Организация"] for з in зв.найти(["FR"], None, log=lambda s: None)]
if фр != ["FR ГОДНАЯ"]:
    ошибок += 1
    print(f"   ✘ по FR взяли {фр}")
else:
    print("   ✔ ['FR ГОДНАЯ'] — дубль не взят, эстонцы не приплелись")

print()
print("=== 3. «Сколько» режется ПО КАЖДОЙ СТРАНЕ ===")
обе = зв.найти(["EE", "FR"], 2, log=lambda s: None)
по_гео = зв._по_гео(обе)
if по_гео != {"EE": 2, "FR": 1}:
    ошибок += 1
    print(f"   ✘ вышло {по_гео}, а ждали EE:2 (из трёх) и FR:1 (всего одна)")
else:
    print("   ✔ EE:2 из трёх, FR:1 — больше нет; «по 2 на страну», а не "
          "«2 всего»")

print()
print("=== 4. Линию можно сузить ===")
с_сайтом = [з["Организация"] for з in
            зв.найти(["EE"], None, log=lambda s: None, только_с_сайтом=True)]
без = [з["Организация"] for з in
       зв.найти(["EE"], None, log=lambda s: None, только_с_сайтом=False)]
if "EE БЕЗ САЙТА" in с_сайтом or "EE БЕЗ САЙТА" not in без:
    ошибок += 1
    print(f"   ✘ с сайтом={с_сайтом}, без={без}")
else:
    print(f"   ✔ с сайтом {len(с_сайтом)}, без сайта {len(без)}")

print()
print("=== 5. Результат возвращается в таблицу ПО НОМЕРУ ===")
from tempfile import mkdtemp

