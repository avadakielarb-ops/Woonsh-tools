проверить("сказали, что не нашли", разбор2["не_нашлись"], ["ЧУЖАЯ ФИРМА"])
# И ГОДНЫМИ ТОЖЕ НИКОГО. Раньше тут было «не дубль — значит годная», и это
# ровно та щедрость, из-за которой молчание бота сходило за согласие.
проверить("годных нет — про них не сказано ничего",
          len(разбор2["годные"]), 0)
проверить("все трое ждут ответа", len(разбор2["нет_ответа"]), 3)

print()
print("=== 5. ВЕРДИКТ БЕРЁТСЯ ТОЛЬКО ИЗ ОТВЕТА, ЖУРНАЛ НЕ СПРАШИВАЕМ ===")
# Тут стояла «эхо-защита»: если имя уже отправляли и бот его подтверждал, его
# «уже есть» считалось нашим отголоском и фирма оставалась годной. 23.09.2026
# это стоило 421 фирмы — `сохранить_пакет` клеймил именем пакета только копию
# для файла, сравнение «журнал не тот же пакет» давало истину ВСЕГДА, и каждый
# дубль уезжал в годные. В логе: «чужих дублей: 0, годных: 1599».
# Теперь решает текст перед глазами, и никакой файл на диске это не подделает.
настоящий_журнал = пб._журнал
пб._журнал = lambda: {
    пб.ключ_журнала("AU", "BIRCH SHEET METAL PTY LTD"): {
        "дата": "2026-09-16", "пакет": "сайт_AU_16-09"},
}
