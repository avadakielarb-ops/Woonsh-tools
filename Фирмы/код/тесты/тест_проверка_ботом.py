# список. Номера фирм берём из неё же: имя к тому времени может смениться на
# реестровое, и по имени строку в таблице уже не найти.
from tempfile import mkdtemp

from openpyxl import Workbook

книга = Path(mkdtemp()) / "прогон.xlsx"
wb = Workbook()
ws = wb.active
ws.title = "22-09"
ws.append(["Статус", "Организация", "Website", "Гео", "ID",
           "Файл выписки", "Платёжный профиль"])
ws.append(["найдена", "AQUA-360 SIA", "aqua360.lv", "LV", "LV-1", "", "проф1"])
