    вчерашний = [dict(з, пакет="сайт_AU-EE-HR_17-09") for з in пакет]
    р = пб.разложить(вчерашний,
                     "⚠️ Компания уже есть: BIRCH SHEET METAL",
                     log=lambda *a: None)
    проверить("запись в журнале дубля не отменяет",
              [з["ид"] for з in р["отклонены"]], ["AU-1"])
    проверить("в годные он не попал",
              "AU-1" in [з["ид"] for з in р["годные"]], False)
