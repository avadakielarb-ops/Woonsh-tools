"""
Продолжить прерванный прогон: сколько осталось добрать по каждой стране.

Главное решение проверяем прямо здесь: сделанное считается ПО КНИГЕ, а не по
закладке. Закладка помнит только заказ — что просили и сколько. Если бы она
помнила и прогресс, то при аварийном закрытии (прибили процесс, выключили
свет) последняя запись не легла бы — то есть соврала бы ровно тогда, когда
нужна. Книга пишется после каждой фирмы и врать не умеет.
"""
import json
import sys
from pathlib import Path
from tempfile import mkdtemp

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from openpyxl import Workbook

import продолжение
from part1.excel_out import имя_листа

ошибок = 0

# --- готовим книгу, как её оставил бы прерванный прогон ---
папка = Path(mkdtemp())
книга = папка / "Мультигео.xlsx"
wb = Workbook()
ws = wb.active
ws.title = "09-09"
ws.append(["Статус", "№", "Платёжный профиль", "Организация", "Адрес", "Город",
           "Индекс", "Штат", "Website", "Номер в реестре", "Файл выписки",
           "Платёжный профиль выписки", "Гео", "Дата", "Слово", "ID"])
СДЕЛАНО = {"AT": 22, "AU": 100, "BE": 50, "EE": 3}
н = 0
for гео, сколько in СДЕЛАНО.items():
    for i in range(сколько):
        н += 1
        ws.append(["найдена", н, "профиль", f"{гео} FIRMA {i}", "ул. 1", "Город",
                   "00000", "", "site.example", "", "", "", гео, "09-09",
                   "слово", f"{гео}-AAA{i:03d}"])
# строка-пустышка: место освобождено, фирмы нет — считаться не должна
ws.append(["", н + 1, "", "", "", "", "", "", "", "", "", "", "AT", "", "", ""])
wb.save(книга)

продолжение.ФАЙЛ = папка / "продолжение.json"
ГЕО = ["AT", "AU", "BE", "BG", "EE"]
продолжение.запомнить(книга, "09-09", ГЕО, 100)

print("=== 1. Сделанное берётся из книги, а не из закладки ===")
о = продолжение.остаток()
if о["есть"] != СДЕЛАНО:
    ошибок += 1
    print(f"   ✘ насчитал {о['есть']}, а в книге {СДЕЛАНО}")
else:
    print(f"   ✔ по книге: {о['есть']} (пустая строка не посчиталась)")

print()
print("=== 2. Остаток по каждой стране ===")
ждём = {"AT": 78, "AU": 0, "BE": 50, "BG": 100, "EE": 97}
if о["сколько_по_гео"] != ждём:
    ошибок += 1
    print(f"   ✘ остаток {о['сколько_по_гео']}, ждали {ждём}")
elif о["гео_осталось"] != ["AT", "BE", "BG", "EE"]:
    ошибок += 1
    print(f"   ✘ добирать надо {о['гео_осталось']}")
else:
    print(f"   ✔ {о['сколько_по_гео']}")
    print(f"     добираем только: {о['гео_осталось']} (AU набрана — её нет)")

print()
print("=== 3. Заказ выполнен — продолжать нечего ===")
wb2 = Workbook()
ws2 = wb2.active
ws2.title = "09-09"
ws2.append(["Организация", "Гео"])
for гео in ГЕО:
    for i in range(100):
        ws2.append([f"{гео} FIRMA {i}", гео])
полная = папка / "Полная.xlsx"
wb2.save(полная)
продолжение.запомнить(полная, "09-09", ГЕО, 100)
о2 = продолжение.остаток()
if о2["гео_осталось"]:
    ошибок += 1
    print(f"   ✘ считает недобранным: {о2['гео_осталось']}")
elif "выполнен" not in продолжение.словами(о2):
    ошибок += 1
    print(f"   ✘ подпись не та: {продолжение.словами(о2)}")
else:
    print(f"   ✔ {продолжение.словами(о2)}")

print()
print("=== 4. Лист продолжения — ТОТ ЖЕ, а не сегодняшний ===")
# Прогон начали давно, продолжаем сегодня: фирмы обязаны лечь в СТАРЫЙ лист,
# иначе добор окажется отдельно и Часть 2 его не увидит. Берём заведомо не
# сегодняшнее имя, иначе проверка ничего не докажет.
если_задан = имя_листа("EE", мульти=True, лист="01-01")
если_нет = имя_листа("EE", мульти=True)
if если_задан != "01-01":
    ошибок += 1
    print(f"   ✘ заданный лист не сохранился: {если_задан}")
elif если_задан == если_нет:
    ошибок += 1
    print("   ✘ имя по дате совпало со старым — проверка ничего не значит")
else:
    print(f"   ✔ задан «{если_задан}», по дате был бы «{если_нет}»")

print()
print("=== 5. Нет закладки — нет и предложения ===")
продолжение.ФАЙЛ = папка / "нет-такого.json"
if продолжение.остаток():
    ошибок += 1
    print("   ✘ выдумал остаток на пустом месте")
else:
    print("   ✔ пусто")

print()
print("ошибок:", ошибок)
