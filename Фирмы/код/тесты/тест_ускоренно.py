"""
Ускоренный режим: пустое слово не дочитываем до конца.

Зачем. Выдача dnb отсортирована по совпадению с запросом, поэтому хвост всегда
хуже головы: если первые страницы не дали ни одной годной фирмы, десять
следующих не дадут тем более. Цена прочёсывания видна по цифрам прогонов — на
десять фирм С САЙТОМ приходится под три сотни без сайта.

Правило, как просил человек:
  • пустая ПЕРВАЯ страница закрывает слово сразу;
  • дальше нужно ДВЕ пустые подряд (одна случайная страница из дублей и
    «уже использованных» ещё ничего не значит);
  • страница, давшая хоть одну фирму, счёт обнуляет;
  • без автономности режим не работает — менять слово некому.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

ошибок = 0


def проверить(что, вышло, ждём):
    global ошибок
    ладно = вышло == ждём
    ошибок += not ладно
    print(f"   {'✔' if ладно else '✘'} {что}"
          + ("" if ладно else f": вышло {вышло!r}, ждали {ждём!r}"))


def прогнать(страницы: list[int], ускоренно: bool, авто: bool) -> int:
    """
    Сколько страниц прочитаем, прежде чем слово закроется.

    Повторяем ровно ту арифметику, что стоит в движке: счёт пустых подряд и
    разный порог для первой страницы и последующих.
    """
    пустых_подряд = 0
    страница_слова = 0
    прочитано = 0
    for взято_на_странице in страницы:
        страница_слова += 1
        прочитано += 1
        пустых_подряд = 0 if взято_на_странице else пустых_подряд + 1
        предел = 1 if страница_слова == 1 else 2
        if ускоренно and авто and пустых_подряд >= предел:
            break
    return прочитано


print("=== 1. Первая страница пустая — слово закрываем сразу ===")
проверить("прочитали одну страницу",
          прогнать([0, 0, 0, 5, 7], ускоренно=True, авто=True), 1)

print()
print("=== 2. Дальше нужны ДВЕ пустые подряд ===")
# Страница 1 дала фирмы, 2 пустая, 3 дала — слово живёт и читается дальше.
проверить("одна пустая в середине не закрывает",
          прогнать([3, 0, 2, 0, 0, 9], ускоренно=True, авто=True), 5)
# Страницы 2 и 3 пустые подряд — закрываем на третьей.
проверить("две пустые подряд закрывают",
          прогнать([3, 0, 0, 9, 9], ускоренно=True, авто=True), 3)

print()
print("=== 3. Продуктивное слово дочитывается целиком ===")
проверить("ни одной пустой — читаем всё",
          прогнать([2, 1, 3, 1], ускоренно=True, авто=True), 4)

print()
print("=== 4. Без галочки и без автономности — как раньше ===")
проверить("галочка выключена", прогнать([0, 0, 0, 0], ускоренно=False,
                                        авто=True), 4)
проверить("автономности нет", прогнать([0, 0, 0, 0], ускоренно=True,
                                       авто=False), 4)

print()
print("=== 5. Движок и окно действительно принимают флаг ===")
import inspect

import окно as о
from part1 import engine as дв

for имя, ф in (("_по_стране", дв._по_стране), ("run", дв.run),
               ("run_мультигео", дв.run_мультигео)):
    проверить(f"{имя} знает «ускоренно»",
              "ускоренно" in inspect.signature(ф).parameters, True)
# Галочка в окне: без неё флаг некому включить. Живёт она в «_настройка» —
# том ряду, где стоит «Автономно», рядом с которым человек её и ждёт.
проверить("в окне есть галочка",
          "self.ускоренно" in inspect.getsource(о.Окно._настройка), True)
проверить("прогон её читает",
          "ускоренно=быстро" in inspect.getsource(о.Окно.старт), True)

