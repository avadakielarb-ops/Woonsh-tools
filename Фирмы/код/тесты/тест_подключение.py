"""
Подключение к обычному Chrome вместо запуска браузера самим.

Зачем это вообще: 06.09.2026 Cloudflare на dnb.com перестал пускать нас
совсем. Замер показал причину — Playwright, запуская браузер САМ, выставляет
navigator.webdriver=True. Обычный Chrome + подключение по отладочному порту
даёт webdriver=False, и дверь открывается.

Проверяем без браузера три вещи, на которых это держится:
  1. окно, открытое человеком руками, поднимается С ОТЛАДОЧНЫМ ПОРТОМ —
     иначе прогон не сможет к нему подключиться и убьёт его как «занявшее
     профиль» вместе с только что пройденной проверкой;
  2. профиль уже занят — второе окно НЕ плодим (Chrome всё равно откроет
     вкладку в старом, а порта не появится);
  3. подключились к окну человека — оставляем ЕГО вкладку с сайтом, а не
     пустышку about:blank, которая раньше выигрывала просто как первая.
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import common.browser as б

ошибок = 0
запуски: list[list[str]] = []


class ФейкПроцесс:
    def __init__(self, args, **k):
        запуски.append(list(args))


class ФейкВкладка:
    def __init__(self, url):
        self.url = url
        self.закрыта = False

    def close(self): self.закрыта = True
    def bring_to_front(self): pass


class ФейкКонтекст:
    def __init__(self, вкладки):
        self.pages = вкладки

    def new_page(self):
        с = ФейкВкладка("about:blank")
        self.pages.append(с)
        return с


print("=== 1. Окно «для человека» открывается с отладочным портом ===")
import subprocess
было_держат = б.держат_профиль
было_popen = subprocess.Popen
б.держат_профиль = lambda п: []
subprocess.Popen = ФейкПроцесс
try:
    вышло, что = б.открыть_для_входа("dnb", "https://www.dnb.com/")
finally:
    subprocess.Popen = было_popen
    б.держат_профиль = было_держат

порт = [а for а in (запуски[0] if запуски else []) if "remote-debugging-port" in а]
if вышло and порт and порт[0].endswith(str(б.ПОРТ_ОТЛАДКИ)):
    print(f"   ✔ {порт[0]} — прогон найдёт это окно и продолжит в нём")
else:
    ошибок += 1
    print(f"   ✘ порт не выставлен: {запуски[:1]}")
if any("dnb.com" in а for а in (запуски[0] if запуски else [])):
    print("   ✔ адрес dnb передан — человек сразу видит нужную страницу")
else:
    ошибок += 1
    print("   ✘ адрес не передан")

print()
print("=== 2. Профиль занят — второе окно не плодим ===")
запуски.clear()
б.держат_профиль = lambda п: [1234]
subprocess.Popen = ФейкПроцесс
try:
    вышло2, _ = б.открыть_для_входа("dnb", "https://www.dnb.com/")
finally:
    subprocess.Popen = было_popen
    б.держат_профиль = было_держат
if вышло2 and not запуски:
    print("   ✔ окно уже открыто — работаем в нём, ничего не запускаем")
else:
    ошибок += 1
    print(f"   ✘ полез запускать второй Chrome: {запуски}")

print()
print("=== 3. Оставляем вкладку человека, а не пустышку ===")
пустая = ФейкВкладка("about:blank")
рабочая = ФейкВкладка("https://www.dnb.com/business-directory.html")
лишняя = ФейкВкладка("https://example.com/")
br = б.Browser.__new__(б.Browser)
br.ctx = ФейкКонтекст([пустая, рабочая, лишняя])
оставили = б.Browser._одна_вкладка(br)
if оставили is лишняя and пустая.закрыта and рабочая.закрыта:
    print("   ✔ осталась последняя настоящая вкладка, пустышка закрыта")
else:
    ошибок += 1
    print(f"   ✘ осталась {оставили.url}; пустая закрыта={пустая.закрыта}")

одна_пустая = ФейкВкладка("about:blank")
br2 = б.Browser.__new__(б.Browser)
br2.ctx = ФейкКонтекст([одна_пустая])
о2 = б.Browser._одна_вкладка(br2)
if о2 is одна_пустая and not одна_пустая.закрыта:
    print("   ✔ настоящих вкладок нет — берём пустую, не падаем")
else:
    ошибок += 1
    print("   ✘ на одной пустой вкладке сломались")

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
