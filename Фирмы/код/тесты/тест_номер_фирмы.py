"""
Постоянный номер фирмы: рождается вместе с фирмой и переживает переименование.

Проверяем то, ради чего он заведён. Часть 2 подставляет в строку название из
РЕЕСТРА вместо названия с dnb — «Altmer Energy OU» становится «Altmer Energy
OÜ». Строка в таблице при этом остаётся со старым именем, и правка, найденная
по имени, не доезжает. Номер обязан довезти её всё равно.
"""
import sys
import types
from pathlib import Path
from tempfile import mkdtemp

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from common import номер
from part1.excel_out import ExcelWriter
from part1.models import Firm

ошибок = 0

print("=== 1. Вид номера ===")
н = номер.новый("EE")
если_много = {номер.новый("EE") for _ in range(5000)}
if not н.startswith("EE-") or len(н) != 9:
    ошибок += 1
    print(f"   ✘ странный вид: {н}")
elif len(если_много) != 5000:
    ошибок += 1
    print(f"   ✘ повтор на пяти тысячах: уникальных {len(если_много)}")
elif any(с in номер.АЛФАВИТ for с in "01OIL"):
    ошибок += 1
    print("   ✘ в алфавите есть знаки, которые путают глазами")
else:
    print(f"   ✔ {н}, пять тысяч подряд — без повторов, без 0/O/1/I/L")

занят = {номер.новый("EE") for _ in range(3)}
if номер.новый("EE", занятые=занят) in занят:
    ошибок += 1
    print("   ✘ выдал занятый номер")
elif номер.похож("EE-7QK4M2") and not номер.похож("Altmer Energy OU") \
        and not номер.похож("EE-7QK4M"):
    print("   ✔ занятые обходит, свой номер от постороннего текста отличает")
else:
    ошибок += 1
    print("   ✘ «похож» врёт")

print()
print("=== 2. Часть 1 проставляет номер каждой фирме ===")
книга = Path(mkdtemp()) / "PL.xlsx"
w = ExcelWriter(книга, "PL")
w.слово = "amber"
for i in range(3):
    w.фирма(Firm(name=f"FIRMA {i} SP Z O O", address="ul. 1", city="Warszawa",
                 zip_code="00-001", state="", website=f"f{i}.pl",
                 payment_profile="Profil"))
шапка = [c.value for c in w.ws[1]]
if "ID" not in шапка:
    ошибок += 1
    print(f"   ✘ колонки ID нет: {шапка}")
else:
    ки = шапка.index("ID") + 1
    номера = [w.ws.cell(row=r, column=ки).value for r in range(2, 5)]
    if not all(номера) or len(set(номера)) != 3:
        ошибок += 1
        print(f"   ✘ номера не проставились или повторились: {номера}")
    elif not all(str(н).startswith("PL-") for н in номера):
        ошибок += 1
        print(f"   ✘ гео в номере не то: {номера}")
    else:
        print(f"   ✔ три фирмы — три разных номера: {номера}")

print()
print("=== 3. Замена в освобождённую строку тоже получает номер ===")
w.свободные_места([2])
w.фирма(Firm(name="ZAMIANA SP Z O O", address="ul. 2", city="Warszawa",
             zip_code="00-002", state="", website="z.pl",
             payment_profile="Profil"))
подписи = [c.value for c in w.ws[1]]
ки = подписи.index("ID") + 1
корг = подписи.index("Организация") + 1
свой = w.ws.cell(row=2, column=ки).value
if not свой or not str(свой).startswith("PL-"):
    ошибок += 1
    print(f"   ✘ у замены номера нет: {свой!r}")
elif w.ws.cell(row=2, column=корг).value != "ZAMIANA SP Z O O":
    ошибок += 1
    print("   ✘ замена легла не в ту строку")
else:
    print(f"   ✔ замена встала в строку 2 и получила свой номер {свой}")

print()
print("=== 4. Перенос: номер из книги — свой, выдуманный — помечен ===")
import перенос_в_таблицу as перенос

перенос.выписки_на_диске = lambda папка, log=print: ({}, {})
итог = перенос.собрать(log=lambda s: None, только_книга=книга,
                       только_лист=w.sheet_name)
записи = list(итог["фирмы"].values())
if not записи:
    ошибок += 1
    print("   ✘ перенос ничего не собрал")
elif not all(з["ид_из_книги"] for з in записи):
    ошибок += 1
    print(f"   ✘ номер из книги не признан своим: "
          f"{[(з['орг'], з['ид'], з['ид_из_книги']) for з in записи][:2]}")
elif any(з["строка"][16] != з["ид"] for з in записи):
    ошибок += 1
    print("   ✘ в строке для таблицы номер другой")
else:
    print(f"   ✔ {len(записи)} фирм, номера свои и стоят последней колонкой")

# книга без колонки ID — так писали до сих пор
from openpyxl import Workbook

старая = Path(mkdtemp()) / "старая.xlsx"
wb = Workbook()
ws = wb.active
ws.title = "23-08 PL"
ws.append(["№", "Платёжный профиль", "Организация", "Адрес", "Город",
           "Индекс", "Штат", "Website", "Номер в реестре", "Файл выписки"])
ws.append([1, "Profil", "STARA SP Z O O", "ul. 3", "Warszawa", "00-003", "",
           "s.pl", "", ""])
wb.save(старая)
итог2 = перенос.собрать(log=lambda s: None, только_книга=старая,
                        только_лист="23-08 PL")
з2 = list(итог2["фирмы"].values())
if len(з2) != 1:
    ошибок += 1
    print(f"   ✘ старая книга собралась не так: {len(з2)} записей")
elif з2[0]["ид_из_книги"] or not з2[0]["ид"]:
    ошибок += 1
    print(f"   ✘ выдуманный номер выдаётся за свой: {з2[0]['ид']}, "
          f"из книги={з2[0]['ид_из_книги']}")
else:
    print(f"   ✔ старой книге номер выдан ({з2[0]['ид']}), но помечен чужим")

print()
print("=== 5. Выгрузка: правку адресуем номером, даже если имя поменялось ===")
# Часть 2 переименовала фирму: в книге теперь имя из реестра, а в таблице
# лежит старое. Правка обязана уехать по номеру.
переименована = записи[0]
переименована["орг"] = "СОВСЕМ ДРУГОЕ ИМЯ"
переименована["строка"][10] = "выписка.pdf"

отправлено = {}
поддельная = types.ModuleType("common.таблица")
поддельная.настроена = lambda: True
поддельная.читать = lambda лист, сколько=50, всё=False: (
    [["Ключ", "Гео", "Организация", "Статус", "Дата", "Слово", "Откуда", "ID"]]
    + [[f"PL|{к[1]}", "PL", "", "найдена", "", "", "", ""]
       for к in итог["фирмы"]])
поддельная.создать = lambda гео: {"ok": True}
поддельная.дописать = lambda лист, строки, пачка=400: len(строки)
поддельная.обновить = lambda правки, пачка=150: (
    отправлено.setdefault("правки", правки), {"обновлено": len(правки)})[1]
sys.modules["common.таблица"] = поддельная

import выгрузка
from common import пути as _пути

# Тот же тест гоняется и в полигоне, а полигон в таблицу не выгружает вовсе —
# без этой подмены проверка падала бы там на признаке копии, хотя проверяет
# она адресацию правки, а не права.
_пути.это_полигон = lambda: False
выгрузка.перенос.собрать = lambda log=print, только_книга=None, только_лист=None: итог
выгрузка.выгрузить(книга, w.sheet_name, log=lambda s: None)

правки = отправлено.get("правки", [])
свои = [п for п in правки if п.get("ид")]
if not правки:
    ошибок += 1
    print("   ✘ правки не ушли вовсе")
elif not свои:
    ошибок += 1
    print(f"   ✘ правка ушла без номера: {правки[0]}")
elif свои[0]["орг"] != "СОВСЕМ ДРУГОЕ ИМЯ":
    ошибок += 1
    print("   ✘ имя в правке не то, что в книге")
else:
    print(f"   ✔ правка адресована номером {свои[0]['ид']}, "
          f"имя «{свои[0]['орг']}» осталось запасным вариантом")

print()
print("ошибок:", ошибок)
