"""
Правовая форма в ЗАПРОСЕ и одно общее слово в СРАВНЕНИИ — две ловушки Латвии.

Живой случай 17.09.2026. Наша фирма «AQUA-360 SIA». В реестре она записана
как SIA "AQUA-360" — форма ВПЕРЕДИ, имя В КАВЫЧКАХ. Что вышло:

  1. искали по полному имени «AQUA-360 SIA» — реестр отдал двух ЧУЖИХ:
     «Aqua Unitā» и «SIA AQUA», нашей в выдаче не было вовсе;
  2. «SIA AQUA» — имя из одного слова, и по правилу родства оно считалось
     роднёй нашей фирме по общему «aqua». Значит «похожий есть» — и ход
     «поискать иначе» не запускался;
  3. человеку показали две чужие фирмы и попросили выбрать.

А по запросу «AQUA-360» реестр отдаёт нашу первой строкой, и адрес совпадает
до дома: Vīlandes iela 13-5, Rīga.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from common.имена import без_формы
from part2.core.matching import Candidate
from part2.core.models import Company
from part2.engine import _подобрать, запросы_для, не_похожи

ошибок = 0


def проверить(что, вышло, ждём):
    global ошибок
    ладно = вышло == ждём
    ошибок += not ладно
    print(f"   {'✔' if ладно else '✘'} {что}"
          + ("" if ладно else f": вышло {вышло!r}, ждали {ждём!r}"))


print("=== 1. Запрос в реестр идёт БЕЗ правовой формы ===")
проверить("латвийская SIA сзади", без_формы("AQUA-360 SIA"), "AQUA-360")
проверить("форма впереди и кавычки", без_формы('SIA "AQUA-360"'), "AQUA-360")
проверить("эстонская OÜ", без_формы("Altmer Energy OÜ"), "Altmer Energy")
# Буквы не трогаем: латышское имя без диакритики реестр не найдёт.
проверить("диакритика остаётся", без_формы("Ķieģelis SIA"), "Ķieģelis")
проверить("имя без формы не портим", без_формы("HEAT AND COOL"), "HEAT AND COOL")

print()
print("=== 2. Запросы: написание от модели, имя, и никаких «первых слов» ===")
# «AQUA» вместо «AQUA-360 SIA» — это тысяча фирм на десятке страниц.
лв = Company(row=2, name="AQUA-360 SIA")
варианты = запросы_для(лв, "LV")
проверить("одного слова среди запросов нет",
          any(в.strip().upper() == "AQUA" for в in варианты), False)
проверить("Латвия: форма вперёд и в кавычках", 'SIA "AQUA-360"' in варианты, True)
# Кавычки — формат ТОЛЬКО латвийского реестра. Раньше их слали всем.
чех = Company(row=2, name="KOVO SIA")
проверить("Чехии кавычек не шлём",
          any('"' in в for в in запросы_для(чех, "CZ")), False)
# Написание от модели идёт ПЕРВЫМ: им фирма находится с первого запроса.
эст = Company(row=2, name="A.L Timber Components OU",
              extra={"написания": ["A.L. Timber Components OÜ"]})
проверить("сперва написание реестра",
          запросы_для(эст, "EE", сам_режет_форму=True),
          ["A.L. Timber Components OÜ", "A.L Timber Components OU"])
проверить("драйвер режет форму сам — отдельного запроса без формы нет",
          len(запросы_для(Company(row=2, name="HEAT OU"), "EE", True)), 1)
проверить("не режет — добавляем без формы",
          запросы_для(Company(row=2, name="HEAT LTD"), "UK"), ["HEAT LTD", "HEAT"])

print()
print("=== 3. Одно общее слово — ещё не та же фирма ===")
наша = Company(row=2, name="AQUA-360 SIA",
               address="13 - 5 Vilandes iela", city="Riga", zip_code="LV-1010")
чужие = [Candidate(name="Aqua Unitā", address="Jelgavas nov., Ozolnieki"),
         Candidate(name="SIA AQUA", address="Rīga, Riekstu iela 9 - 22")]
адрес1 = "13 - 5 Vilandes iela Riga LV-1010"
проверить("из чужих выбрать нельзя", _подобрать(наша, адрес1, чужие), None)
# Именно из-за этого «похожего» ход «поискать иначе» и не запускался.
проверить("но «похожий» среди них числится", не_похожи(наша, адрес1, чужие),
          False)

print()
print("=== 4. С правильным запросом фирма находится сама ===")
верные = чужие + [Candidate(name='SIA "AQUA-360"',
                            address="Rīga, Vīlandes iela 13 - 5",
                            ref="40003198405")]
выбран = _подобрать(наша, адрес1, верные)
проверить("выбрали нашу", выбран.ref if выбран else None, "40003198405")

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
