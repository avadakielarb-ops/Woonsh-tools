"""
Генератор слов: не повторяет, не нарушает политику Ads, переходит на язык гео.
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from part1 import слова as с

ошибок = 0

print("=== 1. Стоп-лист Google Ads ===")
ПЛОХИЕ = ["health", "healthcare", "casino", "kasyno", "kredyt", "apteka",
          "crypto", "bitcoin", "vape", "wodka", "escort", "weapon", "bank"]
for сл in ПЛОХИЕ:
    причина = с.запрещено(сл)
    if not причина:
        ошибок += 1
        print(f"   ✘ пропустил запрещённое: {сл}")
print(f"   проверено {len(ПЛОХИЕ)} запрещённых")

# Эти ловились подстрочными корнями и терялись зря — самое ценное, что может
# дать генератор: sextant («sex»), bronze («bron»), ammonite («ammo»),
# betula — берёза («bet»), banksia («bank»), hackberry («hack»),
# cashmere («cash»), medallion («med»).
ХОРОШИЕ = ["amber", "granite", "falcon", "bursztyn", "merevaik", "dzintars",
           "sextant", "bronze", "ammonite", "betula", "banksia", "hackberry",
           "cashmere", "medallion", "coincide", "gunnera"]
for сл in ХОРОШИЕ:
    причина = с.запрещено(сл)
    if причина:
        ошибок += 1
        print(f"   ✘ забраковал годное: {сл} — {причина}")
print(f"   проверено {len(ХОРОШИЕ)} годных")

print()
print("=== 2. Ни одно слово словаря не нарушает стоп-лист ===")
всего, битых = 0, []
for язык, слова in с.СЛОВАРЬ.items():
    for сл in слова:
        всего += 1
        п = с.запрещено(сл)
        if п:
            битых.append(f"{язык}/{сл}: {п}")
print(f"   слов в словаре: {всего}, языков: {len(с.СЛОВАРЬ)}")
if битых:
    ошибок += 1
    for б in битых[:6]:
        print("   ✘", б)
else:
    print("   ✔ все чистые")

print()
print("=== 3. Уже отработанное не предлагается ===")
история = [{"страна": "Poland", "слово": "amber", "взято": 10},
           {"страна": "Poland", "слово": "granite", "взято": 10}]
выдача = с.предложить("PL", 30, история)
плохо = [x for x in выдача if x.lower() in ("amber", "granite")]
if плохо:
    ошибок += 1
    print("   ✘ предложил уже гонявшееся:", плохо)
else:
    print(f"   ✔ {len(выдача)} слов, отработанных среди них нет")

print()
print("=== 4. Слабые слова (мало фирм) больше не предлагаются ===")
история2 = [{"страна": "Poland", "слово": "falcon", "взято": 1}]
выдача2 = с.предложить("PL", 30, история2)
if any(x.lower() == "falcon" for x in выдача2):
    ошибок += 1
    print("   ✘ предложил слово, давшее 1 фирму")
else:
    print("   ✔ слово с одной фирмой отброшено")

print()
print("=== 5. Английский кончился — переходим на язык гео ===")
вся_история = [{"страна": "Poland", "слово": w, "взято": 10}
               for w in с.СЛОВАРЬ["EN"]]
выдача3 = с.предложить("PL", 5, вся_история)
польские = [x for x in выдача3 if x in с.СЛОВАРЬ["PL"]]
if len(польские) == len(выдача3) and выдача3:
    print(f"   ✔ перешёл на польский: {выдача3}")
else:
    ошибок += 1
    print(f"   ✘ выдал не польские: {выдача3}")

print()
print("=== 6. Внутри одного захода повторов нет ===")
занятые = set()
всего_слов = []
for гео in ("PL", "EE", "LV", "FR", "NO"):
    н = с.предложить(гео, 2, [], занятые=занятые)
    for x in н:
        занятые.add(x.lower())
    всего_слов += н
if len(всего_слов) != len(set(x.lower() for x in всего_слов)):
    ошибок += 1
    print("   ✘ есть повторы:", всего_слов)
else:
    print(f"   ✔ {len(всего_слов)} слов на 5 стран, все разные")
    print("     ", всего_слов)

print()
print("=== 7. Запас по странам ===")
for гео in ("PL", "EE", "LV", "FI", "HU", "UK", "FR"):
    print(f"   {гео}: {с.сколько_осталось(гео)} слов")

print()
print("ошибок:", ошибок)
