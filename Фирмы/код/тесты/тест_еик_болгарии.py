"""
Болгария: ЕИК, добытый однажды, больше не ищется заново.

Как было. ЕИК собирается на hithorizons и пишется в колонку «ЕИК» — но она
живёт ТОЛЬКО внутри книги прогона. Наряд на выписки каждый раз новый, этой
колонки в нём нет вовсе, и назавтра номер считался неизвестным: заход на
hithorizons повторялся, а если тот не отвечал — драйвер падал на поиск по
кириллице. Жалоба человека дословно: «нахуя мы получали код, чтобы потом
искать по имени».

Как стало. Номер берётся ещё и из «Номера в реестре»: для Болгарии это он и
есть — UIC на 9 или 13 цифр, и он приезжает в наряде с первого же
скачивания. Найденный номер кладётся обратно в «ЕИК», чтобы следующий проход
той же книги не перечитывал соседнюю колонку.
"""
import sys
from pathlib import Path
from tempfile import mkdtemp

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from openpyxl import Workbook

from part2.core.models import Company
from part2.engine import _собрать_еик

ошибок = 0


def проверить(что, вышло, ждём):
    global ошибок
    ладно = вышло == ждём
    ошибок += not ладно
    print(f"   {'✔' if ладно else '✘'} {что}"
          + ("" if ладно else f": вышло {вышло!r}, ждали {ждём!r}"))


книга = Path(mkdtemp()) / "наряд.xlsx"
wb = Workbook()
ws = wb.active
ws.title = "22-09"
ws.append(["Статус", "Организация", "Номер в реестре", "Гео", "ID"])
ws.append(["выписка", "HEAT ENERGY OOD", "131283566", "BG", "BG-1"])      # 9 цифр
ws.append(["выписка", "AQUA SYSTEMS EAD", "2011020304050", "BG", "BG-2"])  # 13
ws.append(["найдена", "NEW FIRM OOD", "", "BG", "BG-3"])                   # нет
ws.append(["найдена", "ODD NUMBER OOD", "12345", "BG", "BG-4"])            # не ЕИК
wb.save(книга)

фирмы = [(2, Company(row=2, name="HEAT ENERGY OOD")),
         (3, Company(row=3, name="AQUA SYSTEMS EAD")),
         (4, Company(row=4, name="NEW FIRM OOD")),
         (5, Company(row=5, name="ODD NUMBER OOD"))]

строки: list[str] = []
# Браузер поднимать нельзя и незачем: проверяем ровно то, что ДО него —
# сколько фирм отсеялось как «номер уже знаем». Если бы отсеялись не все
# известные, функция полезла бы в hithorizons и тест бы это показал.
try:
    _собрать_еик(ws, фирмы, wb, книга, human=None, log=строки.append,
                 stop=None, pause=None)
except Exception as e:
    # Дальше по коду открывается браузер — сюда мы и не собирались.
    строки.append(f"(остановились на браузере: {type(e).__name__})")

print("=== 1. Номер из «Номера в реестре» подхвачен ===")
проверить("девятизначный", фирмы[0][1].extra.get("eik"), "131283566")
проверить("тринадцатизначный", фирмы[1][1].extra.get("eik"), "2011020304050")

print()
print("=== 2. Чего нет или что не похоже на ЕИК — не берём ===")
проверить("пусто осталось пустым", фирмы[2][1].extra.get("eik"), None)
проверить("пятизначный не ЕИК", фирмы[3][1].extra.get("eik"), None)

print()
print("=== 3. Сказано вслух, сколько взято из таблицы ===")
весь = " ".join(строки)
проверить("в логе есть «из «Номера в реестре»»",
          "Номера в реестре" in весь, True)
проверить("посчитаны оба", "ЕИК уже известен у 2" in весь, True)

print()
print("=== 4. Номер лёг обратно в свою колонку ===")
# Чтобы следующий проход этой же книги нашёл его сразу.
шапка = [c.value for c in ws[1]]
к = шапка.index("ЕИК") + 1 if "ЕИК" in шапка else 0
проверить("колонка «ЕИК» появилась", bool(к), True)
if к:
    проверить("в ней номер первой фирмы",
              str(ws.cell(row=2, column=к).value or ""), "131283566")

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
