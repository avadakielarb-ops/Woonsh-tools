class ФейкDnB:
    """
    Первые два слова дают ПУСТО, третье — одну фирму и конец страниц,
    четвёртое — ещё одну. Так выглядит реальность с редкими словами.
    """
    выдача = {"третье": ["ФИРМА А"], "четвёртое": ["ФИРМА Б"]}

    def __init__(self):
        self.слово = ""
        self.поисков = []
        self.отдано = False

    def search(self, keyword, country):
        self.слово = keyword
        self.поисков.append(keyword)
        self.отдано = False
        return True

    def rows(self):
        if self.отдано:
            return []
        self.отдано = True
        имена = self.выдача.get(self.слово, [])
        return [ФейкФирма(и) for и in имена]

    def строк_в_таблице(self):
        # Одна фирма — страница заведомо НЕ полная, значит последняя. Так и в
        # жизни: редкое слово даёт одну строку, и листать там нечего.
        return len(self.выдача.get(self.слово, []))

    def next_page(self):
        return False                      # страницы всегда кончаются сразу

    def enrich_website(self, f, code):
        return f


