"""
Переходник по заголовкам: код перестаёт знать номера колонок наизусть.

Проверяем главное обещание — ПЕРЕХОД НИЧЕГО НЕ ЛОМАЕТ:
  1. обычный лист читается как раньше;
  2. колонку вставили в середину — находим по заголовку, а не мимо;
  3. шапки нет вовсе (таких листов у пользователя 23) — работаем по запасному
     номеру, ровно как до переходника;
  4. «Гео» без запасного: нет колонки — честное «нет», а не выдуманная 12-я;
  5. заголовки пишут по-разному («Сайт», «WEBSITE», «Платежный профиль») —
     всё это одна колонка.
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from openpyxl import Workbook

from common.колонки import Шапка, нормализовать

ошибок = 0
КАНОН = ["№", "Платёжный профиль", "Организация", "Адрес", "Город", "Индекс",
         "Штат", "Website", "Номер в реестре", "Файл выписки",
         "Платёжный профиль выписки", "Гео"]


def лист(заголовки):
    wb = Workbook()
    ws = wb.active
    ws.title = "проба"
    if заголовки:
        ws.append(заголовки)
    return ws


def проверить(что, вышло, ждём):
    global ошибок
    ладно = вышло == ждём
    ошибок += not ладно
    print(f"   {'✔' if ладно else '✘'} {что}: {вышло}" + ("" if ладно else f" (ждали {ждём})"))


print("=== 1. Обычный лист — номера те же, что были зашиты ===")
ш = Шапка(лист(КАНОН))
проверить("Организация", ш.номер("Организация"), 3)
проверить("Файл выписки", ш.номер("Файл выписки"), 10)
проверить("Гео", ш.номер("Гео"), 12)

print()
print("=== 2. Колонка вставлена в середину — не промахиваемся ===")
сдвинутый = КАНОН[:3] + ["Дата"] + КАНОН[3:]
ш = Шапка(лист(сдвинутый))
проверить("Организация осталась на месте", ш.номер("Организация", 3), 3)
проверить("Файл выписки уехал вправо", ш.номер("Файл выписки", 10), 11)
проверить("Гео уехало вправо", ш.номер("Гео"), 13)

print()
print("=== 3. Шапки нет — ведём себя как раньше, по запасному номеру ===")
ш = Шапка(лист([]))
проверить("Организация по запасному", ш.номер("Организация", 3), 3)
проверить("Файл выписки по запасному", ш.номер("Файл выписки", 10), 10)
проверить("без запасного — честный ноль", ш.номер("Организация"), 0)

print()
print("=== 4. «Гео» не выдумываем ===")
ш = Шапка(лист(КАНОН[:11]))          # лист без «Гео», как обычный по-страновой
проверить("Гео нет", ш.номер("Гео"), 0)
проверить("есть() тоже нет", ш.есть("Гео"), False)
try:
    ш.нужен("Гео")
    ошибок += 1
    print("   ✘ нужен() промолчал")
except RuntimeError as e:
    внятно = "нет колонки" in str(e) and "проба" in str(e)
    ошибок += not внятно
    print(f"   {'✔' if внятно else '✘'} нужен() объяснил: {str(e).splitlines()[0]}")

print()
print("=== 5. Одно поле, разные написания ===")
ш = Шапка(лист(["№", "платежный  профиль", "НАЗВАНИЕ", "Address", "City",
                "ZIP", "Region", "Сайт", "Рег номер", "Выписка"]))
для_проверки = [("Платёжный профиль", 2), ("Организация", 3), ("Адрес", 4),
                ("Город", 5), ("Индекс", 6), ("Штат", 7), ("Website", 8),
                ("Номер в реестре", 9), ("Файл выписки", 10)]
for имя, ждём in для_проверки:
    проверить(имя, ш.номер(имя), ждём)

print()
print("=== 6. «Профиль» и «Профиль выписки» не путаются ===")
ш = Шапка(лист(КАНОН))
проверить("Платёжный профиль", ш.номер("Платёжный профиль"), 2)
проверить("Платёжный профиль выписки", ш.номер("Платёжный профиль выписки"), 11)

print()
print("=== 7. Мусор в первой строке не выдаётся за шапку ===")
# такой лист реально есть: в первой строке кусок адреса вместо заголовков
ш = Шапка(лист(["HOME", "Z I DE L'ARGILE 100 CHEMIN", "MOUANS-SARTOUX"]))
проверить("Организация не нашлась", ш.номер("Организация"), 0)
проверить("и уходит на запасной", ш.номер("Организация", 3), 3)

print()
проверить("нормализация «Платёжный  Профиль»",
          нормализовать("Платёжный  Профиль"), "платежныйпрофиль")

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
