"""Непригодные фирмы не возвращаются в оборот, временные сбои — возвращаются."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import shutil
from pathlib import Path
from part1.registry import LocalFileRegistry, отпечаток

песочница = Path("_песочница_непригод")
shutil.rmtree(песочница, ignore_errors=True)
песочница.mkdir()
путь = песочница / "реестр.json"

ошибок = 0
r = LocalFileRegistry(путь)
альфа = отпечаток("ALFA AG", "CH", "8000", "Zurich")
бета = отпечаток("BETA AG", "CH", "8000", "Zurich")
гамма = отпечаток("GAMMA AG", "CH", "8000", "Zurich")

print("=== постоянный отказ: ассоциация ===")
r.забронировать(альфа)
r.непригодна(альфа, "форма не подходит для Google Ads: Association")
print("  свободна после пометки:", r.свободна(альфа), "(ждём False)")
if r.свободна(альфа):
    ошибок += 1
print("  причина:", r.почему_непригодна(альфа))

print()
print("=== временный сбой: бронь просто снята ===")
r.забронировать(бета)
r.снять_бронь(бета)
print("  свободна:", r.свободна(бета), "(ждём True — фирма живая)")
if not r.свободна(бета):
    ошибок += 1

print()
print("=== переживает перезапуск ===")
r2 = LocalFileRegistry(путь)
print("  альфа свободна:", r2.свободна(альфа), "(ждём False)")
print("  бета свободна: ", r2.свободна(бета), "(ждём True)")
if r2.свободна(альфа) or not r2.свободна(бета):
    ошибок += 1
print("  непригодных записей:", len(r2.данные["непригодны"]))

print()
print("=== старый реестр без раздела «непригодны» читается ===")
import json
стар = песочница / "старый.json"
стар.write_text(json.dumps({"брони": {}, "использованы": ["X"]},
                           ensure_ascii=False), encoding="utf-8")
r3 = LocalFileRegistry(стар)
print("  прочитан, использованных:", len(r3.данные["использованы"]))
print("  раздел непригодны создан:", "непригодны" in r3.данные)
r3.непригодна(гамма, "нет в реестре гео")
print("  гамма свободна:", r3.свободна(гамма), "(ждём False)")
if r3.свободна(гамма):
    ошибок += 1

print()
print("=== очистка стирает и непригодных ===")
n = r2.очистить()
print("  стёрто записей:", n)
print("  альфа снова свободна:", r2.свободна(альфа), "(ждём True)")
if not r2.свободна(альфа):
    ошибок += 1

shutil.rmtree(песочница, ignore_errors=True)
print()
print("ошибок:", ошибок)
