"""
Раскладка папок: одна папка на партию, внутри страны, там же книга.

Жалоба 08.09.2026: «несколько неудачных запусков — несколько папок, а они
пустые», «запуск одиночной фирмы оказался в Мультигео», «где искать эксель».
Проверяем, что этого больше не происходит.
"""
import sys
import tempfile
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from common.files import target_path
from part2.engine import папка_гео, папка_книг, папка_листа, прежние_папки

ошибок = 0


def проверить(что, вышло, ждём):
    global ошибок
    ладно = str(вышло) == str(ждём)
    ошибок += not ладно
    print(f"   {'✔' if ладно else '✘'} {что}: {вышло}" + ("" if ладно else f"\n        ждали: {ждём}"))


В = Path("выписки")

from datetime import datetime
СЕГОДНЯ = f"{datetime.now():%d-%m}"

print("=== 1. Папка называется как ЛИСТ, внутри — дата ===")
проверить("обычное гео", папка_гео(В, "21-07 EE", "EE"), В / "EE" / "21-07")
проверить("линия «без сайта»", папка_гео(В, "Без сайта", "EE"),
          В / "EE.БС" / СЕГОДНЯ)
# В мультигео страна остаётся ПОДПАПКОЙ: партия лежит вместе, но внутри
# разобрана по странам, а не свалена в кучу. Так же лежит и всё уже скачанное
# («Мультигео/23-08/AU», «…/BE» и далее), и добор попадает к своим.
проверить("мультигео", папка_гео(В, "07-09", "PL", мультигео=True),
          В / "Мультигео" / "07-09" / "PL")

print()
print("=== 2. Дата — из ИМЕНИ ЛИСТА, а не «сегодня» ===")
проверить("лист «23-08 PL», качаем позже", папка_гео(В, "23-08 PL", "PL"),
          В / "PL" / "23-08")
проверить("в имени листа даты нет", папка_гео(В, "докачка", "PL"),
          В / "PL" / СЕГОДНЯ)

print()
print("=== 3. Пустое имя листа — честное «без-листа», а не сегодняшняя дата ===")
проверить("без листа", папка_листа(В, ""), В / "без-листа")

print()
print("=== 3б. Книги прогона лежат ВМЕСТЕ С ВЫПИСКАМИ ===")
# Лист наряда зовётся просто датой («10-09»), и книги уезжали в «выписки/10-09»
# — папку, похожую на гео, в корне выписок. Теперь книга там же, где выписки.
проверить("одна страна", папка_книг(В, "10-09", "FR"), В / "FR" / "10-09")
проверить("мультигео", папка_книг(В, "10-09", "FR", мультигео=True),
          В / "Мультигео" / "10-09")
проверить("гео не назвали", папка_книг(В, "23-08"), В / "23-08")

print()
print("=== 4. Папка появляется только вместе с файлом ===")
with tempfile.TemporaryDirectory() as врем:
    куда = Path(врем) / "07-09" / "EE"
    проверить("до записи папки нет", куда.exists(), False)
    п = target_path(куда, "Altmer Energy OU")
    проверить("после target_path папка есть", куда.is_dir(), True)
    проверить("имя файла по фирме", п.name, "Altmer Energy OU.pdf")

print()
print("=== 5. Добор находит выписки, лежащие по СТАРОЙ раскладке ===")
with tempfile.TemporaryDirectory() as врем:
    вып = Path(врем)
    старая = вып / "UK" / "2026-09-07_21-03_53шт"
    старая.mkdir(parents=True)
    (старая / "BRONZE LAND LTD.pdf").write_bytes(b"%PDF")
    найдено = прежние_папки(вып, "0709", "UK")
    проверить("нашли старую папку", найдено[:1], [старая])

    мультигео = вып / "Мультигео" / "23-08" / "PL"
    мультигео.mkdir(parents=True)
    (мультигео / "GRANITE.pdf").write_bytes(b"%PDF")
    проверить("нашли папку из «Мультигео»", прежние_папки(вып, "23-08", "PL")[:1],
              [мультигео])

    пустая = вып / "HU"
    пустая.mkdir()
    проверить("пустую папку за находку не считаем",
              прежние_папки(вып, "23-08", "HU"), [])

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
