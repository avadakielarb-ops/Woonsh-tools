"""
Выхлоп по словам и брак по линии.

Просьба человека: «разделить на 2 типа — хороши для фирм с сайтом и без
сайта, статистика, и плюс обновить слова, чтобы не было такого то слова
тупизмы».

Две вещи, на которых это ломается, если не следить:

1. «РЕЕСТР» НЕ СЧИТАЕМ. Там строка на КАЖДУЮ виденную фирму — 10712 штук,
   со словом и БЕЗ колонки «Website». Посчитай его, и каждая фирма учтётся
   дважды, причём второй раз как «без сайта»: у эстонского «velvet»
   выходило 4 с сайтом и 4 без, хотя все четыре с сайтом. Доля схлопывалась
   вдвое, и слова выглядели тупее, чем есть.

2. БРАК ПО ЛИНИИ НЕ ВЫНИМАЕТ СЛОВО ИЗ ОБОРОТА. Эстонское «tamm» нашло 108
   фирм и ровно одну с сайтом — для «с сайтом» тупизм, для «без сайта» одно
   из лучших слов. Выбросить совсем значило бы потерять сотню фирм.
"""
import sys
from pathlib import Path
from tempfile import mkdtemp

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import выхлоп_слов as вс
from part1.запас import Запас

ошибок = 0


def проверить(что, вышло, ждём):
    global ошибок
    ладно = вышло == ждём
    ошибок += not ладно
    print(f"   {'✔' if ладно else '✘'} {что}"
          + ("" if ладно else f": вышло {вышло!r}, ждали {ждём!r}"))


ШАПКА = ["Статус", "Организация", "Website", "Гео", "Слово", "ID"]


def строка(орг, сайт, гео, слово, статус="найдена", ид=""):
    return [статус, орг, сайт, гео, слово, ид or орг]


ЛИСТЫ = [
    {"имя": "EE", "скрыт": False, "строк": 4, "строки": [ШАПКА,
        строка("A OÜ", "a.ee", "EE", "tamm", "годная"),
        строка("B OÜ", "", "EE", "tamm"),
        строка("C OÜ", "", "EE", "tamm")]},
    {"имя": "EE.БС", "скрыт": False, "строк": 3, "строки": [ШАПКА,
        строка("D OÜ", "", "EE", "tamm"),
        строка("E OÜ", "e.ee", "EE", "velvet", "годная")]},
    # «Реестр» — ловушка: те же фирмы, но без колонки Website.
    {"имя": "Реестр", "скрыт": False, "строк": 4, "строки": [
        ["Ключ", "Гео", "Организация", "Слово", "ID"],
        ["k1", "EE", "A OÜ", "tamm", "A OÜ"],
        ["k2", "EE", "B OÜ", "tamm", "B OÜ"],
        ["k3", "EE", "E OÜ", "velvet", "E OÜ"]]},
]

print("=== 1. «Реестр» не считаем — иначе всё вдвое ===")
import common.таблица as тб
настоящее = тб.всё
тб.всё = lambda *a, **k: ЛИСТЫ
try:
    выхлоп = вс.собрать(["EE"], log=lambda *a: None)
finally:
    тб.всё = настоящее
ee = выхлоп["EE"]
проверить("tamm: одна с сайтом", ee["tamm"]["сайт"], 1)
проверить("tamm: три без сайта", ee["tamm"]["бс"], 3)
проверить("tamm: доля 25%", round(ee["tamm"]["доля"], 3), 0.25)
проверить("velvet целиком с сайтом", ee["velvet"]["доля"], 1.0)
проверить("годные посчитаны", ee["tamm"]["годн"], 1)

print()
print("=== 2. Судим только при достаточной выборке ===")
# У «tamm» всего 4 фирмы — это «мало данных», а не «плохое слово».
проверить("при выборке 4 не судим",
          вс.тупые(ee, "сайт", порог=0.5, минимум=30), [])
проверить("при минимуме 2 уже судим",
          вс.тупые(ee, "сайт", порог=0.5, минимум=2), ["tamm"])
# Для линии «без сайта» тупых не бывает: там сайт и не нужен.
проверить("для «бс» тупых нет",
          вс.тупые(ee, "бс", порог=0.5, минимум=2), [])

print()
print("=== 3. Брак по линии НЕ вынимает слово из оборота ===")
файл = Path(mkdtemp()) / "запас.json"
з = Запас(path=файл)
з.пополнить("EE", ["tamm", "velvet", "kivi"])
проверить("в запасе три слова", з.свободно("EE"), 3)
з.забраковать_для("EE", ["tamm"], "сайт")
проверить("свободных по-прежнему три", з.свободно("EE"), 3)
проверить("для «сайт» tamm не выдаётся",
          "tamm" in з.взять("EE", 3, линия="сайт"), False)

з2 = Запас(path=файл)
проверить("а для «бс» выдаётся",
          "tamm" in з2.взять("EE", 3, линия="бс"), True)

print()
print("=== 4. Отбракованное не сгенерируется заново ===")
# Иначе модель предложит «tamm» как новое слово, мы его добавим, и оно
# снова будет выпадать в линию, где уже признано бесполезным.
проверить("tamm помнится известным",
          "tamm" in Запас(path=файл).все_известные("EE"), True)

print()
print("=== 5. Передумали — слово возвращается в линию ===")
з3 = Запас(path=файл)
з3.пополнить("EE", ["tamm"])          # вернулось бы в свободные, если было выдано
з3.вернуть_в_оборот("EE", ["tamm"], "сайт")
проверить("брака линии больше нет", з3.брак_линии("EE", "сайт"), [])

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
