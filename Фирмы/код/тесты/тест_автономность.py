from part1.models import Firm


class ДнбЗалип:
    """Одна и та же страница, «Next» не работает никогда."""

    def __init__(self, фирм=2):
        self.прочтений = 0
        self.фирм = фирм
        self.листаний = 0

    def rows(self):
        self.прочтений += 1
        return [Firm(name=f"Falter-{i} Gesellschaft m.b.H.",
                     url=f"https://dnb/{i}", website="http://www.falter.at")
                for i in range(self.фирм)]

    def строк_в_таблице(self):
        return self.фирм

    def next_page(self):
        self.листаний += 1
        return False

    def enrich_website(self, f, code):
        return f


class ПисарьЗаглушка:
    sheet_name = "09-09"
    path = "Austria.xlsx"
    гео = ""
    слово = ""

    def отсев(self, r): pass
    def без_сайта(self, f): return True
    def фирма(self, f): pass


class РеестрЗаглушка:
    def забронировать(self, fp): pass
    def свободна(self, fp): return True
    def снять_бронь(self, fp): pass


настоящий_этаж = движок1.этаж_1
