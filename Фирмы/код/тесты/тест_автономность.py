спрошено = []


def робот(g: HumanGate) -> HumanGate:
    """Тот же выбор, что делает окно в автономном режиме."""
    def меню(заголовок, сообщение, варианты, фирма=""):
        спрошено.append(заголовок)
        ключ = getattr(g, "авто", "") or ""
        g.answer_menu(ключ)          # пусто — значит безопасного ответа нет
    g.ui_menu = меню
    return g


g = робот(HumanGate())
