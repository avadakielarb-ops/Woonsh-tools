"""
Лестница статусов одна — в Python и в скрипте таблицы.

Статусы живут в двух местах: common/статусы.py (их пишет и читает прогон) и
Код.js (выпадающий список на листах). Разойдутся — запись нового статуса
упадёт с «нарушены правила проверки данных», как уже было при переходе с
пяти ступеней на девять. И «что не выдавать» — тоже одно место: окно и сбор
для бота держали свои копии.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from common import статусы as с

ошибок = 0


def проверить(что, вышло, ждём):
    global ошибок
    ладно = вышло == ждём
    ошибок += not ладно
    print(f"   {'✔' if ладно else '✘'} {что}"
          + ("" if ладно else f": вышло {вышло!r}, ждали {ждём!r}"))


print("=== 1. СПИСОК В ТАБЛИЦЕ = СПИСОК В PYTHON ===")
код = (Path(__file__).resolve().parents[2] / "доки" / "скрипт_таблицы"
       / "Код.js").read_text(encoding="utf-8")
м = re.search(r"var ФИРМЫ_СТАТУСЫ = \[(.*?)\];", код, re.S)
в_таблице = re.findall(r"'([^']*)'", м.group(1)) if м else []
проверить("тот же набор и порядок", в_таблице, с.ВСЕ)

print()
print("=== 2. НАБОРЫ ИЗ ЛЕСТНИЦЫ ===")
проверить("не выдавать = закрытые + нет выписки", с.НЕ_ВЫДАВАТЬ,
          с.ЗАКРЫТЫЕ | {с.НЕТ_ВЫПИСКИ})
проверить("бота не спрашиваем о закрытых и годных", с.НЕ_СПРАШИВАТЬ_БОТА,
          с.ЗАКРЫТЫЕ | {с.ГОДНАЯ})
проверить("«нет выписки» бота спросить можно",
          с.НЕТ_ВЫПИСКИ in с.НЕ_СПРАШИВАТЬ_БОТА, False)

print()
print("=== 3. СВОИХ КОПИЙ БОЛЬШЕ НЕТ ===")
корень = Path(__file__).resolve().parent.parent
окно = (корень / "окно.py").read_text(encoding="utf-8")
проверить("окно не держит свой список", "НЕ_ВЫДАВАТЬ = {" in окно, False)
бот = (корень / "проверка_ботом.py").read_text(encoding="utf-8")
проверить("сбор для бота — по общему набору",
          "статус in ЗАКРЫТЫЕ or статус == ГОДНАЯ" in бот, False)

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
