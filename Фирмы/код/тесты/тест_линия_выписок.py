"""
Скачивание выписок целится в ЛИНИЮ: с сайтом, без сайта или в обе.

Почему это понадобилось. Наряд собирался по обеим линиям сразу, выбора не
было вовсе. А фирм без сайта втрое больше — 4252 против 1240, — поэтому «по
50 на страну» почти целиком уходило на них. Замер 17.09.2026: выписок с
сайтом 368, без сайта 696, и 872 фирмы С САЙТОМ стояли без выписки. Человек
хотел качать линию «с сайтом» и не мог: кнопка не спрашивала.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import задание_выписок
import окно as о

ошибок = 0


def проверить(что, вышло, ждём):
    global ошибок
    ладно = вышло == ждём
    ошибок += not ладно
    print(f"   {'✔' if ладно else '✘'} {что}"
          + ("" if ладно else f": вышло {вышло!r}, ждали {ждём!r}"))


print("=== 1. Подпись линии превращается в правило отбора ===")
проверить("с сайтом", о._линия_в_флаг("сайт"), True)
проверить("без сайта", о._линия_в_флаг("без"), False)
проверить("обе", о._линия_в_флаг("все"), None)

print()
print("=== 2. Отбор действительно делит по сайту ===")
ЛИСТЫ = [{
    "имя": "EE", "скрыт": False, "строк": 5,
    "строки": [
        ["Статус", "Организация", "Website", "Файл выписки", "Гео", "ID"],
        ["выписка", "УЖЕ ЕСТЬ OU", "site.ee", "есть.pdf", "EE", "EE-0"],
        ["найдена", "С САЙТОМ OU", "aqua.ee", "", "EE", "EE-1"],
        ["найдена", "БЕЗ САЙТА OU", "", "", "EE", "EE-2"],
        ["найдена", "ЕЩЁ БЕЗ САЙТА OU", "", "", "EE", "EE-3"],
    ]}]


class Таблица:
    @staticmethod
    def всё(*a, **к):
        return ЛИСТЫ


настоящая = sys.modules.get("common.таблица")
sys.modules["common.таблица"] = Таблица

try:
    def имена(флаг):
        найдено = задание_выписок.найти(["EE"], None, log=lambda s: None,
                                        только_с_сайтом=флаг)
        return sorted(з["Организация"] for з in найдено)

    проверить("только с сайтом", имена(True), ["С САЙТОМ OU"])
    проверить("только без сайта", имена(False),
              ["БЕЗ САЙТА OU", "ЕЩЁ БЕЗ САЙТА OU"])
    проверить("обе линии", имена(None),
              ["БЕЗ САЙТА OU", "ЕЩЁ БЕЗ САЙТА OU", "С САЙТОМ OU"])
    # У кого выписка уже есть — не качаем повторно ни в какой линии.
    проверить("скачанную не берём заново", "УЖЕ ЕСТЬ OU" in имена(None), False)
finally:
    if настоящая is not None:
        sys.modules["common.таблица"] = настоящая
    else:
        sys.modules.pop("common.таблица", None)

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
