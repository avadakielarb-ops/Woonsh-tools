"""
Строка состояния: что делаем, где, сколько из скольких, сколько мимо.

Прогон идёт часами, и по бегущему логу не понять главного — где мы сейчас.
Просьба человека дословно: «статус бар, какой статус, 50/250, какое гео, и
что делаем — ищем сайт или качаем выписки, сколько скачено сколько пропущено».

Читаем ТОТ ЖЕ лог, что и так течёт в окно: заводить вторую дорогу из трёх
движков ради одной надписи — это три места, где однажды забудут её дёрнуть.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import окно as о

ошибок = 0


def проверить(что, вышло, ждём):
    global ошибок
    ладно = вышло == ждём
    ошибок += not ладно
    print(f"   {'✔' if ладно else '✘'} {что}"
          + ("" if ладно else f": вышло {вышло!r}, ждали {ждём!r}"))


class Табло:
    """Подделка ярлыка: запоминает последнюю надпись."""
    def __init__(self):
        self.текст = ""

    def configure(self, text=None, foreground=None):
        if text is not None:
            self.текст = text


class Окошко:
    """Только то, что нужно строке состояния."""
    ШАБЛОН_ФИРМЫ = о.Окно.ШАБЛОН_ФИРМЫ
    ШАБЛОН_ГЕО2 = о.Окно.ШАБЛОН_ГЕО2
    ШАБЛОН_ГЕО1 = о.Окно.ШАБЛОН_ГЕО1
    _сбросить_статус = о.Окно._сбросить_статус
    _статус_из_строки = о.Окно._статус_из_строки
    _показать_статус = о.Окно._показать_статус

    def __init__(self):
        self.статус = Табло()


print("=== 1. Поиск фирм: гео и счёт из лога ===")
w = Окошко()
w._сбросить_статус("🔍 Ищем фирмы с сайтом")
for строка in ("Гео CH. Ищу «hazel», нужно 100 фирм. Лист: 22-09",
               "  · открываю dnb.com/business-directory…",
               "  ✔ [1/100] AQUA AG — aqua.ch",
               "  ✘ BRAND GMBH — бренд",
               "  ✔ [2/100] HEAT AG — heat.ch"):
    w._статус_из_строки(строка)
проверить("страна из строки «Гео CH»", "CH" in w.статус.текст, True)
проверить("сделано посчитано", "сделано 2" in w.статус.текст, True)
проверить("пропущено посчитано", "пропущено 1" in w.статус.текст, True)

print()
print("=== 2. Выписки: «12/50» и смена страны ===")
w = Окошко()
w._сбросить_статус("⬇ Качаем выписки с сайтом")
w._статус_из_строки("[1/3]  гео FR — строки 2–51 (50 фирм)")
w._статус_из_строки("[12/50] COOL-HEAT SERVICES SAS")
проверить("гео и счёт вместе",
          "FR" in w.статус.текст and "12/50" in w.статус.текст, True)
# Новая страна — счёт фирм начинается заново, иначе «12/50» висит от чужой.
w._статус_из_строки("[2/3]  гео EE — строки 52–101 (50 фирм)")
проверить("страна сменилась", "EE" in w.статус.текст, True)
проверить("счёт обнулился", "12/50" not in w.статус.текст, True)

print()
print("=== 3. Строка «[3/19] гео XX» — это страна, а не фирма ===")
w = Окошко()
w._сбросить_статус("⬇ Качаем выписки")
w._статус_из_строки("[3/19]  гео PL — строки 2–101 (100 фирм)")
проверить("счёт фирм не подхватил номер страны",
          "3/19" not in w.статус.текст, True)

print()
print("=== 4. Пока ничего не запускали — «Готов к работе» ===")
w = Окошко()
w._показать_статус()
проверить("покой", w.статус.текст, о.ПОКОЙ)
# И строки лога до запуска ничего не считают: счётчика ещё нет.
w._статус_из_строки("  ✔ [1/10] ЧТО-ТО")
проверить("ничего не сломалось", w.статус.текст, о.ПОКОЙ)

print()
print("=== 5. Цифры на кнопках — сколько для них работы ===")
# Кнопка должна говорить о себе сама: раньше человек жал «Скачать выписки» и
# только внутри окошка узнавал, что качать нечего.


class Кнопка:
    def __init__(self):
        self.текст = ""

    def configure(self, text=None, **_):
        if text is not None:
            self.текст = text


class Окошко2:
    _цифры_на_кнопки = о.Окно._цифры_на_кнопки

    def __init__(self, счётчики, выбор=()):
        self.счётчики = счётчики
        self._выбор_гео = list(выбор)
        self.кн_выписки = Кнопка()
        self.кн_проверка = Кнопка()
        self.кн_выдача = Кнопка()

    def выбранные_гео(self):
        return list(self._выбор_гео)


счёт = {
    "UK": {"сайт": 130, "сайт_в": 83, "бс": 239, "бс_в": 115,
           "годн": 83, "пров": 83, "непров": 286},
    "EE": {"сайт": 81, "сайт_в": 26, "бс": 2434, "бс_в": 136,
           "годн": 26, "пров": 26, "непров": 2489},
}
w2 = Окошко2(счёт, ["UK"])
w2._цифры_на_кнопки()
# Качать = (130−83) + (239−115) = 171; проверять = 83+115−83 = 115; выдать = 83
проверить("сколько качать по UK", w2.кн_выписки.текст,
          "⬇  Скачать выписки (171)")
проверить("сколько проверять по UK", w2.кн_проверка.текст,
          "🤖  Проверить у бота (115)")
проверить("сколько можно выдать", w2.кн_выдача.текст,
          "✅  Взять в работу (83)")

# Ничего не выбрано — считаем по всем странам: «сколько работы вообще».
w3 = Окошко2(счёт)
w3._цифры_на_кнопки()
проверить("без выбора — по всем", w3.кн_выдача.текст,
          "✅  Взять в работу (109)")

# Нечего — цифру не пишем вовсе, чтобы «(0)» не мозолило глаз.
w4 = Окошко2({"HU": dict(о.ПУСТОЙ_СЧЁТ)}, ["HU"])
w4._цифры_на_кнопки()
проверить("пусто — без скобок", w4.кн_выдача.текст, "✅  Взять в работу")

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
