"""
Слова: местные и английские вперемешку, брак выбрасывается навсегда.

Две беды, обе уже случались, обе зеркальные:
  · «англ + местные» — до местных очередь не доходила никогда (замер 08.09:
    в EE первые девяносто слов английские, эстонские лежат в хвосте);
  · «местные + англ» — та же беда наоборот.
Чередование лечит обе: обе половины идут в дело с первого слова.

Плюс проверка брака: слово, которое модель признала выдуманным или служебным,
уходит НАВСЕГДА и второй раз не генерируется. Редкое слово браком не считается.
"""
import json
import sys
import tempfile
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from part1.запас import Запас
from part1.слова_gemini import вперемешку

ошибок = 0


def проверить(что, вышло, ждём):
    global ошибок
    ладно = вышло == ждём
    ошибок += not ладно
    print(f"   {'✔' if ладно else '✘'} {что}: {вышло}"
          + ("" if ладно else f"  (ждали {ждём})"))


print("=== 1. Чередование, поровну ===")
проверить("местное первым", вперемешку(["a", "b"], ["x", "y"]),
          ["a", "x", "b", "y"])

print()
print("=== 2. Местных больше — хвост идёт как есть ===")
проверить("хвост не потерян", вперемешку(["a", "b", "c"], ["x"]),
          ["a", "x", "b", "c"])

print()
print("=== 3. Английских больше ===")
проверить("хвост не потерян", вперемешку(["a"], ["x", "y", "z"]),
          ["a", "x", "y", "z"])

print()
print("=== 4. Местных нет вовсе (UK, US) — список остаётся английским ===")
проверить("без местных", вперемешку([], ["x", "y"]), ["x", "y"])

print()
print("=== 5. Ни одно слово не теряется и не двоится ===")
м, а = [f"м{i}" for i in range(7)], [f"а{i}" for i in range(4)]
итог = вперемешку(м, а)
проверить("длина сходится", len(итог), len(м) + len(а))
проверить("повторов нет", len(set(итог)), len(итог))
проверить("все на месте", sorted(итог), sorted(м + а))

print()
print("=== 6. Брак уходит навсегда и не возвращается генерацией ===")
with tempfile.TemporaryDirectory() as врем:
    файл = Path(врем) / "запас.json"
    з = Запас(файл)
    з.пополнить("EE", ["teras", "qwertyxz", "vask", "sest"])
    проверить("до чистки", з.свободно("EE"), 4)

    убрано = з.забраковать("EE", ["qwertyxz", "sest"])
    проверить("выброшено", убрано, 2)
    проверить("осталось", з.свободно("EE"), 2)

    # главное: повторная генерация НЕ вернёт брак обратно
    добавлено = з.пополнить("EE", ["qwertyxz", "sest", "pronks"])
    проверить("из повторной генерации взяли только новое", добавлено, 1)
    проверить("брак не вернулся", з.свободно("EE"), 3)

    з2 = Запас(файл)
    проверить("брак пережил перезапуск",
              json.loads(файл.read_text(encoding="utf-8"))["EE"]["брак"],
              ["qwertyxz", "sest"])
    проверить("живое слово не тронуто", "teras" in з2._гнездо("EE")["свободные"], True)

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
