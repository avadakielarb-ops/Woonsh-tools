py = sys.executable
итоги = []
for имя, файл in ПРОВЕРКИ:
    путь = ПАПКА / файл
    if not путь.exists():
        итоги.append((имя, "НЕТ ФАЙЛА", ""))
        continue
    р = subprocess.run([py, str(путь)], capture_output=True, text=True,
                       encoding="utf-8", errors="replace", cwd=str(КОРЕНЬ))
    вывод = (р.stdout or "") + (р.stderr or "")
    плохо = [с for с in вывод.splitlines()
             if "✘" in с or "ПЛОХО" in с or "Traceback" in с
             or ("ошибок:" in с.lower() and "ошибок: 0" not in с.lower())]
    статус = "ok" if (р.returncode == 0 and not плохо) else "УПАЛА"
    итоги.append((имя, статус, "; ".join(плохо[:2])[:110]))

print("=" * 66)
print("СВОДКА ПРОВЕРОК")
print("=" * 66)
упало = 0
for имя, статус, деталь in итоги:
    значок = "✔" if статус == "ok" else "✘"
    if статус != "ok":
        упало += 1
    print(f"  {значок} {имя:<26} {статус}")
    if деталь:
        print(f"       {деталь}")
print()
print(f"всего: {len(итоги)},  упало: {упало}")
sys.exit(1 if упало else 0)














