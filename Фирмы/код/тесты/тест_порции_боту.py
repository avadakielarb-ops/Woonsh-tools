"""
Список боту отдаётся ПОРЦИЯМИ, а журнал пишется по факту выдачи.

Просьба человека дословно: «я выберу эстонию там будет 2000 фирм, я хочу
выбрать количество и буфер собереться полностью но будет давать мне по
очереди по 50. Он дает окно 50 я вношу овтет отправляю идем дальше».

Две вещи, каждая из которых иначе стоила бы фирм:

1. ЖУРНАЛ ПИШЕТСЯ НА ПОРЦИЮ, А НЕ НА ВЕСЬ СПИСОК. Запись значит «это имя у
   бота уже есть», и `собрать` по ней отсеивает. Поставь её на все 2000
   вперёд — и человек, бросивший на третьей полусотне, навсегда вычеркнет
   1850 имён, которых бот в глаза не видел.

2. ОТВЕТ РАЗБИРАЕТСЯ ПО ТЕКУЩЕЙ ПОРЦИИ. Возьми мы весь список, все ещё не
   отданные имена попали бы в «бот промолчал».
"""
import json
import sys
from pathlib import Path
from tempfile import mkdtemp

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import проверка_ботом as пб

ошибок = 0


def проверить(что, вышло, ждём):
    global ошибок
    ладно = вышло == ждём
    ошибок += not ладно
    print(f"   {'✔' if ладно else '✘'} {что}"
          + ("" if ладно else f": вышло {вышло!r}, ждали {ждём!r}"))


def фирма(n: int) -> dict:
    return {"ид": f"EE-{n}", "лист": "EE", "гео": "EE", "орг": f"FIRMA {n} OÜ",
            "для_бота": f"FIRMA {n}", "файл": f"{n}.pdf", "платёжка": ""}


настоящая_папка, настоящий_журнал = пб.ПАПКА, пб.ЖУРНАЛ
пб.ПАПКА = Path(mkdtemp())
пб.ЖУРНАЛ = пб.ПАПКА / "журнал.json"
try:
    print("=== 1. Сбор списка НЕ пишет в журнал ===")
    все = [фирма(n) for n in range(1, 126)]      # 125 фирм, порция 50
    текст, дано = пб.сохранить_пакет(все, "сайт", log=lambda *a: None,
                                     журналить=False)
    проверить("список собран целиком", len(json.loads(
        дано.read_text(encoding="utf-8"))), 125)
    проверить("журнала ещё нет", пб.ЖУРНАЛ.exists(), False)
    проверить("клеймо пакета проставлено", bool(все[0].get("пакет")), True)

    print()
    print("=== 2. Выдача порции пишет в журнал ТОЛЬКО ЕЁ ===")
    пб.записать_в_журнал(все[0:50], дано.stem, log=lambda *a: None)
    ж = json.loads(пб.ЖУРНАЛ.read_text(encoding="utf-8"))
    проверить("в журнале ровно первая полусотня", len(ж), 50)
    проверить("51-я не записана",
              пб.ключ_журнала("EE", "FIRMA 51 OÜ") in ж, False)

    print()
    print("=== 3. Ответ разбирается ПО ПОРЦИИ, а не по всему списку ===")
    порция = все[0:50]
    ответ = "\n".join(f"✅ Компания добавлена: FIRMA {n}" for n in range(1, 51))
    р = пб.разложить(порция, ответ, log=lambda *a: None)
    проверить("годных — вся порция", len(р["годные"]), 50)
    # ВОТ ОНА, ЦЕНА ОШИБКИ: разбери мы весь список, 75 неотданных имён
    # оказались бы «бот промолчал» — при том что боту их не показывали.
    целиком = пб.разложить(все, ответ, log=lambda *a: None)
    проверить("по всему списку было бы 75 «без ответа»",
              len(целиком["нет_ответа"]), 75)
    проверить("по порции — ни одного", len(р["нет_ответа"]), 0)

    print()
    print("=== 4. Брошенная на середине очередь не жжёт остаток ===")
    # Человек ушёл после первой порции. Второй заход должен снова предложить
    # ему имена с 51-го — они боту не уходили.
    остаток = [з for з in все
               if пб.ключ_журнала(з["гео"], з["орг"]) not in ж]
    проверить("остаток цел", len(остаток), 75)
    проверить("начинается с 51-й", остаток[0]["ид"], "EE-51")
finally:
    пб.ПАПКА, пб.ЖУРНАЛ = настоящая_папка, настоящий_журнал

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
