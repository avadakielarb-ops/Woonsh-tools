import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import json
import shutil
from pathlib import Path
from part1.registry import LocalFileRegistry, РеестрПовреждён, ПАПКА_БЭКАПОВ

песочница = Path("_песочница_реестр")
shutil.rmtree(песочница, ignore_errors=True)
песочница.mkdir()
файл = песочница / "реестр_фирм.json"
сообщения = []
лог = сообщения.append

print("=== 1. Первый запуск: файла нет — пустой реестр это НОРМА ===")
r = LocalFileRegistry(файл, log=лог)
print("   свободна PL|альфа:", r.свободна("PL|альфа|100"))
r.забронировать("PL|альфа|100")
r.подтвердить("PL|альфа|100", "PL#12345")
r.забронировать("PL|бета|200")
print("   после работы: использованных", len(r.данные["использованы"]),
      "| броней", len(r.данные["брони"]))

print()
print("=== 2. Второй запуск: данные на месте, снят снимок ===")
r2 = LocalFileRegistry(файл, log=лог)
print("   использованных:", len(r2.данные["использованы"]))
print("   свободна PL|альфа:", r2.свободна("PL|альфа|100"), "(должно быть False)")
снимки = list((песочница / ПАПКА_БЭКАПОВ).glob("реестр_*.json"))
print("   снимков в бэкапе:", len(снимки))

print()
print("=== 3. Файл ПОРТИМ — реестр должен подняться из бэкапа ===")
файл.write_text("{битый мусор", encoding="utf-8")
r3 = LocalFileRegistry(файл, log=лог)
print("   использованных после подъёма:", len(r3.данные["использованы"]),
      "(должно быть 1, а не 0)")
print("   свободна PL|альфа:", r3.свободна("PL|альфа|100"), "(должно быть False)")
for м in сообщения:
    if "бэкап" in м:
        print("   лог:", м)

print()
print("=== 4. Файл битый И бэкапов нет — обязан ОТКАЗАТЬСЯ, а не молчать ===")
файл.write_text("{опять мусор", encoding="utf-8")
shutil.rmtree(песочница / ПАПКА_БЭКАПОВ)
try:
    LocalFileRegistry(файл, log=лог)
    print("   ✘ ПЛОХО: запустился с пустым реестром")
except РеестрПовреждён as e:
    print("   ✔ отказался запускаться, как и должен")
    print("   сообщение:", str(e).splitlines()[0])

print()
print("=== 5. Атомарность: временный файл не остаётся ===")
файл.unlink()
r5 = LocalFileRegistry(файл, log=лог)
r5.забронировать("FR|гамма|300")
хвосты = list(песочница.glob("*.tmp"))
print("   .tmp файлов после записи:", len(хвосты), "(ждём 0)")
print("   реестр читается:", LocalFileRegistry._прочитать(файл) is not None)

print()
print("=== 6. Очистка снимает снимок ДО стирания ===")
r6 = LocalFileRegistry(файл, log=лог)
r6.подтвердить("FR|гамма|300", "FR#999")
было = len(r6.данные["использованы"])
n = r6.очистить()
снимки = sorted((песочница / ПАПКА_БЭКАПОВ).glob("*перед-очисткой*"))
print(f"   очищено записей: {n}, было использованных: {было}")
print("   снимок «перед-очисткой»:", снимки[-1].name if снимки else "НЕТ")
if снимки:
    д = json.loads(снимки[-1].read_text(encoding="utf-8"))
    print("   в снимке использованных:", len(д["использованы"]), "(данные спасены)")

shutil.rmtree(песочница, ignore_errors=True)
print()
print("песочница убрана")
