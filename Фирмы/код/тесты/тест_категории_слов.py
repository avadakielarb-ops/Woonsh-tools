"""
Слова разных категорий: чтобы находки не складывались в узор.

Если весь запас — камни, то и фирмы будут «Гранит», «Кобальт», «Базальт»:
со стороны это один почерк. Плюс категории дают честное сравнение — по одному
слову судить нельзя, а по сорока словам одного поля против сорока другого уже
видно, где искать дальше.

Проверяем два свойства порядка, потому что запас выдаётся строго по нему:
соседи должны различаться и КАТЕГОРИЕЙ, и ЯЗЫКОМ.
"""
import json
import sys
from pathlib import Path
from tempfile import mkdtemp

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from part1.запас import Запас
from part1.слова_gemini import КАТЕГОРИИ, разложить

ошибок = 0

print("=== 1. Порядок чередует категории ===")
слова = []
for кат in ("камни", "звери", "ремёсла"):
    for i in range(4):
        слова.append({"w": f"{кат}-англ-{i}", "англ": True, "cat": кат})
        слова.append({"w": f"{кат}-мест-{i}", "англ": False, "cat": кат})
порядок = разложить(слова)

подряд = 0
худшее = 0
for i in range(1, len(порядок)):
    своя = порядок[i].split("-")[0]
    прежняя = порядок[i - 1].split("-")[0]
    подряд = подряд + 1 if своя == прежняя else 0
    худшее = max(худшее, подряд)
if len(порядок) != len(слова):
    ошибок += 1
    print(f"   ✘ потерялись слова: {len(порядок)} из {len(слова)}")
elif худшее > 0:
    ошибок += 1
    print(f"   ✘ {худшее + 1} слов одной категории подряд")
else:
    print(f"   ✔ {len(порядок)} слов, две подряд из одной категории не встретились")
    print(f"     начало: {порядок[:6]}")

print()
print("=== 2. Порядок чередует и язык ===")
from itertools import groupby

языки = ["англ" if "-англ-" in с else "мест" for с in порядок]
# groupby отдаёт ПАРЫ (ключ, группа) — считать надо группу, а не пару.
одинаковых = max((len(list(гр)) for _, гр in groupby(языки)), default=0)
предел = len(set(с.split("-")[0] for с in порядок))   # ширина круга = категорий
if одинаковых > предел:
    ошибок += 1
    print(f"   ✘ {одинаковых} слов одного языка подряд при {предел} категориях "
          f"— половина запаса не попробуется")
else:
    print(f"   ✔ подряд одного языка не больше {одинаковых} — это ровно круг "
          f"по {предел} категориям, дальше язык меняется")

print()
print("=== 3. Категория без потерь доезжает до запаса ===")
файл = Path(mkdtemp()) / "запас.json"
з = Запас(файл)
з.пополнить("EE", ["kivi", "kotkas"], {"kivi": "камни", "kotkas": "звери"})
if з.категория("EE", "kivi") != "камни" or з.категория("EE", "KOTKAS") != "звери":
    ошибок += 1
    print(f"   ✘ не сохранилась: kivi={з.категория('EE', 'kivi')!r}")
elif з.категория("EE", "старое") != "":
    ошибок += 1
    print("   ✘ выдумал категорию неизвестному слову")
else:
    print("   ✔ kivi→камни, kotkas→звери, регистр не важен, чужому — пусто")

print()
print("=== 4. Старый запас без категорий читается как раньше ===")
старый = Path(mkdtemp()) / "старый.json"
старый.write_text(json.dumps(
    {"PL": {"свободные": ["amber", "granit"], "выданные": [], "обновлено": ""}}),
    encoding="utf-8")
з2 = Запас(старый)
if з2.свободно("PL") != 2:
    ошибок += 1
    print("   ✘ старый файл не прочитался")
elif з2.категория("PL", "amber") != "":
    ошибок += 1
    print("   ✘ приписал категорию слову из старого запаса")
else:
    print("   ✔ два слова на месте, категорий нет и не выдумано")
    # и дополнение старого файла категориями не ломает его
    з2.пополнить("PL", ["kwarc"], {"kwarc": "камни"})
    if з2.категория("PL", "kwarc") != "камни" or з2.свободно("PL") != 3:
        ошибок += 1
        print("   ✘ дополнение старого файла сломалось")
    else:
        print("   ✔ новое слово с категорией лёг рядом со старыми")

print()
print("=== 5. Категорий хватает, чтобы узора не было ===")
if len(КАТЕГОРИИ) < 6:
    ошибок += 1
    print(f"   ✘ всего {len(КАТЕГОРИИ)} категорий — мало")
else:
    print(f"   ✔ {len(КАТЕГОРИИ)}: {', '.join(sorted(КАТЕГОРИИ))}")

print()
print("ошибок:", ошибок)
