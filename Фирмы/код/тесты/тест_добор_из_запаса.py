"""
Добор берёт слово из запаса, когда поле оставлено пустым.

Раньше пустое поле значило «закончить», и чтобы просто продолжить, человеку
приходилось каждый раз придумывать и вбивать слово — при уже настроенном запасе.
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from part1 import engine as дв
from part1.запас import Запас

ошибок = 0
врем = Path("запас_добор_тест.json")
врем.unlink(missing_ok=True)
Path("запас_добор_тест.tmp").unlink(missing_ok=True)

print("=== 1. Есть отдельный маркер «Хватит» ===")
print(f"   СТОП_ДОБОРА = {дв.СТОП_ДОБОРА!r}")
if not дв.СТОП_ДОБОРА or дв.СТОП_ДОБОРА == "":
    ошибок += 1
    print("   ✘ маркер пустой — не отличить от «бери сам»")
else:
    print("   ✔ пустая строка и «стоп» — разные вещи")

print()
print("=== 2. Слово берётся из запаса ===")
буфер = Запас(path=врем)
буфер.пополнить("PL", ["jaspis", "kwarc", "ametyst"])

# подменяем Запас, чтобы движок взял НАШ файл, а не рабочий
import part1.запас as модуль_запаса
настоящий = модуль_запаса.Запас
модуль_запаса.Запас = lambda *a, **k: Запас(path=врем)
try:
    строки = []
    слово = дв.слово_из_запаса("Poland", log=строки.append)
    print(f"   взято: {слово!r}")
    for с in строки:
        print("     ", с.strip())
    if слово not in ("jaspis", "kwarc", "ametyst"):
        ошибок += 1
        print("   ✘ взято не из запаса")
    else:
        print("   ✔")

    print()
    print("=== 3. Второй вызов даёт ДРУГОЕ слово ===")
    второе = дв.слово_из_запаса("Poland", log=lambda s: None)
    print(f"   второе: {второе!r}")
    if второе == слово or not второе:
        ошибок += 1
        print("   ✘ повтор или пусто")
    else:
        print("   ✔")

    print()
    print("=== 4. Запас кончился — слово всё равно находится ===")
    # Пустой буфер → просим Gemini пополнить → если и он молчит, берём из
    # встроенного словаря. Откуда именно пришло слово, неважно; важно, что
    # добор не встаёт и что слово прошло наш фильтр политики Ads.
    Запас(path=врем).взять("PL", 999)          # опустошаем
    строки4 = []
    третье = дв.слово_из_запаса("Poland", log=строки4.append)
    from part1 import слова as словарь
    из_словаря = any(третье in сл for сл in словарь.СЛОВАРЬ.values())
    откуда = "встроенный словарь" if из_словаря else "Gemini (пополнил запас)"
    print(f"   третье: {третье!r}  ←  {откуда}")
    if not третье:
        ошибок += 1
        print("   ✘ добор встал — слова не нашлось нигде")
    elif словарь.запрещено(третье):
        ошибок += 1
        print("   ✘ слово не прошло бы фильтр:", словарь.запрещено(третье))
    else:
        print("   ✔ добор продолжится")
finally:
    модуль_запаса.Запас = настоящий

врем.unlink(missing_ok=True)
Path("запас_добор_тест.tmp").unlink(missing_ok=True)
print()
print("ошибок:", ошибок)
