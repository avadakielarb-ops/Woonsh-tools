"""Пустой статус — повод переспросить, а не выбросить фирму."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from part2.engine import статус_не_прочитан

ошибок = 0
print("=== что считаем «не прочитал» ===")
не_прочитан = [
    "статус: —",
    "статус не aktywna (—)",
    "статус: ",
    "",
    "СТАТУС: —",
    "статус не Active (—)",
]
прочитан = [
    "статус: в ликвидация",
    "статус не Normal (Under liquidation)",
    "статус не aktywna (wykreslona)",
    "статус: Deleted",
    "нет документа Incorporation",
    "статус-стоп: заличен",
]
for с in не_прочитан:
    вышло = статус_не_прочитан(с)
    метка = "ok " if вышло else "✘  "
    if not вышло:
        ошибок += 1
    print(f"  {метка} {с!r:42} -> переспросить")
print()
for с in прочитан:
    вышло = статус_не_прочитан(с)
    метка = "ok " if not вышло else "✘  "
    if вышло:
        ошибок += 1
    print(f"  {метка} {с!r:42} -> честный отказ")

print()
print("=== сколько таких было в живом логе ===")
from pathlib import Path
лог = Path("логи/лог_2026-08-23_20-31-51.txt")
if лог.exists():
    строки = лог.read_text(encoding="utf-8", errors="replace").splitlines()
    спорных = [с.strip() for с in строки
               if "✘" in с and статус_не_прочитан(с.split("✘", 1)[1].strip())]
    честных = [с.strip() for с in строки
               if "✘ статус" in с and not статус_не_прочитан(с.split("✘", 1)[1].strip())]
    print(f"  фирм спасено от несправедливого брака: {len(спорных)}")
    for с in спорных[:4]:
        # «✘» из лога не печатаем: сводный прогонщик считает такие строки
        # за провал теста, хотя это просто пример данных.
        print("      пример:", с.replace("✘", "x")[:70])
    print(f"  честных отказов по статусу осталось: {len(честных)}")

print()
print("ошибок:", ошибок)
