"""
«Обновить страницу» — повтор последнего действия, не отвечая на вопрос.

Просьба человека 08.10.2026: «бывает затупы на странице — добавь кнопку
обновить = повтор последнего действия», «в панели, чтобы высвечивалось».

Сайты реестров подвисают на ровном месте: страница открыта, данных на ней
нет. Раньше человеку оставалось только смириться — «Продолжить» или
«Пропустить». Теперь он жмёт обновление, страница перезагружается, а вопрос
ОСТАЁТСЯ на экране: посмотрел — и ответил уже по-настоящему.

Две вещи, которые тут легко сломать:
  · кнопка не должна появляться, когда перезагружать нечем (браузер ещё не
    отдал ссылку) — обещать несуществующее действие хуже, чем молчать;
  · нажатие НЕ должно отвечать на вопрос.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from common.human import HumanGate

ошибок = 0


def проверить(что, вышло, ждём):
    global ошибок
    ладно = вышло == ждём
    ошибок += not ладно
    print(f"   {'✔' if ладно else '✘'} {что}"
          + ("" if ладно else f": вышло {вышло!r}, ждали {ждём!r}"))


class Кнопки:
    """Подделка панели: запоминает, какие кнопки нарисовали."""
    def __init__(self, human, есть_перезагрузка):
        self.human = human
        self.нарисованы = []
        self.отвечено = []
        if not есть_перезагрузка:
            self.human.перезагрузить = None

    # --- то, что проверяем, повторяет логику окна ---
    def _чп_кнопка(self, текст, *_цвета, команда=None):
        self.нарисованы.append(текст)

    def _чп_повтор(self):
        if not getattr(self.human, "перезагрузить", None):
            return
        self._чп_кнопка("🔄  Обновить страницу")

    def вопрос(self):
        self._чп_кнопка("✓  Продолжить")
        self._чп_повтор()
        self._чп_кнопка("⏭  Пропустить фирму")

    def меню(self, варианты):
        for _ключ, подпись in варианты:
            self._чп_кнопка(подпись)
        if not any(к == "повтор" for к, _ in варианты):
            self._чп_повтор()


print("=== 1. ЕСТЬ ЧЕМ ПЕРЕЗАГРУЖАТЬ — КНОПКА ЕСТЬ ===")
g = HumanGate()
g.перезагрузить = lambda log=None: True
п = Кнопки(g, True)
п.вопрос()
проверить("кнопка нарисована", "🔄  Обновить страницу" in п.нарисованы, True)
проверить("и стоит сразу за «Продолжить»", п.нарисованы[1],
          "🔄  Обновить страницу")

print()
print("=== 2. НЕЧЕМ — КНОПКИ НЕТ ===")
# Браузер ещё не отдал ссылку на перезагрузку: обещать действие, которого
# не существует, хуже, чем его не предлагать.
g2 = HumanGate()
п2 = Кнопки(g2, False)
п2.вопрос()
проверить("кнопки нет", "🔄  Обновить страницу" in п2.нарисованы, False)
проверить("остальные на месте", len(п2.нарисованы), 2)

print()
print("=== 3. НАЖАТИЕ НЕ ОТВЕЧАЕТ НА ВОПРОС ===")
# Иначе «обновить» молча означало бы «Продолжить», и человек подтвердил бы
# фирму, которую ещё не посмотрел.
звали = []
g3 = HumanGate()
g3.перезагрузить = lambda log=None: звали.append("перезагрузка") or True
g3._event.clear()
g3.перезагрузить(None)
проверить("перезагрузка вызвана", звали, ["перезагрузка"])
проверить("ответа на вопрос НЕ дано", g3._event.is_set(), False)

print()
print("=== 4. В МЕНЮ СО СВОИМ «ПОВТОРОМ» ВТОРОЙ КНОПКИ НЕТ ===")
# Две кнопки про одно и то же сбивают с толку.
g4 = HumanGate()
g4.перезагрузить = lambda log=None: True
п4 = Кнопки(g4, True)
п4.меню([("качать", "⬇ Всё равно скачать"),
         ("повтор", "🔄 Повтор последнего действия"),
         ("пропустить", "⏭ Пропустить фирму")])
проверить("своя кнопка одна", sum("овтор" in т for т in п4.нарисованы), 1)
проверить("общей не добавилось",
          "🔄  Обновить страницу" in п4.нарисованы, False)

print()
print("=== 5. В МЕНЮ БЕЗ «ПОВТОРА» КНОПКА ДОБАВЛЯЕТСЯ ===")
п5 = Кнопки(g4, True)
п5.меню([("новые", "⏭ Только недостающие"), ("стоп", "■ Остановить")])
проверить("добавилась", "🔄  Обновить страницу" in п5.нарисованы, True)

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
