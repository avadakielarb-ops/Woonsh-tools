"""
Ручное управление: вмешаться ДО того, как движок сам о чём-то спросит.

Просьба человека 08.10.2026: «кнопку отдельно от действий, чтобы эти действия
были до того как скрипт додумается выбить — о тех случаях когда он завис и не
идёт дальше и не показывает действия человека. Там где панель ход работы
делаем через галочку ручное управление: нажал — появилось меню».

Панель с кнопками появляется, ТОЛЬКО когда движок решил спросить. Если он
завис внутри ожидания, нажать нечего и остаётся убивать прогон целиком.

УСТРОЙСТВО. Окно кладёт приказ в шлюз, а забирает и исполняет его САМ ДВИЖОК
— в своём потоке, на ближайшей передышке. Иначе никак: Playwright привязан к
потоку, который его создал, и дёрнуть браузер из окна значит сломать прогон
вернее, чем он уже сломан. Первая версия кнопки «Обновить» звала браузер
прямо из окна — это и было ошибкой, которую чинит этот механизм.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from common.human import HumanGate, SkipCompany, SkipGeo, AbortRun

ошибок = 0


def проверить(что, вышло, ждём):
    global ошибок
    ладно = вышло == ждём
    ошибок += not ладно
    print(f"   {'✔' if ладно else '✘'} {что}"
          + ("" if ладно else f": вышло {вышло!r}, ждали {ждём!r}"))


class Браузер:
    def __init__(self):
        self.перезагрузок = 0

    def перезагрузить(self, log=None):
        self.перезагрузок += 1
        return True


тихо = lambda *_: None

print("=== 1. ПУСТО — НИЧЕГО НЕ ДЕЛАЕМ ===")
g = HumanGate()
проверить("приказа нет", g.исполнить_приказ(Браузер(), тихо), False)

print()
print("=== 2. «ОБНОВИТЬ» ПЕРЕЧИТЫВАЕТ СТРАНИЦУ ===")
g = HumanGate()
бр = Браузер()
g.приказать("обновить")
проверить("исполнено", g.исполнить_приказ(бр, тихо), True)
проверить("страница перечитана", бр.перезагрузок, 1)

print()
print("=== 3. ПРИКАЗ РАЗОВЫЙ ===")
# Иначе одно нажатие «Пропустить» выкосило бы всю страну подряд.
проверить("второй раз пусто", g.исполнить_приказ(бр, тихо), False)
проверить("лишних перезагрузок нет", бр.перезагрузок, 1)

print()
print("=== 4. ОСТАЛЬНЫЕ КОМАНДЫ БРОСАЮТ СВОЁ ===")
for ключ, искл in (("пропустить", SkipCompany),
                   ("страна", SkipGeo),
                   ("стоп", AbortRun)):
    g.приказать(ключ)
    try:
        g.исполнить_приказ(бр, тихо)
        проверить(f"«{ключ}»", "ничего не бросил", искл.__name__)
    except искл:
        проверить(f"«{ключ}»", искл.__name__, искл.__name__)

print()
print("=== 5. НЕЗНАКОМЫЙ ПРИКАЗ НЕ ВАЛИТ ПРОГОН ===")
# Окно и движок переживают друг друга: старое окно может прислать команду,
# которой новый движок не знает. Это повод промолчать, а не упасть.
g.приказать("чтототакое")
проверить("пережили", g.исполнить_приказ(бр, тихо), False)

print()
print("=== 6. «ПОВТОРИТЬ» — САМОСТОЯТЕЛЬНАЯ КОМАНДА ===")
# Сперва «повторить» значило «сделай то же, что в прошлый раз», и человек
# справедливо не понял: он жмёт «повторить последнее действие», а в логе
# «повторяю: Обновить страницу» — при том что до этого ничего не нажимал.
# Повторять надо то, на чём встал ДВИЖОК, а не то, что жал человек.
g = HumanGate()
бр = Браузер()
проверить("не подменяется ничем", g.приказать("повторить"), "повторить")
проверить("исполняется", g.исполнить_приказ(бр, тихо), True)
проверить("страница перечитана", бр.перезагрузок, 1)

print()
print("=== 7. ПЕРЕКЛЮЧЕНИЕ РЕЖИМА ТОЛКАЕТ ПРОГОН ===")
# «Включаю и выключаю режим бота — значит хочу, чтобы он дальше работал».
# Галочка меняла только то, кого спрашивать, и на зависшем прогоне не делала
# ничего. Теперь она шлёт тот же «повторить».
g2 = HumanGate()
бр2 = Браузер()
проверить("шлёт повтор", g2.приказать("повторить"), "повторить")
проверить("и он доходит", g2.исполнить_приказ(бр2, тихо), True)

print()
print("=== 8. КОМАНДЫ ОКНА И ШЛЮЗА СОВПАДАЮТ ===")
# Разъедутся — человек будет жать кнопку, которая ничего не делает.
import окно as о
ключи = {к for к, _ in о.Окно.КОМАНДЫ}
проверить("набор тот же", ключи,
          {"продолжить", "обновить", "повторить",
           "пропустить", "страна", "стоп"})

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
