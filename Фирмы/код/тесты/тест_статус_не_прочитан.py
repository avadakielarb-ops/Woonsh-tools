"""
Нечитаемый статус — не повод терять фирму.

Решение человека 08.10.2026: «насрать, скачать; кнопка всё равно скачать;
в авторежиме тоже так».

Раньше тут стоял `require` с кнопкой «Продолжить»: человеку приходилось
подтверждать каждую такую фирму руками, а в автономном режиме она отлетала.
Причина же почти всегда не в фирме — реестр отдал карточку другого вида или
страница не догрузилась. Замер по логам Словении: 40 фирм, у которых
«карточка так и не открылась», и среди них ни одной d.o.o. — все частные
предприниматели, то есть живые.

Кнопка «Пропустить» осталась: если человек ГЛАЗАМИ видит, что фирма закрыта,
он её закроет.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from common.human import HumanGate, SkipCompany, AbortRun

ошибок = 0


def проверить(что, вышло, ждём):
    global ошибок
    ладно = вышло == ждём
    ошибок += not ладно
    print(f"   {'✔' if ладно else '✘'} {что}"
          + ("" if ладно else f": вышло {вышло!r}, ждали {ждём!r}"))


ВАРИАНТЫ = [("качать", "⬇ Всё равно скачать"),
            ("пропустить", "⏭ Пропустить фирму"),
            ("стоп", "■ Остановить прогон")]


class Шлюз(HumanGate):
    """Шлюз, который отвечает заранее заданным ключом."""
    def __init__(self, ответ: str | None):
        super().__init__()
        self.ответ = ответ
        self.спрошено = []

    def меню(self, title, message, варианты, company="", авто=""):
        self.спрошено.append((title, [к for к, _ in варианты], авто))
        # Человека нет — отвечает «авто», ровно как в автономном режиме.
        return self.ответ if self.ответ is not None else авто


def разобрать(шлюз: Шлюз):
    """Тот же выбор, что делает движок на нечитаемом статусе."""
    выбор = шлюз.меню(
        "Не читается статус фирмы", "…", ВАРИАНТЫ, "ФИРМА", авто="качать")
    if выбор == "стоп":
        raise AbortRun("остановлено человеком")
    if выбор == "пропустить":
        raise SkipCompany("статус не прочитался — пропущено человеком")
    return "качаем"


print("=== 1. В АВТОНОМНОМ РЕЖИМЕ — КАЧАЕМ, НЕ СПРАШИВАЯ ===")
ш = Шлюз(None)                     # человека нет: сработает «авто»
проверить("качаем", разобрать(ш), "качаем")
проверить("автоответ именно «качать»", ш.спрошено[0][2], "качать")

print()
print("=== 2. ЧЕЛОВЕК ВИДИТ КНОПКУ «ВСЁ РАВНО СКАЧАТЬ» ===")
ключи = [к for к, _ in ВАРИАНТЫ]
подписи = {к: п for к, п in ВАРИАНТЫ}
проверить("кнопка первая — её и жмут чаще", ключи[0], "качать")
проверить("подпись говорит прямо", подписи["качать"], "⬇ Всё равно скачать")

print()
print("=== 3. ЧЕЛОВЕК МОЖЕТ ЗАКРЫТЬ ФИРМУ РУКАМИ ===")
# Если он ГЛАЗАМИ видит, что фирма ликвидирована, выбор за ним.
try:
    разобрать(Шлюз("пропустить"))
    проверить("бросили SkipCompany", False, True)
except SkipCompany:
    проверить("бросили SkipCompany", True, True)

print()
print("=== 4. И ОСТАНОВИТЬ ВЕСЬ ПРОГОН ===")
try:
    разобрать(Шлюз("стоп"))
    проверить("бросили AbortRun", False, True)
except AbortRun:
    проверить("бросили AbortRun", True, True)

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
