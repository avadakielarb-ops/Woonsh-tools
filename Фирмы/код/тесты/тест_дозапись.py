"""
Живая дозапись в таблицу: фирмы уезжают туда по ходу прогона.

Было: прогон писал в книгу, а в таблицу выгружал ОДИН раз в конце. Пока он
идёт — часами — в таблице пусто; прерванный прогон не выгружал ничего вовсе.

Проверяем три вещи, на которых это ломается:
  · пачкой, а не по одной фирме (каждый запрос — секунды);
  · известную фирму второй раз не пишем;
  · сеть отвалилась — строки НЕ теряются и уезжают со следующим сбросом.
"""
import sys
import types
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import дозапись
from part1.models import Firm

ошибок = 0
отправлено: list = []
падать = {"да": False}

поддельная = types.ModuleType("common.таблица")
поддельная.настроена = lambda: True
# Ключ «Реестра» — ровно то, что делает normalize(): нижний регистр и без
# правовой формы. Писать его руками наугад нельзя, иначе проверка на повтор
# сойдётся только в тесте.
from part2.core.matching import normalize

КЛЮЧ_ИЗВЕСТНОЙ = f"EE|{normalize('Already Here OU')}"
поддельная.читать = lambda лист, сколько=50, всё=False: [
    ["Ключ", "Гео", "Организация", "Статус", "Дата", "Слово", "Откуда", "ID"],
    [КЛЮЧ_ИЗВЕСТНОЙ, "EE", "Already Here OU", "найдена", "", "", "", "EE-1"],
]
поддельная.создать = lambda гео: {"ok": True}


def дописать(лист, строки, пачка=400):
    if падать["да"]:
        raise ConnectionError("сеть моргнула")
    отправлено.append((лист, list(строки)))
    return len(строки)


поддельная.дописать = дописать
sys.modules["common.таблица"] = поддельная


def фирма(имя, сайт="site.example"):
    return Firm(name=имя, address="ул. 1", city="Таллинн", zip_code="10115",
                website=сайт, payment_profile=f"{имя}\nAddress: ул. 1")


print("=== 1. Копим пачкой, а не шлём по одной ===")
д = дозапись.Дозапись("Мультигео", log=lambda s: None, мультигео=True)
for i in range(10):
    д.добавить(фирма(f"FIRMA {i} OU"), "EE", "ice", f"EE-{i:04d}")
if отправлено:
    ошибок += 1
    print(f"   ✘ уже отправил {len(отправлено)} раз на десяти фирмах")
else:
    print(f"   ✔ десять фирм лежат в пачке, сеть не тронута")

for i in range(10, 25):
    д.добавить(фирма(f"FIRMA {i} OU"), "EE", "ice", f"EE-{i:04d}")
if not отправлено:
    ошибок += 1
    print("   ✘ на 25 фирмах пачка не ушла")
else:
    листы = [л for л, _ in отправлено]
    строк = sum(len(с) for л, с in отправлено if л == "Мультигео")
    if "Мультигео" not in листы or строк != 25:
        ошибок += 1
        print(f"   ✘ ушло не то: {[(л, len(с)) for л, с in отправлено]}")
    elif "Реестр" not in листы:
        ошибок += 1
        print("   ✘ в «Реестр» не записали — фирма считается невиданной")
    else:
        print(f"   ✔ пачка ушла на 25-й фирме: лист «Мультигео» 25 строк "
              f"+ «Реестр»")

print()
print("=== 2. Фирма из «Реестра» второй раз не пишется ===")
отправлено.clear()
д2 = дозапись.Дозапись("Мультигео", log=lambda s: None, мультигео=True)
д2.добавить(фирма("Already Here OU"), "EE", "ice", "EE-9")
if д2.пачка:
    ошибок += 1
    print(f"   ✘ взял в пачку уже известную: {д2.пачка[0]['орг']}")
else:
    print("   ✔ известную пропустил")

print()
print("=== 3. Без сайта уходит на «<ГЕО>.БС» ===")
д2.добавить(фирма("BEZ SAITA OU", сайт=""), "EE", "ice", "EE-10",
            без_сайта=True)
if not д2.пачка or д2.пачка[0]["лист"] != "EE.БС":
    ошибок += 1
    print(f"   ✘ лист не тот: {[з['лист'] for з in д2.пачка]}")
else:
    print("   ✔ EE.БС")

print()
print("=== 4. Сеть отвалилась — строки не теряются ===")
отправлено.clear()
д3 = дозапись.Дозапись("Мультигео", log=lambda s: None, мультигео=True)
for i in range(5):
    д3.добавить(фирма(f"NETWORK {i} OU"), "EE", "ice", f"EE-N{i}")
падать["да"] = True
ушло = д3.сбросить()
if ушло:
    ошибок += 1
    print(f"   ✘ отчитался об отправке {ушло}, хотя сеть лежала")
elif len(д3.пачка) != 5:
    ошибок += 1
    print(f"   ✘ строки потеряны: осталось {len(д3.пачка)} из 5")
else:
    print("   ✔ пять строк ждут в пачке")

падать["да"] = False
ушло2 = д3.сбросить()
if ушло2 != 5 or д3.пачка:
    ошибок += 1
    print(f"   ✘ после починки сети ушло {ушло2}, в пачке {len(д3.пачка)}")
else:
    print("   ✔ сеть вернулась — те же пять уехали")

print()
print("=== 5. Таблица не настроена — прогон идёт, дозаписи нет ===")
поддельная.настроена = lambda: False
д4 = дозапись.Дозапись("Мультигео", log=lambda s: None)
д4.добавить(фирма("OFFLINE OU"), "EE", "ice", "EE-X")
if д4.пачка:
    ошибок += 1
    print("   ✘ копит, хотя таблицы нет")
elif д4.живая:
    ошибок += 1
    print("   ✘ считает себя живой без таблицы")
else:
    print("   ✔ молча выключилась, книга пишется как раньше")

print()
print("ошибок:", ошибок)
