"""
СЛАБЫЕ МЕСТА: что делает приложение, когда всё плохо.

Проверяем не «работает ли в хорошую погоду», а поведение в бедах, которые уже
случались или случатся: таблица недоступна, кэш от прошлой раскладки, книга
занята Excel, лист в таблице зовётся не так, как в книге.
"""
import json
import sys
import types
from pathlib import Path
from tempfile import mkdtemp

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

ошибок = 0

print("=== 1. Кэш цифр от прошлой раскладки не показывается как нули ===")
import окно as о_модуль

класс = о_модуль.Окно
старый_кэш = {"EE": {"свободно": 500, "выписка": 3, "отработано": 10}}
новый_кэш = {"EE": dict(о_модуль.ПУСТОЙ_СЧЁТ, сайт=43, бс=555)}


class Фейк:
    """Только то, что нужно методу: файл и сам метод."""
    _цифры_из_кэша = класс._цифры_из_кэша


for имя, кэш, ждём_пусто in (("старый", старый_кэш, True),
                             ("новый", новый_кэш, False)):
    ф = Фейк()
    путь = Path(mkdtemp()) / "счётчики.json"
    путь.write_text(json.dumps(кэш, ensure_ascii=False), encoding="utf-8")
    ф.ФАЙЛ_ЦИФР = путь
    вышло = ф._цифры_из_кэша()
    пусто = not вышло
    if пусто != ждём_пусто:
        ошибок += 1
        print(f"   ✘ {имя} кэш: вышло {'пусто' if пусто else вышло}, "
              f"ждали {'пусто' if ждём_пусто else 'данные'}")
    else:
        print(f"   ✔ {имя} кэш → {'забыт' if пусто else 'взят'}")

print()
print("=== 2. Лист мультигео в ТАБЛИЦЕ зовётся «Мультигео», а не датой ===")
import дозапись

if дозапись.Дозапись.ЛИСТ_МУЛЬТИГЕО != "Мультигео":
    ошибок += 1
    print("   ✘ имя листа не то")
else:
    д = дозапись.Дозапись(мультигео=True, log=lambda s: None)
    if д.лист != "Мультигео":
        ошибок += 1
        print(f"   ✘ по умолчанию лист «{д.лист}»")
    else:
        print("   ✔ по умолчанию «Мультигео» — писать в лист книги «09-09» "
              "нельзя, его в таблице нет")

print()
print("=== 3. Таблица недоступна — прогон продолжается, книга пишется ===")
поддельная = types.ModuleType("common.таблица")


class НетДоступа(RuntimeError):
    pass


поддельная.НетДоступа = НетДоступа
поддельная.настроена = lambda: True


def читать_падает(лист, сколько=50, всё=False):
    raise НетДоступа("сеть лежит")


поддельная.читать = читать_падает
sys.modules["common.таблица"] = поддельная

from part1.models import Firm

д2 = дозапись.Дозапись(мультигео=True, log=lambda s: None)
try:
    д2.добавить(Firm(name="TEST OU", address="ул.", city="Т", zip_code="1",
                     website="t.ee"), "EE", "ice", "EE-1")
    if д2.живая:
        ошибок += 1
        print("   ✘ считает себя живой, хотя таблица упала")
    elif д2.пачка:
        ошибок += 1
        print("   ✘ копит строки в никуда")
    else:
        print("   ✔ выключилась молча, прогон не упал")
except Exception as e:
    ошибок += 1
    print(f"   ✘ уронила прогон: {type(e).__name__}: {e}")

print()
print("=== 4. Книга занята Excel — говорим по-человечески, а не трассой ===")
from part1.excel_out import ExcelWriter

книга = Path(mkdtemp()) / "занята.xlsx"
w = ExcelWriter(книга, "EE")


class ЗанятаяКнига:
    def save(self, path):
        raise PermissionError(13, "Permission denied", str(path))


w.wb = ЗанятаяКнига()
try:
    w.save()
    ошибок += 1
    print("   ✘ сохранил книгу, которая не сохраняется")
except RuntimeError as e:
    if "Excel" not in str(e):
        ошибок += 1
        print(f"   ✘ сообщение непонятное: {e}")
    else:
        print(f"   ✔ «{e}»")
except PermissionError:
    ошибок += 1
    print("   ✘ наружу вылезла системная ошибка вместо объяснения")

print()
print("=== 5. Продолжение: книги нет — не падаем ===")
import продолжение

продолжение.ФАЙЛ = Path(mkdtemp()) / "нет.json"
if продолжение.остаток():
    ошибок += 1
    print("   ✘ выдумал остаток")
else:
    print("   ✔ пусто")

продолжение.ФАЙЛ = Path(mkdtemp()) / "есть.json"
продолжение.ФАЙЛ.write_text(json.dumps(
    {"книга": r"C:\нет\такой\книги.xlsx", "лист": "09-09",
     "гео": ["EE"], "сколько": 100}), encoding="utf-8")
о = продолжение.остаток()
if о.get("сколько_по_гео", {}).get("EE") != 100:
    ошибок += 1
    print(f"   ✘ на пропавшей книге посчитал {о.get('сколько_по_гео')}")
else:
    print("   ✔ книга пропала → считает, что не сделано ничего (а не падает)")

print()
print("ошибок:", ошибок)
