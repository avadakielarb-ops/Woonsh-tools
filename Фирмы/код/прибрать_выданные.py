r"""
УВЕЗТИ В ВЫДАЧУ ВЫПИСКИ ТЕХ, КОГО УЖЕ ОТДАЛИ.

Зачем. Фирма помечена «отработано» — значит ушла фармеру, и её выписка
должна лежать в папке выдачи. Замер 23.09.2026: у 114 отработанных фирм
выписка так и осталась в рабочей папке «Выписки».

Причина историческая: эти выдачи делались до того, как появились папки
выдачи (даты 21-07, 05-08, 23-08, 06-09, 07-09 и часть вовсе без даты —
колонку «Дата» тогда не заполняли). Папок под них просто нет.

Опасности в этом нет: строк на рабочих листах у этих фирм не осталось,
второй раз они не уйдут. Беда в другом — рабочая папка захламлена чужим,
и «сколько выписок готово» перестаёт быть правдой.

КУДА КЛАДЁМ. «выдачи/Отработано ранее/<дата>/». Имя выбрано так, чтобы
через месяц было видно: это не настоящая выдача того дня, а разбор задним
числом. Рядом кладётся «список.txt» — что за фирмы, иначе папка с
двумя десятками PDF ни о чём не говорит.

Запуск:
    …\прибрать_выданные.py             — примерка, ничего не трогает
    …\прибрать_выданные.py --писать    — перенести
"""
from __future__ import annotations

import shutil
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import пути
from common.статусы import есть_выписка

КУДА = "Отработано ранее"
БЕЗ_ДАТЫ = "без даты"


def собрать() -> list[tuple[Path, str, str, str]]:
    """[(файл на диске, дата выдачи, гео, имя фирмы)] — что не доехало."""
    from common import таблица as т

    выдачи = пути.КОРЕНЬ / "выдачи"
    уже_там = {п.name for п in выдачи.rglob("*") if п.is_file()}
    в_выписках = {п.name: п for п in пути.ВЫПИСКИ.rglob("*") if п.is_file()}

    план: list[tuple[Path, str, str, str]] = []
    for л in т.всё(["Отработано"], служебные=True):
        стр = л.get("строки") or []
        if not стр:
            continue
        ш = [str(х or "").strip() for х in стр[0]]
        if "Организация" not in ш or "Файл выписки" not in ш:
            continue
        ко, кф = ш.index("Организация"), ш.index("Файл выписки")
        кг = ш.index("Гео") if "Гео" in ш else -1
        кд = ш.index("Дата") if "Дата" in ш else -1
        for с in стр[1:]:
            орг = str(с[ко]).strip() if ко < len(с) else ""
            if not орг:
                continue
            ф = str(с[кф]).strip() if кф < len(с) else ""
            if not есть_выписка(ф) or ф in уже_там:
                continue
            путь = в_выписках.get(ф)
            if not путь:
                continue
            дата = (str(с[кд]).strip() if 0 <= кд < len(с) else "") or БЕЗ_ДАТЫ
            гео = (str(с[кг]).strip().upper() if 0 <= кг < len(с) else "")
            план.append((путь, дата, гео, орг))
    return план


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    print("Читаю «Отработано» и диск…")
    план = собрать()
    if not план:
        print("Переносить нечего — все выписки отработанных уже в выдаче.")
        raise SystemExit(0)

    по_датам: dict[str, list] = defaultdict(list)
    for путь, дата, гео, орг in план:
        по_датам[дата].append((путь, гео, орг))

    print()
    print(f"=== УВЕЗЁМ {len(план)} ВЫПИСОК ===")
    for дата in sorted(по_датам):
        кусок = по_датам[дата]
        гео = ", ".join(f"{г}:{n}" for г, n in
                        Counter(г for _, г, _ in кусок).most_common(6))
        print(f"  {дата:<10} {len(кусок):>4}   ({гео})")
        print(f"       → выдачи/{КУДА}/{дата}/")

    if "--писать" not in sys.argv:
        print()
        print("Это ПРИМЕРКА, ничего не тронуто. Перенести: --писать")
        raise SystemExit(0)

    корень = пути.КОРЕНЬ / "выдачи" / КУДА
    перенесено, сорвалось = 0, []
    for дата, кусок in sorted(по_датам.items()):
        папка = корень / дата
        папка.mkdir(parents=True, exist_ok=True)
        строки = []
        for путь, гео, орг in кусок:
            цель = папка / путь.name
            try:
                shutil.move(str(путь), str(цель))
                перенесено += 1
            except Exception as e:
                # Не смогли перенести — копируем: потерять выписку нельзя,
                # а лишний файл видно и он чинится уборкой.
                try:
                    shutil.copy2(путь, цель)
                    перенесено += 1
                except Exception as e2:
                    сорвалось.append(f"{путь.name}: {type(e2).__name__}")
                    continue
                сорвалось.append(f"{путь.name}: перенос не вышел "
                                 f"({type(e).__name__}), скопировал")
            строки.append(f"{гео}\t{орг}\t{путь.name}")
        # СПИСОК РЯДОМ С ФАЙЛАМИ. Папка с двумя десятками PDF без него не
        # говорит ничего: какие это фирмы и почему они здесь.
        (папка / "список.txt").write_text(
            f"Выписки фирм, отданных {дата}.\n"
            "Собраны задним числом: выдача делалась до появления папок,\n"
            "и файлы остались в рабочей папке «Выписки».\n\n"
            + "\n".join(sorted(строки)) + "\n", encoding="utf-8")

    print()
    print(f"  ✔ перенесено: {перенесено} из {len(план)}")
    if сорвалось:
        print(f"  ⚠ с оговорками: {len(сорвалось)}")
        for с in сорвалось[:5]:
            print(f"      {с}")
    print(f"  Лежат в: {корень}")
