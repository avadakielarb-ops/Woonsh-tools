def записать_вердикт(фирмы: list[dict], вердикт: str, log=print) -> int:
    """
    Запомнить в журнале, что бот про эти фирмы ответил.

    ЭТО ЗАПИСЬ ДЛЯ ПАМЯТИ, А НЕ ДЛЯ РЕШЕНИЙ. Вердикт целиком определяется
    текстом ответа (см. `разложить`); журнал же отвечает на два других
    вопроса: отправляли ли мы это имя (чтобы не отправить второй раз) и
    почему у фирмы такой статус, если через неделю придётся разбираться.

    Раньше на этом поле стояла защита от чужих дублей, и она развалилась:
    одно несогласованное поле в другом месте — и 421 живая фирма получила
    чужой вердикт. Решение, которое можно принять по тексту перед глазами,
    не должно зависеть от файла на диске.
    """
    if not фирмы:
        return 0
    ж = _журнал()
    сегодня = f"{date.today():%Y-%m-%d}"
    записано = 0
    for з in фирмы:
        к = ключ_журнала(з.get("гео", ""), з.get("орг", ""))
        запись = ж.get(к)
        if not запись:
            запись = {"дата": сегодня, "пакет": з.get("пакет", ""),
                      "гео": з.get("гео", ""), "имя": з.get("орг", ""),
                      "ид": з.get("ид", "")}
            ж[к] = запись
        запись["вердикт"] = вердикт
        запись["отвечено"] = сегодня
        записано += 1
    try:
        ЖУРНАЛ.write_text(json.dumps(ж, ensure_ascii=False, indent=1),
                          encoding="utf-8")
    except Exception as e:
        log(f"  ⚠ вердикт в журнал не записался ({type(e).__name__})")
        return 0
    return записано


def дубли_из_ответа(текст: str) -> list[str]:
    """
    Имена, про которые бот сказал «уже есть».

    Формат ответа не наш, поэтому берём по смыслу, а не по разметке: строка,
    где есть «уже есть» или «дубл…», а дальше имя. Так же читает окно.
    """
    return [м.group(1).strip() for м in
            re.finditer(r"(?:уже есть|дубл\w*)\s*:?\s*(.+)", текст or "", re.I)]


def добавленные_из_ответа(текст: str) -> list[str]:
    """
    Имена, про которые бот сказал «добавлена» — то есть увидел ВПЕРВЫЕ.

    Это и есть подтверждение. «Не упомянута в ответе» подтверждением не
    считается: бот мог оборвать список, человек мог вставить его наполовину,
    строка могла потеряться. Годной фирму делает прямое «добавлена», а не
    наше предположение (правило пользователя 22.09.2026).
    """
    return [м.group(1).strip() for м in
            re.finditer(r"добавлен\w*\s*:?\s*(.+)", текст or "", re.I)]


def разложить(пакет: list[dict], ответ: str, log=print) -> dict:
    """
    Развести пакет на годных, отклонённых и тех, про кого бот промолчал.

    ВЕСЬ ВЕРДИКТ БЕРЁТСЯ ИЗ ОТВЕТА, И БОЛЬШЕ НИОТКУДА (правило человека,
    23.09.2026):

        названа «добавлена»            → ГОДНАЯ
        названа и так, и «уже есть»    → ГОДНАЯ («уже есть» — ответ на нашу
                                         же вторую посылку того же имени)
        названа ТОЛЬКО «уже есть»      → ОТКЛОНЕНА
        не названа вовсе               → вердикта нет, статус не трогаем

    ПОЧЕМУ ЗДЕСЬ БОЛЬШЕ НЕТ ЖУРНАЛА. Раньше тут стояла «эхо-защита»: если
    имя уже отправляли и бот его подтверждал, его «уже есть» считалось нашим
    собственным отголоском, и фирма оставалась годной. Идея была верной,
    исполнение — нет, и 23.09.2026 это стоило 421 фирмы.
    Ломалось так: `сохранить_пакет` клеймил именем пакета ТОЛЬКО ту копию
    списка, что уходила в .json, а окно применяло ответ списком из памяти —
    без клейма. Имя пакета выходило пустым, сравнение «журнал не тот же
    пакет» давало истину ВСЕГДА, и каждый дубль записывался в отголоски.
    В логе это выглядело как «чужих дублей: 0, годных: 1599».
    Правило человека делает журнал ненужным: признак нашей второй посылки —
    не запись в журнале, а противоречие ВНУТРИ одного ответа. Его нельзя
    подделать несогласованным состоянием на диске, потому что оно целиком
    в том тексте, который человек только что вставил.

    СВЕРЯЕМ В ПРЕДЕЛАХ ГЕО. normalize срезает правовую форму, и эстонская
    «AQUA Invest OÜ» превращается в то же «aqua invest», что хорватская
    «AQUA INVEST d.o.o.». Без страны в ключе ответ бота по одной стране
    закрыл бы фирму в другой.

    ПРО КОГО ПРОМОЛЧАЛИ — НЕ ГОДНЫЕ И НЕ ОТКЛОНЁННЫЕ. Бот на длинном списке
    отвечает кусками и часть имён теряет (на 1645 потерял 40). Считать
    молчание согласием нельзя, отказом — тоже: мы просто не знаем. Статус
    таких строк не трогаем вовсе, а имена складываем в досыл.
    """
    дубли = дубли_из_ответа(ответ)
    добавленные = добавленные_из_ответа(ответ)
    по_ключу: dict[tuple[str, str], dict] = {}
    for з in пакет:
        for имя in (з["орг"], з["для_бота"]):
            к = (з["гео"], normalize(имя))
            if к[1]:
                по_ключу.setdefault(к, з)

    def найти(имя: str) -> dict | None:
        к = normalize(имя)
        свои = [з for (г, кл), з in по_ключу.items() if кл == к]
        return свои[0] if свои else None

    # СНАЧАЛА «ДОБАВЛЕНА», ПОТОМ ДУБЛИ — в этом порядке и заключается правило.
    годные, отклонены, не_нашлись = [], [], []
    названы: set[str] = set()
    for имя in добавленные:
        з = найти(имя)
        if not з:
            не_нашлись.append(имя)
            continue
        if з["ид"] in названы:
            continue
        названы.add(з["ид"])
        годные.append(з)

    спорных = 0
    for имя in дубли:
        з = найти(имя)
        if not з:
            не_нашлись.append(имя)
            continue
        if з["ид"] in названы:
            # Бот сказал про одно имя и «добавлена», и «уже есть». Значит имя
            # ушло ему ДВАЖДЫ, и «уже есть» — ответ на нашу же вторую посылку.
            спорных += 1
            continue
        if з["ид"] in {о["ид"] for о in отклонены}:
            continue
        отклонены.append(з)

    нет_ответа = [з for з in пакет
                  if з["ид"] not in названы
                  and з["ид"] not in {о["ид"] for о in отклонены}]

    log(f"  · бот назвал добавленными: {len(годные)}, дублями: "
        f"{len(отклонены)}, промолчал про: {len(нет_ответа)}")
    if спорных:
        log(f"  · спорных {спорных}: названы и добавленными, и дублями — "
            f"считаю годными, «уже есть» это ответ на нашу вторую посылку")
    if нет_ответа:
        log(f"  · про {len(нет_ответа)} бот не сказал ничего — статус НЕ "
            f"трогаю: без вердикта фирма не годна и не отклонена")
    if не_нашлись:
        log(f"  ⚠ в пакете не нашлось: {len(не_нашлись)} "
            f"({', '.join(не_нашлись[:3])}…)")
    return {"отклонены": отклонены, "годные": годные,
            "отголоски": [], "не_нашлись": не_нашлись,
            "нет_ответа": нет_ответа, "спорных": спорных}


def дослать(нет_ответа: list[dict], пакет_имя: str = "", log=print) -> Path | None:
    """
    Собрать ДОСЫЛ: имена, про которые бот не сказал ничего.

    Зачем. Бот отвечает вперемешку и кусками, а на длинном списке просто
    теряет часть имён: в ответе на 1645 названий целые блоки не вернулись ни
    как «добавлена», ни как «уже есть». Само по себе это не беда — такие
    фирмы остаются непроверенными и придут в следующий список. Беда в том,
    что искать их глазами в ответе невозможно, и человек не знает, скольких
    недосчитался.

    Поэтому кладём их отдельным файлом: открыл, скопировал, переспросил бота.
    Сопоставление имён при этом ничего не теряет — бот может дописывать
    «GmbH», точки, «PTY. LTD.» и даже многоточие, мы всё равно узнаём фирму
    (проверено на живом ответе).
    """
    if not нет_ответа:
        return None
    ПАПКА.mkdir(parents=True, exist_ok=True)
    основа = (пакет_имя or f"пакет_{date.today():%d-%m}").removesuffix(".json")
    путь = ПАПКА / f"{основа}_досыл.txt"
    путь.write_text("\n".join(з["для_бота"] for з in нет_ответа),
                    encoding="utf-8")
    log(f"  · без ответа осталось {len(нет_ответа)} — сложил в {путь.name}, "
        f"переспроси бота по ним")
    return путь


def выписки_на_диске(заказ: list[dict]) -> dict[str, Path]:
    """Где лежат файлы этих фирм. Ищем по имени файла — путь мог смениться."""
    нужны = {з["файл"] for з in заказ if з.get("файл")}
    найдено: dict[str, Path] = {}
    if not нужны:
        return найдено
    for п in пути.ВЫПИСКИ.rglob("*"):
        if п.is_file() and п.name in нужны and п.name not in найдено:
            найдено[п.name] = п
    return найдено


def применить(разбор: dict, писать: bool, log=print) -> dict:
    """
    Отклонённых — в «Недостойные» и удалить их выписки. Годных — пометить.

    Порядок именно такой: сперва таблица, потом диск. Если оборвётся между
    ними, на диске останется лишний файл — это видно и чинится уборкой. А вот
    удалённый файл при неотмеченной строке выглядит как «выписка была и
    пропала», и искать её будут вручную.
    """
    from common import таблица as т

    отклонены, годные = разбор["отклонены"], разбор["годные"]
    итог = {"отклонено": 0, "годных": 0, "файлов удалено": 0,
            "не удалилось": [], "уже закрыты": 0, "досыл": None,
            "без ответа": len(разбор.get("нет_ответа") or [])}
    if not писать:
        return итог

    # ВЕРДИКТ — В ЖУРНАЛ, но уже НЕ для того, чтобы им что-то решать.
    # Решает только текст ответа (см. `разложить`). Журнал нужен для двух
    # других вещей: не отправить имя второй раз и суметь потом объяснить,
    # откуда у фирмы её статус.
    записать_вердикт(годные, ГОДНАЯ, log)
    записать_вердикт(отклонены, ОТКЛОНЕНА, log)

    # ДОСЫЛ ПИШЕМ ВСЕГДА, ДАЖЕ ЕСЛИ ДАЛЬШЕ ЧТО-ТО СОРВЁТСЯ: это просто файл,
    # и он — единственный способ узнать, кого бот пропустил.
    if разбор.get("нет_ответа"):
        пакет_имя = next((з.get("пакет") for з in разбор["нет_ответа"]
                          if з.get("пакет")), "")
        итог["досыл"] = дослать(разбор["нет_ответа"], пакет_имя, log)

    # ВТОРОЙ ПОЯС: СМОТРИМ, ЧТО С ЭТИМИ СТРОКАМИ СЕЙЧАС.
    #
    # Ответ бота можно применить дважды — по тому же файлу пакета, из другого
    # окна, через день. Первый раз фирма уехала в «Недостойные» и её выписка
    # удалена; второй раз удалять уже нечего, но и трогать её незачем. А если
    # строка за это время стала годной (ответ разобрали иначе), удаление
    # выписки было бы прямой потерей.
    #
    # Поэтому перед удалением перечитываем таблицу и выбрасываем из отказа
    # всё, что уже закрыто или уже признано годным. Чтение стоит секунд
    # пятнадцать — против сорока минут прогона за новой выпиской это даром.
    if отклонены:
        сейчас: dict[str, str] = {}
        try:
            for л in т.всё(служебные=True):
                if not л["строки"] or "ID" not in л["строки"][0]:
                    continue
                ш = л["строки"][0]
                iи = ш.index("ID")
                iс = ш.index("Статус") if "Статус" in ш else -1
                for с in л["строки"][1:]:
                    ид = с[iи].strip() if iи < len(с) and с[iи] else ""
                    if ид:
                        сейчас[ид] = (с[iс].strip().lower()
                                      if 0 <= iс < len(с) and с[iс] else "")
        except Exception as e:
            log(f"  ⚠ не смог свериться с таблицей ({type(e).__name__}) — "
                "на всякий случай ничего не удаляю")
            return итог
        живые = []
        for з in отклонены:
            статус = сейчас.get(з.get("ид", ""), "")
            if статус in НЕ_СПРАШИВАТЬ_БОТА:
                итог["уже закрыты"] += 1
                continue
            живые.append(з)
        if итог["уже закрыты"]:
            log(f"  · пропускаю {итог['уже закрыты']}: эти строки уже закрыты "
                f"или признаны годными — ответ применяли раньше")
        отклонены = живые

    if годные:
        о = т.обновить([{"лист": з["лист"], "орг": з["орг"], "ид": з["ид"],
                         "поля": {"Статус": ГОДНАЯ}} for з in годные])
        итог["годных"] = о.get("обновлено", 0)
        log(f"  ☁ помечено годными: {итог['годных']} из {len(годные)}")

    if отклонены:
        о = т.обновить([{"лист": з["лист"], "орг": з["орг"], "ид": з["ид"],
                         "поля": {"Статус": ОТКЛОНЕНА}} for з in отклонены])
        log(f"  ☁ помечено отклонёнными: {о.get('обновлено', 0)} "
            f"из {len(отклонены)}")
        ид = [з["ид"] for з in отклонены if з.get("ид")]
        if ид:
            п = т.перенести(НЕДОСТОЙНЫЕ, ид)
            итог["отклонено"] = п.get("перенесено", 0)
            log(f"  ☁ уехало на «{НЕДОСТОЙНЫЕ}»: {итог['отклонено']}")

        # ФАЙЛЫ — ПОСЛЕДНИМИ. Фирма отклонена, её выписка больше не нужна и
        # только путается под ногами: человек просил, чтобы локально лежало
        # лишь то, чем можно работать.
        где = выписки_на_диске(отклонены)
        for з in отклонены:
            п = где.get(з.get("файл") or "")
            if not п:
                continue
            try:
                п.unlink()
                итог["файлов удалено"] += 1
            except Exception as e:
                итог["не удалилось"].append(f"{п.name}: {type(e).__name__}")
        log(f"  · выписок удалено: {итог['файлов удалено']}")
        for с in итог["не удалилось"][:5]:
            log(f"    ⚠ {с}")
    return итог


# ──────────────────────────────── запуск ────────────────────────────────

def main() -> int:
    р = argparse.ArgumentParser(description="Проверка скачанных выписок у бота")
    под = р.add_subparsers(dest="что", required=True)

    с = под.add_parser("список", help="собрать имена для бота")
    с.add_argument("--гео", default="", help="EE,FR — пусто значит все")
    с.add_argument("--линия", default="все", choices=("сайт", "без", "все"))
    с.add_argument("--сколько", type=int, default=0, help="0 — все")
    с.add_argument("--без-выписки", action="store_true",
                   help="брать и тех, у кого выписки ещё нет")

    о = под.add_parser("ответ", help="применить ответ бота")
    о.add_argument("--пакет", required=True, help="json, созданный «списком»")
    о.add_argument("--ответ", required=True, help="файл с ответом бота")
    о.add_argument("--писать", action="store_true")

    а = р.parse_args()
    if а.что == "список":
        гео = [г for г in re.split(r"[,\s;]+", а.гео.upper()) if г]
        пакет = собрать(гео, а.линия, а.сколько,
                        только_с_выпиской=not а.без_выписки)
        if not пакет:
            print("Нечего проверять: таких фирм нет.")
            return 0
        текст, _ = сохранить_пакет(пакет, а.линия)
        в_буфер(текст.read_text(encoding="utf-8"))
        return 0

    пакет = json.loads(Path(а.пакет).read_text(encoding="utf-8"))
    ответ = Path(а.ответ).read_text(encoding="utf-8", errors="replace")
    разбор = разложить(пакет, ответ)
    if not а.писать:
        print()
        print("Это ПРИМЕРКА, ничего не тронуто. Применить: --писать")
        for з in разбор["отклонены"][:10]:
            print(f"   отклонить  {з['гео']} {з['орг'][:44]:46} {з['файл']}")
        if len(разбор["отклонены"]) > 10:
            print(f"   … и ещё {len(разбор['отклонены']) - 10}")
        return 0
    применить(разбор, писать=True)
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    raise SystemExit(main())
