def из_прогона(книга: Path, лист: str, гео: list[str], линия: str,
               log=print) -> list[dict]:
    """
    Фирмы ПОСЛЕДНЕГО ПРОГОНА — из его книги, а не из всей таблицы.

    Зачем отдельный источник. По стране накопились тысячи фирм, и отдавать их
    боту целиком незачем: чаще всего надо проверить ровно то, что нашлось
    сейчас. Книга прогона и есть этот список — в ней ровно найденное.

    Номера фирм берём из книги же: Часть 1 пишет их в колонку ID при записи
    строки. Без номера строку в таблице потом не найти — имя к тому времени
    может смениться на реестровое.
    """
    from openpyxl import load_workbook

    from common.колонки import Шапка

    нужны = {г.strip().upper() for г in (гео or []) if г and г.strip()}
    wb = load_workbook(книга, read_only=True, data_only=True)
    ws = wb[лист] if лист in wb.sheetnames else wb[wb.sheetnames[0]]
    ш = Шапка(ws)
    н = {к: ш.номер(к) for к in
         ("Организация", "Website", "Гео", "ID", "Файл выписки",
          "Платёжный профиль выписки", "Платёжный профиль")}
    свой = лист.split(".")[0].upper()
    найдено: list[dict] = []
    for с in ws.iter_rows(min_row=2, values_only=True):
        def в(поле: str) -> str:
            i = н.get(поле) or 0
            return (str(с[i - 1]).strip()
                    if i and i <= len(с) and с[i - 1] else "")

        орг = в("Организация")
        if not орг:
            continue
        г = (в("Гео") or свой).upper()
        if нужны and г not in нужны:
            continue
        сайт = в("Website")
        if линия == "сайт" and not сайт:
            continue
        if линия == "без" and сайт:
            continue
        найдено.append({
            "ид": в("ID"), "лист": г, "гео": г, "орг": орг,
            "файл": в("Файл выписки"), "для_бота": без_формы_ascii(орг),
            "платёжка": (в("Платёжный профиль выписки")
                         or в("Платёжный профиль")),
        })
    wb.close()
    найдено.sort(key=lambda з: (з["гео"], з["орг"]))
    log(f"  · из прогона «{лист}»: {len(найдено)} фирм"
        + (f" ({', '.join(f'{г}:{n}' for г, n in sorted(_по_гео(найдено).items()))})"
           if найдено else ""))
    return найдено


def собрать(гео: list[str], линия: str, сколько: int, log=print,
            только_с_выпиской: bool = True) -> list[dict]:
    """
    Фирмы, которых бот ещё не видел.

    линия: «сайт» — только с сайтом, «без» — только без сайта, «все» — обе.
    только_с_выпиской: брать лишь тех, у кого документ уже скачан. Это
    обычный случай — отдавать боту фирму, которую нечем подтвердить, смысла
    мало; но галочку человек снимает, если хочет отсеять дубли ЗАРАНЕЕ, до
    скачивания, и не тратить на них прогон Части 2.
    """
    from common import таблица as т

    нужны = {г.strip().upper() for г in (гео or []) if г and г.strip()}
    найдено: list[dict] = []
    # УЖЕ ОТПРАВЛЕННОЕ БОЛЬШЕ НЕ ИДЁТ (правило человека, 23.09.2026).
    #
    # Бот заводит у себя КАЖДОЕ полученное имя. Значит вторая посылка того же
    # имени вернётся одиноким «уже есть» — и по правилу разбора закроет живую
    # фирму, хотя единственный, кто её «занял», это мы сами. Замер: во второй
    # список 23.09 попала 201 фирма, и ВСЕ 201 были в первом.
    # Кого бот потерял, добираем досылом — там имена берутся из пакета, а не
    # отсюда, и человек видит, что именно переспрашивает.
    журнал = _журнал()
    уже_слали = 0
    в_пачке: set[str] = set()
    for л in т.всё():
        if л["скрыт"] or not л["строк"] or not л["строки"]:
            continue
        ш = л["строки"][0]
        if "Организация" not in ш:
            continue
        н = {к: (ш.index(к) if к in ш else -1) for к in
             ("Организация", "Статус", "Файл выписки", "Гео", "Website", "ID",
              "Платёжный профиль выписки", "Платёжный профиль")}
        свой = л["имя"].split(".")[0].upper()
        for с in л["строки"][1:]:
            def взять(поле: str) -> str:
                i = н.get(поле, -1)
                return с[i].strip() if 0 <= i < len(с) and с[i] else ""

            орг = взять("Организация")
            if not орг:
                continue
            г = (взять("Гео") or свой).upper()
            if нужны and г not in нужны:
                continue
            статус = взять("Статус").lower()
            # УЖЕ ЗАКРЫТЫЕ И УЖЕ ПРОВЕРЕННЫЕ НЕ СПРАШИВАЕМ ПОВТОРНО.
            # Иначе каждый заход тянет боту один и тот же список, и в ответе
            # не разобрать, что нового.
            if статус in НЕ_СПРАШИВАТЬ_БОТА:
                continue
            if только_с_выпиской and not есть_выписка(взять("Файл выписки")):
                continue
            сайт = взять("Website")
            if линия == "сайт" and not сайт:
                continue
            if линия == "без" and сайт:
                continue
            if ключ_журнала(г, орг) in журнал:
                уже_слали += 1
                continue
            # ОДНО ИМЯ — ОДИН РАЗ И ВНУТРИ ПАЧКИ. Журнал помнит только прошлые
            # отправки, а близнецы строки (одна фирма дважды на листе, см.
            # «дубли_строк») уходили боту дважды в одном списке: живой случай
            # 19.10 — 96 имён из 344 в пакете UK. Второе «уже есть» на своё же
            # имя закрыло бы живую фирму.
            if ключ_журнала(г, орг) in в_пачке:
                continue
            в_пачке.add(ключ_журнала(г, орг))
            найдено.append({
                "ид": взять("ID"), "лист": л["имя"], "гео": г, "орг": орг,
                "файл": взять("Файл выписки"),
                "для_бота": без_формы_ascii(орг),
                "платёжка": (взять("Платёжный профиль выписки")
                             or взять("Платёжный профиль")),
            })

    найдено.sort(key=lambda з: (з["гео"], з["орг"]))
    if сколько:
        # Режем ПО КАЖДОЙ СТРАНЕ. «50 по трём странам» человек понимает как
        # «по 50 на страну», а не «50 на всех».
        по_гео: dict[str, list] = {}
        for з in найдено:
            по_гео.setdefault(з["гео"], []).append(з)
        найдено = [з for г in sorted(по_гео) for з in по_гео[г][:сколько]]
    log(f"  · к проверке: {len(найдено)}"
        + (f" ({', '.join(f'{г}:{n}' for г, n in sorted(_по_гео(найдено).items()))})"
           if найдено else ""))
    if уже_слали:
        log(f"  · пропущено {уже_слали}: их боту уже отправляли — второй раз "
            f"он ответит «уже есть» на нашу же посылку")
    if len(найдено) > УДОБНЫЙ_ПАКЕТ:
        # ДЛИННЫЙ СПИСОК БОТ НЕ ДОЧИТЫВАЕТ. Живой случай 22.09.2026: на 1645
        # имён ответ пришёл вперемешку и кусками, 40 имён не вернулись ни как
        # «добавлена», ни как «уже есть». И переспросить их уже нельзя:
        # отправлять дважды нельзя, бот их у себя завёл. Потеря окончательная,
        # поэтому это предупреждение — не про удобство, а про цену.
        log(f"  ⚠ это много для одного ответа: бот на длинных списках теряет "
            f"имена, а переспросить их нельзя — он их уже завёл. Поставь "
            f"«сколько на страну», чтобы выходило частями.")
    return найдено


def _по_гео(строки: list[dict]) -> dict[str, int]:
    return dict(Counter(з["гео"] for з in строки))


def сохранить_пакет(пакет: list[dict], линия: str, log=print,
                    журналить: bool = True) -> tuple[Path, Path]:
    """
    Имена — в текст для бота, всё остальное — в json для второго захода.

    журналить=False — когда список отдают боту ПОРЦИЯМИ. Запись в журнал
    значит «это имя у бота уже есть», и делать её на весь список вперёд
    нельзя: человек остановится на третьей полусотне, а остальные полторы
    тысячи имён окажутся навсегда вычеркнуты из оборота, ни разу боту не
    показанные. Журналит тогда тот, кто выдаёт порцию, — по факту выдачи.
    """
    ПАПКА.mkdir(parents=True, exist_ok=True)
    метка = "-".join(sorted(_по_гео(пакет))) or "пусто"
    основа = ПАПКА / f"{линия}_{метка}_{date.today():%d-%m}"
    текст, дано = основа.with_suffix(".txt"), основа.with_suffix(".json")
    # Одно имя в строке — так его ждёт бот и так его удобно вставлять.
    текст.write_text("\n".join(з["для_бота"] for з in пакет), encoding="utf-8")
    # КЛЕЙМИМ СПИСОК НА МЕСТЕ, А НЕ ЕГО КОПИЮ.
    #
    # Раньше здесь было `для_файла = [dict(з, пакет=...) for з in пакет]`:
    # имя пакета попадало только в .json, а тот же список, что остаётся в
    # руках у окна, уходил в разбор БЕЗ клейма. Разбор сравнивал имя пакета
    # из журнала с пустотой, решал «это другой, более ранний пакет» — и
    # 23.09.2026 записал 421 чужой дубль в годные. Правило разбора с тех пор
    # журнала не спрашивает, но поле всё равно должно быть правдой: по нему
    # живут журнал, досыл и разбор ответа, открытого из файла назавтра.
    for з in пакет:
        з["пакет"] = основа.name
    дано.write_text(json.dumps(пакет, ensure_ascii=False, indent=1),
                    encoding="utf-8")
    if журналить:
        записать_в_журнал(пакет, основа.name, log)
    log(f"  · список:  {текст}")
    log(f"  · пакет:   {дано.name} (нужен, чтобы применить ответ)")
    return текст, дано


# ─────────────────────── журнал: что мы уже отправляли ───────────────────

def _журнал() -> dict:
    try:
        return json.loads(ЖУРНАЛ.read_text(encoding="utf-8"))
    except Exception:
        return {}


def ключ_журнала(гео: str, имя: str) -> str:
    return f"{(гео or '').upper()}|{normalize(имя or '')}"


ОТПРАВЛЕНА = "отправлена"    # имя ушло боту — значит он его у себя завёл


def записать_в_журнал(пакет: list[dict], имя_пакета: str, log=print) -> int:
    """
    Запомнить, что эти имена УШЛИ БОТУ и когда.

    ЗАЧЕМ. Бот заводит у себя КАЖДОЕ полученное имя — ответ так и устроен:
    «✅ добавлена» либо «⚠️ уже есть». Значит вторая посылка того же имени
    вернётся одиноким «уже есть», и по правилу разбора закроет живую фирму,
    хотя единственный, кто её «занял», это мы сами. Журнал и есть список
    «этих боту больше не предлагать»: `собрать` по нему отсеивает.

    Запись делаем ОДИН РАЗ на имя — первая отправка и есть та, что завела
    фирму у бота. Повторные не перетирают дату: «когда впервые отправили»
    понадобится ровно тогда, когда придётся разбираться, откуда дубль.

    ЗАПИСЬ НИЧЕГО НЕ РЕШАЕТ. Вердикт живёт в тексте ответа (см. `разложить`).
    Так сделано после 23.09.2026: пока журнал участвовал в решении, одно
    несогласованное поле в `сохранить_пакет` перевело 421 чужой дубль в
    годные — и это не было видно ни в одной цифре, кроме итоговой.
    """
    ж = _журнал()
    новых = 0
    сегодня = f"{date.today():%Y-%m-%d}"
    for з in пакет:
        к = ключ_журнала(з.get("гео", ""), з.get("орг", ""))
        if к in ж:
            continue
        ж[к] = {"дата": сегодня, "пакет": имя_пакета, "состояние": ОТПРАВЛЕНА,
                "гео": з.get("гео", ""), "имя": з.get("орг", ""),
                "ид": з.get("ид", "")}
        новых += 1
    try:
        ЖУРНАЛ.parent.mkdir(parents=True, exist_ok=True)
        ЖУРНАЛ.write_text(json.dumps(ж, ensure_ascii=False, indent=1),
                          encoding="utf-8")
    except Exception as e:
        log(f"  ⚠ журнал отправок не записался ({type(e).__name__}) — "
            "повторная отправка может выглядеть дублем")
    if новых != len(пакет):
        log(f"  · в журнале уже были: {len(пакет) - новых} из {len(пакет)}")
    return новых


def в_буфер(текст: str, log=print) -> None:
    """Положить в буфер обмена. Не вышло — не беда, файл всё равно есть."""
    try:
        subprocess.run("clip", input=текст, text=True, encoding="utf-8",
                       check=True, shell=True)
        log("  · список скопирован в буфер обмена")
    except Exception as e:
        log(f"  · в буфер не положил ({type(e).__name__}) — бери из файла")


