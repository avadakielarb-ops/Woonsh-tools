r"""
ДОСОБРАТЬ ПЛАТЁЖКУ ЛИНИИ «БЕЗ САЙТА» из имени и адреса, которые уже есть.

Что случилось. Платёжка собиралась только в ветке «есть сайт» — у фирм без
сайта колонки D «Платёжный профиль» и P «Исходное с dnb» оставались пустыми.
Замер 22.09.2026: пусто у ВСЕХ 8520 строк этой линии. А это сегодня основная
добыча: до скачивания выписки у фирмы не было платёжки вообще, и отдать её в
работу было нечем.

Починено в `part1/dnb.py` — новые строки приезжают с платёжкой. Но восемь с
половиной тысяч уже лежащих никто не перезальёт, а имя и адрес у них есть:
платёжка из них собирается один в один, как собрал бы прогон.

    <Организация>
    Address: <Адрес>

Строки «Website» здесь нет намеренно: сайта у фирмы нет, пустое поле в
платёжке не нужно.

Колонку C «Платёжный профиль выписки» НЕ ТРОГАЕМ. Там имя и адрес ИЗ РЕЕСТРА,
их пишет Часть 2 после скачивания выписки, и они вернее наших: реестр знает
официальное написание. Заполняем только то, что пусто.

Запуск:
    .venv\Scripts\python.exe код\платёжки_без_сайта.py            — показать
    .venv\Scripts\python.exe код\платёжки_без_сайта.py --писать   — записать
"""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

ПОЛЯ = ("Платёжный профиль", "Исходное с dnb")

# НЕ АДРЕС, А ЗАГЛУШКА САМОГО DNB. Попадается в карточках без адреса; 29 строк
# на 22.09.2026. Написать «Address: Street Address» в платёжку значит отдать
# фармеру заведомую чепуху, поэтому такой адрес просто опускаем — остаётся имя.
ЗАГЛУШКИ = {"street address", "address", "n/a", "-", "—"}


def платёжка(имя: str, адрес: str) -> str:
    """Ровно та же сборка, что в прогоне, — одна на оба места."""
    имя = (имя or "").strip()
    адрес = (адрес or "").strip()
    if not имя:
        return ""
    if адрес.lower() in ЗАГЛУШКИ:
        адрес = ""
    return f"{имя}\nAddress: {адрес}" if адрес else имя


def разобрать(log=print) -> list[dict]:
    """Кому чего не хватает. Ничего не пишет."""
    from common import таблица as т

    правки: list[dict] = []
    счёт = Counter()
    for л in т.всё():
        if л["скрыт"] or not л["строки"]:
            continue
        ш = л["строки"][0]
        if "Организация" not in ш or "Исходное с dnb" not in ш:
            continue
        н = {к: (ш.index(к) if к in ш else -1) for к in
             ("Организация", "Адрес", "Website", "ID", *ПОЛЯ)}
        for с in л["строки"][1:]:
            def в(поле):
                i = н.get(поле, -1)
                return с[i].strip() if 0 <= i < len(с) and с[i] else ""

            орг = в("Организация")
            if not орг or в("Website"):
                continue                     # линия «с сайтом» уже с платёжкой
            чего_нет = {п: платёжка(орг, в("Адрес")) for п in ПОЛЯ if not в(п)}
            if not чего_нет or not any(чего_нет.values()):
                continue
            счёт[л["имя"]] += 1
            правки.append({"лист": л["имя"], "орг": орг, "ид": в("ID"),
                           "поля": чего_нет})

    for лист, n in счёт.most_common(12):
        log(f"   {лист:14} {n:>6}")
    if len(счёт) > 12:
        log(f"   … и ещё листов: {len(счёт) - 12}")
    log(f"  · строк без платёжки: {len(правки)}")
    return правки


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    print("Смотрю, у кого пусто…")
    правки = разобрать()
    if не_надо := not правки:
        print("У всех линии «без сайта» платёжка на месте.")
        raise SystemExit(0)

    print()
    print("=== ПРИМЕР ТОГО, ЧТО ЗАПИШЕМ ===")
    for п in правки[:3]:
        print(f"   {п['лист']} {п['ид']}")
        for строка in (п["поля"].get("Исходное с dnb") or "").splitlines():
            print(f"      {строка}")
    if "--писать" not in sys.argv:
        print()
        print("Это ПРИМЕРКА, таблица не тронута. Записать: --писать")
        raise SystemExit(0)

    from common import таблица as т
    о = т.обновить(правки)
    print()
    print(f"   ✔ дописано строк: {о.get('обновлено', 0)} из {len(правки)}")
