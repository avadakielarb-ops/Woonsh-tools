# -*- coding: utf-8 -*-
"""
================================================================================
ПАРСЕР «ПЛАТЁЖНОГО ПРОФИЛЯ» (колонка B) → организация / website / улица / город /
индекс / штат.  САМОДОСТАТОЧНЫЙ ФАЙЛ (без зависимостей от проекта).
================================================================================

ЗАЧЕМ
-----
В Excel в колонку B («Платёжный профиль») кладётся ОДИН блок текста на фирму:

    <Название организации>
    Address: <полный адрес одной строкой>
    Website: <сайт>

Пример (Франция):
    BARRIQUAND HEAT EXCHANGERS
    Address: 9-13 9 RUE SAINT CLAUDE 42300, ROANNE, AUVERGNE RHONE ALPES France
    Website: www.barriquand.com

Парсер делит этот блок на поля:
    организация | website | улица | город | индекс | штат(только US/AU)

ДВА ЭТАПА
---------
1) `разобрать_блок_B(блок)` — режет блок на: имя, сырой_адрес, сайт.
   • имя  = ВСЁ до «Address:»
   • адрес = между «Address:» и «Website:» (или до конца)
   • сайт = первый токен после «Website:»
   Работает и если строки через \n, и если весь блок в одну строку.

2) `разобрать(адрес, geo)` — режет сырой_адрес на улица/город/индекс ПО СХЕМЕ СТРАНЫ,
   и `штат(...)` — только для US/AU.

ГЛАВНАЯ ОСОБЕННОСТЬ: у стран РАЗНЫЙ порядок кусков адреса, поэтому нет одного
универсального правила — «якорь» это ИНДЕКС (почтовый код), формат которого свой
у каждой страны; от него и режем.

СХЕМЫ ПОРЯДКА (куда встаёт индекс):
    • ИНДЕКС ПЕРЕД городом:   «улица ИНДЕКС, город, регион»
          FR SE NO DK SI CH BE HU AT DE NL FI HR
    • ИНДЕКС В КОНЦЕ + ШТАТ:  «улица город, ШТАТ, индекс»   (штат ТОЛЬКО тут)
          US AU
    • ИНДЕКС В КОНЦЕ:         «улица город, регион, индекс»
          UK CZ PL EE LV
    • BG (особый):           «улица, город, регион, ИНДЕКС» (город = перед регионом)

ОСОБЕННОСТИ/ЛОВУШКИ (почему код такой):
    • Индекс — «якорь». Ищем его РЕГУЛЯРКОЙ формата страны (ИНДЕКС[geo]).
    • Для «ИНДЕКС ПЕРЕД» берём индекс в ГОЛОВЕ (до первой запятой); если там нет —
      это скрытый «конец» (AT/FI/HR/CH иногда «улица город, регион, ИНДЕКС»),
      тогда город = последнее слово первого куска.
    • US/AU: перед индексом ШТАТ, перед штатом ГОРОД. Город часто СЛИТ с улицей
      одним куском («…Ste 236 Hollywood») → город = последнее слово предпоследнего
      куска, остальное — улица. Плюс срезаем прилипшую форму (LLC/INC/…).
    • UK: слова региона (England/Scotland/Wales/Northern Ireland) выкидываем.
    • LV: «улица город, индекс» → город = последний кусок.
    • BG: «…, город, регион, ИНДЕКС» → город = последнее слово предпоследнего куска.
    • Страну в конце («France», «United Kingdom»…) отрезаем ДО разбора.
    • ШТАТ есть ТОЛЬКО у US/AU (кусок между городом и индексом): US→FL, AU→NEW SOUTH WALES.
    • Неизвестное гео (нет регэкспа индекса): улица = первый кусок, город = последний.

ИСТОЧНИК В ПРОЕКТЕ:
    part1/data/address_rules.py  (разобрать, штат, константы)
    part2/engine.py              (_разобрать_блок_B)
================================================================================
"""
from __future__ import annotations

import re
from dataclasses import dataclass


# ============================================================================
# 1. РАЗБОР АДРЕСА ПО ГЕО  (из part1/data/address_rules.py)
# ============================================================================

@dataclass
class Разбор:
    улица: str = ""
    город: str = ""
    индекс: str = ""


# Формат ПОЧТОВОГО ИНДЕКСА по странам (регэксп-«якорь»). Нет страны → универсальный фолбэк.
ИНДЕКС = {
    "US": r"\d{5}(?:-\d{4})?", "UK": r"[A-Z]{1,2}\d[A-Z\d]?\s*\d[A-Z]{2}",
    "AU": r"\d{4}", "DE": r"\d{5}", "AT": r"\d{4}", "BE": r"\d{4}",
    "BG": r"\d{4}", "HU": r"\d{4}", "DK": r"\d{4}", "LV": r"LV-?\d{4}",
    "NL": r"\d{4}\s?[A-Z]{2}", "NO": r"\d{4}", "PL": r"\d{2}-\d{3}",
    "SI": r"\d{4}", "FI": r"\d{5}", "FR": r"\d{5}", "HR": r"\d{5}",
    "CZ": r"\d{3}\s?\d{2}", "CH": r"\d{4}", "SE": r"\d{3}\s?\d{2}", "EE": r"\d{5}",
}

# названия стран (в конце адреса) — отрезаем перед разбором
СТРАНЫ_СЛОВА = [
    "united states", "united kingdom", "australia", "germany", "austria",
    "belgium", "bulgaria", "hungary", "denmark", "latvia", "netherlands",
    "norway", "poland", "slovenia", "finland", "france", "croatia",
    "czech republic", "switzerland", "sweden", "estonia",
]

# КУДА встаёт индекс — три схемы + особая BG:
ИНДЕКС_ПЕРЕД = {"FR", "SE", "NO", "DK", "SI", "CH", "BE", "HU", "AT", "DE", "NL", "FI", "HR"}
ИНДЕКС_ПОСЛЕ_ШТАТ = {"US", "AU"}                 # «улица город, ШТАТ, индекс»
ИНДЕКС_В_КОНЦЕ = {"UK", "CZ", "PL", "EE", "LV"}   # «улица город, регион, индекс»
ИНДЕКС_В_КОНЦЕ_ГОРОД_РЕГИОН = {"BG"}              # «…, город, регион, ИНДЕКС»

ГЕО_СО_ШТАТОМ = {"US", "AU"}                       # штат есть ТОЛЬКО тут


def _страну_прочь(текст: str) -> str:
    """Отрезать название страны в конце («… France» → «…»)."""
    низ = текст.lower()
    for c in СТРАНЫ_СЛОВА:
        i = низ.rfind(c)
        if i != -1:
            return текст[:i].rstrip(" ,").strip()
    return текст.strip()


def _части(s: str) -> list[str]:
    """Разбить по запятым, убрать пустые/пробелы."""
    return [p.strip() for p in s.split(",") if p.strip()]


def разобрать(адрес: str, geo: str) -> Разбор:
    """Сырой адрес → улица/город/индекс по схеме страны. Индекс — «якорь»."""
    if not адрес:
        return Разбор()
    geo = geo.upper()
    текст = _страну_прочь(адрес.replace("\n", " ").strip())
    pat = ИНДЕКС.get(geo)
    if not pat:                                    # неизвестное гео — грубый фолбэк
        ч = _части(текст)
        return Разбор(улица=ч[0] if ч else текст, город=ч[-1] if len(ч) > 1 else "")

    if geo in ИНДЕКС_ПЕРЕД:
        # индекс стоит прямо перед первой запятой: «…улица ИНДЕКС, город»
        голова = текст.split(",", 1)[0]
        мм = list(re.finditer(rf"\b({pat})\b", голова))
        m = мм[-1] if мм else re.search(rf"\b({pat})\b", текст)
    else:
        m = re.search(rf"\b({pat})\b", текст)
    if not m:                                      # индекс не нашли — фолбэк
        ч = _части(текст)
        return Разбор(улица=ч[0] if ч else текст, город=ч[-1] if len(ч) > 1 else "")
    индекс = m.group(1).strip()
    до = текст[:m.start()].strip(" ,")
    после = текст[m.end():].strip(" ,")

    if geo in ИНДЕКС_ПЕРЕД:
        город = _части(после)[0] if _части(после) else ""
        if город:
            улица = до                              # обычный: «улица ИНДЕКС, город, регион»
        else:
            # индекс оказался В КОНЦЕ («улица город, регион, ИНДЕКС» — AT/FI/HR/CH-стиль):
            # город = последнее слово первого куска «до»
            куски = _части(до)
            перв = куски[0] if куски else до
            слова = перв.rsplit(" ", 1)
            улица, город = (слова[0], слова[1]) if len(слова) == 2 else (перв, "")

    elif geo in ИНДЕКС_ПОСЛЕ_ШТАТ:
        # «улица город, ШТАТ, индекс» → перед индексом штат, перед штатом город
        куски = _части(до)                          # [улица+город, ШТАТ] или [улица, город, ШТАТ]
        город = ""
        if len(куски) >= 2:
            город_кусок = куски[-2]                 # предпоследний кусок = город (последний = штат)
            # город часто СЛИТ с улицей одним куском («…Ste 236 Hollywood»):
            # город = ПОСЛЕДНЕЕ слово предпоследнего куска; остальное — улица
            слова = город_кусок.rsplit(" ", 1)
            if len(слова) == 2:
                улица_хвост, город = слова[0], слова[1]
            else:
                улица_хвост, город = "", город_кусок
            перед = ", ".join(куски[:-2]) if len(куски) > 2 else ""
            улица = (перед + " " + улица_хвост).strip() if перед else улица_хвост
            # выкинуть прилипшую к началу улицы правовую форму (LLC 3800…)
            улица = re.sub(r"^(LLC|INC|CORP|LTD|LP|LLP)\b[\s,]*", "", улица, flags=re.I).strip()
        else:
            улица = до

    elif geo in ИНДЕКС_В_КОНЦЕ_ГОРОД_РЕГИОН:
        # BG: «улица (может с запятыми), город, регион, ИНДЕКС» (индекс уже отрезан)
        куски = _части(до)
        if len(куски) >= 2:
            город_кусок = куски[-2]                 # «…Office 9 Sofia» → город = последнее слово
            город = город_кусок.rsplit(" ", 1)[-1]
            остаток = город_кусок[: -len(город)].strip()
            улица = ", ".join(куски[:-2] + ([остаток] if остаток else []))
        else:
            улица, город = до, ""

    else:  # ИНДЕКС_В_КОНЦЕ (UK/CZ/PL/EE/LV): «улица город, регион, индекс»
        куски = _части(до)
        if geo == "LV":
            # «улица город, индекс» → город = последний кусок
            город = куски[-1].split()[-1] if куски else ""
            улица = ", ".join(куски[:-1]) if len(куски) > 1 else (куски[0] if куски else "")
        elif geo == "UK":
            # «улица город, регион» → регион (England…) отбросить, город перед ним
            куски_без_региона = [k for k in куски
                                 if k.lower() not in ("england", "scotland", "wales",
                                                      "northern ireland")]
            город = куски_без_региона[-1].split()[-1] if куски_без_региона else ""
            if куски_без_региона:
                посл = куски_без_региона[-1]
                улица = ", ".join(куски_без_региона[:-1])
                if not улица and " " in посл:
                    улица = посл.rsplit(" ", 1)[0]
            else:
                улица = до
        else:  # CZ/PL/HR/EE: «улица+город, регион, индекс»
            # пример CZ: «Modřická 720/56B Moravany, Jihomoravský kraj» → улица+город, регион
            if len(куски) >= 2:
                улицагород = куски[0]
                слова = улицагород.rsplit(" ", 1)
                улица, город = (слова[0], слова[1]) if len(слова) == 2 else (улицагород, "")
            else:
                улица, город = до, ""

    return Разбор(улица=улица.strip(" ,"), город=город.strip(" ,"), индекс=индекс)


def штат(адрес: str, geo: str, город: str, индекс: str) -> str:
    """Кусок между городом и индексом: US → FL, AU → NEW SOUTH WALES. Иначе пусто."""
    if geo.upper() not in ГЕО_СО_ШТАТОМ or not город or not индекс:
        return ""
    текст = _страну_прочь(адрес.replace("\n", " ").strip())
    m = re.search(re.escape(город) + r"\s*,?\s*(.+?)\s*,?\s*" + re.escape(индекс), текст)
    return m.group(1).strip(" ,") if m else ""


# ============================================================================
# 2. РАЗБОР БЛОКА B (Платёжный профиль)  (из part2/engine.py:_разобрать_блок_B)
# ============================================================================

def разобрать_блок_B(блок: str, geo: str):
    """
    Блок колонки B → (имя, улица, город, индекс, сайт).
    Формат: «Название \\n Address: <адрес> \\n Website: <сайт>» (или всё в одну строку).
      • имя  = всё ДО «Address:»
      • адрес= между «Address:» и «Website:» (или до конца) → далее разобрать(geo)
      • сайт = первый токен после «Website:»
    """
    текст = блок.replace("\r", "\n")
    m_addr = re.search(r"Address:\s*(.+?)(?:\n|Website:|$)", текст, re.I | re.S)
    m_web = re.search(r"Website:\s*(\S+)", текст, re.I)
    имя = re.split(r"Address:", текст, flags=re.I)[0].strip().strip("\n").strip()
    имя = re.sub(r"\s+", " ", имя)                  # схлопнуть пробелы/переводы строк в имени
    сырой_адрес = m_addr.group(1).strip() if m_addr else ""
    сырой_адрес = re.sub(r"\s+", " ", сырой_адрес)
    сайт = m_web.group(1).strip() if m_web else ""
    r = разобрать(сырой_адрес, geo) if сырой_адрес else None
    return (имя,
            (r.улица if r else сырой_адрес),
            (r.город if r else ""),
            (r.индекс if r else ""),
            сайт)


# ============================================================================
# 3. УДОБНАЯ ОБЁРТКА: блок B → словарь всех полей (вкл. штат)
# ============================================================================

def разобрать_профиль(блок: str, geo: str) -> dict:
    """
    Главная точка входа. Блок «Платёжного профиля» → все поля словарём:
        {организация, website, улица, город, индекс, штат}
    штат заполняется только для US/AU.
    """
    имя, улица, город, индекс, сайт = разобрать_блок_B(блок, geo)
    # для штата нужен ПОЛНЫЙ адрес из блока (не только улица)
    m_addr = re.search(r"Address:\s*(.+?)(?:\n|Website:|$)",
                       блок.replace("\r", "\n"), re.I | re.S)
    сырой_адрес = re.sub(r"\s+", " ", m_addr.group(1).strip()) if m_addr else ""
    return {
        "организация": имя,
        "website": сайт,
        "улица": улица,
        "город": город,
        "индекс": индекс,
        "штат": штат(сырой_адрес, geo, город, индекс),
    }


