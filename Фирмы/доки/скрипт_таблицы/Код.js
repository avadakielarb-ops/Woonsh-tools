/**
 * Дописать строки в конец листа ОДНОЙ операцией.
 * тело: {лист: 'EE', строки: [[…], […]]} — строки в порядке ФИРМЫ_КОЛОНКИ.
 * Ничего не перезаписывает: только добавляет в конец.
 */
function _фДописать(тело) {
  var имя = String(тело.лист || '').trim();
  var строки = тело.строки || [];
  if (!имя) throw new Error('не сказано, в какой лист');
  if (!строки.length) return { ok: true, добавлено: 0 };
  var л = SpreadsheetApp.getActive().getSheetByName(имя);
  if (!л) throw new Error('нет листа «' + имя + '» — сначала «создать»');

  // ЛИСТ УЖЕ, ЧЕМ СТРОКА. Строки режутся по ширине листа, и колонка,
  // добавленная в раскладку позже (так пришли «Гео», «Слово», «ID»), молча
  // отваливалась бы у каждой новой фирмы. Дошиваем недостающие заголовки.
  //
  // Только если старая шапка — НАЧАЛО известной раскладки. Иначе на «Реестре»
  // с его семью своими колонками мы бы дописали восьмой «Штат» из раскладки
  // рабочего листа и получили лист, который читается неверно.
  var ширина = Math.max(л.getLastColumn(), 1);
  var нужно = Math.max.apply(null, строки.map(function (с) { return (с || []).length; }));
  var раскладка = ФИРМЫ_СЛУЖЕБНЫЕ[имя] || ФИРМЫ_КОЛОНКИ;
  if (нужно > ширина && л.getLastRow() > 0 && нужно <= раскладка.length) {
    var шапка = л.getRange(1, 1, 1, ширина).getDisplayValues()[0];
    var своя = шапка.every(function (з, i) { return з === раскладка[i]; });
    for (var к = ширина; своя && к < нужно; к++) {
      л.getRange(1, к + 1).setValue(раскладка[к]).setFontWeight('bold')
          .setBackground('#e8eaed');
      л.getRange(2, к + 1, Math.max(л.getMaxRows() - 1, 1), 1)
          .setNumberFormat('@');
    }
    ширина = Math.max(л.getLastColumn(), ширина);
  }
  var ровные = строки.map(function (с) {
    var р = (с || []).slice(0, ширина);
    while (р.length < ширина) р.push('');
    return р.map(function (з) { return з === null || з === undefined ? '' : String(з); });
  });

  // ПОВТОР НЕ ПЛОДИТ БЛИЗНЕЦОВ. Python повторяет вызов, если ответ не дошёл
  // (таймаут 120 с), а строки к тому времени уже легли. Так на листах
  // набралось 516 близнецов. Строку, чей ключ уже есть на листе (или
  // встретился выше в этой же пачке), не дописываем. Ключ — «ID», на
  // «Реестре» — «Ключ» (у одной фирмы там бывает несколько отпечатков).
  var шапкаЛиста = л.getLastRow() > 0
      ? л.getRange(1, 1, 1, ширина).getDisplayValues()[0] : [];
  var кКлюч = имя === 'Реестр' ? шапкаЛиста.indexOf('Ключ') : шапкаЛиста.indexOf('ID');
  var пропущено = 0;
  if (кКлюч >= 0) {
    var есть = {};
    if (л.getLastRow() > 1) {
      л.getRange(2, кКлюч + 1, л.getLastRow() - 1, 1).getDisplayValues()
          .forEach(function (с) { var к = String(с[0] || '').trim(); if (к) есть[к] = 1; });
    }
    ровные = ровные.filter(function (р) {
      var к = String(р[кКлюч] || '').trim();
      if (!к) return true;
      if (есть[к]) { пропущено++; return false; }
      есть[к] = 1;
      return true;
    });
  }
  if (!ровные.length) {
    _фЛог('дописать', имя + ': всё уже было, пропущено ' + пропущено);
    return { ok: true, добавлено: 0, пропущено: пропущено };
  }
  var начало = л.getLastRow() + 1;
  л.getRange(начало, 1, ровные.length, ширина).setValues(ровные);
  _фЛог('дописать', имя + ': +' + ровные.length + ' строк' +
        (пропущено ? ', уже были ' + пропущено : ''));
  return { ok: true, добавлено: ровные.length, с_строки: начало, пропущено: пропущено };
}

