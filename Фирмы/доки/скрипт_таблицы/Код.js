/**
 * Завести недостающие листы. Существующие НЕ ТРОГАЕМ вообще.
 * гео — массив кодов: ['EE','PL',…]. На каждый заводится два листа:
 * «EE» (с сайтом) и «EE.БС» (без сайта, но с адресом).
 */
function _фСоздать(гео) {
  var ss = SpreadsheetApp.getActive();
  var создано = [], было = [];

  Object.keys(ФИРМЫ_СЛУЖЕБНЫЕ).forEach(function (имя) {
    var р = _фЛист(ss, имя, ФИРМЫ_СЛУЖЕБНЫЕ[имя], true, false);
    (р ? создано : было).push(имя);
  });

  var р = _фЛист(ss, 'Мультигео', ФИРМЫ_КОЛОНКИ, false, true);
  (р ? создано : было).push('Мультигео');

  (гео || []).forEach(function (г) {
    г = String(г || '').trim().toUpperCase();
    if (!г) return;
    [г, г + '.БС'].forEach(function (имя) {
      var р = _фЛист(ss, имя, ФИРМЫ_КОЛОНКИ, false, true);
      (р ? создано : было).push(имя);
    });
  });

  _фЛог('создание', 'заведено ' + создано.length + ', уже было ' + было.length);
  return { ok: true, создано: создано, уже_было: было };
}

/** Один лист. Возвращает true, если ЗАВЕЛИ (а не нашли готовый). */
function _фЛист(ss, имя, шапка, скрыть, статусы) {
  var л = ss.getSheetByName(имя);
  if (л) {
    // Лист есть — не трогаем данные. Только дошьём шапку, если её нет вовсе:
    // пустой лист без заголовков приложение прочитать не сможет.
    if (л.getLastRow() === 0) _фШапка(л, шапка, статусы);
    return false;
  }
  л = ss.insertSheet(имя);
  _фШапка(л, шапка, статусы);
  if (скрыть) л.hideSheet();
  return true;
}

function _фШапка(л, шапка, статусы) {
  л.getRange(1, 1, 1, шапка.length).setValues([шапка])
      .setFontWeight('bold').setBackground('#e8eaed');
  л.setFrozenRows(1);
  if (шапка === ФИРМЫ_КОЛОНКИ || шапка.length >= ФИРМЫ_КОЛОНКИ.length) {
    for (var i = 0; i < ФИРМЫ_ШИРИНЫ.length && i < шапка.length; i++) {
      л.setColumnWidth(i + 1, ФИРМЫ_ШИРИНЫ[i]);
    }
  }
  if (статусы) {
    // Выпадающий список в первой колонке — как просил пользователь.
    // Ставим на весь лист сразу, чтобы не переставлять на каждую новую строку.
    var правило = SpreadsheetApp.newDataValidation()
        .requireValueInList(ФИРМЫ_СТАТУСЫ, true).setAllowInvalid(false).build();
    л.getRange(2, 1, л.getMaxRows() - 1, 1).setDataValidation(правило);
  }
  // Текстовый формат: индексы вроде «01234» и номера реестра не должны
  // превращаться в числа и терять ведущие нули.
  л.getRange(2, 1, л.getMaxRows() - 1, шапка.length).setNumberFormat('@');
}

