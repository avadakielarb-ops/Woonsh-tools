// ---------------------------------------------------------------- вход

function doGet(e) {
  return _фРабота((e && e.parameter) || {}, null);
}

function doPost(e) {
  var тело = {};
  try {
    if (e && e.postData && e.postData.contents) тело = JSON.parse(e.postData.contents);
  } catch (err) {
    return _фОтвет({ ok: false, ошибка: 'тело не JSON: ' + err });
  }
  return _фРабота((e && e.parameter) || {}, тело);
}

function _фРабота(п, тело) {
  var ключ = (тело && тело.key) || п.key;
  if (ключ !== ФИРМЫ_КЛЮЧ) return _фОтвет({ ok: false, ошибка: 'нет ключа' });
  var действие = (тело && тело.action) || п.action;
  try {
    switch (действие) {
      case 'ping':
        return _фОтвет({ ok: true, сборка: ФИРМЫ_СБОРКА, таблица: SpreadsheetApp.getActive().getName(),
                         листов: SpreadsheetApp.getActive().getSheets().length });
      case 'схема':
        return _фОтвет({ ok: true, листы: _фСхема() });
      case 'всё':
      case 'все':
        return _фОтвет(_фВсё(тело || {}));
      case 'читать':
        var прочитано = _фЧитать((тело && тело.лист) || п.лист,
                                 (тело && тело.сколько) || п.сколько);
        return _фОтвет({ ok: true, строки: прочитано.строки,
                         обрезано: прочитано.обрезано });
      case 'создать':
        return _фОтвет(_фСоздать((тело && тело.гео) || []));
      case 'дописать':
        return _фОтвет(_фДописать(тело || {}));
      case 'отработать':
        return _фОтвет(_фОтработать(тело || {}));
      case 'обновить':
        return _фОтвет(_фОбновить(тело || {}));
      case 'сортировать':
        return _фОтвет(_фСортировать(тело || {}));
      case 'слова':
        return _фОтвет(_фСлова((тело && тело.строки) || []));
      case 'ид':
        return _фОтвет(_фИд(тело || {}));
      case 'перенести':
        return _фОтвет(_фПеренести(тело || {}));
      case 'переставить':
        return _фОтвет(_фПереставить(тело || {}));
      case 'статусы':
        return _фОтвет(_фСтатусы());
      case 'дубли_строк':
        return _фОтвет(_фДубли(тело || {}));
      case 'убрать_строки':
        return _фОтвет(_фУбрать(тело || {}));
      case 'порядок':
        return _фОтвет(_фПорядок());
      default:
        return _фОтвет({ ok: false, ошибка: 'нет action',
                         можно: ['ping', 'схема', 'читать', 'создать',
                                 'дописать', 'отработать', 'обновить',
                                 'сортировать', 'слова', 'ид', 'порядок'] });
    }
  } catch (err) {
    return _фОтвет({ ok: false, ошибка: String(err) });
  }
}

// ---------------------------------------------------------------- чтение

function _фСхема() {
  return SpreadsheetApp.getActive().getSheets().map(function (л) {
    var кол = Math.max(л.getLastColumn(), 1), стр = л.getLastRow();
    return {
      имя: л.getName(),
      скрыт: л.isSheetHidden(),
      строк: Math.max(стр - 1, 0),
      колонок: кол,
      шапка: стр ? л.getRange(1, 1, 1, кол).getDisplayValues()[0] : []
    };
  });
}

/**
 * ПРОЧИТАТЬ ВСЮ ТАБЛИЦУ ОДНИМ ОТВЕТОМ.
 * тело: {листы: ['EE', …] — пусто значит все; служебные: true/false}
 *
 * ЗАЧЕМ. Каждый лист отдельным запросом — это круговая поездка на 2,6 секунды.
 * Замер 10.09.2026: схема 23 с плюс 43 листа по 2,6 — сто тридцать семь секунд
 * на ОДНО обновление цифр. Столько же стоит «Заменить дубли» и «Взять в
 * работу»: они тоже обходят таблицу целиком. Здесь всё читается за один заход
 * по листу, без сети между ними.
 *
 * ПОЧЕМУ НЕ ВСЕГДА ВСЁ. «Реестр» — это тысячи строк, которые нужны только
 * выгрузке, а «Отработано» — история. Тянуть их каждому, кому нужны рабочие
 * листы, значит менять одну беду на другую: вместо сети раздувать ответ.
 * Поэтому служебные листы отдаются, только если о них попросили.
 */
function _фВсё(тело) {
  var только = (тело && тело.листы) || [];
  var служебные = !!(тело && тело.служебные);
  var предел = Math.min(parseInt((тело && тело.сколько), 10) || 20000, 20000);
  var листы = [];
  var обрезано = false;
  SpreadsheetApp.getActive().getSheets().forEach(function (л) {
    var имя = л.getName();
    if (только.length ? только.indexOf(имя) < 0
                      : (!служебные && ФИРМЫ_СЛУЖЕБНЫЕ[имя])) return;
    var стр = л.getLastRow(), кол = Math.max(л.getLastColumn(), 1);
    if (стр < 1) return;
    var сколько = Math.min(стр, предел + 1);
    if (стр - 1 > предел) обрезано = true;
    листы.push({
      имя: имя,
      скрыт: л.isSheetHidden(),
      строк: Math.max(стр - 1, 0),
      строки: л.getRange(1, 1, сколько, кол).getDisplayValues()
    });
  });
  return { ok: true, листы: листы, обрезано: обрезано };
}

/**
 * ПРОЧИТАТЬ ЛИСТ. Возвращает {строки, обрезано}.
 *
 * ПРО ПОТОЛОК. Он был 500 строк — и молча. «Реестр» к этому времени вырос до
 * 2793 строк, то есть проверка «работали мы с этой фирмой» шла по первой
 * пятой части базы, а остальные четыре пятых считались новыми и дописывались
 * заново. Снаружи это выглядело как «фирма нашлась второй раз», и списать
 * было не на что.
 *
 * Теперь потолок 20000 строк, а если запрошено больше, чем влезло, ответ
 * прямо говорит «обрезано». Тихо недодать — хуже, чем отказать.
 */
function _фЧитать(имя, сколько) {
  var л = SpreadsheetApp.getActive().getSheetByName(имя);
  if (!л) throw new Error('нет листа «' + имя + '»');
  var н = Math.min(parseInt(сколько, 10) || 20, 20000);
  var стр = л.getLastRow(), кол = Math.max(л.getLastColumn(), 1);
  if (стр < 1) return { строки: [], обрезано: false };
  return {
    строки: л.getRange(1, 1, Math.min(стр, н + 1), кол).getDisplayValues(),
    обрезано: стр - 1 > н
  };
}

