function проверка() {
  var ss = SpreadsheetApp.getActive();
  var имена = ss.getSheets().map(function (л) { return л.getName(); });
  Logger.log('Таблица: %s | листов: %s | %s',
             ss.getName(), имена.length, имена.join(', '));
  return имена;
}

// ---------------------------------------------------------------- вход

function doGet(e) {
  return _фРабота((e && e.parameter) || {}, null);
}

function doPost(e) {
  var тело = {};
  try {
    if (e && e.postData && e.postData.contents) тело = JSON.parse(e.postData.contents);
  } catch (err) {
    return _фОтвет({ ok: false, ошибка: 'тело не JSON: ' + err });
  }
  return _фРабота((e && e.parameter) || {}, тело);
}

function _фРабота(п, тело) {
  var ключ = (тело && тело.key) || п.key;
  if (ключ !== ФИРМЫ_КЛЮЧ) return _фОтвет({ ok: false, ошибка: 'нет ключа' });
  var действие = (тело && тело.action) || п.action;
  try {
    switch (действие) {
      case 'ping':
        return _фОтвет({ ok: true, таблица: SpreadsheetApp.getActive().getName(),
                         листов: SpreadsheetApp.getActive().getSheets().length });
      case 'схема':
        return _фОтвет({ ok: true, листы: _фСхема() });
      case 'читать':
        return _фОтвет({ ok: true, строки: _фЧитать((тело && тело.лист) || п.лист,
                                                    (тело && тело.сколько) || п.сколько) });
      case 'создать':
        return _фОтвет(_фСоздать((тело && тело.гео) || []));
      case 'дописать':
        return _фОтвет(_фДописать(тело || {}));
      case 'отработать':
        return _фОтвет(_фОтработать(тело || {}));
      case 'обновить':
        return _фОтвет(_фОбновить(тело || {}));
      case 'сортировать':
        return _фОтвет(_фСортировать(тело || {}));
      case 'порядок':
        return _фОтвет(_фПорядок());
      default:
        return _фОтвет({ ok: false, ошибка: 'нет action',
                         можно: ['ping', 'схема', 'читать', 'создать',
                                 'дописать', 'отработать', 'обновить',
                                 'сортировать', 'порядок'] });
    }
  } catch (err) {
    return _фОтвет({ ok: false, ошибка: String(err) });
  }
}

// ---------------------------------------------------------------- чтение

function _фСхема() {
  return SpreadsheetApp.getActive().getSheets().map(function (л) {
    var кол = Math.max(л.getLastColumn(), 1), стр = л.getLastRow();
    return {
      имя: л.getName(),
      скрыт: л.isSheetHidden(),
      строк: Math.max(стр - 1, 0),
      колонок: кол,
      шапка: стр ? л.getRange(1, 1, 1, кол).getDisplayValues()[0] : []
    };
  });
}

function _фЧитать(имя, сколько) {
  var л = SpreadsheetApp.getActive().getSheetByName(имя);
  if (!л) throw new Error('нет листа «' + имя + '»');
  var н = Math.min(parseInt(сколько, 10) || 20, 500);
  var стр = л.getLastRow(), кол = Math.max(л.getLastColumn(), 1);
  if (стр < 1) return [];
  return л.getRange(1, 1, Math.min(стр, н + 1), кол).getDisplayValues();
}

// ---------------------------------------------------------------- создание

/**
 * Завести недостающие листы. Существующие НЕ ТРОГАЕМ вообще.
 * гео — массив кодов: ['EE','PL',…]. На каждый заводится два листа:
 * «EE» (с сайтом) и «EE.БС» (без сайта, но с адресом).
 */
function _фСоздать(гео) {
  var ss = SpreadsheetApp.getActive();
  var создано = [], было = [];

  Object.keys(ФИРМЫ_СЛУЖЕБНЫЕ).forEach(function (имя) {
    var р = _фЛист(ss, имя, ФИРМЫ_СЛУЖЕБНЫЕ[имя], true, false);
    (р ? создано : было).push(имя);
  });

  var р = _фЛист(ss, 'Мультигео', ФИРМЫ_КОЛОНКИ, false, true);
  (р ? создано : было).push('Мультигео');

  (гео || []).forEach(function (г) {
    г = String(г || '').trim().toUpperCase();
    if (!г) return;
    [г, г + '.БС'].forEach(function (имя) {
      var р = _фЛист(ss, имя, ФИРМЫ_КОЛОНКИ, false, true);
      (р ? создано : было).push(имя);
    });
  });

  _фЛог('создание', 'заведено ' + создано.length + ', уже было ' + было.length);
  return { ok: true, создано: создано, уже_было: было };
}

/** Один лист. Возвращает true, если ЗАВЕЛИ (а не нашли готовый). */
function _фЛист(ss, имя, шапка, скрыть, статусы) {
  var л = ss.getSheetByName(имя);
  if (л) {
    // Лист есть — не трогаем данные. Только дошьём шапку, если её нет вовсе:
    // пустой лист без заголовков приложение прочитать не сможет.
    if (л.getLastRow() === 0) _фШапка(л, шапка, статусы);
    return false;
  }
  л = ss.insertSheet(имя);
  _фШапка(л, шапка, статусы);
  if (скрыть) л.hideSheet();
  return true;
}

function _фШапка(л, шапка, статусы) {
  л.getRange(1, 1, 1, шапка.length).setValues([шапка])
      .setFontWeight('bold').setBackground('#e8eaed');
  л.setFrozenRows(1);
  if (шапка === ФИРМЫ_КОЛОНКИ || шапка.length >= ФИРМЫ_КОЛОНКИ.length) {
    for (var i = 0; i < ФИРМЫ_ШИРИНЫ.length && i < шапка.length; i++) {
      л.setColumnWidth(i + 1, ФИРМЫ_ШИРИНЫ[i]);
    }
  }
  if (статусы) {
    // Выпадающий список в первой колонке — как просил пользователь.
    // Ставим на весь лист сразу, чтобы не переставлять на каждую новую строку.
    var правило = SpreadsheetApp.newDataValidation()
        .requireValueInList(ФИРМЫ_СТАТУСЫ, true).setAllowInvalid(false).build();
    л.getRange(2, 1, л.getMaxRows() - 1, 1).setDataValidation(правило);
  }
  // Текстовый формат: индексы вроде «01234» и номера реестра не должны
  // превращаться в числа и терять ведущие нули.
  л.getRange(2, 1, л.getMaxRows() - 1, шапка.length).setNumberFormat('@');
}

