/**
 * Дописать строки в конец листа ОДНОЙ операцией.
 * тело: {лист: 'EE', строки: [[…], […]]} — строки в порядке ФИРМЫ_КОЛОНКИ.
 * Ничего не перезаписывает: только добавляет в конец.
 */
function _фДописать(тело) {
  var имя = String(тело.лист || '').trim();
  var строки = тело.строки || [];
  if (!имя) throw new Error('не сказано, в какой лист');
  if (!строки.length) return { ok: true, добавлено: 0 };
  var л = SpreadsheetApp.getActive().getSheetByName(имя);
  if (!л) throw new Error('нет листа «' + имя + '» — сначала «создать»');

  var ширина = Math.max(л.getLastColumn(), 1);
  var ровные = строки.map(function (с) {
    var р = (с || []).slice(0, ширина);
    while (р.length < ширина) р.push('');
    return р.map(function (з) { return з === null || з === undefined ? '' : String(з); });
  });
  var начало = л.getLastRow() + 1;
  л.getRange(начало, 1, ровные.length, ширина).setValues(ровные);
  _фЛог('дописать', имя + ': +' + ровные.length + ' строк');
  return { ok: true, добавлено: ровные.length, с_строки: начало };
}

/**
 * ОТМЕТИТЬ ОТРАБОТАННЫЕ и убрать их с рабочего листа.
 * тело: {отметки: [{лист: 'UK', орг: 'BRONZE LAND LTD'}, …], дата: '08-09'}
 *
 * Строка не удаляется бесследно: она целиком уезжает на скрытый лист
 * «Отработано» вместе с датой и именем листа, откуда пришла. Это прямая
 * просьба пользователя: отработанное не должно мешать в работе, но должно
 * помниться — иначе следующий прогон найдёт ту же фирму заново.
 *
 * Ищем по ТОЧНОМУ совпадению «Организации»: строки писало то же приложение,
 * поэтому строка совпадает символ в символ. Никакой нормализации здесь нет
 * намеренно — она живёт в Python, и держать вторую копию правил в JS значит
 * рано или поздно получить два разных ответа на один вопрос.
 */
function _фОтработать(тело) {
  var отметки = тело.отметки || [];
  var дата = String(тело.дата || Utilities.formatDate(
      new Date(), Session.getScriptTimeZone(), 'dd-MM-yyyy'));
  if (!отметки.length) return { ok: true, помечено: 0 };

  var ss = SpreadsheetApp.getActive();
  var куда = ss.getSheetByName('Отработано');
  if (!куда) throw new Error('нет листа «Отработано» — сначала «создать»');

  var поЛистам = {};
  отметки.forEach(function (о) {
    var л = String(о.лист || '').trim();
    if (!л) return;
    (поЛистам[л] = поЛистам[л] || []).push(String(о.орг || '').trim());
  });

  var помечено = 0, ненайдено = [], перенос = [];
  Object.keys(поЛистам).forEach(function (имя) {
    var л = ss.getSheetByName(имя);
    if (!л) { ненайдено.push('нет листа ' + имя); return; }
    var последняя = л.getLastRow(), кол = Math.max(л.getLastColumn(), 1);
    if (последняя < 2) return;
    var данные = л.getRange(1, 1, последняя, кол).getDisplayValues();
    var шапка = данные[0];
    var кОрг = шапка.indexOf('Организация') + 1;
    if (!кОрг) { ненайдено.push('нет колонки Организация в ' + имя); return; }

    // Индекс «имя → номера строк». Одна фирма может лежать в нескольких
    // строках, если её случайно записали дважды: убираем все.
    var индекс = {};
    for (var r = 1; r < данные.length; r++) {
      var ключ = данные[r][кОрг - 1];
      if (ключ) (индекс[ключ] = индекс[ключ] || []).push(r + 1);
    }
    var строки = [];
    поЛистам[имя].forEach(function (орг) {
      var найдены = индекс[орг];
      if (!найдены || !найдены.length) { ненайдено.push(имя + ': ' + орг); return; }
      найдены.forEach(function (н) { строки.push(н); });
    });
    строки.sort(function (a, b) { return b - a; });     // снизу вверх
    строки.forEach(function (н) {
      var строка = данные[н - 1].slice(0, кол);
      // СТАТУС МОЖНО СОХРАНИТЬ. Отработанные помечаются «отработано», а
      // закрытые по другой причине — ликвидирована, нет в реестре — должны
      // уехать с рабочего листа, НЕ прикидываясь отработанными: иначе завтра
      // не отличить «сделали» от «не годится».
      строка[0] = тело.сохранять_статус ? (строка[0] || 'брак') : 'отработано';
      перенос.push(строка.concat([дата, имя]));
      л.deleteRow(н);
      помечено++;
    });
  });

  if (перенос.length) {
    var ширина = Math.max(куда.getLastColumn(), перенос[0].length);
    var ровные = перенос.map(function (с) {
      var р = с.slice(0, ширина);
      while (р.length < ширина) р.push('');
      return р;
    });
    куда.getRange(куда.getLastRow() + 1, 1, ровные.length, ширина)
        .setValues(ровные);
  }
  _фЛог('отработано', 'помечено ' + помечено +
        (ненайдено.length ? ', не нашлось ' + ненайдено.length : ''));
  return { ok: true, помечено: помечено, не_нашлось: ненайдено.slice(0, 50) };
}

/**
 * ОБНОВИТЬ ОТДЕЛЬНЫЕ КЛЕТКИ существующих строк.
 * тело: {правки: [{лист, орг, поля: {'Файл выписки': '…', 'Статус': '…'}}, …]}
 *
 * Только названные колонки и только у названных фирм. Всё остальное на листе
 * не трогаем: человек мог что-то поправить руками, и затирать это нельзя.
 *
 * Строку ищем по ТОЧНОМУ имени в «Организации» — те же строки писало наше же
 * приложение, поэтому совпадение посимвольное. Нормализации здесь нет
 * намеренно: она живёт в Python, и вторая копия правил в JS однажды ответила
 * бы иначе.
 */
function _фОбновить(тело) {
  var правки = тело.правки || [];
  if (!правки.length) return { ok: true, обновлено: 0 };
  var ss = SpreadsheetApp.getActive();

  var поЛистам = {};
  правки.forEach(function (п) {
    var л = String(п.лист || '').trim();
    if (л) (поЛистам[л] = поЛистам[л] || []).push(п);
  });

  var обновлено = 0, ненайдено = [];
  Object.keys(поЛистам).forEach(function (имя) {
    var л = ss.getSheetByName(имя);
    if (!л) { ненайдено.push('нет листа ' + имя); return; }
    var последняя = л.getLastRow(), кол = Math.max(л.getLastColumn(), 1);
    if (последняя < 2) return;
    var сетка = л.getRange(1, 1, последняя, кол).getDisplayValues();
    var шапка = сетка[0];
    var кОрг = шапка.indexOf('Организация');
    if (кОрг < 0) { ненайдено.push('нет колонки Организация в ' + имя); return; }

    var индекс = {};
    for (var r = 1; r < сетка.length; r++) {
      var к = сетка[r][кОрг];
      if (к && !(к in индекс)) индекс[к] = r + 1;      // первая строка выигрывает
    }
    поЛистам[имя].forEach(function (п) {
      var н = индекс[String(п.орг || '').trim()];
      if (!н) { ненайдено.push(имя + ': ' + п.орг); return; }
      var менялось = false;
      Object.keys(п.поля || {}).forEach(function (подпись) {
        var c = шапка.indexOf(подпись);
        if (c < 0) return;
        л.getRange(н, c + 1).setValue(String(п.поля[подпись]));
        менялось = true;
      });
      if (менялось) обновлено++;
    });
  });
  _фЛог('обновить', 'строк ' + обновлено +
        (ненайдено.length ? ', не нашлось ' + ненайдено.length : ''));
  return { ok: true, обновлено: обновлено, не_нашлось: ненайдено.slice(0, 50) };
}

/**
 * ОТСОРТИРОВАТЬ ЛИСТ по названным колонкам.
 * тело: {лист: 'EE', по: ['Гео', 'Организация']}
 *
 * Шапку не трогаем — сортируем со второй строки. Пустые значения уводим вниз:
 * строка без организации это освобождённое место, и ему место в конце, а не
 * посреди списка.
 */
function _фСортировать(тело) {
  var имя = String(тело.лист || '').trim();
  var по = тело.по || ['Гео', 'Организация'];
  var л = SpreadsheetApp.getActive().getSheetByName(имя);
  if (!л) throw new Error('нет листа «' + имя + '»');
  var последняя = л.getLastRow(), кол = Math.max(л.getLastColumn(), 1);
  if (последняя < 3) return { ok: true, отсортировано: 0 };

  var шапка = л.getRange(1, 1, 1, кол).getDisplayValues()[0];
  var порядок = [];
  по.forEach(function (подпись) {
    var i = шапка.indexOf(подпись);
    if (i >= 0) порядок.push({ column: i + 1, ascending: true });
  });
  if (!порядок.length) throw new Error('нет колонок для сортировки на «' + имя + '»');

  var кОрг = шапка.indexOf('Организация');
  var диапазон = л.getRange(2, 1, последняя - 1, кол);
  if (кОрг >= 0) {
    // Пустые строки вниз: сортируем сначала по «есть ли организация».
    var данные = диапазон.getValues();
    данные.sort(function (a, b) {
      var пустаяA = !String(a[кОрг] || '').trim();
      var пустаяB = !String(b[кОрг] || '').trim();
      if (пустаяA !== пустаяB) return пустаяA ? 1 : -1;
      for (var i = 0; i < порядок.length; i++) {
        var c = порядок[i].column - 1;
        var x = String(a[c] || ''), y = String(b[c] || '');
        if (x !== y) return x < y ? -1 : 1;
      }
      return 0;
    });
    диапазон.setValues(данные);
  } else {
    диапазон.sort(порядок);
  }
  _фЛог('сортировка', имя + ' по ' + по.join(', '));
  return { ok: true, отсортировано: последняя - 1 };
}

/**
 * Разложить вкладки по алфавиту: «Мультигео», потом гео парами («EE», «EE.БС»),
 * служебные — в конец. Google вставляет новый лист рядом с текущим, поэтому
 * после создания сорока листов порядок выходит случайным.
 */
function _фПорядок() {
  var ss = SpreadsheetApp.getActive();
  var служебные = Object.keys(ФИРМЫ_СЛУЖЕБНЫЕ);
  var листы = ss.getSheets().map(function (л) { return л.getName(); });
  var вес = function (имя) {
    if (имя === 'Мультигео') return '0';
    if (служебные.indexOf(имя) >= 0) return '2' + имя;
    return '1' + имя;
  };
  листы.sort(function (a, b) { return вес(a) < вес(b) ? -1 : 1; });
  листы.forEach(function (имя, i) {
    var л = ss.getSheetByName(имя);
    ss.setActiveSheet(л);
    ss.moveActiveSheet(i + 1);
  });
  return { ok: true, порядок: листы };
}

function _фЛог(событие, подробности) {
  try {
    var л = SpreadsheetApp.getActive().getSheetByName('Лог');
    if (л) л.appendRow([new Date(), '', событие, подробности]);
  } catch (e) {}
}

