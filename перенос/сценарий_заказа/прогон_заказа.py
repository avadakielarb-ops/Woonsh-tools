def бот(excel, лист, гео, линия="сайт"):
    из_книги = [з for з in пб.из_прогона(excel, лист, гео, линия, log=лог) if з.get("файл")]
    пакет = из_книги or пб.собрать(гео, линия, 0, log=лог, только_с_выпиской=True)
    if not пакет:
        return {"пакет": 0, "из_книги": 0}
    ответ = М.ответ_бота(пакет, ФИРМЫ_МИРА)
    лог("ОТВЕТ БОТА:\n" + ответ)
    разбор = пб.разложить(пакет, ответ, log=лог)
    итог = пб.применить(разбор, True, log=лог)
    итог["пакет"] = len(пакет)
    итог["из_книги"] = len(из_книги)
    return итог


def взять_в_работу(гео: list[str], сколько: int):
    """
    НОВОЕ ПОВЕДЕНИЕ, которое просил владелец: выбрал гео и количество → программа берёт N годных.
    Сейчас в окне владельца иначе: человек вставляет платёжки забранных фирм. Здесь выбор N годных
    сделан снаружи, а дальше работает НАСТОЯЩИЙ код выдачи (Окно._отметить → _собрать_папку).
    """
    годные = []
    for л in т.всё():
        if л["имя"].split(".")[0].upper() not in гео and л["имя"] != "Мультигео":
            continue
        ш = л["строки"][0] if л["строки"] else []
        for с in л["строки"][1:]:
            з = dict(zip(ш, с))
            if з.get("Статус", "").lower() == "годная" and (з.get("Гео") or л["имя"][:2]).upper() in гео:
                годные.append(з.get("Платёжный профиль выписки") or з["Организация"])
    имена = [g.split("\n")[0] for g in годные[:сколько]]
    итог = Окошко()._отметить(имена, гео)
    итог["годных_было"] = len(годные)
    итог["просили"] = сколько
    return итог


# ── проверки ──────────────────────────────────────────────────────────────────
РЕЗУЛЬТАТЫ: list[tuple[str, list[tuple[str, bool, str]]]] = []


def строки_книги(excel, лист):
    wb = load_workbook(excel, read_only=True, data_only=True)
    if лист not in wb.sheetnames:
        return []
    ws = wb[лист]
    шапка = [c.value for c in next(ws.iter_rows(max_row=1))]
    out = [dict(zip(шапка, [c.value for c in r])) for r in ws.iter_rows(min_row=2)]
    wb.close()
    return [r for r in out if r.get("Организация")]


def статусы_таблицы():
    st = {}
    for л in ТАБЛИЦА.листы:
        if л == "Реестр":
            continue
        for з in ТАБЛИЦА.строки_листа(л):
            if з.get("Организация"):
                st[з["Организация"]] = (л, з.get("Статус", ""))
    return st


def сценарий(название):
    def обёртка(функция):
        проверки: list[tuple[str, bool, str]] = []

        def чек(что, усл, деталь=""):
            проверки.append((что, bool(усл), str(деталь)[:300]))
        лог(f"\n{'#' * 70}\n# {название}\n{'#' * 70}")
        try:
            функция(чек)
        except Exception as e:
            чек("сценарий дошёл до конца без исключения", False,
                f"{type(e).__name__}: {e}\n{traceback.format_exc()[-1500:]}")
        РЕЗУЛЬТАТЫ.append((название, проверки))
        return функция
    return обёртка


